#!/usr/bin/env python3
"""Generate the per-language copies of the retired-app table.

Source of truth: docs/retired-apps.json (prose: docs/retired-apps.md,
conformance corpus: docs/retired-apps-fixtures.json) plus the replacement
apps' own folders under repo/apps/code. Outputs (all committed):

  cloud/apps/auth-web/src/lib/retired-apps.gen.ts   the cloud: the table and each
                                                    replacement as a scene-local app
  frameos/src/frameos/retired_apps_gen.nim          the Linux runtime's fallback for a
                                                    scene that still names a retired app

The backend keeps its own copy of the table (backend/app/utils/retired_apps.py,
pinned by its test) and reads repo/apps/code at run time — the backend image
ships it.

    python3 frameos/tools/generate_retired_apps.py          # write
    python3 frameos/tools/generate_retired_apps.py --check  # CI: fail if stale

A change to a replacement app's files therefore needs a run of this script:
the cloud and the Linux fallback carry a copy. The scenes themselves carry
their own copy, so that is never what a frame runs once its scenes were
converted — the copies only serve scenes that still name the retired keyword.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "docs" / "retired-apps.json"
OUTPUTS = {
    "ts_cloud": REPO / "cloud" / "apps" / "auth-web" / "src" / "lib" / "retired-apps.gen.ts",
    "nim": REPO / "frameos" / "src" / "frameos" / "retired_apps_gen.nim",
}
BANNER = (
    "Generated by frameos/tools/generate_retired_apps.py from docs/retired-apps.json "
    "and repo/apps/code — do not edit."
)
SPEC_KEYS = ("replacement", "sceneAppKey", "runtime", "needs")


def load() -> dict:
    doc = json.loads(SOURCE.read_text())
    apps = doc.get("apps")
    if not isinstance(apps, dict) or not apps:
        raise SystemExit(f"{SOURCE}: `apps` must be a non-empty object")
    for keyword, spec in apps.items():
        missing = [key for key in SPEC_KEYS if not isinstance(spec.get(key), str) or not spec[key]]
        if missing:
            raise SystemExit(f"{SOURCE}: {keyword} is missing {', '.join(missing)}")
        if not (REPO / spec["replacement"] / "config.json").is_file():
            raise SystemExit(f"{SOURCE}: {keyword}: {spec['replacement']}/config.json does not exist")
    return apps


def replacement_entry(origin: str) -> dict:
    """The scene-local app a repo JS app becomes — the same shape as
    backend/app/utils/retired_apps.py `replacement_app_entry`."""
    app_dir = REPO / origin
    config = json.loads((app_dir / "config.json").read_text())
    sources = {
        path.name: path.read_text()
        for path in sorted(app_dir.iterdir())
        if path.is_file() and not path.name.endswith(".nim")
    }
    return {**config, "origin": origin, "sources": sources}


def gen_ts(apps: dict) -> str:
    table = {keyword: {key: spec[key] for key in SPEC_KEYS} for keyword, spec in apps.items()}
    entries = {spec["replacement"]: replacement_entry(spec["replacement"]) for spec in apps.values()}
    return "\n".join([
        f"// {BANNER}",
        "",
        "export type RetiredAppSpec = {",
        "  replacement: string;",
        "  sceneAppKey: string;",
        "  runtime: string;",
        "  needs: string;",
        "};",
        "",
        f"export const RETIRED_APPS: Record<string, RetiredAppSpec> = {json.dumps(table, indent=2)};",
        "",
        "// Each replacement as the scene-local app a scene carries: its config.json",
        "// keys plus `origin` and `sources`.",
        "export const REPLACEMENT_APPS: Record<string, Record<string, unknown>> = "
        f"{json.dumps(entries, indent=2, ensure_ascii=False)};",
        "",
    ])


def gen_nim(apps: dict) -> str:
    sources = {keyword: replacement_entry(spec["replacement"])["sources"] for keyword, spec in apps.items()}
    payload = json.dumps(sources, ensure_ascii=False, separators=(",", ":"))
    if '"""' in payload:
        raise SystemExit("a replacement's sources serialize with a triple quote; cannot embed")
    return "\n".join([
        f"## {BANNER}",
        "##",
        "## Read by frameos/retired_apps.nim, on Linux builds only.",
        "",
        "const RetiredAppKeywords* = [" + ", ".join(json.dumps(keyword) for keyword in apps) + "]",
        "",
        "## {retired keyword: {file name: contents}} of each replacement app.",
        f'const RetiredAppSourcesJson* = """{payload}"""',
        "",
    ])


GENERATORS = {"ts_cloud": gen_ts, "nim": gen_nim}


def main() -> int:
    check = "--check" in sys.argv
    apps = load()
    stale = []
    for key, path in OUTPUTS.items():
        text = GENERATORS[key](apps)
        if check:
            if not path.is_file() or path.read_text() != text:
                stale.append(path.relative_to(REPO))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        for path in stale:
            print(f"stale: {path}", file=sys.stderr)
        print("run: python3 frameos/tools/generate_retired_apps.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
