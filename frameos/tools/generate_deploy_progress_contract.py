#!/usr/bin/env python3
"""Generate the per-language tables of the deploy-progress contract.

Source of truth: docs/deploy-progress-contract.json (prose:
docs/deploy-progress.md, conformance corpus: docs/deploy-progress-fixtures.json).
Outputs (all committed):

  backend/app/utils/deploy_progress_gen.py                  the self-hosted backend (folds its tasks + device log lines)
  cloud/apps/auth-web/src/lib/deploy-progress.gen.ts        the cloud routes and the frame hub
  frontend/src/utils/deployProgress.gen.ts                  the shared SPA (the bar: stage order, labels, stale rules)

    python3 frameos/tools/generate_deploy_progress_contract.py          # write
    python3 frameos/tools/generate_deploy_progress_contract.py --check  # CI: fail if stale

Same arrangement as generate_events_contract.py: this script only turns one
JSON document into data files; the fold itself is hand-written once per
plane (backend/app/utils/deploy_progress.py, the cloud's lib/deploy-progress.ts)
and the SPA only reads the tables (frontend/src/decorators/frame.tsx).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "docs" / "deploy-progress-contract.json"
OUTPUTS = {
    "py": REPO / "backend" / "app" / "utils" / "deploy_progress_gen.py",
    "ts_cloud": REPO / "cloud" / "apps" / "auth-web" / "src" / "lib" / "deploy-progress.gen.ts",
    "ts_frontend": REPO / "frontend" / "src" / "utils" / "deployProgress.gen.ts",
}
BANNER = "Generated by frameos/tools/generate_deploy_progress_contract.py from docs/deploy-progress-contract.json — do not edit."

STATUSES = ("running", "done", "error")
TERMINALS = ("done", "error")
PLANES = ("backend", "cloud")


def load() -> dict:
    doc = json.loads(SOURCE.read_text())
    validate(doc)
    return doc


def validate(doc: dict) -> None:
    stages = doc["stages"]
    known_signals: set[str] = set()
    for name in doc["signals"]["device"]:
        known_signals.add(name)
    queue_patterns = [name for name in doc["signals"]["queue"]]

    def signal_ok(signal: str) -> bool:
        if signal in known_signals:
            return True
        for pattern in queue_patterns:
            if pattern.endswith("<type>"):
                if signal.startswith(pattern[: -len("<type>")]) and len(signal) > len(pattern) - len("<type>"):
                    return True
            elif pattern == signal:
                return True
        return False

    for key, stage in stages.items():
        if key.startswith("$"):
            continue
        if key in TERMINALS:
            raise ValueError(f"stage {key!r} collides with a terminal status")
        if not isinstance(stage.get("label"), str) or not stage["label"]:
            raise ValueError(f"stage {key!r} needs a label")
        if not isinstance(stage.get("staleAfterSeconds"), int) or stage["staleAfterSeconds"] <= 0:
            raise ValueError(f"stage {key!r} needs a positive staleAfterSeconds")
    for kind, spec in doc["kinds"].items():
        if kind.startswith("$"):
            continue
        for plane in spec["planes"]:
            if plane not in PLANES:
                raise ValueError(f"kind {kind!r}: unknown plane {plane!r}")
        seen: list[str] = []
        for entry in spec["stages"]:
            stage = entry["stage"]
            if stage not in stages or stage.startswith("$"):
                raise ValueError(f"kind {kind!r}: unknown stage {stage!r}")
            if stage in seen:
                raise ValueError(f"kind {kind!r}: stage {stage!r} listed twice")
            seen.append(stage)
        for entry in spec["stages"]:
            for signal, target in entry.get("on", {}).items():
                if not signal_ok(signal):
                    raise ValueError(f"kind {kind!r} stage {entry['stage']!r}: unknown signal {signal!r}")
                if target not in TERMINALS and target not in seen:
                    raise ValueError(f"kind {kind!r} stage {entry['stage']!r}: {signal!r} -> unknown stage {target!r}")
                if target not in TERMINALS and seen.index(target) <= seen.index(entry["stage"]):
                    raise ValueError(
                        f"kind {kind!r} stage {entry['stage']!r}: {signal!r} -> {target!r} would move backwards"
                    )
            for signal in entry.get("holdOn", []):
                if not signal_ok(signal):
                    raise ValueError(f"kind {kind!r} stage {entry['stage']!r}: unknown holdOn signal {signal!r}")


def public_doc(doc: dict) -> dict:
    """The contract without its prose: what the runners carry."""

    def strip(value):
        if isinstance(value, dict):
            return {k: strip(v) for k, v in value.items() if not k.startswith("$") and k != "description"}
        if isinstance(value, list):
            return [strip(v) for v in value]
        return value

    out = strip(doc)
    out.pop("signals", None)
    for kind in out["kinds"].values():
        kind.pop("frames", None)
    out["record"] = {k: v for k, v in out["record"].items() if k != "fields"}
    return out


def py_literal(value) -> str:
    """A dict as a Python literal with sorted keys (json.dumps would print `true`)."""
    return repr(json.loads(json.dumps(value, sort_keys=True)))


def gen_py(doc: dict) -> str:
    public = public_doc(doc)
    out = [f'"""{BANNER}"""', "from __future__ import annotations", "", ""]
    out.append(f"DEPLOY_PROGRESS_VERSION = {int(doc['version'])}")
    out.append(f"DEPLOY_PROGRESS_DONE_SHOWN_SECONDS = {int(doc['record']['doneShownSeconds'])}")
    out.append(f"DEPLOY_PROGRESS_ERROR_SHOWN_SECONDS = {int(doc['record']['errorShownSeconds'])}")
    out.append(f"DEPLOY_PROGRESS_WAKE_GRACE_SECONDS = {int(doc['record']['wakeGraceSeconds'])}")
    out.append("")
    out.append("# stage -> label, staleAfterSeconds, freshWhileSleeping")
    out.append("DEPLOY_PROGRESS_STAGES: dict[str, dict] = {")
    for key, stage in public["stages"].items():
        out.append(f"    {json.dumps(key)}: {py_literal(stage)},")
    out.append("}")
    out.append("")
    out.append("# kind -> label, planes, stages (ordered: stage, on, holdOn)")
    out.append("DEPLOY_PROGRESS_KINDS: dict[str, dict] = {")
    for kind, spec in public["kinds"].items():
        out.append(f"    {json.dumps(kind)}: {{")
        out.append(f"        \"label\": {json.dumps(spec['label'])},")
        out.append(f"        \"planes\": {json.dumps(spec['planes'])},")
        out.append("        \"stages\": [")
        for entry in spec["stages"]:
            out.append(f"            {py_literal(entry)},")
        out.append("        ],")
        out.append("    },")
    out.append("}")
    out.append("")
    return "\n".join(out)


def gen_ts(doc: dict, *, frontend: bool) -> str:
    public = public_doc(doc)
    body = json.dumps(public, indent=2)
    out = [f"// {BANNER}"]
    if frontend:
        out.append("// The helper that reads these tables is frameDeployProgress in decorators/frame.tsx.")
    else:
        out.append("// The fold that walks these tables is lib/deploy-progress.ts (routes + the frame hub).")
    out.append("")
    out.append("export type DeployProgressStatus = 'running' | 'done' | 'error'")
    stage_keys = " | ".join(json.dumps(k).replace('"', "'") for k in public["stages"])
    kind_keys = " | ".join(json.dumps(k).replace('"', "'") for k in public["kinds"])
    out.append(f"export type DeployProgressStage = {stage_keys}")
    out.append(f"export type DeployProgressKind = {kind_keys}")
    out.append("")
    out.append("export interface DeployProgressStageSpec {")
    out.append("  label: string")
    out.append("  staleAfterSeconds: number")
    out.append("  freshWhileSleeping?: boolean")
    out.append("}")
    out.append("")
    out.append("export interface DeployProgressKindStage {")
    out.append("  stage: DeployProgressStage")
    out.append("  on?: Record<string, DeployProgressStage | 'done' | 'error'>")
    out.append("  holdOn?: string[]")
    out.append("}")
    out.append("")
    out.append("export interface DeployProgressKindSpec {")
    out.append("  label: string")
    out.append("  planes: string[]")
    out.append("  stages: DeployProgressKindStage[]")
    out.append("}")
    out.append("")
    out.append("export interface DeployProgressContract {")
    out.append("  version: number")
    out.append("  record: { doneShownSeconds: number; errorShownSeconds: number; wakeGraceSeconds: number }")
    out.append("  stages: Record<DeployProgressStage, DeployProgressStageSpec>")
    out.append("  kinds: Record<DeployProgressKind, DeployProgressKindSpec>")
    out.append("}")
    out.append("")
    out.append(f"export const deployProgressContract: DeployProgressContract = {body}")
    out.append("")
    return "\n".join(out)


GENERATORS = {
    "py": gen_py,
    "ts_cloud": lambda doc: gen_ts(doc, frontend=False),
    "ts_frontend": lambda doc: gen_ts(doc, frontend=True),
}


def main() -> int:
    check = "--check" in sys.argv
    doc = load()
    stale = []
    for key, path in OUTPUTS.items():
        text = GENERATORS[key](doc)
        if check:
            if not path.is_file() or path.read_text() != text:
                stale.append(path.relative_to(REPO))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        for path in stale:
            print(f"stale: {path}", file=sys.stderr)
        print("run: python3 frameos/tools/generate_deploy_progress_contract.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
