#!/usr/bin/env python3
"""Generate the scene categories' tables from docs/scene-categories.json.

The categories are the store's shelves and what a scene's `settings.category`
may name (docs/scene-icons.md "Category"). One list, in shelf order, and this
script writes every copy of it:

  frameos/src/frameos/scene_categories_gen.nim   the runtime's: ids and names (app.frame.categories)
  frontend/src/utils/storeCategories.ts          the SPA's shelves and names, its generated region
  cloud/apps/auth-web/src/lib/categories.ts      the cloud store's, its generated region

  python3 frameos/tools/generate_scene_categories.py           write
  python3 frameos/tools/generate_scene_categories.py --check   exit 1 when anything is stale
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONTRACT = REPO / "docs" / "scene-categories.json"
NIM_OUT = REPO / "frameos" / "src" / "frameos" / "scene_categories_gen.nim"
SPA = REPO / "frontend" / "src" / "utils" / "storeCategories.ts"
CLOUD = REPO / "cloud" / "apps" / "auth-web" / "src" / "lib" / "categories.ts"

BEGIN = "// BEGIN GENERATED: scene categories (frameos/tools/generate_scene_categories.py, docs/scene-categories.json)"
END = "// END GENERATED: scene categories"
KEYS = ("id", "title", "name", "description", "hint")


def fail(message: str) -> None:
    print(f"generate_scene_categories: {message}", file=sys.stderr)
    sys.exit(1)


def load() -> list[dict[str, str]]:
    categories = json.loads(CONTRACT.read_text())["categories"]
    seen: set[str] = set()
    for category in categories:
        if set(category) != set(KEYS) or not all(isinstance(category[key], str) and category[key] for key in KEYS):
            fail(f"every category has exactly {', '.join(KEYS)}, as text: {category}")
        if not re.fullmatch(r"[a-z]+", category["id"]) or category["id"] in seen or category["id"] == "other":
            fail(f"an id is a unique word in lower case, and 'other' is the store's shelf for none: {category['id']!r}")
        seen.add(category["id"])
    return categories


def nim(categories: list[dict[str, str]]) -> str:
    def items(key: str) -> str:
        return ", ".join(json.dumps(category[key]) for category in categories)

    return (
        "## Generated by frameos/tools/generate_scene_categories.py from\n"
        "## docs/scene-categories.json. Do not edit: change the contract and run it.\n"
        "##\n"
        "## The scene categories in shelf order: the slug a scene's\n"
        "## `settings.category` names, and the short name apps get for it in\n"
        "## `app.frame.categories` (scene_category.nim).\n"
        "\n"
        "const\n"
        f"  SceneCategoryIds* = [{items('id')}]\n"
        f"  SceneCategoryNames* = [{items('name')}]\n"
    )


def single(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def spa_region(categories: list[dict[str, str]]) -> str:
    lines = [BEGIN, "export const storeCategoryShelves: StoreCategoryShelf[] = ["]
    lines += [f"  {{ slug: {single(c['id'])}, title: {single(c['title'])} }}," for c in categories]
    lines += [
        "]",
        "",
        "/** Each category's short name: a folder's label, a group of a scene list (`app.frame.categories`). */",
        "export const sceneCategoryNames: Record<string, string> = {",
    ]
    lines += [f"  {c['id']}: {single(c['name'])}," for c in categories]
    lines += ["}", END]
    return "\n".join(lines)


def cloud_region(categories: list[dict[str, str]]) -> str:
    lines = [BEGIN, "export const storeCategories: StoreCategory[] = ["]
    for category in categories:
        lines.append("  {")
        lines.append(f"    slug: {json.dumps(category['id'], ensure_ascii=False)},")
        for key in ("title", "name", "description", "hint"):
            lines.append(f"    {key}: {json.dumps(category[key], ensure_ascii=False)},")
        lines.append("  },")
    lines += ["];", END]
    return "\n".join(lines)


def with_region(path: Path, region: str) -> str:
    text = path.read_text()
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < start:
        fail(f"{path.relative_to(REPO)} has no generated region ({BEGIN!r} ... {END!r})")
    return text[:start] + region + text[end + len(END):]


def main() -> None:
    check = "--check" in sys.argv[1:]
    categories = load()
    outputs = {
        NIM_OUT: nim(categories),
        SPA: with_region(SPA, spa_region(categories)),
        CLOUD: with_region(CLOUD, cloud_region(categories)),
    }
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if check:
        if stale:
            fail("stale: " + ", ".join(str(path.relative_to(REPO)) for path in stale)
                 + " (run python3 frameos/tools/generate_scene_categories.py)")
        return
    for path in stale:
        path.write_text(outputs[path])
        print(f"wrote {path.relative_to(REPO)}")


if __name__ == "__main__":
    main()
