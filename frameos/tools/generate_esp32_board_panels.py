#!/usr/bin/env python3
"""Generate the tables behind the ESP32 `device` setting: which panels a
board can be pushed.

Sources of truth:
  docs/esp32-board-panels.json   the boards (preset -> panel, built in or a socket)
  embedded/esp32/components/frameos_display/generate_panel_table.py
                                 the panels the firmware compiles in (panel_catalog)

Outputs (all committed):

  embedded/esp32/main/fos_board_panels_gen.h      firmware (fos_board_panels.c)
  cloud/apps/auth-web/src/lib/esp32-board-panels.gen.ts   cloud (lib/esp32-board-panels.ts)
  frontend/src/utils/esp32BoardPanels.gen.ts       SPA (utils/esp32BoardPanels.ts)

    python3 frameos/tools/generate_esp32_board_panels.py          # write
    python3 frameos/tools/generate_esp32_board_panels.py --check  # CI: fail if stale

The rule that reads these tables is hand-written, once per language, and runs
the `panels` cases of docs/cloud-frames-fixtures.json. The firmware already
holds the panel list itself (frameos_panel_table.c), so its table carries the
built-in boards and the device-key aliases only.

The script also refuses a board whose panel differs from the one the USB
console's `set hardware` applies (embedded/esp32/main/fos_console.c), and a
console preset this file does not list: a new board has to say whether its
display is built in.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "docs" / "esp32-board-panels.json"
CONSOLE = REPO / "embedded" / "esp32" / "main" / "fos_console.c"
PANEL_TABLE_DIR = REPO / "embedded" / "esp32" / "components" / "frameos_display"
OUTPUTS = {
    "c": REPO / "embedded" / "esp32" / "main" / "fos_board_panels_gen.h",
    "ts_cloud": REPO / "cloud" / "apps" / "auth-web" / "src" / "lib" / "esp32-board-panels.gen.ts",
    "ts_frontend": REPO / "frontend" / "src" / "utils" / "esp32BoardPanels.gen.ts",
}
BANNER = "Generated by frameos/tools/generate_esp32_board_panels.py from docs/esp32-board-panels.json — do not edit."
DISPLAYS = ("builtin", "connector")
BUS_NAMES = {0: "spi", 1: "i2c"}


def load_catalog() -> list[dict]:
    sys.path.insert(0, str(PANEL_TABLE_DIR))
    import generate_panel_table  # noqa: E402

    return generate_panel_table.panel_catalog(REPO)


def console_presets() -> dict[str, str]:
    """preset -> panel, as the console's `set hardware` table applies them."""
    text = CONSOLE.read_text()
    start = text.index("} presets[] = {")
    end = text.index("};", start)
    return dict(re.findall(r'\{\s*"([a-z0-9_]+)",\s*"([A-Za-z0-9_]+)",', text[start:end]))


def load() -> tuple[dict, list[dict]]:
    doc = json.loads(SOURCE.read_text())
    catalog = load_catalog()
    names = {panel["name"] for panel in catalog}
    errors = []
    for board, spec in doc["boards"].items():
        if set(spec) != {"panel", "display"}:
            errors.append(f"{board}: wants exactly `panel` and `display`")
            continue
        if spec["display"] not in DISPLAYS:
            errors.append(f"{board}: display must be one of {', '.join(DISPLAYS)}")
        if spec["panel"] not in names:
            errors.append(f"{board}: panel {spec['panel']} is not compiled into the firmware")
    console = console_presets()
    for board, panel in console.items():
        if board not in doc["boards"]:
            errors.append(f"{board}: a console preset ({CONSOLE.relative_to(REPO)}) this file does not list")
        elif doc["boards"][board]["panel"] != panel:
            errors.append(f"{board}: the console applies {panel}, this file says {doc['boards'][board]['panel']}")
    for board in doc["boards"]:
        if board not in console:
            errors.append(f"{board}: not a console preset ({CONSOLE.relative_to(REPO)})")
    if errors:
        for error in errors:
            print(f"{SOURCE.relative_to(REPO)}: {error}", file=sys.stderr)
        sys.exit(1)
    return doc, catalog


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def aliases(catalog: list[dict]) -> list[tuple[str, str]]:
    return [(p["device"], p["name"]) for p in catalog if p["device"] != f"waveshare.{p['name']}"]


def gen_c(doc: dict, catalog: list[dict]) -> str:
    lines = [
        f"/* {BANNER}",
        " *",
        " * The boards whose display is built in, and the panels the control planes",
        " * name by a key other than `waveshare.<panel>`. Read by fos_board_panels.c;",
        " * the panels themselves are the firmware's own table (frameos_panel_table.c). */",
        "#pragma once",
        "",
        "static const struct {",
        "    const char *preset;",
        "    const char *panel;",
        "} fos_board_builtin_panels[] = {",
    ]
    for board, spec in doc["boards"].items():
        if spec["display"] == "builtin":
            lines.append(f"    {{{c_string(board)}, {c_string(spec['panel'])}}},")
    lines += [
        "};",
        "",
        "static const struct {",
        "    const char *device;",
        "    const char *panel;",
        "} fos_panel_device_aliases[] = {",
    ]
    for device, panel in aliases(catalog):
        lines.append(f"    {{{c_string(device)}, {c_string(panel)}}},")
    lines += ["};", ""]
    return "\n".join(lines)


def gen_ts(doc: dict, catalog: list[dict]) -> str:
    panels = [
        {
            "name": p["name"],
            "device": p["device"],
            "width": p["width"],
            "height": p["height"],
            "bus": BUS_NAMES[p["bus"]],
            **({"requiresCs2": True} if p["requiresCs2"] else {}),
        }
        for p in catalog
    ]
    return (
        f"// {BANNER}\n"
        "// The panels the ESP32 firmware compiles in (name = the firmware's key,\n"
        "// device = the control planes' key) and the hardware presets with the\n"
        "// panel each applies; `builtin` boards drive that panel and no other.\n"
        "// esp32BoardPanels.ts / esp32-board-panels.ts hold the rule.\n\n"
        f"export const esp32Panels = {json.dumps(panels, indent=2)} as const\n\n"
        f"export const esp32Boards = {json.dumps(doc['boards'], indent=2)} as const\n"
    )


def main():
    check = "--check" in sys.argv
    doc, catalog = load()
    ts = gen_ts(doc, catalog)
    outputs = {"c": gen_c(doc, catalog), "ts_cloud": ts, "ts_frontend": ts}
    stale = []
    for name, text in outputs.items():
        path = OUTPUTS[name]
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(REPO)}")
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(REPO)}", file=sys.stderr)
        print("run: python3 frameos/tools/generate_esp32_board_panels.py", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
