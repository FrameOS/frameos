#!/usr/bin/env python3
"""Write the copies of what every board's keys do (docs/buttons.md).

The source is the backend: each hardware preset's keys and their roles
(`EMBEDDED_BOARD_KEYS` in backend/app/tasks/embedded_firmware.py), the Linux
devices that come with keys (`DEVICE_GPIO_BUTTON_DEFAULTS` in
backend/app/drivers/devices.py) or a glass (every HyperPixel), and the one
function that makes a board's event map of them
(backend/app/utils/button_standard.py). Written from it:

- embedded/esp32/main/fos_board_keys_gen.h: the firmware's own table, each
  rule once and each board its list of them (fos_board_event_map), and each
  key's role (fos_board_key_role, which the button task sends with a press);
- frontend/src/generated/boardKeys.gen.ts: the SPA's (a new frame's buttons
  and map, "Button actions"' defaults);
- frameos/src/frameos/device_event_map_gen.nim: the maps a Linux frame never
  given one runs with (device_event_map.nim).

`--check` fails when a file is stale (the backend suite runs it:
backend/app/tasks/tests/test_board_keys.py).
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
C_OUT = ROOT / "embedded/esp32/main/fos_board_keys_gen.h"
TS_OUT = ROOT / "frontend/src/generated/boardKeys.gen.ts"
NIM_OUT = ROOT / "frameos/src/frameos/device_event_map_gen.nim"


def load_backend():
    sys.path.insert(0, str(ROOT / "backend"))
    os.environ.setdefault("SECRET_KEY", "generate-board-keys")
    import app.drivers.devices as devices  # noqa: E402
    import app.tasks.embedded_firmware as firmware  # noqa: E402
    import app.utils.button_standard as standard  # noqa: E402

    return firmware, devices, standard


def old_default_maps() -> dict:
    """Each preset's map before the button standard, as the firmware wrote it
    into a board's settings (byte for byte the compact JSON of the backend
    migration's frozen copies, d1b5e7a9c3f2 OLD_PRESET_MAPS)."""
    import importlib.util
    import types

    path = ROOT / "backend/migrations/versions/d1b5e7a9c3f2_button_standard_event_maps.py"
    stubs = {"alembic": types.SimpleNamespace(op=None), "sqlalchemy": types.SimpleNamespace()}
    saved = {name: sys.modules.get(name) for name in stubs}
    sys.modules.update(stubs)
    try:
        spec = importlib.util.spec_from_file_location("button_standard_migration", path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    finally:
        for name, value in saved.items():
            if value is None:
                sys.modules.pop(name, None)
            else:
                sys.modules[name] = value
    return {key: compact(value) for key, value in module.OLD_PRESET_MAPS.items()}


def fnv1a(text: str) -> int:
    h = 2166136261
    for byte in text.encode("utf-8"):
        h ^= byte
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def compact(value) -> str:
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_c(firmware, standard) -> str:
    presets = {
        key: preset
        for key, preset in firmware.EMBEDDED_HARDWARE_PRESETS.items()
        if not str(preset.get("platform") or "").startswith("pico")
    }
    rules: list[str] = []
    rows = []
    old = old_default_maps()
    for key, preset in presets.items():
        indexes = []
        for rule in preset.get("eventMap") or []:
            text = compact(rule)
            if text not in rules:
                rules.append(text)
            indexes.append(rules.index(text) + 1)
        keys = firmware.EMBEDDED_BOARD_KEYS[key]
        roles = " ".join(f"{k['label']}={k['role']}" for k in keys)
        was = old.get(key)
        rows.append((key, indexes, roles, fnv1a(was) if was is not None else 0))
    longest = max(len("[" + ",".join(rules[i - 1] for i in r[1]) + "]") for r in rows)
    if longest > 1023:
        raise SystemExit(f"a board's event map is {longest} bytes: the firmware holds 1023 (FOS_EVENT_MAP_LEN)")
    out = [
        "/* Generated by frameos/tools/generate_board_keys.py from the backend's",
        " * hardware presets (EMBEDDED_BOARD_KEYS) and app/utils/button_standard.py:",
        " * do not edit. What each board's keys do (docs/buttons.md): every rule of",
        " * every board's event map once (`k_board_rules`), each board the rules it",
        " * has, by number from 1 (`rules`, joined into a map by fos_board_event_map),",
        " * and its keys' roles (`roles`: LABEL=role, for fos_board_key_role).",
        " * `was` is the FNV-1a of the map the board came with before the button",
        " * standard, as the firmware wrote it into its settings (the backend",
        " * migration d1b5e7a9c3f2's OLD_PRESET_MAPS): a board that stored that one",
        " * runs today's (fos_board_event_map_is_default).",
        f" * The longest map is {longest} bytes (FOS_EVENT_MAP_LEN holds 1023). */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "static const char *const k_board_rules[] = {",
    ]
    out += [f"    {c_string(text)}," for text in rules]
    out += [
        "};",
        "",
        "typedef struct {",
        "    const char *preset;",
        "    const char *rules; /* rule numbers, from 1, as bytes */",
        "    const char *roles; /* LABEL=role, space-separated */",
        "    uint32_t was; /* FNV-1a of the map it came with before the button standard, 0: none */",
        "} fos_board_keys_t;",
        "",
        "static const fos_board_keys_t k_board_keys[] = {",
    ]
    for key, indexes, roles, was in rows:
        numbers = "".join(f"\\x{i:02x}" for i in indexes)
        out.append(f'    {{"{key}", "{numbers}", {c_string(roles)}, 0x{was:08x}u}},')
    out += ["};", ""]
    return "\n".join(out)


def ts_value(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def linux_maps(devices, standard):
    inky_keys = [dict(button) for button in devices.INKY_GPIO_BUTTONS]
    inky = standard.default_event_map(inky_keys, touch=False, mic=False)
    hyperpixel = standard.default_event_map([], touch=True, mic=False)
    return hyperpixel, inky, sorted(devices.INKY_BUTTON_DEVICES)


def write_ts(firmware, devices, standard) -> str:
    hyperpixel, inky, inky_devices = linux_maps(devices, standard)
    out = [
        "// Generated by frameos/tools/generate_board_keys.py from the backend's",
        "// hardware presets (EMBEDDED_BOARD_KEYS) and app/utils/button_standard.py:",
        "// do not edit. What each board's keys do (docs/buttons.md).",
        "import type { EventMapRule, GPIOButton } from '../types'",
        "",
        "export interface BoardKeys {",
        "  /** The board's GPIO buttons, each with its role. */",
        "  gpioButtons: GPIOButton[]",
        "  /** The frame event map the board comes with; empty for none. */",
        "  eventMap: EventMapRule[]",
        "}",
        "",
        "/** By hardware preset. */",
        "export const BOARD_KEYS: Record<string, BoardKeys> = {",
    ]
    for key, preset in firmware.EMBEDDED_HARDWARE_PRESETS.items():
        out.append(f"  {ts_value(key)}: {{")
        out.append(f"    gpioButtons: {ts_value(preset.get('gpioButtons') or [])},")
        out.append(f"    eventMap: {ts_value(preset.get('eventMap') or [])},")
        out.append("  },")
    out += [
        "}",
        "",
        "/** A HyperPixel's: its glass's edges. */",
        f"export const HYPERPIXEL_EVENT_MAP: EventMapRule[] = {ts_value(hyperpixel)}",
        "",
        "/** An Inky Impression's: A to D down its side. */",
        f"export const INKY_IMPRESSION_EVENT_MAP: EventMapRule[] = {ts_value(inky)}",
        "",
        f"export const INKY_IMPRESSION_DEVICES: string[] = {ts_value(inky_devices)}",
        "",
    ]
    return "\n".join(out)


def write_nim(devices, standard) -> str:
    hyperpixel, inky, inky_devices = linux_maps(devices, standard)
    devices_list = ", ".join(json.dumps(d) for d in inky_devices)
    return "\n".join(
        [
            "## Generated by frameos/tools/generate_board_keys.py from the backend's",
            "## devices and backend/app/utils/button_standard.py: do not edit. The maps",
            "## a Linux frame never given one runs with (device_event_map.nim,",
            "## docs/buttons.md).",
            "",
            f"const HyperPixelEventMap* = {json.dumps(compact(hyperpixel))}",
            f"const InkyImpressionEventMap* = {json.dumps(compact(inky))}",
            f"const InkyImpressionDevices* = [{devices_list}]",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file is stale")
    args = parser.parse_args()
    firmware, devices, standard = load_backend()
    outputs = {
        C_OUT: write_c(firmware, standard),
        TS_OUT: write_ts(firmware, devices, standard),
        NIM_OUT: write_nim(devices, standard),
    }
    stale = []
    for path, text in outputs.items():
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale, run python3 frameos/tools/generate_board_keys.py:", *stale, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
