## Rasterizes the FrameOS mark (src/frameos/utils/status_screen/frameos_mark.svg)
## for the boot splash of the ESP32's RGB LCDs
## (embedded/esp32/components/frameos_display/lcd_splash.c). The splash shows
## before the runtime and pixie are up, so the mark ships rasterized: the
## frame and each of the three squares as a layer of its own, anti-aliased,
## run-length encoded by row, so the squares can be recolored while it boots.
## Re-run after changing the SVG:
##
##   cd frameos && nim r tools/gen_splash_mark.nim
##
import std/[os, strutils, strformat]
import pixie
import pixie/fileformats/svg as pixie_svg

const
  markHeight = 160
  svgPath = "../src/frameos/utils/status_screen/frameos_mark.svg"
  header = "../../embedded/esp32/components/frameos_display/include/lcd_splash_mark.h"

let source = readFile(currentSourcePath().parentDir() / svgPath)
let open = source.find("<svg")
let groupOpen = source.find("<g", open)
let groupEnd = source.find(">", groupOpen) + 1
let svgHead = source[open ..< groupEnd]

# The four shapes in document order: the frame, then the squares from the
# bottom-left one to the top-right one.
var paths: seq[string] = @[]
var at = 0
while true:
  let start = source.find("<path", at)
  if start < 0:
    break
  let stop = source.find("/>", start) + 2
  paths.add(source[start ..< stop])
  at = stop
doAssert paths.len == 4, "the mark is a frame and three squares, found " & $paths.len & " paths"

let width = int(round(markHeight.float * 464.0 / 544.0))
var layers: seq[Image] = @[]
for path in paths:
  layers.add(newImage(pixie_svg.parseSvg(svgHead & path & "</g></svg>", width, markHeight)))

# A run is (length << 8) | (layer << 5) | alpha: `length` pixels (1..255) of
# layer `layer` (0 none, 1 the frame, 2..4 the squares) at coverage alpha/31.
var runs: seq[uint16] = @[]
var rows: seq[int] = @[]
for y in 0 ..< markHeight:
  rows.add(runs.len)
  var x = 0
  var current = -1
  var length = 0
  proc flush() =
    if length > 0:
      runs.add(uint16((length shl 8) or current))
  while x < width:
    var layer = 0
    var alpha = 0
    for i, image in layers:
      let a = int(image[x, y].a)
      if a > alpha:
        alpha = a
        layer = i + 1
    let alpha5 = (alpha * 31 + 127) div 255
    let cell = if alpha5 == 0: 0 else: (layer shl 5) or alpha5
    if cell == current and length < 255:
      inc length
    else:
      flush()
      current = cell
      length = 1
    inc x
  flush()
rows.add(runs.len)
doAssert runs.len < 65536

var lines: seq[string] = @[]
lines.add("/* Generated by frameos/tools/gen_splash_mark.nim from")
lines.add(" * frameos/src/frameos/utils/status_screen/frameos_mark.svg — do not edit. */")
lines.add("#pragma once")
lines.add("#include <stdint.h>")
lines.add("")
lines.add(&"#define FOS_SPLASH_MARK_W {width}")
lines.add(&"#define FOS_SPLASH_MARK_H {markHeight}")
lines.add(&"#define FOS_SPLASH_MARK_RUN_COUNT {runs.len}")
lines.add("")
lines.add("/* Row y is FOS_SPLASH_MARK_RUNS[FOS_SPLASH_MARK_ROWS[y]] up to the row after's")
lines.add(" * first. A run is (length << 8) | (layer << 5) | alpha: `length` pixels of")
lines.add(" * layer `layer` (0 none, 1 the frame, 2..4 the squares from the bottom-left")
lines.add(" * one to the top-right one) at coverage alpha/31. */")
proc table(name: string, values: seq[int]) =
  lines.add(&"static const uint16_t {name}[{values.len}] = {{")
  var line = "   "
  for i, value in values:
    let item = &" 0x{value:04X},"
    if line.len + item.len > 100:
      lines.add(line)
      line = "   "
    line.add(item)
  if line.strip().len > 0:
    lines.add(line)
  lines.add("};")
table("FOS_SPLASH_MARK_ROWS", rows)
lines.add("")
var runValues: seq[int] = @[]
for run in runs:
  runValues.add(int(run))
table("FOS_SPLASH_MARK_RUNS", runValues)
lines.add("")
let path = currentSourcePath().parentDir() / header
writeFile(path, lines.join("\n"))
echo "wrote ", path.normalizedPath(), " (", width, "x", markHeight, ", ", runs.len, " runs, ",
  runs.len * 2 + rows.len * 2, " bytes)"
