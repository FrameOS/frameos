## Rasterizes the FrameOS mark (src/frameos/utils/status_screen/frameos_mark.svg)
## for the boot splash of the ESP32's RGB LCDs
## (embedded/esp32/components/frameos_display/lcd_splash.c). The splash shows
## before the runtime and pixie are up, so the mark ships rasterized: the
## frame and each of the three squares as a layer of its own, anti-aliased,
## run-length encoded by row, so the squares can be recolored while it boots.
## The lines under it (what the boot is waiting for) are rendered here too,
## in the runtime's default font (Ubuntu Regular), the same way. Re-run after changing the
## SVG or a line:
##
##   cd frameos && nim r tools/gen_splash_mark.nim
##
import std/[os, strutils, strformat]
import pixie
import pixie/fileformats/svg as pixie_svg

const
  markHeight = 160
  svgPath = "../src/frameos/utils/status_screen/frameos_mark.svg"
  header = "../../embedded/esp32/components/frameos_display/include/lcd_splash_mark.h"
  textHeader = "../../embedded/esp32/components/frameos_display/include/lcd_splash_text.h"
  fontPath = "../assets/compiled/fonts/Ubuntu-Regular.ttf"
  textSize = 22.0
  # lcd_splash.h's fos_lcd_splash_status_t, in order from 1.
  statusLines = ["Connecting to Wi-Fi", "Updating firmware", "Starting"]

let source = readFile(currentSourcePath().parentDir() / svgPath)
let open = source.find("<svg")
let groupOpen = source.find("<g", open)
let groupEnd = source.find(">", groupOpen) + 1
let svgHead = source[open ..< groupEnd]

# The four shapes in document order: the frame, then the squares from the
# bottom-left one to the top-right one.
var paths: seq[string] = @[]
var at = 0
while true:
  let start = source.find("<path", at)
  if start < 0:
    break
  let stop = source.find("/>", start) + 2
  paths.add(source[start ..< stop])
  at = stop
doAssert paths.len == 4, "the mark is a frame and three squares, found " & $paths.len & " paths"

let width = int(round(markHeight.float * 464.0 / 544.0))
var layers: seq[Image] = @[]
for path in paths:
  layers.add(newImage(pixie_svg.parseSvg(svgHead & path & "</g></svg>", width, markHeight)))

proc encode(layers: seq[Image], runs: var seq[uint16]): seq[int] =
  ## Appends the layers' rows to `runs` and returns where each row starts,
  ## and where the last one ends. A run is (length << 8) | (layer << 5) |
  ## alpha: `length` pixels (1..255) of layer `layer` (0 none, then the
  ## layers from 1) at coverage alpha/31.
  let (w, h) = (layers[0].width, layers[0].height)
  for y in 0 ..< h:
    result.add(runs.len)
    var current = -1
    var length = 0
    for x in 0 ..< w:
      var layer = 0
      var alpha = 0
      for i, image in layers:
        let a = int(image[x, y].a)
        if a > alpha:
          alpha = a
          layer = i + 1
      let alpha5 = (alpha * 31 + 127) div 255
      let cell = if alpha5 == 0: 0 else: (layer shl 5) or alpha5
      if cell == current and length < 255:
        inc length
      else:
        if length > 0:
          runs.add(uint16((length shl 8) or current))
        current = cell
        length = 1
    if length > 0:
      runs.add(uint16((length shl 8) or current))
  result.add(runs.len)
  doAssert runs.len < 65536

var runs: seq[uint16] = @[]
let rows = encode(layers, runs)

var lines: seq[string] = @[]
lines.add("/* Generated by frameos/tools/gen_splash_mark.nim from")
lines.add(" * frameos/src/frameos/utils/status_screen/frameos_mark.svg — do not edit. */")
lines.add("#pragma once")
lines.add("#include <stdint.h>")
lines.add("")
lines.add(&"#define FOS_SPLASH_MARK_W {width}")
lines.add(&"#define FOS_SPLASH_MARK_H {markHeight}")
lines.add(&"#define FOS_SPLASH_MARK_RUN_COUNT {runs.len}")
lines.add("")
lines.add("/* Row y is FOS_SPLASH_MARK_RUNS[FOS_SPLASH_MARK_ROWS[y]] up to the row after's")
lines.add(" * first. A run is (length << 8) | (layer << 5) | alpha: `length` pixels of")
lines.add(" * layer `layer` (0 none, 1 the frame, 2..4 the squares from the bottom-left")
lines.add(" * one to the top-right one) at coverage alpha/31. */")
proc table(name: string, values: seq[int]) =
  lines.add(&"static const uint16_t {name}[{values.len}] = {{")
  var line = "   "
  for i, value in values:
    let item = &" 0x{value:04X},"
    if line.len + item.len > 100:
      lines.add(line)
      line = "   "
    line.add(item)
  if line.strip().len > 0:
    lines.add(line)
  lines.add("};")
table("FOS_SPLASH_MARK_ROWS", rows)
lines.add("")
var runValues: seq[int] = @[]
for run in runs:
  runValues.add(int(run))
table("FOS_SPLASH_MARK_RUNS", runValues)
lines.add("")
let path = currentSourcePath().parentDir() / header
writeFile(path, lines.join("\n"))
echo "wrote ", path.normalizedPath(), " (", width, "x", markHeight, ", ", runs.len, " runs, ",
  runs.len * 2 + rows.len * 2, " bytes)"

# The status lines: white on transparent, one line height for all of them,
# each as wide as its text.
var font = newFont(readTypeface(currentSourcePath().parentDir() / fontPath))
font.size = textSize
font.paint = color(1, 1, 1, 1)
let lineHeight = int(ceil(font.defaultLineHeight)) + 2
var textRuns: seq[uint16] = @[]
var textRows: seq[int] = @[]
var textWidths: seq[int] = @[]
for line in statusLines:
  let arrangement = typeset(font, line)
  let lineWidth = int(ceil(arrangement.layoutBounds().x)) + 2
  let image = newImage(lineWidth, lineHeight)
  image.fillText(arrangement, translate(vec2(1, 1)))
  textWidths.add(lineWidth)
  let starts = encode(@[image], textRuns)
  for i in 0 ..< lineHeight:
    textRows.add(starts[i])
textRows.add(textRuns.len)

lines = @[]
lines.add("/* Generated by frameos/tools/gen_splash_mark.nim — do not edit. */")
lines.add("#pragma once")
lines.add("#include <stdint.h>")
lines.add("")
lines.add(&"#define FOS_SPLASH_TEXT_COUNT {statusLines.len}")
lines.add(&"#define FOS_SPLASH_TEXT_H {lineHeight}")
lines.add(&"#define FOS_SPLASH_TEXT_MAX_W {max(textWidths)}")
lines.add("")
lines.add("/* Line i (fos_lcd_splash_status_t i + 1), in Ubuntu Regular at " & $int(textSize) & " px:")
for i, line in statusLines:
  lines.add(&" *   {i}: \"{line}\"")
lines.add(" * is FOS_SPLASH_TEXT_W[i] wide, and its row y is FOS_SPLASH_TEXT_RUNS from")
lines.add(" * FOS_SPLASH_TEXT_ROWS[i * FOS_SPLASH_TEXT_H + y] up to the next row's start,")
lines.add(" * runs as lcd_splash_mark.h's with one layer. */")
table("FOS_SPLASH_TEXT_W", textWidths)
lines.add("")
table("FOS_SPLASH_TEXT_ROWS", textRows)
lines.add("")
var textRunValues: seq[int] = @[]
for run in textRuns:
  textRunValues.add(int(run))
table("FOS_SPLASH_TEXT_RUNS", textRunValues)
lines.add("")
let textPath = currentSourcePath().parentDir() / textHeader
writeFile(textPath, lines.join("\n"))
echo "wrote ", textPath.normalizedPath(), " (", statusLines.len, " lines, ", textRuns.len, " runs, ",
  textRuns.len * 2 + textRows.len * 2 + textWidths.len * 2, " bytes)"
