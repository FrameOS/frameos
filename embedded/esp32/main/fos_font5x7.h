static inline const uint8_t *fos_font5x7_glyph(char raw)
{
    unsigned char c = (unsigned char)raw;
    if (c >= 'A' && c <= 'Z') return FOS_FONT5X7_LETTERS[c - 'A'];
    if (c >= 'a' && c <= 'z') return FOS_FONT5X7_LOWER_LETTERS[c - 'a'];
    if (c >= '0' && c <= '9') return FOS_FONT5X7_DIGITS[c - '0'];
    if (c == '-') return FOS_FONT5X7_GLYPH_DASH;
    if (c == '.') return FOS_FONT5X7_GLYPH_DOT;
    if (c == ':') return FOS_FONT5X7_GLYPH_COLON;
    if (c == '/') return FOS_FONT5X7_GLYPH_SLASH;
    if (c == '(') return FOS_FONT5X7_GLYPH_LPAREN;
    if (c == ')') return FOS_FONT5X7_GLYPH_RPAREN;
    if (c == ',') return FOS_FONT5X7_GLYPH_COMMA;
    if (c == '"') return FOS_FONT5X7_GLYPH_QUOTE;
    return NULL;
}
