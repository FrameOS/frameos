#!/usr/bin/env node
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const frontendRoot = path.resolve(__dirname, '..')
const repoRoot = path.resolve(frontendRoot, '..')
// repo/apps/<what the app returns>/<name>: image, text, json, logic.
const sourceRoot = path.join(repoRoot, 'repo', 'apps')
const outputPath = path.join(frontendRoot, 'src', 'generated', 'repoApps.ts')
const keyedOutputPath = path.join(frontendRoot, 'src', 'generated', 'keyedRepoApps.ts')
const sourceFiles = ['app.ts', 'app.tsx', 'app.js', 'app.jsx']

async function pathExists(filePath) {
  try {
    await fs.access(filePath)
    return true
  } catch {
    return false
  }
}

async function getAppDirs() {
  if (!(await pathExists(sourceRoot))) {
    return []
  }
  const appDirs = []
  for (const folder of (await fs.readdir(sourceRoot, { withFileTypes: true })).filter((entry) => entry.isDirectory())) {
    for (const app of (await fs.readdir(path.join(sourceRoot, folder.name), { withFileTypes: true })).filter((entry) =>
      entry.isDirectory()
    )) {
      appDirs.push(`${folder.name}/${app.name}`)
    }
  }
  return appDirs.sort((a, b) => a.split('/')[1].localeCompare(b.split('/')[1]))
}

async function buildEmbeddedRepoApps() {
  const configs = {}
  const sources = {}

  for (const appPath of await getAppDirs()) {
    const appDir = path.join(sourceRoot, appPath)
    const configPath = path.join(appDir, 'config.json')
    if (!(await pathExists(configPath))) {
      continue
    }

    const config = JSON.parse(await fs.readFile(configPath, 'utf8'))
    if (!config || typeof config !== 'object' || !config.name) {
      continue
    }

    const files = (await fs.readdir(appDir, { withFileTypes: true }))
      .filter((entry) => entry.isFile())
      .map((entry) => entry.name)
      .sort()
    const hasJavaScriptSource = files.some((file) => sourceFiles.includes(file))
    const keyword = `repo/apps/${appPath}`

    configs[keyword] = { ...config, origin: keyword }
    sources[keyword] = {}

    for (const file of files) {
      if (file === 'app_loader.nim') {
        continue
      }
      if (hasJavaScriptSource && file === 'app.nim') {
        continue
      }
      sources[keyword][file] = await fs.readFile(path.join(appDir, file), 'utf8')
    }
  }

  return { configs, sources }
}

function renderModule({ configs, sources }) {
  return `${[
    '// Auto-generated by scripts/generateRepoApps.mjs.',
    "import type { AppConfig } from '../types'",
    '',
    `export const embeddedRepoAppConfigs: Record<string, AppConfig> = ${JSON.stringify(configs, null, 2)}`,
    '',
    `export const embeddedRepoAppSources: Record<string, Record<string, string>> = ${JSON.stringify(sources, null, 2)}`,
    '',
  ].join('\n')}`
}

// Several builds run this generator at the same time (turbo runs the frontend,
// cloud-frontend and frame-frontend builds in parallel) while esbuild is
// reading the output, and a plain writeFile truncates first: a reader can see
// an empty file. Skip the write when nothing changed, rename into place
// otherwise. Inlined, not shared: deploys copy this script on its own
// (frameos/tools/prepare_assets.py).
async function writeFileAtomic(filePath, contents) {
  const existing = await fs.readFile(filePath, 'utf8').catch(() => null)
  if (existing === contents) {
    return
  }
  const tempPath = `${filePath}.${process.pid}.tmp`
  await fs.writeFile(tempPath, contents)
  await fs.rename(tempPath, filePath)
}

// The repo apps that read the viewer's stored keys (config.json "settings"),
// file by file, in a module of their own: the store's live preview holds a
// scene back until it is started when the scene's own app code reads a key,
// and an app carrying exactly this code is FrameOS's own, not the scene's
// (cloud/apps/auth-web/src/lib/preview-settings.ts). The full module above is
// too big for that page.
function renderKeyedModule({ configs, sources }) {
  const keyed = Object.fromEntries(
    Object.entries(sources).filter(([keyword]) => (configs[keyword]?.settings ?? []).length > 0)
  )
  return `${[
    '// Auto-generated by scripts/generateRepoApps.mjs: the repo apps that read stored keys.',
    `export const keyedRepoAppSources: Record<string, Record<string, string>> = ${JSON.stringify(keyed, null, 2)}`,
    '',
  ].join('\n')}`
}

await fs.mkdir(path.dirname(outputPath), { recursive: true })
const repoApps = await buildEmbeddedRepoApps()
await writeFileAtomic(outputPath, renderModule(repoApps))
await writeFileAtomic(keyedOutputPath, renderKeyedModule(repoApps))
