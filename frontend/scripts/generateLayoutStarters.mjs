#!/usr/bin/env node
// The layout starters the frame's Settings offers (docs/scene-layouts.md): every
// repo sample whose scene is a layout, embedded so they work on both control
// planes with no repository to reach. The iOS app gets the same list as JSON
// (ios/FrameOSKit, LayoutStarters.swift).
//
// Beside them, the scenes a layout is previewed around when it is all there
// is (a layout's store page, a starter on its own: docs/scene-layouts.md "In
// the preview"): small keyless samples, a clock first.
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const frontendRoot = path.resolve(__dirname, '..')
const samplesRoot = path.resolve(frontendRoot, '..', 'repo', 'scenes', 'samples')
const outputPath = path.join(frontendRoot, 'src', 'generated', 'layoutStarters.ts')
const iosOutputPath = path.resolve(
  frontendRoot,
  '..',
  'ios',
  'FrameOSKit',
  'Sources',
  'FrameOSKit',
  'Generated',
  'LayoutStarters.json'
)

const starters = []
for (const entry of await fs.readdir(samplesRoot, { withFileTypes: true })) {
  if (!entry.isDirectory()) {
    continue
  }
  const scenes = JSON.parse(await fs.readFile(path.join(samplesRoot, entry.name, 'scenes.json'), 'utf8'))
  if (scenes[0]?.settings?.isLayout !== true) {
    continue
  }
  const template = JSON.parse(await fs.readFile(path.join(samplesRoot, entry.name, 'template.json'), 'utf8'))
  const thumb = await fs.readFile(path.join(samplesRoot, entry.name, 'thumb.jpg'))
  starters.push({
    name: scenes[0].name,
    description: template.description,
    image: `data:image/jpeg;base64,${thumb.toString('base64')}`,
    scene: scenes[0],
  })
}
const PREVIEW_SAMPLES = ['Clock', 'Weather demo', 'Calculator']
const previewScenes = []
for (const name of PREVIEW_SAMPLES) {
  const scenes = JSON.parse(await fs.readFile(path.join(samplesRoot, name, 'scenes.json'), 'utf8'))
  const { default: _default, ...scene } = scenes[0]
  previewScenes.push(scene)
}

// The desktops (`settings.desktop`), then the layouts around one scene, each by
// name: the order the frame's own settings page lists them in, and the two
// groups every list of starters shows (sceneLayouts.ts `layoutGroups`).
const isDesktop = (starter) => starter.scene.settings?.desktop === true
starters.sort(
  (a, b) => Number(isDesktop(b)) - Number(isDesktop(a)) || a.name.localeCompare(b.name, 'en', { sensitivity: 'base' })
)

await fs.writeFile(
  outputPath,
  `// Generated by scripts/generateLayoutStarters.mjs from repo/scenes/samples. Do not edit.
import type { FrameScene } from '../types'

export interface LayoutStarter {
  name: string
  description: string
  /** A small picture of it, as a data URL: shown in the list, saved as the added scene's image. */
  image: string
  scene: FrameScene
}

export const LAYOUT_STARTERS: LayoutStarter[] = ${JSON.stringify(starters, null, 2)} as unknown as LayoutStarter[]

/** The scenes a layout is previewed around when there are no others (${PREVIEW_SAMPLES.join(', ')}). */
export const LAYOUT_PREVIEW_SCENES: FrameScene[] = ${JSON.stringify(previewScenes, null, 2)} as unknown as FrameScene[]
`
)
// Only where the app is checked out: a build that copies frontend/ and repo/
// alone (the Docker image) has no ios/.
const iosDirExists = await fs
  .stat(path.dirname(iosOutputPath))
  .then((stat) => stat.isDirectory())
  .catch(() => false)
if (iosDirExists) {
  await fs.writeFile(iosOutputPath, `${JSON.stringify(starters, null, 2)}\n`)
}
console.log(
  `Wrote ${starters.length} layout starters to ${path.relative(frontendRoot, outputPath)}${
    iosDirExists ? ` and ${path.relative(frontendRoot, iosOutputPath)}` : ''
  }`
)
