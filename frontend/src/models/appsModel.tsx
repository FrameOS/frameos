import { MakeLogicType, afterMount, kea, path, selectors } from 'kea'

import { loaders } from 'kea-loaders'
import { AppConfig } from '../types'
import { apiFetch } from '../utils/apiFetch'
import { embeddedBuiltinAppConfigs } from '../generated/builtinApps'
import { embeddedRepoAppConfigs } from '../generated/repoApps'

export const categoryLabels: Record<string, any> = {
  code: 'Code',
  render: 'Render',
  logic: 'Logic',
  data: 'Data',
}

function withEmbeddedRepoApps(apps: Record<string, AppConfig>): Record<string, AppConfig> {
  // Build-time catalogs fill the gaps; anything the backend serves wins.
  return { ...embeddedBuiltinAppConfigs, ...apps, ...embeddedRepoAppConfigs }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface appsModelValues {
  apps: Record<string, AppConfig>
  appsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface appsModelActions {
  loadApps: () => any
  loadAppsFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadAppsSuccess: (
    apps: Record<string, AppConfig>,
    payload?: any
  ) => {
    apps: Record<string, AppConfig>
    payload?: any
  }
}

export type appsModelType = MakeLogicType<appsModelValues, appsModelActions>

export const appsModel = kea<appsModelType>([
  path(['src', 'models', 'appsModel']),
  loaders(({ values }) => ({
    apps: [
      {} as Record<string, AppConfig>,
      {
        loadApps: async () => {
          try {
            const response = await apiFetch('/api/apps')
            if (!response.ok) {
              throw new Error('Failed to fetch apps')
            }
            const data = await response.json()
            return withEmbeddedRepoApps(data.apps as Record<string, AppConfig>)
          } catch (error) {
            console.error(error)
            return withEmbeddedRepoApps(values.apps)
          }
        },
      },
    ],
  })),
  afterMount(({ actions }) => {
    actions.loadApps()
  }),
])
