// The SSH keys an account (cloud) or backend keeps, and the "Add SSH key"
// modal that appends to them. One logic for every place the list is drawn —
// the SD card builders, the frame settings panel, the settings page — so
// adding a key in one of them shows up in all of them.
//
// The keys are the `ssh_keys` group of /api/settings, but this logic reads
// and writes that group itself instead of connecting to (or even importing)
// settingsLogic: that logic's graph is the whole legacy workspace (socket,
// user, frames), which the cloud's SD card builder neither needs nor may
// pull into its strict type program. When the settings page IS open, a save
// here refreshes its form through utils/settingsInvalidation.
export const sshKeysLogic = kea<sshKeysLogicType>([
  path(['src', 'components', 'sshKeys', 'sshKeysLogic']),
  actions({
    openAddKeyModal: true,
    closeAddKeyModal: true,
    generateKeyPair: true,
    setGenerating: (generating: boolean) => ({ generating }),
    keyAdded: (id: string) => ({ id }),
    removeKey: (id: string) => ({ id }),
  }),
  loaders(() => ({
    keys: [
      [] as SSHKeyEntry[],
      {
        loadKeys: async () => {
          const response = await apiFetch(`/api/settings`)
          if (!response.ok) {
            throw new Error('Failed to load SSH keys')
          }
          const settings = await response.json()
          return normalizeSshKeys(settings?.ssh_keys).keys
        },
        saveKeys: async ({ keys }: { keys: SSHKeyEntry[] }) => {
          const response = await apiFetch(`/api/settings`, {
            method: 'POST',
            body: JSON.stringify({ ssh_keys: { keys } }),
            headers: { 'Content-Type': 'application/json' },
          })
          if (!response.ok) {
            throw new Error('Failed to save SSH keys')
          }
          const settings = await response.json()
          // The settings page keeps its own copy of the form; make it reload
          // so it does not offer to overwrite the new key.
          notifySettingsChanged()
          // The cloud strips private halves from its response; the backend
          // echoes everything. Either way the list is what the server holds.
          return normalizeSshKeys(settings?.ssh_keys).keys
        },
      },
    ],
  })),
  reducers({
    addKeyModalOpen: [
      false,
      {
        openAddKeyModal: () => true,
        closeAddKeyModal: () => false,
      },
    ],
    generating: [
      false,
      {
        setGenerating: (_, { generating }) => generating,
      },
    ],
    // The id of the key the modal just saved, for a selectable list to tick
    // it without the user having to find it.
    lastAddedKeyId: [
      null as string | null,
      {
        keyAdded: (_, { id }) => id,
      },
    ],
  }),
  selectors({
    // The cloud has nothing to ssh with and stores no private keys; only a
    // self-hosted backend generates pairs and keeps the private half.
    keepsPrivateKeys: [() => [], (): boolean => !isCloudMode()],
  }),
  forms(({ actions, values }) => ({
    newKey: {
      defaults: { name: '', public: '', private: '', use_for_new_frames: true } as NewSshKeyForm,
      errors: ({ name, public: publicKey }: NewSshKeyForm) => ({
        name: !name.trim() ? 'Give the key a name' : undefined,
        public: !normalizeSshPublicKey(publicKey)
          ? 'Paste an OpenSSH public key (it starts with ssh-ed25519, ssh-rsa or ecdsa-sha2-…)'
          : undefined,
      }),
      submit: async (form: NewSshKeyForm) => {
        const id = uuidv4()
        const entry: SSHKeyEntry = {
          id,
          name: form.name.trim(),
          public: normalizeSshPublicKey(form.public) ?? '',
          use_for_new_frames: form.use_for_new_frames,
          ...(values.keepsPrivateKeys && form.private.trim() ? { private: form.private.trim() } : {}),
        }
        actions.saveKeys({ keys: [...values.keys, entry] })
        actions.keyAdded(id)
        actions.closeAddKeyModal()
        actions.resetNewKey()
      },
    },
  })),
  listeners(({ actions, values }) => ({
    generateKeyPair: async () => {
      if (!values.keepsPrivateKeys) {
        return
      }
      actions.setGenerating(true)
      try {
        const response = await apiFetch(`/api/generate_ssh_keys`, { method: 'POST' })
        if (!response.ok) {
          throw new Error('Failed to generate a key pair')
        }
        const data = await response.json()
        actions.setNewKeyValues({
          private: data.private,
          public: `${data.public} frameos@${window.location.hostname}`,
        })
      } finally {
        actions.setGenerating(false)
      }
    },
    removeKey: ({ id }) => {
      actions.saveKeys({ keys: values.keys.filter((key) => key.id !== id) })
    },
  })),
  afterMount(({ actions }) => {
    actions.loadKeys()
  }),
])
