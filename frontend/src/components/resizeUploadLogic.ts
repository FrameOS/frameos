function edge(value: unknown): number | null {
  const n = Math.round(Number(value))
  return Number.isFinite(n) && n > 0 ? Math.min(16384, n) : null
}

/** A frame's panel as a longer and a shorter edge. */
export function frameUploadEdges(frame: Pick<FrameType, 'width' | 'height' | 'rotate'>): {
  longEdge: number
  shortEdge: number
} {
  const { width, height } = panelRenderSize(frame)
  return { longEdge: Math.max(width, height), shortEdge: Math.min(width, height) }
}

export const resizeUploadLogic = kea<resizeUploadLogicType>([
  path(['src', 'components', 'resizeUploadLogic']),
  connect(() => ({ values: [framesModel, ['framesList']] })),
  actions({
    /** Open the dialog for a page's upload; a frame's own Files preselect that frame's size. */
    openResizeUpload: (target: ResizeUploadTarget, frame?: FrameType | null) => ({ target, frame: frame ?? null }),
    closeResizeUpload: true,
    setSize: (key: string, longEdge: number | null, shortEdge: number | null) => ({ key, longEdge, shortEdge }),
    setLongEdge: (longEdge: number | null) => ({ longEdge }),
    setShortEdge: (shortEdge: number | null) => ({ shortEdge }),
    setFit: (fit: UploadResizeFit) => ({ fit }),
    setFormat: (format: UploadResizeFormat) => ({ format }),
    setQuality: (quality: number) => ({ quality }),
    setUpscale: (upscale: boolean) => ({ upscale }),
    setBackground: (background: string) => ({ background }),
    setKeepMetadata: (keepMetadata: boolean) => ({ keepMetadata }),
    /** The files picked in the dialog: resized one at a time, then uploaded. */
    resizeAndUpload: (files: File[]) => ({ files }),
    resizeProgressed: (progress: ResizeUploadProgress) => ({ progress }),
    resizeFinished: (failures: string[]) => ({ failures }),
  }),
  reducers({
    target: [
      null as ResizeUploadTarget | null,
      { openResizeUpload: (_, { target }) => target, closeResizeUpload: () => null },
    ],
    progress: [
      null as ResizeUploadProgress | null,
      {
        resizeAndUpload: (_, { files }) => ({ done: 0, total: files.length }),
        resizeProgressed: (_, { progress }) => progress,
        resizeFinished: () => null,
        closeResizeUpload: () => null,
      },
    ],
    failures: [
      [] as string[],
      {
        openResizeUpload: () => [],
        resizeAndUpload: () => [],
        resizeFinished: (_, { failures }) => failures,
        closeResizeUpload: () => [],
      },
    ],
    sizeKey: [
      'size:800x480' as string,
      { persist: true, storageKey: 'resizeUploadLogic.sizeKey' },
      {
        setSize: (_, { key }) => key,
        setLongEdge: () => UPLOAD_RESIZE_CUSTOM,
        setShortEdge: () => UPLOAD_RESIZE_CUSTOM,
      },
    ],
    longEdge: [
      800 as number | null,
      { persist: true, storageKey: 'resizeUploadLogic.longEdge' },
      { setSize: (_, { longEdge }) => edge(longEdge), setLongEdge: (_, { longEdge }) => edge(longEdge) },
    ],
    shortEdge: [
      480 as number | null,
      { persist: true, storageKey: 'resizeUploadLogic.shortEdge' },
      { setSize: (_, { shortEdge }) => edge(shortEdge), setShortEdge: (_, { shortEdge }) => edge(shortEdge) },
    ],
    fit: [
      'inside' as UploadResizeFit,
      { persist: true, storageKey: 'resizeUploadLogic.fit' },
      { setFit: (_, { fit }) => fit },
    ],
    format: [
      'keep' as UploadResizeFormat,
      { persist: true, storageKey: 'resizeUploadLogic.format' },
      { setFormat: (_, { format }) => format },
    ],
    quality: [
      85,
      { persist: true, storageKey: 'resizeUploadLogic.quality' },
      { setQuality: (_, { quality }) => Math.max(1, Math.min(100, Math.round(Number(quality) || 85))) },
    ],
    upscale: [
      false,
      { persist: true, storageKey: 'resizeUploadLogic.upscale' },
      { setUpscale: (_, { upscale }) => upscale },
    ],
    background: [
      '#ffffff',
      { persist: true, storageKey: 'resizeUploadLogic.background' },
      { setBackground: (_, { background }) => background },
    ],
    // On by default: an upload keeps what the owner's photo says unless they ask (docs/photos.md, "Metadata").
    keepMetadata: [
      true,
      { persist: true, storageKey: 'resizeUploadLogic.keepMetadata' },
      { setKeepMetadata: (_, { keepMetadata }) => keepMetadata },
    ],
  }),
  selectors({
    // The frames' own panels, the common sizes, and "custom".
    sizeChoices: [
      (s) => [s.framesList],
      (framesList: FrameType[]): UploadResizeSizeChoice[] => [
        ...framesList
          .filter((frame) => !frame.archived && frame.width && frame.height)
          .map((frame): UploadResizeSizeChoice => {
            const edges = frameUploadEdges(frame)
            return {
              key: `frame:${frame.id}`,
              label: `${frame.name || `Frame ${frame.id}`} (${edges.longEdge}×${edges.shortEdge})`,
              group: 'frames',
              ...edges,
            }
          }),
        ...PREVIEW_SIZE_PRESETS.map(
          (preset): UploadResizeSizeChoice => ({
            key: `size:${preset.width}x${preset.height}`,
            label: `${preset.width}×${preset.height} — ${preset.label}`,
            group: 'presets',
            longEdge: Math.max(preset.width, preset.height),
            shortEdge: Math.min(preset.width, preset.height),
          })
        ),
        { key: UPLOAD_RESIZE_CUSTOM, label: 'Custom size', group: 'custom', longEdge: null, shortEdge: null },
      ],
    ],
    /** What the resize is told; null while the form cannot be used (no longer edge, a missing shorter one). */
    options: [
      (s) => [s.longEdge, s.shortEdge, s.fit, s.format, s.quality, s.upscale, s.background, s.keepMetadata],
      (
        longEdge: number | null,
        shortEdge: number | null,
        fit: UploadResizeFit,
        format: UploadResizeFormat,
        quality: number,
        upscale: boolean,
        background: string,
        keepMetadata: boolean
      ): UploadResizeOptions | null => {
        if (longEdge === null || (shortEdge === null && fit !== 'inside')) {
          return null
        }
        if (shortEdge !== null && shortEdge > longEdge) {
          return null
        }
        return { longEdge, shortEdge, fit, format, quality, upscale, background, keepMetadata }
      },
    ],
  }),
  listeners(({ actions, values }) => ({
    openResizeUpload: ({ frame }) => {
      if (frame?.width && frame.height) {
        const edges = frameUploadEdges(frame)
        actions.setSize(`frame:${frame.id}`, edges.longEdge, edges.shortEdge)
      }
    },
    resizeAndUpload: async ({ files }) => {
      const target = values.target
      const options = values.options
      if (!target || !options) {
        return
      }
      const ready: File[] = []
      const failures: string[] = []
      for (const [index, file] of files.entries()) {
        if (!isResizableImage(file)) {
          // Not a picture (a font, a JSON file): it goes up as it is.
          ready.push(file)
        } else {
          try {
            ready.push(await resizeImageFile(file, options))
          } catch (error) {
            console.error(error)
            failures.push(file.name)
          }
        }
        // Closed while resizing: nothing is uploaded.
        if (values.target !== target) {
          return
        }
        actions.resizeProgressed({ done: index + 1, total: files.length })
      }
      if (ready.length) {
        target.onUpload(ready)
      }
      actions.resizeFinished(failures)
      if (!failures.length) {
        actions.closeResizeUpload()
      }
    },
  })),
])
