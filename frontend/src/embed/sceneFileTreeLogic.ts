// What the embedded editor's file tree has open: the selected file (the
// template, the shown scene's diagram, or one of its apps) and which
// folders are expanded. The app editor that used to open in a modal over
// the diagram is a file in this tree now: a node's "Edit app" selects its
// folder here (frameEditorsLogic.editApp) and the pane shows the source.
export const sceneFileTreeLogic = kea<sceneFileTreeLogicType>([
  path(['src', 'embed', 'sceneFileTreeLogic']),
  props({} as SceneFileTreeLogicProps),
  key((props) => props.frameId),
  connect((props: SceneFileTreeLogicProps) => ({
    values: [frameLogic(props), ['frameForm']],
    actions: [frameEditorsLogic(props), ['editApp']],
  })),
  actions({
    selectTemplate: true,
    showDiagram: (sceneId: string) => ({ sceneId }),
    /** The editor shows another scene (a tab picked in the tree, or the
     * host's `sceneId`): its diagram takes the keyboard while it is shown. */
    syncScene: (sceneId: string) => ({ sceneId }),
    selectApp: (sceneId: string, nodeId: string) => ({ sceneId, nodeId }),
    /** Opens one file of an app: its folder must be expanded (the folder
     * mounts the app's editAppLogic, which holds the files). */
    openAppFile: (sceneId: string, nodeId: string, file: string) => ({ sceneId, nodeId, file }),
    toggleExpanded: (treeKey: string) => ({ treeKey }),
    setTreeOpen: (open: boolean) => ({ open }),
    setTemplateSourceView: (source: boolean) => ({ source }),
    setTemplateSourceError: (error: string | null) => ({ error }),
  }),
  reducers(({ props }) => ({
    selection: [
      (props.initialFile === 'template' ? { kind: 'template' } : { kind: 'diagram' }) as SceneFileSelection,
      {
        selectTemplate: () => ({ kind: 'template' }),
        showDiagram: () => ({ kind: 'diagram' }),
        selectApp: (_, { sceneId, nodeId }) => ({ kind: 'app', sceneId, nodeId }),
        openAppFile: (_, { sceneId, nodeId }) => ({ kind: 'app', sceneId, nodeId }),
        editApp: (_, { sceneId, nodeId }) => ({ kind: 'app', sceneId, nodeId }),
      },
    ],
    // Scenes start expanded (their apps are what the tree is for); app
    // folders start closed — opening one loads its files.
    collapsed: [
      {} as Record<string, boolean>,
      {
        toggleExpanded: (state, { treeKey }) => ({
          ...state,
          [treeKey]: !(state[treeKey] ?? defaultCollapsed(treeKey)),
        }),
        selectApp: (state, { sceneId, nodeId }) => ({
          ...state,
          [sceneTreeKey(sceneId)]: false,
          [appTreeKey(sceneId, nodeId)]: false,
        }),
        editApp: (state, { sceneId, nodeId }) => ({
          ...state,
          [sceneTreeKey(sceneId)]: false,
          [appTreeKey(sceneId, nodeId)]: false,
        }),
      },
    ],
    treeOpen: [true, { setTreeOpen: (_, { open }) => open }],
    templateSourceView: [false, { setTemplateSourceView: (_, { source }) => source }],
    templateSourceError: [
      null as string | null,
      { setTemplateSourceError: (_, { error }) => error, setTemplateSourceView: () => null },
    ],
  })),
  selectors({
    shownSelection: [
      (s) => [s.selection, s.frameForm],
      (selection: SceneFileSelection, frameForm: Partial<FrameType>): SceneFileSelection =>
        shownSelection(selection, frameForm?.scenes ?? []),
    ],
    isExpanded: [
      (s) => [s.collapsed],
      (collapsed: Record<string, boolean>) =>
        (treeKey: string): boolean =>
          !(collapsed[treeKey] ?? defaultCollapsed(treeKey)),
    ],
  }),
  listeners(({ actions, values, props }) => ({
    // frameEditorsLogic's active editor is what scopes the diagrams' global
    // shortcuts (diagramLogic's isVisibleDiagram) and the chat's context:
    // it follows what the pane shows. An app folder mounts its scene's
    // diagramLogic, so without this a Cmd+Z in an app's code could reach a
    // diagram nobody is looking at.
    showDiagram: ({ sceneId }) => {
      frameEditorsLogic(props).actions.editScene(sceneId)
    },
    syncScene: ({ sceneId }) => {
      if (values.selection.kind === 'diagram') {
        frameEditorsLogic(props).actions.editScene(sceneId)
      }
    },
    openAppFile: ({ sceneId, nodeId, file }) => {
      editAppLogic.findMounted({ frameId: props.frameId, sceneId, nodeId })?.actions.setActiveFile(file)
      const node = values.frameForm?.scenes
        ?.find((scene) => scene.id === sceneId)
        ?.nodes?.find((candidate) => candidate.id === nodeId)
      if (node && node.type === 'app') {
        actions.editApp(sceneId, nodeId, node.data as AppNodeData)
      }
    },
  })),
])

function defaultCollapsed(treeKey: string): boolean {
  return treeKey.startsWith('app:')
}
