// What the embedded editor's file tree has open: the selected file (the
// template, the shown scene's diagram, or one of its apps) and which
// folders are expanded. A node's "Edit app" (frameEditorsLogic.editApp)
// selects the app's folder here when the scene carries its source; a
// built-in app is no file of the template, and opens in a modal instead.
export const sceneFileTreeLogic = kea<sceneFileTreeLogicType>([
  path(['src', 'embed', 'sceneFileTreeLogic']),
  props({} as SceneFileTreeLogicProps),
  key((props) => props.frameId),
  connect((props: SceneFileTreeLogicProps) => ({
    values: [frameLogic(props), ['frameForm'], frameEditorsLogic(props), ['openEditors']],
    actions: [frameEditorsLogic(props), ['editApp']],
  })),
  actions({
    selectTemplate: true,
    showDiagram: (sceneId: string) => ({ sceneId }),
    /** The editor shows another scene (a tab picked in the tree, or the
     * host's `sceneId`): its diagram takes the keyboard while it is shown. */
    syncScene: (sceneId: string) => ({ sceneId }),
    selectApp: (sceneId: string, nodeId: string) => ({ sceneId, nodeId }),
    /** A built-in app's "Edit app": shown in a modal over the pane. */
    openBuiltinApp: (sceneId: string, nodeId: string) => ({ sceneId, nodeId }),
    closeBuiltinApp: (sceneId: string, nodeId: string) => ({ sceneId, nodeId }),
    /** Opens one file of an app: its folder must be expanded (the folder
     * mounts the app's editAppLogic, which holds the files). */
    openAppFile: (sceneId: string, nodeId: string, file: string) => ({ sceneId, nodeId, file }),
    /** The app's folder showed the file openAppFile asked for. */
    appFileOpened: true,
    toggleExpanded: (treeKey: string) => ({ treeKey }),
    setTreeOpen: (open: boolean) => ({ open }),
    setTemplateSourceView: (source: boolean) => ({ source }),
    setTemplateSourceError: (error: string | null) => ({ error }),
  }),
  reducers(({ props }) => ({
    selection: [
      (props.initialFile === 'template' ? { kind: 'template' } : { kind: 'diagram' }) as SceneFileSelection,
      {
        selectTemplate: () => ({ kind: 'template' }),
        showDiagram: () => ({ kind: 'diagram' }),
        selectApp: (_, { sceneId, nodeId }) => ({ kind: 'app', sceneId, nodeId }),
        openAppFile: (_, { sceneId, nodeId }) => ({ kind: 'app', sceneId, nodeId }),
      },
    ],
    // The file openAppFile asked for, until its app's folder has loaded the
    // files and shown it: an app's files load after its folder mounts (and
    // the load opens the first file), so a file asked for before then — a
    // host's initialAppFile, on the editor's first render — waits here.
    pendingAppFile: [
      null as { sceneId: string; nodeId: string; file: string } | null,
      {
        openAppFile: (_, { sceneId, nodeId, file }) => ({ sceneId, nodeId, file }),
        appFileOpened: () => null,
        selectTemplate: () => null,
        showDiagram: () => null,
        // openAppFile selects its own app (through editApp): that keeps it.
        selectApp: (state, { sceneId, nodeId }) =>
          state && state.sceneId === sceneId && state.nodeId === nodeId ? state : null,
      },
    ],
    builtinApp: [
      null as { sceneId: string; nodeId: string } | null,
      {
        openBuiltinApp: (_, { sceneId, nodeId }) => ({ sceneId, nodeId }),
        closeBuiltinApp: () => null,
      },
    ],
    // Every folder starts expanded, app folders too: the tree is for seeing
    // a scene's files, and a scene app's files are in the scene already
    // (built-in apps get no folder), so opening them costs no request.
    collapsed: [
      {} as Record<string, boolean>,
      {
        toggleExpanded: (state, { treeKey }) => ({
          ...state,
          [treeKey]: !(state[treeKey] ?? defaultCollapsed(treeKey)),
        }),
        selectApp: (state, { sceneId, nodeId }) => ({
          ...state,
          [sceneTreeKey(sceneId)]: false,
          [appTreeKey(sceneId, nodeId)]: false,
        }),
        showDiagram: (state, { sceneId }) => ({ ...state, [sceneTreeKey(sceneId)]: false }),
      },
    ],
    treeOpen: [true, { setTreeOpen: (_, { open }) => open }],
    templateSourceView: [false, { setTemplateSourceView: (_, { source }) => source }],
    templateSourceError: [
      null as string | null,
      { setTemplateSourceError: (_, { error }) => error, setTemplateSourceView: () => null },
    ],
  })),
  selectors({
    shownSelection: [
      (s) => [s.selection, s.frameForm],
      (selection: SceneFileSelection, frameForm: Partial<FrameType>): SceneFileSelection =>
        shownSelection(selection, frameForm?.scenes ?? []),
    ],
    /** The editor the built-in app's modal shows (frameEditorsLogic's). */
    builtinAppEditor: [
      (s) => [s.builtinApp, s.openEditors],
      (builtinApp: { sceneId: string; nodeId: string } | null, openEditors: FrameEditor[]): FrameEditor | null =>
        builtinApp
          ? (openEditors.find((editor) => editor.key === editAppEditorKey(builtinApp.sceneId, builtinApp.nodeId)) ??
            null)
          : null,
    ],
    isExpanded: [
      (s) => [s.collapsed],
      (collapsed: Record<string, boolean>) =>
        (treeKey: string): boolean =>
          !(collapsed[treeKey] ?? defaultCollapsed(treeKey)),
    ],
  }),
  listeners(({ actions, values, props }) => ({
    // frameEditorsLogic's active editor is what scopes the diagrams' global
    // shortcuts (diagramLogic's isVisibleDiagram) and the chat's context:
    // it follows what the pane shows. An app folder mounts its scene's
    // diagramLogic, so without this a Cmd+Z in an app's code could reach a
    // diagram nobody is looking at.
    showDiagram: ({ sceneId }) => {
      frameEditorsLogic(props).actions.editScene(sceneId)
    },
    syncScene: ({ sceneId }) => {
      if (values.selection.kind === 'diagram') {
        frameEditorsLogic(props).actions.editScene(sceneId)
      }
    },
    editApp: ({ sceneId, nodeId }) => {
      const scene = values.frameForm?.scenes?.find((candidate) => candidate.id === sceneId)
      if (isSceneApp(scene, nodeId)) {
        actions.selectApp(sceneId, nodeId)
      } else {
        actions.openBuiltinApp(sceneId, nodeId)
      }
    },
    closeBuiltinApp: ({ sceneId, nodeId }) => {
      const editors = frameEditorsLogic(props).actions
      editors.closeEditor(editAppEditorKey(sceneId, nodeId))
      // The keyboard goes back to what the pane shows.
      const selection = values.shownSelection
      if (selection.kind === 'diagram') {
        editors.editScene(sceneId)
      } else if (selection.kind === 'app') {
        const node = values.frameForm?.scenes
          ?.find((scene) => scene.id === selection.sceneId)
          ?.nodes?.find((candidate) => candidate.id === selection.nodeId)
        if (node && node.type === 'app') {
          actions.editApp(selection.sceneId, selection.nodeId, node.data as AppNodeData)
        }
      }
    },
    openAppFile: ({ sceneId, nodeId, file }) => {
      editAppLogic.findMounted({ frameId: props.frameId, sceneId, nodeId })?.actions.setActiveFile(file)
      const node = values.frameForm?.scenes
        ?.find((scene) => scene.id === sceneId)
        ?.nodes?.find((candidate) => candidate.id === nodeId)
      if (node && node.type === 'app') {
        actions.editApp(sceneId, nodeId, node.data as AppNodeData)
      }
    },
  })),
])

function defaultCollapsed(_treeKey: string): boolean {
  return false
}
