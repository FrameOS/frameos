export interface frameEditorsLogicValues {
  frameForm: Partial<FrameType> // frameLogic
  activeEditApp: FrameEditor | null
  activeEditor: FrameEditor | null
  activeEditorKey: string | null
  activeSceneEditorId: string | null
  lastSelectedScene: string | null
  openEditors: FrameEditor[]
  scenesOpen: boolean
  selectedSceneId: string | null
  selectedSceneIsInterpreted: boolean
  selectedSceneName: string | null
}

