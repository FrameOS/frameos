import { MakeLogicType, actions, connect, kea, key, listeners, path, props, selectors } from 'kea'
import type { DeepPartial } from 'kea-forms'

import type { FrameId, FrameScene, FrameType, TemplateType } from '../../../../types'
import {
  commonSceneLayoutId,
  layoutScenes,
  scenesWithoutLayouts,
  withLayoutOnEveryScene,
} from '../../../../utils/sceneLayouts'
import { LAYOUT_STARTERS } from '../../../../generated/layoutStarters'
import { frameLogic } from '../../frameLogic'

// The Layouts section of a frame's Settings (docs/scene-layouts.md): the one
// select that dresses every scene. A scene's own select is SceneLayoutPicker.
// Like it, this writes the scenes' `layout` into the frame form; Save pushes it.

export interface FrameLayoutsLogicProps {
  frameId: FrameId
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface frameLayoutsLogicValues {
  frame: FrameType // frameLogic
  frameForm: Partial<FrameType> // frameLogic
  commonLayoutId: string | null
  contentScenes: FrameScene[]
  layouts: FrameScene[]
  scenes: FrameScene[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface frameLayoutsLogicActions {
  applyTemplate: (
    template: Partial<TemplateType>,
    openDrawer?: boolean | undefined,
    preserveSceneIds?: boolean | undefined
  ) => {
    openDrawer: boolean
    preserveSceneIds: boolean
    template: Partial<TemplateType>
  } // frameLogic
  setFrameFormValues: (values: DeepPartial<FrameType>) => {
    values: DeepPartial<FrameType>
  } // frameLogic
  addStarterLayout: (name: string) => {
    name: string
  }
  chooseLayoutForEveryScene: (layoutSceneId: string) => {
    layoutSceneId: string
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface frameLayoutsLogicMeta {
  key: FrameId
  __keaTypeGenInternalSelectorTypes: {
    scenes: (frameForm: Partial<FrameType>, frame: FrameType) => FrameScene[]
    layouts: (scenes: FrameScene[]) => FrameScene[]
    contentScenes: (scenes: FrameScene[]) => FrameScene[]
    commonLayoutId: (contentScenes: FrameScene[], layouts: FrameScene[]) => string | null
  }
}

export type frameLayoutsLogicType = MakeLogicType<
  frameLayoutsLogicValues,
  frameLayoutsLogicActions,
  FrameLayoutsLogicProps
> &
  frameLayoutsLogicMeta

export const frameLayoutsLogic = kea<frameLayoutsLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'FrameSettings', 'frameLayoutsLogic']),
  props({} as FrameLayoutsLogicProps),
  key((props) => props.frameId),
  connect(({ frameId }: FrameLayoutsLogicProps) => ({
    values: [frameLogic({ frameId }), ['frame', 'frameForm']],
    actions: [frameLogic({ frameId }), ['setFrameFormValues', 'applyTemplate']],
  })),
  actions({
    chooseLayoutForEveryScene: (layoutSceneId: string) => ({ layoutSceneId }),
    addStarterLayout: (name: string) => ({ name }),
  }),
  selectors({
    scenes: [
      (s) => [s.frameForm, s.frame],
      (frameForm: Partial<FrameType>, frame: FrameType): FrameScene[] => frameForm?.scenes ?? frame?.scenes ?? [],
    ],
    layouts: [(s) => [s.scenes], (scenes: FrameScene[]): FrameScene[] => layoutScenes(scenes)],
    contentScenes: [(s) => [s.scenes], (scenes: FrameScene[]): FrameScene[] => scenesWithoutLayouts(scenes)],
    /** What the select for every scene shows; null while the scenes differ. */
    commonLayoutId: [
      (s) => [s.contentScenes, s.layouts],
      (contentScenes: FrameScene[], layouts: FrameScene[]): string | null =>
        commonSceneLayoutId(contentScenes, layouts),
    ],
  }),
  listeners(({ actions, values }) => ({
    chooseLayoutForEveryScene: ({ layoutSceneId }) => {
      actions.setFrameFormValues({
        scenes: withLayoutOnEveryScene(values.scenes, layoutSceneId),
      } as DeepPartial<FrameType>)
    },
    addStarterLayout: ({ name }) => {
      const starter = LAYOUT_STARTERS.find((candidate) => candidate.name === name)
      if (starter) {
        actions.applyTemplate({ name: starter.name, scenes: [starter.scene] }, false)
      }
    },
  })),
])
