import { confirmDialog } from '../../../../utils/confirmDialogLogic'

/**
 * A cloud virtual frame's own settings (docs/cloud-frames.md "Virtual
 * frames"): its size, its view link, and what its last render came to.
 *
 * Not frame form fields. The size is the frame's "hardware" and the link is a
 * secret; neither is a `set_settings` key, so both go through
 * `/api/frames/{id}/virtual` and apply at once, like the local network access
 * switch does.
 */

/** The `virtual` object of GET/POST /api/frames/{id}/virtual. */
export interface CloudVirtualFrame {
  height: number
  image_url: string
  /** Seconds between renders while someone is looking. */
  interval_seconds: number
  /** The least a plan allows. */
  min_interval_seconds: number
  render_error: string | null
  render_ms: number | null
  rendered_at: string | null
  view_url: string
  viewed_at: string | null
  width: number
}

/** Mirrors virtualFrameMinDimension / MaxDimension in the cloud's virtual-frames.ts. */
export const VIRTUAL_FRAME_MIN_DIMENSION = 16
export const VIRTUAL_FRAME_MAX_DIMENSION = 4096

const ERROR_COPY: Record<string, string> = {
  frame_not_active: 'This frame is not active.',
  invalid_size: `Width and height are whole numbers from ${VIRTUAL_FRAME_MIN_DIMENSION} to ${VIRTUAL_FRAME_MAX_DIMENSION}.`,
  login_required: 'Your session expired. Sign in again.',
  not_virtual: 'This frame is not a virtual frame.',
  size_too_large: 'That is more pixels than one frame can have. Make it smaller.',
}

export function cloudVirtualFrameErrorMessage(code: string | null | undefined): string {
  return (code && ERROR_COPY[code]) || 'Something went wrong. Try again.'
}

/** A whole number of pixels from the text of a size field, or null. */
export function parseVirtualDimension(value: string): number | null {
  const trimmed = value.trim()
  if (!/^\d+$/.test(trimmed)) {
    return null
  }
  const parsed = Number(trimmed)
  return parsed >= VIRTUAL_FRAME_MIN_DIMENSION && parsed <= VIRTUAL_FRAME_MAX_DIMENSION ? parsed : null
}

/** "every 5 minutes", "every 90 seconds": how the section says an interval. */
export function virtualIntervalLabel(seconds: number): string {
  if (seconds >= 3600 && seconds % 3600 === 0) {
    const hours = seconds / 3600
    return hours === 1 ? 'every hour' : `every ${hours} hours`
  }
  if (seconds >= 60 && seconds % 60 === 0) {
    const minutes = seconds / 60
    return minutes === 1 ? 'every minute' : `every ${minutes} minutes`
  }
  return `every ${seconds} seconds`
}

function isCloudVirtualFrame(value: unknown): value is CloudVirtualFrame {
  if (typeof value !== 'object' || value === null) {
    return false
  }
  const record = value as Record<string, unknown>
  return (
    typeof record.view_url === 'string' &&
    typeof record.image_url === 'string' &&
    typeof record.width === 'number' &&
    typeof record.height === 'number'
  )
}

async function readVirtual(response: Response): Promise<CloudVirtualFrame> {
  const body = (await response.json().catch(() => ({}))) as { error?: unknown; virtual?: unknown }
  if (!response.ok || !isCloudVirtualFrame(body.virtual)) {
    throw new Error(cloudVirtualFrameErrorMessage(typeof body.error === 'string' ? body.error : null))
  }
  return body.virtual
}

function postVirtual(frameId: FrameId, body: Record<string, unknown>): Promise<Response> {
  return apiFetch(`/api/frames/${frameId}/virtual`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  })
}

function errorMessage(error: unknown): string {
  return error instanceof Error && error.message ? error.message : cloudVirtualFrameErrorMessage(null)
}

export interface CloudVirtualFrameLogicProps {
  frameId: FrameId
}

