export type cloudVirtualFrameLogicType = MakeLogicType<
  cloudVirtualFrameLogicValues,
  cloudVirtualFrameLogicActions,
  CloudVirtualFrameLogicProps
> &
  cloudVirtualFrameLogicMeta

export const cloudVirtualFrameLogic = kea<cloudVirtualFrameLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'FrameSettings', 'cloudVirtualFrameLogic']),
  props({} as CloudVirtualFrameLogicProps),
  key((props) => props.frameId),
  actions({
    loadVirtual: true,
    loadVirtualSuccess: (virtual: CloudVirtualFrame) => ({ virtual }),
    loadVirtualFailure: (message: string) => ({ message }),
    setWidth: (width: string) => ({ width }),
    setHeight: (height: string) => ({ height }),
    saveSize: true,
    saveSizeRequest: true,
    resetLink: true,
    resetLinkRequest: true,
    requestSuccess: (virtual: CloudVirtualFrame) => ({ virtual }),
    requestFailure: (message: string) => ({ message }),
  }),
  reducers({
    virtual: [
      null as CloudVirtualFrame | null,
      {
        loadVirtualSuccess: (_, { virtual }) => virtual,
        requestSuccess: (_, { virtual }) => virtual,
      },
    ],
    loading: [
      true,
      {
        loadVirtual: () => true,
        loadVirtualSuccess: () => false,
        loadVirtualFailure: () => false,
      },
    ],
    // The fields hold text: what the row says until someone types.
    width: [
      '',
      {
        setWidth: (_, { width }) => width,
        loadVirtualSuccess: (_, { virtual }) => String(virtual.width),
        requestSuccess: (_, { virtual }) => String(virtual.width),
      },
    ],
    height: [
      '',
      {
        setHeight: (_, { height }) => height,
        loadVirtualSuccess: (_, { virtual }) => String(virtual.height),
        requestSuccess: (_, { virtual }) => String(virtual.height),
      },
    ],
    request: [
      'idle' as 'idle' | 'resettingLink' | 'savingSize',
      {
        saveSizeRequest: () => 'savingSize',
        resetLinkRequest: () => 'resettingLink',
        requestSuccess: () => 'idle',
        requestFailure: () => 'idle',
      },
    ],
    error: [
      null as string | null,
      {
        loadVirtual: () => null,
        loadVirtualFailure: (_, { message }) => message,
        saveSizeRequest: () => null,
        resetLinkRequest: () => null,
        requestSuccess: () => null,
        requestFailure: (_, { message }) => message,
        setWidth: () => null,
        setHeight: () => null,
      },
    ],
  }),
  selectors({
    sizeChanged: [
      (s) => [s.virtual, s.width, s.height],
      (
        virtual: cloudVirtualFrameLogicValues['virtual'],
        width: cloudVirtualFrameLogicValues['width'],
        height: cloudVirtualFrameLogicValues['height']
      ): boolean =>
        virtual !== null && (width.trim() !== String(virtual.width) || height.trim() !== String(virtual.height)),
    ],
    canSaveSize: [
      (s) => [s.sizeChanged, s.width, s.height, s.request],
      (
        sizeChanged: cloudVirtualFrameLogicValues['sizeChanged'],
        width: cloudVirtualFrameLogicValues['width'],
        height: cloudVirtualFrameLogicValues['height'],
        request: cloudVirtualFrameLogicValues['request']
      ): boolean =>
        sizeChanged &&
        request === 'idle' &&
        parseVirtualDimension(width) !== null &&
        parseVirtualDimension(height) !== null,
    ],
  }),
  listeners(({ actions, props, values }) => ({
    loadVirtual: async () => {
      try {
        actions.loadVirtualSuccess(await readVirtual(await apiFetch(`/api/frames/${props.frameId}/virtual`)))
      } catch (error) {
        actions.loadVirtualFailure(errorMessage(error))
      }
    },
    saveSize: async () => {
      const width = parseVirtualDimension(values.width)
      const height = parseVirtualDimension(values.height)
      if (width === null || height === null) {
        actions.requestFailure(cloudVirtualFrameErrorMessage('invalid_size'))
        return
      }
      actions.saveSizeRequest()
      try {
        actions.requestSuccess(await readVirtual(await postVirtual(props.frameId, { height, width })))
      } catch (error) {
        actions.requestFailure(errorMessage(error))
      }
    },
    resetLink: async () => {
      const confirmed = await confirmDialog({
        title: 'Replace the view link?',
        message:
          'The link this frame is shown at stops working at once, on every screen that has it open. You get a new one to put there instead.',
        confirmLabel: 'Replace the link',
      })
      if (!confirmed) {
        return
      }
      actions.resetLinkRequest()
      try {
        actions.requestSuccess(await readVirtual(await postVirtual(props.frameId, { reset_link: true })))
      } catch (error) {
        actions.requestFailure(errorMessage(error))
      }
    },
  })),
  afterMount(({ actions }) => {
    actions.loadVirtual()
  }),
])
