/** The config.json form beside the code editor: every edit is written back
 * into the file's source, which stays the truth. */
export const appConfigFormLogic = kea<appConfigFormLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'EditApp', 'appConfigFormLogic']),
  props({} as EditAppLogicProps),
  key((props) => `${props.frameId}:${props.sceneId}.${props.nodeId}`),
  connect((props: EditAppLogicProps) => ({
    values: [editAppLogic(props), ['sources', 'requiresCompiledOnSave']],
    actions: [editAppLogic(props), ['updateFile']],
  })),
  actions({
    /** Source or form, remembered across apps. */
    setShowConfigSource: (showConfigSource: boolean) => ({ showConfigSource }),
    toggleEntry: (index: number) => ({ index }),
    setOpenEntry: (index: number | null) => ({ index }),
    writeConfig: (config: AppConfigDraft) => ({ config }),
    setConfigKey: (key: string, value: unknown) => ({ key, value }),
    addField: true,
    addMarkdown: true,
    updateEntry: (index: number, patch: Record<string, unknown>) => ({ index, patch }),
    renameField: (index: number, name: string) => ({ index, name }),
    removeEntry: (index: number) => ({ index }),
    moveEntry: (index: number, delta: number) => ({ index, delta }),
    addOutput: true,
    updateOutput: (index: number, patch: Record<string, unknown>) => ({ index, patch }),
    removeOutput: (index: number) => ({ index }),
    updateCache: (patch: Partial<Record<keyof CacheConfig, unknown>>) => ({ patch }),
  }),
  reducers({
    showConfigSource: [
      false,
      { persist: true, storageKey: 'appConfigForm.showSource' },
      { setShowConfigSource: (_, { showConfigSource }) => showConfigSource },
    ],
    // The field whose editor is open; the rest show as one-line rows.
    openEntry: [
      null as number | null,
      {
        toggleEntry: (state, { index }) => (state === index ? null : index),
        setOpenEntry: (_, { index }) => index,
        removeEntry: (state, { index }) =>
          state === index ? null : state !== null && state > index ? state - 1 : state,
        moveEntry: (state, { index, delta }) =>
          state === index ? index + delta : state === index + delta ? index : state,
      },
    ],
  }),
  selectors({
    parsedConfig: [(s) => [s.sources], (sources: Record<string, string>) => parseAppConfigSource(sources[CONFIG_FILE])],
    config: [
      (s) => [s.parsedConfig],
      (parsed: ReturnType<typeof parseAppConfigSource>): AppConfigDraft | null => parsed.config,
    ],
    configError: [
      (s) => [s.parsedConfig],
      (parsed: ReturnType<typeof parseAppConfigSource>): string | null => parsed.error,
    ],
    entries: [(s) => [s.config], (config: AppConfigDraft | null): AppConfigEntry[] => configEntries(config)],
    inputFields: [
      (s) => [s.entries],
      (entries: AppConfigEntry[]): AppConfigField[] =>
        entries.filter((entry): entry is AppConfigField => !isMarkdownEntry(entry)),
    ],
    outputs: [(s) => [s.config], (config: AppConfigDraft | null): OutputField[] => configOutputs(config)],
    settings: [(s) => [s.config], (config: AppConfigDraft | null): string[] => configStrings(config, 'settings')],
    permissions: [(s) => [s.config], (config: AppConfigDraft | null): string[] => configStrings(config, 'permissions')],
    apt: [(s) => [s.config], (config: AppConfigDraft | null): string[] => configStrings(config, 'apt')],
    cache: [(s) => [s.config], (config: AppConfigDraft | null): CacheConfig => configCache(config)],
    /** Codenames used twice: the frame would keep only one of them. */
    duplicateNames: [
      (s) => [s.inputFields],
      (fields: AppConfigField[]): string[] => {
        const seen = new Set<string>()
        const duplicates = new Set<string>()
        for (const field of fields) {
          if (field.name && seen.has(field.name)) {
            duplicates.add(field.name)
          }
          seen.add(field.name)
        }
        return [...duplicates]
      },
    ],
  }),
  listeners(({ actions, values }) => {
    const writeEntries = (entries: AppConfigEntry[]): void =>
      actions.writeConfig(withConfigKey(values.config ?? {}, 'fields', entries))
    const writeOutputs = (outputs: OutputField[]): void =>
      actions.writeConfig(withConfigKey(values.config ?? {}, 'output', outputs))
    return {
      writeConfig: ({ config }) => {
        if (values.requiresCompiledOnSave) {
          return
        }
        actions.updateFile(CONFIG_FILE, formatAppConfigLike(values.sources[CONFIG_FILE], config))
      },
      setConfigKey: ({ key, value }) => {
        if (values.config) {
          actions.writeConfig(withConfigKey(values.config, key, value))
        }
      },
      addField: () => {
        const entries = values.entries
        writeEntries([...entries, newConfigField(entries)])
        actions.setOpenEntry(entries.length)
      },
      addMarkdown: () => {
        const entries = values.entries
        writeEntries([...entries, { markdown: '' }])
        actions.setOpenEntry(entries.length)
      },
      updateEntry: ({ index, patch }) => {
        writeEntries(values.entries.map((entry, i) => (i === index ? patchObject(entry, patch) : entry)))
      },
      renameField: ({ index, name }) => {
        const entry = values.entries[index]
        if (!entry || isMarkdownEntry(entry)) {
          return
        }
        const renamed = values.entries.map((item, i) => (i === index ? renamedField(entry, name) : item))
        writeEntries(renameFieldReferences(renamed, entry.name, name))
      },
      removeEntry: ({ index }) => {
        writeEntries(values.entries.filter((_, i) => i !== index))
      },
      moveEntry: ({ index, delta }) => {
        writeEntries(moveItem(values.entries, index, delta))
      },
      addOutput: () => {
        writeOutputs([...values.outputs, { name: values.outputs.length ? 'output' : 'image', type: 'image' }])
      },
      updateOutput: ({ index, patch }) => {
        writeOutputs(values.outputs.map((output, i) => (i === index ? patchObject(output, patch) : output)))
      },
      removeOutput: ({ index }) => {
        writeOutputs(values.outputs.filter((_, i) => i !== index))
      },
      updateCache: ({ patch }) => {
        actions.setConfigKey('cache', patchObject(values.cache, patch))
      },
    }
  }),
])
