  frame: FrameType // frameLogic
  frameForm: Partial<FrameType> // frameLogic
  editedSceneJSON: string | null
  hasChanges: boolean
  hasError: boolean
  scene: FrameScene | null
  sceneJSON: string
  sceneName: string
  scenes: FrameScene[]
