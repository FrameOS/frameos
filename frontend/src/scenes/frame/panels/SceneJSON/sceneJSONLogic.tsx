export type sceneJSONLogicType = MakeLogicType<sceneJSONLogicValues, sceneJSONLogicActions, SceneJSONLogicProps> &
  sceneJSONLogicMeta

export const sceneJSONLogic = kea<sceneJSONLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'SceneJSON', 'sceneJSONLogic']),
  props({} as SceneJSONLogicProps),
  key((props) => `${props.frameId}/${props.sceneId}`),
  connect(({ frameId }: SceneJSONLogicProps) => ({
    values: [frameLogic({ frameId }), ['frame', 'frameForm']],
    actions: [frameLogic({ frameId }), ['updateScene']],
  })),
  actions({
    setEditedSceneJSON: (sceneJSON: string | null) => ({ sceneJSON }),
    saveChanges: true,
  }),
  reducers({
    editedSceneJSON: [
      null as string | null,
      {
        setEditedSceneJSON: (_, { sceneJSON }) => sceneJSON,
      },
    ],
  }),
  selectors({
    scenes: [
      (s) => [s.frame, s.frameForm],
      (frame: sceneJSONLogicValues['frame'], frameForm: sceneJSONLogicValues['frameForm']) =>
        frameForm.scenes ?? frame.scenes ?? [],
    ],
    scene: [
      (s, p) => [s.scenes, p.sceneId],
      (scenes: sceneJSONLogicValues['scenes'], sceneId: string | null): FrameScene | null =>
        scenes?.find((scene) => scene.id === sceneId) ?? null,
    ],
    sceneJSON: [
      (s) => [s.scene, s.editedSceneJSON],
      (scene: sceneJSONLogicValues['scene'], editedSceneJSON: sceneJSONLogicValues['editedSceneJSON']): string => {
        if (editedSceneJSON !== null) {
          return editedSceneJSON
        }
        return printScene(scene)
      },
    ],
    hasChanges: [
      (s) => [s.sceneJSON, s.scene],
      (sceneJSON: sceneJSONLogicValues['sceneJSON'], scene: sceneJSONLogicValues['scene']) =>
        sceneJSON !== printScene(scene),
    ],
    hasError: [
      (s) => [s.sceneJSON],
      (sceneJSON: sceneJSONLogicValues['sceneJSON']) => {
        if (sceneJSON === null) {
          return false
        }
        try {
          JSON.parse(sceneJSON)
          return false
        } catch {
          return true
        }
      },
    ],
    sceneName: [(s) => [s.scene], (scene: sceneJSONLogicValues['scene']) => scene?.name ?? 'Scene'],
  }),
  events(({ actions }) => ({
    afterMount: () => {
      actions.setEditedSceneJSON(null)
    },
  })),
  listeners(({ values, props, actions }) => ({
    saveChanges: async () => {
      try {
        if (!props.sceneId) {
          return
        }
        const { id: _, default: __, name, ...scene } = JSON.parse(values.sceneJSON)
        actions.updateScene(props.sceneId, {
          id: props.sceneId,
          name,
          ...(values.scene?.default ? { default: true } : {}),
          ...scene,
        })
        actions.setEditedSceneJSON(null)
      } catch {
        console.error('Cannot save invalid JSON')
      }
    },
  })),
])
