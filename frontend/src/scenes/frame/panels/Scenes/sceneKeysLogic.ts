import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import type { DeepPartial } from 'kea-forms'

import { appsModel } from '../../../../models/appsModel'
import { framesModel } from '../../../../models/framesModel'
import type { AppConfig, FrameId, FrameOSSettings, FrameScene, FrameType } from '../../../../types'
import { isCloudMode } from '../../../../utils/cloudMode'
import { sceneKeyBindings } from '../../../../utils/sceneKeyBindings'
import {
  DEFAULT_KEY_REF,
  SERVICE_CREDENTIALS_GROUP,
  type SceneKeyBindings,
  credentialsForService,
  keyRefLabel,
  withSceneKeys,
} from '../../../../utils/serviceKeys'
import { settingsLogic } from '../../../settings/settingsLogic'
import { appServiceDefinitionsFromScenes, collectSecretSettingsFromScenes, settingsDetailsFor } from '../secretSettings'
import { frameLogic } from '../../frameLogic'

// "Keys" for one installed scene (docs/service-keys.md "Which key a scene
// gets"): which key of each service the scene's apps declare it gets — the
// default, a named key, or none. The result is the install's `keys`, written
// into the frame form next to the scene like its button map, and saved with
// the frame: the backend keeps it on the installed entry, the cloud on the
// assignment row (cloudFrameScenesSave.ts posts it as `service_keys`).

export interface SceneKeysLogicProps {
  frameId: FrameId
  sceneId: string
}

/** The select's value for a refused service ('' is no valid key ref). */
export const KEY_REFUSED = ''

export interface SceneKeyRow {
  service: string
  title: string
  /** The default key has no value yet. */
  defaultMissing: boolean
  options: { value: string; label: string }[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneKeysLogicValues {
  frame: FrameType // frameLogic
  frameForm: Partial<FrameType> // frameLogic
  apps: Record<string, AppConfig> // appsModel
  savedSettings: FrameOSSettings // settingsLogic
  frames: Record<FrameId, FrameType> // framesModel
  isOpen: boolean
  choices: SceneKeyBindings
  scene: FrameScene | null
  current: SceneKeyBindings
  rows: SceneKeyRow[]
  changed: boolean
  keyChoiceLabels: Record<string, string>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneKeysLogicActions {
  setFrameFormValues: (values: DeepPartial<FrameType>) => { values: DeepPartial<FrameType> } // frameLogic
  openSceneKeys: () => { value: true }
  closeSceneKeys: () => { value: true }
  saveSceneKeys: () => { value: true }
  seedKeyChoices: (choices: SceneKeyBindings) => { choices: SceneKeyBindings }
  setKeyChoice: (service: string, ref: string | null) => { service: string; ref: string | null }
  setSceneKey: (service: string, ref: string | null) => { service: string; ref: string | null }
}

export type sceneKeysLogicType = MakeLogicType<sceneKeysLogicValues, sceneKeysLogicActions, SceneKeysLogicProps>

export const sceneKeysLogic = kea<sceneKeysLogicType>([
  path((key) => ['scenes', 'frame', 'panels', 'Scenes', 'sceneKeysLogic', key]),
  props({} as SceneKeysLogicProps),
  key((props) => `${props.frameId}:${props.sceneId}`),
  connect((props: SceneKeysLogicProps) => ({
    values: [
      frameLogic({ frameId: props.frameId }),
      ['frame', 'frameForm'],
      appsModel,
      ['apps'],
      settingsLogic,
      ['savedSettings'],
      framesModel,
      ['frames'],
    ],
    actions: [frameLogic({ frameId: props.frameId }), ['setFrameFormValues']],
  })),
  actions({
    openSceneKeys: true,
    closeSceneKeys: true,
    saveSceneKeys: true,
    seedKeyChoices: (choices: SceneKeyBindings) => ({ choices }),
    setKeyChoice: (service: string, ref: string | null) => ({ service, ref }),
    /** One choice written into the frame form at once (the store scenes' list in the frame's settings). */
    setSceneKey: (service: string, ref: string | null) => ({ service, ref }),
  }),
  reducers({
    isOpen: [
      false,
      {
        openSceneKeys: () => true,
        closeSceneKeys: () => false,
        saveSceneKeys: () => false,
      },
    ],
    choices: [
      {} as SceneKeyBindings,
      {
        seedKeyChoices: (_, { choices }) => choices,
        setKeyChoice: (state, { service, ref }) => ({ ...state, [service]: ref }),
      },
    ],
  }),
  selectors(({ props }) => ({
    scene: [
      (s) => [s.frameForm, s.frame],
      (frameForm: Partial<FrameType>, frame: FrameType): FrameScene | null =>
        (frameForm?.scenes ?? frame?.scenes ?? []).find((scene) => scene.id === props.sceneId) ?? null,
    ],
    current: [
      (s) => [s.scene, s.apps, s.frame, s.savedSettings, s.frames],
      (
        scene: FrameScene | null,
        apps: Record<string, AppConfig>,
        frame: FrameType,
        savedSettings: FrameOSSettings,
        frames: Record<FrameId, FrameType>
      ): SceneKeyBindings =>
        sceneKeyBindings(
          scene,
          scene ? collectSecretSettingsFromScenes([scene], apps ?? {}) : [],
          frame,
          savedSettings?.[SERVICE_CREDENTIALS_GROUP],
          {
            cloud: isCloudMode(),
            source: frames?.[props.frameId]?.cloud_scene_sources?.[props.sceneId] ?? null,
          }
        ),
    ],
    rows: [
      (s) => [s.current, s.scene, s.apps, s.savedSettings],
      (
        current: SceneKeyBindings,
        scene: FrameScene | null,
        apps: Record<string, AppConfig>,
        savedSettings: FrameOSSettings
      ): SceneKeyRow[] => {
        const definitions = appServiceDefinitionsFromScenes(scene ? [scene] : [], apps ?? {})
        return Object.keys(current).map((service) => {
          const details = settingsDetailsFor(service, definitions, savedSettings?.[service])
          const stored = savedSettings?.[service] as Record<string, unknown> | undefined
          return {
            service,
            title: details.title,
            defaultMissing: details.fields
              .filter((field) => field.secret)
              .some(
                (field) => !(typeof stored?.[field.path[1] as string] === 'string' && stored?.[field.path[1] as string])
              ),
            options: [
              { value: DEFAULT_KEY_REF, label: 'Default key' },
              ...credentialsForService(savedSettings?.[SERVICE_CREDENTIALS_GROUP], service).map((credential) => ({
                value: credential.id,
                label: credential.name,
              })),
              { value: KEY_REFUSED, label: "Don't give a key" },
            ],
          }
        })
      },
    ],
    // What the scene's tags add per service: a named key's name, or that it
    // gets none; nothing for the default ("uses OpenAI key" says that).
    keyChoiceLabels: [
      (s) => [s.current, s.savedSettings],
      (current: SceneKeyBindings, savedSettings: FrameOSSettings): Record<string, string> => {
        const labels: Record<string, string> = {}
        for (const [service, ref] of Object.entries(current)) {
          if (ref === null) {
            labels[service] = 'not given'
          } else if (ref !== DEFAULT_KEY_REF) {
            labels[service] = keyRefLabel(ref, savedSettings?.[SERVICE_CREDENTIALS_GROUP])
          }
        }
        return labels
      },
    ],
    changed: [
      (s) => [s.choices, s.current],
      (choices: SceneKeyBindings, current: SceneKeyBindings): boolean =>
        Object.keys(current).some((service) => (choices[service] ?? null) !== (current[service] ?? null)),
    ],
  })),
  listeners(({ actions, values, props }) => ({
    openSceneKeys: () => {
      actions.seedKeyChoices({ ...values.current })
    },
    setSceneKey: ({ service, ref }) => {
      actions.seedKeyChoices({ ...values.current, [service]: ref })
      actions.saveSceneKeys()
    },
    saveSceneKeys: () => {
      const scenes = values.frameForm?.scenes ?? values.frame?.scenes ?? []
      if (!scenes.some((scene) => scene.id === props.sceneId)) {
        return
      }
      // Every declared service is written, so the choice is the install's
      // from now on and no older grant answers for it.
      const keys: SceneKeyBindings = {}
      for (const service of Object.keys(values.current)) {
        keys[service] = values.choices[service] ?? null
      }
      actions.setFrameFormValues({
        scenes: scenes.map((scene) => (scene.id === props.sceneId ? withSceneKeys(scene, keys) : scene)),
      })
    },
  })),
])
