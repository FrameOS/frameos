import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import type { DeepPartial } from 'kea-forms'

import type { EventMapRule, FrameId, FrameScene, FrameType, GPIOButton } from '../../../../types'
import { frameLogic } from '../../frameLogic'
import {
  type ButtonGesture,
  type ButtonListener,
  buttonGestures,
  buttonMapChoices,
  buttonMapConflicts,
  buttonMapRules,
  frameButtons,
  sceneButtonListeners,
  withSceneEventMap,
} from '../../../../utils/sceneEventMap'

// "Map buttons" for one installed scene (docs/events.md, "Event map"): which
// press of which of the frame's buttons each `button` listener of the scene
// answers to. The result is the scene's `eventMap`, written into the frame
// form next to the scene like a rename is, and saved with the frame: the
// backend keeps it on the installed entry, the cloud on the assignment row
// (cloudFrameScenesSave.ts posts it as `event_maps`), and a scene update
// keeps it on both.

export interface ButtonMapLogicProps {
  frameId: FrameId
  sceneId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface buttonMapLogicValues {
  frame: FrameType // frameLogic
  frameForm: Partial<FrameType> // frameLogic
  buttons: GPIOButton[]
  changed: boolean
  choices: Record<string, string>
  conflicts: string[]
  custom: EventMapRule[]
  gestures: ButtonGesture[]
  isOpen: boolean
  listeners: ButtonListener[]
  rules: EventMapRule[]
  scene: FrameScene | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface buttonMapLogicActions {
  setFrameFormValues: (values: DeepPartial<FrameType>) => {
    values: DeepPartial<FrameType>
  } // frameLogic
  closeButtonMap: () => {
    value: true
  }
  openButtonMap: () => {
    value: true
  }
  saveButtonMap: () => {
    value: true
  }
  seedChoices: (
    choices: Record<string, string>,
    custom: EventMapRule[]
  ) => {
    choices: Record<string, string>
    custom: EventMapRule[]
  }
  setChoice: (
    listenerKey: string,
    value: string
  ) => {
    listenerKey: string
    value: string
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface buttonMapLogicMeta {
  key: string
  __keaTypeGenInternalSelectorTypes: {
    scene: (frameForm: Partial<FrameType>, frame: FrameType) => FrameScene | null
    buttons: (frame: FrameType, frameForm: Partial<FrameType>) => GPIOButton[]
    listeners: (scene: FrameScene | null) => ButtonListener[]
    gestures: (buttons: GPIOButton[]) => ButtonGesture[]
    conflicts: (listeners: ButtonListener[], choices: Record<string, string>) => string[]
    rules: (listeners: ButtonListener[], choices: Record<string, string>, custom: EventMapRule[]) => EventMapRule[]
    changed: (rules: EventMapRule[], scene: FrameScene | null) => boolean
  }
}

export type buttonMapLogicType = MakeLogicType<buttonMapLogicValues, buttonMapLogicActions, ButtonMapLogicProps> &
  buttonMapLogicMeta

export const buttonMapLogic = kea<buttonMapLogicType>([
  path((key) => ['scenes', 'frame', 'panels', 'Scenes', 'buttonMapLogic', key]),
  props({} as ButtonMapLogicProps),
  key((props) => `${props.frameId}:${props.sceneId}`),
  connect((props: ButtonMapLogicProps) => ({
    values: [frameLogic({ frameId: props.frameId }), ['frame', 'frameForm']],
    actions: [frameLogic({ frameId: props.frameId }), ['setFrameFormValues']],
  })),
  actions({
    openButtonMap: true,
    closeButtonMap: true,
    setChoice: (listenerKey: string, value: string) => ({ listenerKey, value }),
    seedChoices: (choices: Record<string, string>, custom: EventMapRule[]) => ({ choices, custom }),
    saveButtonMap: true,
  }),
  reducers({
    isOpen: [
      false,
      {
        openButtonMap: () => true,
        closeButtonMap: () => false,
        saveButtonMap: () => false,
      },
    ],
    // Listener key → the chosen gesture's value ('' = as is).
    choices: [
      {} as Record<string, string>,
      {
        seedChoices: (_, { choices }) => choices,
        setChoice: (state, { listenerKey, value }) => {
          const next = { ...state }
          if (value) {
            next[listenerKey] = value
          } else {
            delete next[listenerKey]
          }
          return next
        },
      },
    ],
    // Rules the dialog does not draw (hand-written, or for another event):
    // kept exactly as they were.
    custom: [
      [] as EventMapRule[],
      {
        seedChoices: (_, { custom }) => custom,
      },
    ],
  }),
  selectors(({ props }) => ({
    scene: [
      (s) => [s.frameForm, s.frame],
      (frameForm: buttonMapLogicValues['frameForm'], frame: buttonMapLogicValues['frame']): FrameScene | null =>
        (frameForm?.scenes ?? frame?.scenes ?? []).find((scene) => scene.id === props.sceneId) ?? null,
    ],
    buttons: [
      (s) => [s.frame, s.frameForm],
      (frame: buttonMapLogicValues['frame'], frameForm: buttonMapLogicValues['frameForm']): GPIOButton[] =>
        frameButtons(frame, frameForm),
    ],
    listeners: [
      (s) => [s.scene],
      (scene: buttonMapLogicValues['scene']): ButtonListener[] => sceneButtonListeners(scene),
    ],
    gestures: [
      (s) => [s.buttons],
      (buttons: buttonMapLogicValues['buttons']): ButtonGesture[] => buttonGestures(buttons),
    ],
    conflicts: [
      (s) => [s.listeners, s.choices],
      (listeners: buttonMapLogicValues['listeners'], choices: buttonMapLogicValues['choices']): string[] =>
        buttonMapConflicts(listeners, choices),
    ],
    rules: [
      (s) => [s.listeners, s.choices, s.custom],
      (
        listeners: buttonMapLogicValues['listeners'],
        choices: buttonMapLogicValues['choices'],
        custom: buttonMapLogicValues['custom']
      ): EventMapRule[] => buttonMapRules(listeners, choices, custom),
    ],
    changed: [
      (s) => [s.rules, s.scene],
      (rules: buttonMapLogicValues['rules'], scene: buttonMapLogicValues['scene']): boolean =>
        JSON.stringify(rules) !== JSON.stringify(scene?.eventMap ?? []),
    ],
  })),
  listeners(({ actions, values, props }) => ({
    openButtonMap: () => {
      const { choices, custom } = buttonMapChoices(values.scene?.eventMap, values.listeners)
      actions.seedChoices(choices, custom)
    },
    saveButtonMap: () => {
      const scenes = values.frameForm?.scenes ?? values.frame?.scenes ?? []
      if (!scenes.some((scene) => scene.id === props.sceneId)) {
        return
      }
      actions.setFrameFormValues({
        scenes: scenes.map((scene) => (scene.id === props.sceneId ? withSceneEventMap(scene, values.rules) : scene)),
      })
    },
  })),
])
