import { MakeLogicType, actions, kea, listeners, path, reducers } from 'kea'

import type { AppConfig, FrameScene } from '../../../../types'
import {
  PreviewKeyConsentAnswer,
  PreviewKeyConsentRequest,
  PreviewKeyDecision,
  previewKeyGroupsRemembered,
  previewKeyGroupsToAsk,
  readRememberedPreviewKeyDecisions,
  rememberPreviewKeyDecisions,
  settingsWithoutGroups,
} from './previewKeyConsent'

// One dialog for the whole app (PreviewKeyConsentModal, mounted by App). A
// preview that needs an answer parks its request here and awaits it; the
// modal answers through the actions below. Without a mounted host (an embed
// that never mounted the modal) the gate does not block: it answers "allow",
// which is what every preview did before the gate existed.

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface previewKeyConsentLogicValues {
  hosts: number
  pending: PreviewKeyConsentRequest | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface previewKeyConsentLogicActions {
  answer: (
    decision: PreviewKeyDecision,
    remember: string[]
  ) => {
    decision: PreviewKeyDecision
    remember: string[]
  }
  cancel: () => {
    value: true
  }
  hostMounted: () => {
    value: true
  }
  hostUnmounted: () => {
    value: true
  }
  open: (request: PreviewKeyConsentRequest) => {
    request: PreviewKeyConsentRequest
  }
}

export type previewKeyConsentLogicType = MakeLogicType<previewKeyConsentLogicValues, previewKeyConsentLogicActions>

type Resolver = (answer: PreviewKeyConsentAnswer | null) => void
let resolver: Resolver | null = null

export const previewKeyConsentLogic = kea<previewKeyConsentLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'Scenes', 'previewKeyConsentLogic']),
  actions({
    open: (request: PreviewKeyConsentRequest) => ({ request }),
    answer: (decision: PreviewKeyDecision, remember: string[]) => ({ decision, remember }),
    cancel: true,
    hostMounted: true,
    hostUnmounted: true,
  }),
  reducers({
    pending: [
      null as PreviewKeyConsentRequest | null,
      {
        open: (_, { request }) => request,
        answer: () => null,
        cancel: () => null,
      },
    ],
    hosts: [
      0,
      {
        hostMounted: (state) => state + 1,
        hostUnmounted: (state) => Math.max(0, state - 1),
      },
    ],
  }),
  listeners(() => ({
    answer: ({ decision, remember }) => {
      const resolve = resolver
      resolver = null
      resolve?.({ decision, remember })
    },
    cancel: () => {
      const resolve = resolver
      resolver = null
      resolve?.(null)
    },
  })),
])

/** Ask the user; null means they cancelled the preview. */
export function requestPreviewKeyConsent(request: PreviewKeyConsentRequest): Promise<PreviewKeyConsentAnswer | null> {
  if (!previewKeyConsentLogic.findMounted()) {
    previewKeyConsentLogic.mount()
  }
  const logic = previewKeyConsentLogic
  if (logic.values.hosts === 0) {
    return Promise.resolve({ decision: 'allow', remember: [] })
  }
  // A second request while one is open replaces it: the first preview gets
  // "cancelled" rather than hanging on a dialog that no longer shows it.
  resolver?.(null)
  return new Promise<PreviewKeyConsentAnswer | null>((resolve) => {
    resolver = resolve
    logic.actions.open(request)
  })
}

export interface GatedPreviewSettings<T extends Record<string, unknown>> {
  /** The settings to hand the preview, or null when the user cancelled. */
  settings: T | null
  /** Groups kept out of this preview (denied now or remembered). */
  withheld: string[]
}

/**
 * The gate every browser preview goes through once it has fetched settings:
 * remembered answers apply silently, the rest asks. Owner-authored scenes
 * never ask (`treatAllAsStore` marks a store template preview whose scenes
 * are not stamped yet).
 */
export async function gatePreviewSettings<T extends Record<string, unknown>>(
  scenes: FrameScene[],
  apps: Record<string, AppConfig>,
  settings: T,
  treatAllAsStore = false
): Promise<GatedPreviewSettings<T>> {
  let remembered = readRememberedPreviewKeyDecisions()
  const toAsk = previewKeyGroupsToAsk(scenes, apps, settings, remembered, treatAllAsStore)
  let deniedNow: string[] = []
  if (toAsk.length > 0) {
    const answer = await requestPreviewKeyConsent({
      sceneNames: (treatAllAsStore ? scenes : scenes.filter((scene) => scene.origin?.storeSceneId)).map(
        (scene) => scene.name || scene.id
      ),
      groups: toAsk,
    })
    if (!answer) {
      return { settings: null, withheld: [] }
    }
    if (answer.remember.length) {
      remembered = rememberPreviewKeyDecisions(answer)
    }
    if (answer.decision === 'deny') {
      deniedNow = toAsk
    }
  }
  const { denied } = previewKeyGroupsRemembered(scenes, apps, remembered, treatAllAsStore)
  const withheld = Array.from(new Set([...deniedNow, ...denied])).sort()
  return { settings: settingsWithoutGroups(settings, withheld), withheld }
}
