export type SceneUpdateDeployKind = 'deploy' | 'fast' | 'full'

/** The backend's key for a template's copies (sceneOrigin's matching). */
function templateUpdateKey(repository: RepositoryType, template: TemplateType): string {
  return `${repository.id ?? repository.url}::${template.id ?? template.name}`
}

// The install's own bookkeeping, which a store version never carries: kept
// over the new version so the diff shows what the update changes and no more.
function withInstallBookkeeping(scene: FrameScene, installed: FrameScene | undefined): FrameScene {
  if (!installed) {
    return scene
  }
  return {
    ...scene,
    ...(installed.eventMap ? { eventMap: installed.eventMap } : {}),
    ...(installed.layout ? { layout: installed.layout } : {}),
  }
}

