// How old the catalogs may be before a surface showing scenes asks again. The
// models load once at mount, and a workspace tab stays open for days; without
// this a new version only showed after a reload. (The backend itself re-reads
// a repository at most once a day; the cloud lists its assignments every
// minute and needs no catalog at all.)
const CATALOG_MAX_AGE_MS = 15 * 60 * 1000

