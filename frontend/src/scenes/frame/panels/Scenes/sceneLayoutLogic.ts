import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import type { DeepPartial } from 'kea-forms'

import type { FrameId, FrameScene, FrameType, SceneLayoutRef, StateField } from '../../../../types'
import { sceneStateFields } from '../../../../utils/refreshInterval'
import {
  currentSceneLayout,
  isLayoutScene,
  layoutScenes,
  sceneLayoutRef,
  withSceneLayout,
} from '../../../../utils/sceneLayouts'
import { visiblePublicStateFields } from '../../../../utils/showIf'
import { frameLogic } from '../../frameLogic'

// Which layout one installed scene wears, and the layout's settings for it
// (docs/scene-layouts.md). The result is the scene's `layout`, written into
// the frame form next to the scene like a rename is and saved with the frame:
// the backend keeps it on the installed entry, the cloud on the assignment
// row (cloudFrameScenesSave.ts posts it as `layouts`).

export interface SceneLayoutLogicProps {
  frameId: FrameId
  sceneId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneLayoutLogicValues {
  frame: FrameType // frameLogic
  frameForm: Partial<FrameType> // frameLogic
  current: SceneLayoutRef | null
  currentLayoutScene: FrameScene | null
  draftState: Record<string, any>
  fields: StateField[]
  layouts: FrameScene[]
  pickerVisible: boolean
  scene: FrameScene | null
  scenes: FrameScene[]
  settingsForEveryScene: boolean
  settingsOpen: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneLayoutLogicActions {
  setFrameFormValues: (values: DeepPartial<FrameType>) => {
    values: DeepPartial<FrameType>
  } // frameLogic
  chooseLayout: (layoutSceneId: string) => {
    layoutSceneId: string
  }
  closeLayoutSettings: () => {
    value: true
  }
  openLayoutSettings: (everyScene?: boolean) => {
    everyScene: boolean
  }
  saveLayoutSettings: () => {
    value: true
  }
  seedState: (state: Record<string, any>) => {
    state: Record<string, any>
  }
  setStateValue: (
    field: StateField,
    value: any
  ) => {
    field: StateField
    value: any
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneLayoutLogicMeta {
  key: string
  __keaTypeGenInternalSelectorTypes: {
    scenes: (frameForm: Partial<FrameType>, frame: FrameType) => FrameScene[]
    scene: (scenes: FrameScene[]) => FrameScene | null
    layouts: (scenes: FrameScene[]) => FrameScene[]
    pickerVisible: (scene: FrameScene | null, layouts: FrameScene[]) => boolean
    current: (scene: FrameScene | null, layouts: FrameScene[]) => SceneLayoutRef | null
    currentLayoutScene: (current: SceneLayoutRef | null, layouts: FrameScene[]) => FrameScene | null
    fields: (currentLayoutScene: FrameScene | null, draftState: Record<string, any>) => StateField[]
  }
}

export type sceneLayoutLogicType = MakeLogicType<
  sceneLayoutLogicValues,
  sceneLayoutLogicActions,
  SceneLayoutLogicProps
> &
  sceneLayoutLogicMeta

export const sceneLayoutLogic = kea<sceneLayoutLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'Scenes', 'sceneLayoutLogic']),
  props({} as SceneLayoutLogicProps),
  key((props) => `${props.frameId}-${props.sceneId}`),
  connect(({ frameId }: SceneLayoutLogicProps) => ({
    values: [frameLogic({ frameId }), ['frame', 'frameForm']],
    actions: [frameLogic({ frameId }), ['setFrameFormValues']],
  })),
  actions({
    chooseLayout: (layoutSceneId: string) => ({ layoutSceneId }),
    /** `everyScene`: Apply writes the settings to every scene wearing this layout, not this one alone. */
    openLayoutSettings: (everyScene: boolean = false) => ({ everyScene }),
    closeLayoutSettings: true,
    setStateValue: (field: StateField, value: any) => ({ field, value }),
    seedState: (state: Record<string, any>) => ({ state }),
    saveLayoutSettings: true,
  }),
  reducers({
    settingsOpen: [
      false,
      {
        openLayoutSettings: () => true,
        closeLayoutSettings: () => false,
        saveLayoutSettings: () => false,
      },
    ],
    settingsForEveryScene: [
      false,
      {
        openLayoutSettings: (_, { everyScene }) => everyScene,
      },
    ],
    draftState: [
      {} as Record<string, any>,
      {
        seedState: (_, { state }) => state,
        setStateValue: (state, { field, value }) => ({ ...state, [field.name]: value }),
      },
    ],
  }),
  selectors(({ props }) => ({
    scenes: [
      (s) => [s.frameForm, s.frame],
      (frameForm: Partial<FrameType>, frame: FrameType): FrameScene[] => frameForm?.scenes ?? frame?.scenes ?? [],
    ],
    scene: [
      (s) => [s.scenes],
      (scenes: FrameScene[]): FrameScene | null => scenes.find((scene) => scene.id === props.sceneId) ?? null,
    ],
    layouts: [(s) => [s.scenes], (scenes: FrameScene[]): FrameScene[] => layoutScenes(scenes)],
    /** A layout cannot wear a layout, and a frame without any has nothing to pick. */
    pickerVisible: [
      (s) => [s.scene, s.layouts],
      (scene: FrameScene | null, layouts: FrameScene[]): boolean =>
        !!scene && !isLayoutScene(scene) && layouts.length > 0,
    ],
    current: [
      (s) => [s.scene, s.layouts],
      (scene: FrameScene | null, layouts: FrameScene[]): SceneLayoutRef | null => currentSceneLayout(scene, layouts),
    ],
    currentLayoutScene: [
      (s) => [s.current, s.layouts],
      (current: SceneLayoutRef | null, layouts: FrameScene[]): FrameScene | null =>
        layouts.find((layout) => layout.id === current?.sceneId) ?? null,
    ],
    fields: [
      (s) => [s.currentLayoutScene, s.draftState],
      (layout: FrameScene | null, draftState: Record<string, any>): StateField[] =>
        layout ? visiblePublicStateFields(sceneStateFields(layout), draftState) : [],
    ],
  })),
  listeners(({ actions, values, props }) => ({
    chooseLayout: ({ layoutSceneId }) => {
      const scenes: FrameScene[] = values.scenes
      actions.setFrameFormValues({
        scenes: scenes.map((scene) =>
          scene.id === props.sceneId
            ? withSceneLayout(
                scene,
                layoutSceneId
                  ? {
                      sceneId: layoutSceneId,
                      // The settings stay while it is the same layout.
                      ...(values.current?.sceneId === layoutSceneId && values.current?.state
                        ? { state: values.current.state }
                        : {}),
                    }
                  : null
              )
            : scene
        ),
      } as DeepPartial<FrameType>)
    },
    openLayoutSettings: () => {
      actions.seedState({ ...(values.current?.state ?? {}) })
    },
    saveLayoutSettings: () => {
      const current: SceneLayoutRef | null = values.current
      if (!current) {
        return
      }
      const scenes: FrameScene[] = values.scenes
      actions.setFrameFormValues({
        scenes: scenes.map((scene) =>
          scene.id === props.sceneId ||
          (values.settingsForEveryScene && sceneLayoutRef(scene.layout)?.sceneId === current.sceneId)
            ? withSceneLayout(scene, { sceneId: current.sceneId, state: values.draftState })
            : scene
        ),
      } as DeepPartial<FrameType>)
    },
  })),
])
