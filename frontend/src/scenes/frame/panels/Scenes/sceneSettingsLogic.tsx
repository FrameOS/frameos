import { MakeLogicType, connect, kea, key, path, props, selectors } from 'kea'
import { frameLogic } from '../../frameLogic'
import { FrameScene, FrameId } from '../../../../types'
import type { FrameType } from '../../../../types'
import type { Option } from '../../../../components/Select'
import {
  ASSET_ACCESS_VALUES,
  SceneAccess,
  assetAccessLabels,
  assetAccessRefusesContent,
  sceneAccess,
  sceneAccessFlagLabels,
  sceneAccessFlagsForScene,
  sceneHomeFolder,
} from '../../../../utils/sceneAccess'

export interface SceneSettingsLogicProps {
  frameId: FrameId
  sceneId: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneSettingsLogicValues {
  frame: FrameType // frameLogic
  frameForm: Partial<FrameType> // frameLogic
  assetAccessNote: string | null
  assetAccessOptions: Option[]
  scene: FrameScene | null
  sceneAccess: SceneAccess | null
  sceneIndex: number
  scenes: FrameScene[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneSettingsLogicMeta {
  key: string
  __keaTypeGenInternalSelectorTypes: {
    scenes: (frame: FrameType, frameForm: Partial<FrameType>) => FrameScene[]
    scene: (scenes: FrameScene[], sceneId: string | null) => FrameScene | null
    sceneIndex: (scenes: FrameScene[], sceneId: string | null) => number
    sceneAccess: (scene: FrameScene | null) => SceneAccess | null
    assetAccessOptions: (scene: FrameScene | null) => Option[]
    assetAccessNote: (sceneAccess: SceneAccess | null) => string | null
  }
}

export type sceneSettingsLogicType = MakeLogicType<sceneSettingsLogicValues, {}, SceneSettingsLogicProps> &
  sceneSettingsLogicMeta

export const sceneSettingsLogic = kea<sceneSettingsLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'Scenes', 'sceneSettingsLogic']),
  props({} as SceneSettingsLogicProps),
  key((props) => `${props.frameId}-${props.sceneId}`),
  connect(({ frameId }: SceneSettingsLogicProps) => ({
    values: [frameLogic({ frameId }), ['frame', 'frameForm']],
  })),
  selectors({
    scenes: [
      (s) => [s.frame, s.frameForm],
      (frame: sceneSettingsLogicValues['frame'], frameForm: sceneSettingsLogicValues['frameForm']) =>
        frameForm.scenes ?? frame.scenes ?? [],
    ],
    scene: [
      (s, p) => [s.scenes, p.sceneId],
      (scenes: sceneSettingsLogicValues['scenes'], sceneId: string | null): FrameScene | null =>
        scenes?.find((scene) => scene.id === sceneId) ?? null,
    ],
    sceneIndex: [
      (s, p) => [s.scenes, p.sceneId],
      (scenes: sceneSettingsLogicValues['scenes'], sceneId: string | null): number =>
        scenes?.findIndex((scene) => scene.id === sceneId) ?? 0,
    ],
    // What the scene declares (settings.assetAccess) and what its content
    // reaches for (utils/sceneAccess.ts), recomputed as the scene is edited.
    sceneAccess: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): SceneAccess | null => (scene ? sceneAccess(scene) : null),
    ],
    assetAccessOptions: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): Option[] => {
        // What "auto" comes to: the flags the content shows with nothing
        // declared, reading and writing alike (shell has its own chip).
        const auto = scene
          ? sceneAccessFlagsForScene({ ...scene, settings: { ...scene.settings, assetAccess: 'auto' } })
              .filter((flag) => flag !== 'shell')
              .map((flag) => sceneAccessFlagLabels[flag])
          : []
        return ASSET_ACCESS_VALUES.map((value) => ({
          value,
          label:
            value === 'auto'
              ? `Auto (${auto.length > 0 ? auto.join(', ') : 'no files'})`
              : value === 'cache-home-only'
              ? `${assetAccessLabels[value]} (assets/${sceneHomeFolder(scene?.id ?? '')})`
              : assetAccessLabels[value],
        }))
      },
    ],
    assetAccessNote: [
      (s) => [s.sceneAccess],
      (access: sceneSettingsLogicValues['sceneAccess']): string | null => {
        if (!access || access.reasons.length === 0) {
          return null
        }
        const found = access.reasons.join('; ')
        return assetAccessRefusesContent(access)
          ? `The frame will refuse part of this scene: ${found}.`
          : `Found in this scene: ${found}.`
      },
    ],
  }),
])
