export type sceneSettingsLogicType = MakeLogicType<
  sceneSettingsLogicValues,
  sceneSettingsLogicActions,
  SceneSettingsLogicProps
> &
  sceneSettingsLogicMeta

export const sceneSettingsLogic = kea<sceneSettingsLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'Scenes', 'sceneSettingsLogic']),
  props({} as SceneSettingsLogicProps),
  key((props) => `${props.frameId}-${props.sceneId}`),
  connect(({ frameId }: SceneSettingsLogicProps) => ({
    values: [frameLogic({ frameId }), ['frame', 'frameForm']],
    actions: [frameLogic({ frameId }), ['updateScene', 'setFrameFormValue']],
  })),
  actions({
    /** An .svg file picked in the Icon area: made into one path (utils/svgToSceneIcon.ts). */
    uploadIcon: (file: File) => ({ file }),
    setIcon: (icon: string | null) => ({ icon }),
    setIconUploadError: (error: string | null) => ({ error }),
  }),
  reducers({
    // Why the last upload was refused, until the icon changes another way.
    iconUploadError: [
      null as string | null,
      {
        setIconUploadError: (_, { error }) => error,
        setIcon: () => null,
        setFrameFormValue: () => null,
      },
    ],
  }),
  selectors({
    scenes: [
      (s) => [s.frame, s.frameForm],
      (frame: sceneSettingsLogicValues['frame'], frameForm: sceneSettingsLogicValues['frameForm']) =>
        frameForm.scenes ?? frame.scenes ?? [],
    ],
    scene: [
      (s, p) => [s.scenes, p.sceneId],
      (scenes: sceneSettingsLogicValues['scenes'], sceneId: string | null): FrameScene | null =>
        scenes?.find((scene) => scene.id === sceneId) ?? null,
    ],
    sceneIndex: [
      (s, p) => [s.scenes, p.sceneId],
      (scenes: sceneSettingsLogicValues['scenes'], sceneId: string | null): number =>
        scenes?.findIndex((scene) => scene.id === sceneId) ?? 0,
    ],
    // A generated split's interval is the fastest it renders: it waits longer
    // when none of its panels is due by then (utils/sceneRhythm.ts). Null for
    // every other scene.
    splitRhythm: [
      (s) => [s.scene, s.scenes, s.frameForm],
      (
        scene: sceneSettingsLogicValues['scene'],
        scenes: sceneSettingsLogicValues['scenes'],
        frameForm: sceneSettingsLogicValues['frameForm']
      ): string | null =>
        splitSceneRhythmHint(
          scene,
          scenes,
          DEFAULT_REFRESH_INTERVAL_SECONDS,
          framePacedByInterval(frameForm as FrameType)
        ),
    ],
    pacedByInterval: [
      (s) => [s.frameForm],
      (frameForm: sceneSettingsLogicValues['frameForm']): boolean => framePacedByInterval(frameForm as FrameType),
    ],
    // What the scene's apps ask for (utils/sceneAccess.ts), recomputed as the
    // scene is edited.
    sceneAccess: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): SceneAccess | null => (scene ? sceneAccess(scene) : null),
    ],
    permissionRows: [
      (s) => [s.sceneAccess],
      (access: sceneSettingsLogicValues['sceneAccess']): ScenePermissionRow[] => {
        // Every app's own asks, nothing folded: unlike the tags, an app that
        // reads the assets folder is listed even when another reads all files.
        const askers = new Map<SceneAccessFlag, string[]>()
        const ask = (flag: SceneAccessFlag, name: string): void => {
          const names = askers.get(flag) ?? []
          if (!names.includes(name)) {
            askers.set(flag, [...names, name])
          }
        }
        for (const app of access?.apps ?? []) {
          for (const permission of app.permissions) {
            ask(permission, app.name)
          }
          for (const namespace of app.settings) {
            ask(`key:${namespace}`, app.name)
          }
        }
        if (access?.legacyShell) {
          ask('shell', 'a Nim code node')
        }
        const order = [...SCENE_PERMISSIONS, ...knownSceneAccessFlags([...askers.keys()])]
        return [...new Set(order)]
          .filter((flag) => askers.has(flag))
          .map((flag) => ({ flag, askedBy: askers.get(flag) ?? [] }))
      },
    ],
    // The Scale select: the frame's, then the steps (and the scene's own
    // value if it is none of them).
    /** Why this scene cannot be a layout, null when it can (docs/scene-layouts.md). */
    layoutProblem: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): string | null => sceneLayoutProblemText(scene),
    ],
    renderScaleOptions: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): RenderScaleOption[] =>
        sceneRenderScaleOptions(scene?.settings?.renderScale),
    ],
    // The Window size select: the default, then the presets (and the scene's
    // own size if it is none of them). utils/sceneWindowSize.ts.
    windowSizeOptions: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): WindowSizeOption[] =>
        sceneWindowSizeOptions(scene?.settings?.windowSize),
    ],
    // The Category select: None, the store's category titles for a scene (the
    // layout ones for a layout), and a name of the scene's own kept as it is.
    categoryOptions: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): SceneCategoryOption[] =>
        sceneCategoryOptions(scene?.settings?.category, !!scene?.settings?.isLayout),
    ],
    // The scene's icon as the frame reads it (utils/sceneIcon.ts): null when it
    // has none or what it has is no icon, which iconProblem then explains.
    iconPath: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): string | null => sceneIconPath(scene?.settings?.icon),
    ],
    iconProblem: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): string | null => sceneIconProblem(scene?.settings?.icon),
    ],
    // The state field with role renderScale, whose value wins over the
    // setting on the frame (utils/renderScale.ts); null when there is none.
    renderScaleFieldName: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): string | null => {
        const index = renderScaleFieldIndex(scene?.fields)
        return index >= 0 ? scene?.fields?.[index]?.name || null : null
      },
    ],
    permissionApps: [
      (s) => [s.sceneAccess],
      (access: sceneSettingsLogicValues['sceneAccess']): ScenePermissionApp[] =>
        (access?.apps ?? [])
          .filter((app) => app.kind === 'scene')
          .map((app) => {
            const shortfall = appPermissionShortfall(app)
            return {
              name: app.name,
              source:
                app.declared === null
                  ? 'no list yet'
                  : app.declared.join() === app.detected.join()
                    ? 'from its code'
                    : 'updates on the next save',
              warning:
                shortfall.length > 0
                  ? `${app.reasons.join(' and ')} but does not ask for ${shortfall
                      .map((permission) => sceneAccessFlagLabel(permission))
                      .join(' or ')}; the frame refuses it.`
                  : null,
            }
          }),
    ],
  }),
  listeners(({ actions, values, props }) => ({
    uploadIcon: async ({ file }) => {
      let text: string
      try {
        text = await file.text()
      } catch {
        actions.setIconUploadError('That file could not be read.')
        return
      }
      const result = svgToSceneIcon(text)
      if (result.ok) {
        actions.setIcon(result.icon)
      } else {
        actions.setIconUploadError(result.error)
      }
    },
    // Through updateScene, so it lands like any edit of the scene; null drops the key.
    setIcon: ({ icon }) => {
      const scene = values.scene
      if (!scene || !props.sceneId) {
        return
      }
      const { icon: _previous, ...settings } = scene.settings ?? {}
      actions.updateScene(props.sceneId, { settings: icon ? { ...settings, icon } : settings })
    },
  })),
])
