import { MakeLogicType, connect, kea, key, path, props, selectors } from 'kea'
import { frameLogic } from '../../frameLogic'
import { FrameScene, FrameId } from '../../../../types'
import type { FrameType } from '../../../../types'
import {
  SCENE_PERMISSIONS,
  SceneAccess,
  SceneAccessFlag,
  appPermissionShortfall,
  knownSceneAccessFlags,
  sceneAccess,
  sceneAccessFlagLabel,
} from '../../../../utils/sceneAccess'
import { splitSceneRhythmHint } from '../../../../utils/sceneRhythm'
import { renderScaleFieldIndex, sceneRenderScaleOptions, type RenderScaleOption } from '../../../../utils/renderScale'

export interface SceneSettingsLogicProps {
  frameId: FrameId
  sceneId: string | null
}

/** One tag of the scene and the apps that ask for it. */
export interface ScenePermissionRow {
  flag: SceneAccessFlag
  /** The apps (or "a Nim code node") asking for it, by name. */
  askedBy: string[]
}

/** One JavaScript app of the scene: where its list comes from, and what the frame refuses. */
export interface ScenePermissionApp {
  name: string
  /** "from its code", "updates on the next save" or "no list yet". */
  source: string
  /** The calls its list does not cover (the frame refuses them), or null. */
  warning: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneSettingsLogicValues {
  frame: FrameType // frameLogic
  frameForm: Partial<FrameType> // frameLogic
  permissionApps: ScenePermissionApp[]
  permissionRows: ScenePermissionRow[]
  renderScaleFieldName: string | null
  renderScaleOptions: RenderScaleOption[]
  scene: FrameScene | null
  sceneAccess: SceneAccess | null
  sceneIndex: number
  scenes: FrameScene[]
  splitRhythm: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneSettingsLogicMeta {
  key: string
  __keaTypeGenInternalSelectorTypes: {
    scenes: (frame: FrameType, frameForm: Partial<FrameType>) => FrameScene[]
    scene: (scenes: FrameScene[], sceneId: string | null) => FrameScene | null
    sceneIndex: (scenes: FrameScene[], sceneId: string | null) => number
    splitRhythm: (scene: FrameScene | null, scenes: FrameScene[], frameForm: Partial<FrameType>) => string | null
    sceneAccess: (scene: FrameScene | null) => SceneAccess | null
    permissionRows: (sceneAccess: SceneAccess | null) => ScenePermissionRow[]
    renderScaleOptions: (scene: FrameScene | null) => RenderScaleOption[]
    renderScaleFieldName: (scene: FrameScene | null) => string | null
    permissionApps: (sceneAccess: SceneAccess | null) => ScenePermissionApp[]
  }
}

export type sceneSettingsLogicType = MakeLogicType<sceneSettingsLogicValues, {}, SceneSettingsLogicProps> &
  sceneSettingsLogicMeta

export const sceneSettingsLogic = kea<sceneSettingsLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'Scenes', 'sceneSettingsLogic']),
  props({} as SceneSettingsLogicProps),
  key((props) => `${props.frameId}-${props.sceneId}`),
  connect(({ frameId }: SceneSettingsLogicProps) => ({
    values: [frameLogic({ frameId }), ['frame', 'frameForm']],
  })),
  selectors({
    scenes: [
      (s) => [s.frame, s.frameForm],
      (frame: sceneSettingsLogicValues['frame'], frameForm: sceneSettingsLogicValues['frameForm']) =>
        frameForm.scenes ?? frame.scenes ?? [],
    ],
    scene: [
      (s, p) => [s.scenes, p.sceneId],
      (scenes: sceneSettingsLogicValues['scenes'], sceneId: string | null): FrameScene | null =>
        scenes?.find((scene) => scene.id === sceneId) ?? null,
    ],
    sceneIndex: [
      (s, p) => [s.scenes, p.sceneId],
      (scenes: sceneSettingsLogicValues['scenes'], sceneId: string | null): number =>
        scenes?.findIndex((scene) => scene.id === sceneId) ?? 0,
    ],
    // A generated split's interval is the fastest it renders: it waits longer
    // when none of its panels is due by then (utils/sceneRhythm.ts). Null for
    // every other scene.
    splitRhythm: [
      (s) => [s.scene, s.scenes, s.frameForm],
      (
        scene: sceneSettingsLogicValues['scene'],
        scenes: sceneSettingsLogicValues['scenes'],
        frameForm: sceneSettingsLogicValues['frameForm']
      ): string | null => splitSceneRhythmHint(scene, scenes, frameForm.interval || 300),
    ],
    // What the scene's apps ask for (utils/sceneAccess.ts), recomputed as the
    // scene is edited.
    sceneAccess: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): SceneAccess | null => (scene ? sceneAccess(scene) : null),
    ],
    permissionRows: [
      (s) => [s.sceneAccess],
      (access: sceneSettingsLogicValues['sceneAccess']): ScenePermissionRow[] => {
        // Every app's own asks, nothing folded: unlike the tags, an app that
        // reads the assets folder is listed even when another reads all files.
        const askers = new Map<SceneAccessFlag, string[]>()
        const ask = (flag: SceneAccessFlag, name: string): void => {
          const names = askers.get(flag) ?? []
          if (!names.includes(name)) {
            askers.set(flag, [...names, name])
          }
        }
        for (const app of access?.apps ?? []) {
          for (const permission of app.permissions) {
            ask(permission, app.name)
          }
          for (const namespace of app.settings) {
            ask(`key:${namespace}`, app.name)
          }
        }
        if (access?.legacyShell) {
          ask('shell', 'a Nim code node')
        }
        const order = [...SCENE_PERMISSIONS, ...knownSceneAccessFlags([...askers.keys()])]
        return [...new Set(order)]
          .filter((flag) => askers.has(flag))
          .map((flag) => ({ flag, askedBy: askers.get(flag) ?? [] }))
      },
    ],
    // The Scale select: the frame's, then the steps (and the scene's own
    // value if it is none of them).
    renderScaleOptions: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): RenderScaleOption[] =>
        sceneRenderScaleOptions(scene?.settings?.renderScale),
    ],
    // The state field with role renderScale, whose value wins over the
    // setting on the frame (utils/renderScale.ts); null when there is none.
    renderScaleFieldName: [
      (s) => [s.scene],
      (scene: sceneSettingsLogicValues['scene']): string | null => {
        const index = renderScaleFieldIndex(scene?.fields)
        return index >= 0 ? scene?.fields?.[index]?.name || null : null
      },
    ],
    permissionApps: [
      (s) => [s.sceneAccess],
      (access: sceneSettingsLogicValues['sceneAccess']): ScenePermissionApp[] =>
        (access?.apps ?? [])
          .filter((app) => app.kind === 'scene')
          .map((app) => {
            const shortfall = appPermissionShortfall(app)
            return {
              name: app.name,
              source:
                app.declared === null
                  ? 'no list yet'
                  : app.declared.join() === app.detected.join()
                  ? 'from its code'
                  : 'updates on the next save',
              warning:
                shortfall.length > 0
                  ? `${app.reasons.join(' and ')} but does not ask for ${shortfall
                      .map((permission) => sceneAccessFlagLabel(permission))
                      .join(' or ')}; the frame refuses it.`
                  : null,
            }
          }),
    ],
  }),
])
