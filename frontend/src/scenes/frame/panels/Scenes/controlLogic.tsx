export type controlLogicType = MakeLogicType<controlLogicValues, controlLogicActions, ControlLogicProps> &
  controlLogicMeta

export const controlLogic = kea<controlLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'Scenes', 'controlLogic']),
  props({} as ControlLogicProps),
  key((props) => props.frameId),
  connect(({ frameId }: ControlLogicProps) => ({
    logic: [longRunningTasksModel],
    values: [frameLogic({ frameId }), ['frame', 'frameForm']],
    actions: [frameLogic({ frameId }), ['updateScene', 'applyTemplate']],
  })),
  actions({
    sync: true,
    setCurrentScene: (sceneId: string) => ({ sceneId }),
    currentSceneChanged: (sceneId: string) => ({ sceneId }),
  }),
  loaders(({ props, values }) => ({
    stateRecord: [
      emptyFrameStateRecord,
      {
        sync: async (_, breakpoint) => {
          await breakpoint(100)

          // The standalone embedded editor has no frame to sync state from.
          if (typeof window !== 'undefined' && (window as any).FRAMEOS_EMBEDDED_NO_BACKEND) {
            return emptyFrameStateRecord
          }

          // The cloud has no /states or /state route (both used to 404 and
          // log a loader error every time the drawer or scene editor
          // mounted). The hub stores the device's last reported state on the
          // frame row instead — the active scene is what the drawer's
          // controls need; per-scene public state has no cloud store yet.
          if (isCloudMode()) {
            return normaliseFrameStateRecord({
              sceneId: activeSceneFromLastState(values.frame?.last_state) ?? '',
              states: {},
            })
          }

          try {
            const statesResponse = await apiFetch(`/api/frames/${props.frameId}/states`)
            if (statesResponse.ok) {
              return normaliseFrameStateRecord(await statesResponse.json())
            }
          } catch (error) {
            console.error(error)
          }

          const response = await apiFetch(`/api/frames/${props.frameId}/state`)
          if (!response.ok) {
            throw new Error('Failed to fetch frame state')
          }
          console.error('Failed to fetch frame states, but could load one state. You might need to redeploy the frame.')
          const resp = await response.json()
          return normaliseFrameStateRecord({ states: { [resp.sceneId]: resp.state }, sceneId: resp.sceneId })
        },
      },
    ],
    uploadedScenes: [
      [] as FrameScene[],
      {
        loadUploadedScenes: async () => {
          // No /uploaded_scenes route on the cloud: the pushed set already
          // lives in the frame form / frame row the drawer resolves against.
          if (isCloudMode()) {
            return []
          }
          const response = await apiFetch(`/api/frames/${props.frameId}/uploaded_scenes`)
          if (!response.ok) {
            throw new Error('Failed to fetch uploaded scenes')
          }
          const payload = await response.json()
          return (payload?.scenes ?? []) as FrameScene[]
        },
      },
    ],
  })),
  reducers({
    stateRecord: [
      emptyFrameStateRecord,
      {
        currentSceneChanged: (state, { sceneId }) => ({ ...state, sceneId }),
      },
    ],
    sceneChanging: [
      null as null | string,
      {
        setCurrentScene: (_, { sceneId }) => sceneId,
        syncSuccess: () => null,
        syncFailure: () => null,
        currentSceneChanged: () => null,
      },
    ],
  }),
  selectors({
    scenes: [
      (s) => [s.frame, s.frameForm],
      (frame: controlLogicValues['frame'], frameForm: controlLogicValues['frameForm']) =>
        frameForm.scenes ?? frame.scenes,
    ],
    scene: [
      (s) => [s.scenes, s.sceneId],
      (scenes: controlLogicValues['scenes'], sceneId: controlLogicValues['sceneId']): FrameScene | null =>
        scenes?.find((scene) => scene.id === sceneId) ?? null,
    ],
    fields: [
      (s) => [s.scene],
      (scene: controlLogicValues['scene']) => (scene?.fields ?? []).filter((field) => field.access === 'public'),
    ],
    scenesAsOptions: [
      (s) => [s.scenes],
      (scenes: controlLogicValues['scenes']): { label: string; value: string }[] =>
        (scenes ?? []).map((scene) => ({
          label: scene.name || 'Unnamed Scene',
          value: scene.id || '',
        })),
    ],
    states: [(s) => [s.stateRecord], (stateRecord: controlLogicValues['stateRecord']) => stateRecord?.states ?? {}],
    sceneId: [(s) => [s.stateRecord], (stateRecord: controlLogicValues['stateRecord']) => stateRecord?.sceneId ?? null],
    loading: [
      (s) => [s.stateRecord, s.sceneChanging, s.stateRecordLoading],
      (
        stateRecord: controlLogicValues['stateRecord'],
        stateRecordLoading: controlLogicValues['sceneChanging'],
        sceneChanging: controlLogicValues['stateRecordLoading']
      ) => !stateRecord?.sceneId || stateRecordLoading || !!sceneChanging,
    ],
  }),
  listeners(({ actions, props, values }) => ({
    [socketLogic.actionTypes.socketReconnected]: () => {
      // The active scene / state record is event-sourced from newLog, so a
      // scene change during the outage would go unnoticed. Resync once -- this
      // is a single small state snapshot, not a bulk download.
      if (!values.stateRecordLoading) {
        actions.sync()
      }
    },
    setCurrentScene: async ({ sceneId }) => {
      const scene =
        values.frameForm.scenes?.find((item) => item.id === sceneId) ??
        values.frame?.scenes?.find((item) => item.id === sceneId)
      longRunningTasksModel.actions.startTask({
        frameId: props.frameId,
        kind: 'activate',
        sceneId,
        title: 'Activating scene',
        detail: scene?.name || sceneId,
      })
      try {
        let usbSucceeded = false
        if ((values.frame?.mode ?? 'rpios') === 'embedded' && embeddedUsbApiCanUse(props.frameId)) {
          try {
            await runEmbeddedUsbApiCommand(props.frameId, 'scene-payload', { payload: sceneId, timeoutMs: 10000 })
            usbSucceeded = true
          } catch (error) {
            // A stale or busy USB port must not strand a network-reachable
            // frame — fall through to the HTTP event below.
          }
        }
        if (!usbSucceeded) {
          const response = await apiFetch(`/api/frames/${props.frameId}/event/setCurrentScene`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ sceneId }),
          })
          if (!response.ok) {
            throw new Error('Failed to send scene activation event')
          }
          await response.text()
        }
        actions.currentSceneChanged(sceneId)
        socketLogic.actions.updateFrame({ id: props.frameId, active_scene_id: sceneId } as FrameType)
        longRunningTasksModel.actions.finishTask({
          frameId: props.frameId,
          kind: 'activate',
          sceneId,
          status: 'success',
          detail: scene?.name || sceneId,
        })
      } catch (error) {
        longRunningTasksModel.actions.taskFailed({
          frameId: props.frameId,
          kind: 'activate',
          sceneId,
          detail: error instanceof Error ? error.message : 'Failed to activate scene',
        })
        throw error
      }
    },
    syncSuccess: async ({ stateRecord }, breakpoint) => {
      if (stateRecord?.sceneId?.startsWith(UPLOADED_SCENE_PREFIX)) {
        actions.loadUploadedScenes()
      }
      if (stateRecord?.cache?.refreshing && !stateRecord.cache.cached) {
        const retryAfterSeconds = Math.max(1, Number(stateRecord.cache.retry_after) || 5)
        await breakpoint(retryAfterSeconds * 1000)
        if (!values.stateRecordLoading) {
          actions.sync()
        }
      }
    },
    [socketLogic.actionTypes.newLog]: ({ log }) => {
      // Only react to logs for THIS frame; otherwise a scene change on another
      // frame would overwrite this frame's active scene and trigger a redundant
      // sync() per mounted controlLogic.
      if (log.frame_id !== props.frameId) {
        return
      }
      try {
        const { event, sceneId } = JSON.parse(log.line)
        if (event === 'render:sceneChange') {
          if (sceneId !== values.sceneId) {
            actions.currentSceneChanged(sceneId)
            if (!values.stateRecordLoading) {
              actions.sync()
            }
          } else {
            actions.currentSceneChanged(sceneId)
          }
        } else if (
          event === 'event:setSceneState' ||
          event === 'event:setCurrentScene' ||
          event === 'event:uploadScenes'
        ) {
          if (!values.stateRecordLoading) {
            actions.sync()
          }
        }
      } catch (error) {}
    },
  })),
  afterMount(({ actions }) => {
    actions.sync()
  }),
])
