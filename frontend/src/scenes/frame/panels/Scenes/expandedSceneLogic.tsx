export const expandedSceneLogic = kea<expandedSceneLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'Scenes', 'expandedSceneLogic']),
  props({} as ExpandedSceneLogicProps),
  key((props) => `${props.frameId}${props.sceneId}`),
  connect(({ frameId }: ExpandedSceneLogicProps) => ({
    logic: [longRunningTasksModel],
    values: [frameLogic({ frameId }), ['frame', 'frameForm'], controlLogic({ frameId }), ['states', 'loading']],
    actions: [frameLogic({ frameId }), ['updateScene', 'applyTemplate']],
  })),
  actions({
    /** The locate button's answer: both coordinates into the form. */
    setLocation: (location: GeoLocation) => ({ location }),
  }),
  forms(({ values, props }) => ({
    stateChanges: {
      defaults: {} as Record<string, any>,
      submit: async (formValues) => {
        const state: Record<string, any> = {}
        // Only submit fields the user can currently see, matching the
        // on-frame control page: hidden fields keep their current values
        const fields = visiblePublicStateFields(
          sceneStateFields(values.scene),
          values.states[props.sceneId] ?? {},
          formValues
        )
        for (const field of fields) {
          if (field.name in formValues && field.access === 'public') {
            if (field.type === 'boolean') {
              // "false" in the form used to fall through to a `true` default.
              state[field.name] = booleanFieldValue(formValues[field.name] ?? field.value)
            } else if (field.type === 'integer') {
              state[field.name] = parseInt(formValues[field.name] ?? field.value)
            } else if (field.type === 'float') {
              state[field.name] = parseFloat(formValues[field.name] ?? field.value)
            } else {
              state[field.name] = formValues[field.name] ?? field.value
            }
          }
        }
        // The one activation (controlLogic): the task, the button's wait,
        // the plane first and USB only when it cannot be reached.
        await controlLogic({ frameId: props.frameId }).asyncActions.setCurrentScene(props.sceneId, state)
      },
    },
  })),
  selectors({
    scenes: [
      (s) => [s.frame, s.frameForm],
      (frame: expandedSceneLogicValues['frame'], frameForm: expandedSceneLogicValues['frameForm']) =>
        frameForm.scenes ?? frame.scenes,
    ],
    scene: [
      (s) => [s.scenes, (_, p) => p.sceneId, (_, p) => p.scene],
      (scenes: expandedSceneLogicValues['scenes'], sceneId, sceneOverride): FrameScene | null =>
        sceneOverride ?? scenes?.find((scene) => scene.id === sceneId) ?? null,
    ],
    fields: [
      (s) => [s.scene],
      (scene: expandedSceneLogicValues['scene']) =>
        sceneStateFields(scene).filter((field) => field.access === 'public'),
    ],
    visibleFields: [
      (s) => [s.fields, s.states, s.stateChanges, (_, props) => props.sceneId],
      (
        fields: expandedSceneLogicValues['fields'],
        states: expandedSceneLogicValues['states'],
        stateChanges: expandedSceneLogicValues['stateChanges'],
        sceneId
      ) => visiblePublicStateFields(fields, states[sceneId] ?? {}, stateChanges),
    ],
    // The latitude and longitude fields, when the scene shows both: the
    // first of them carries the locate button.
    locationFields: [
      (s) => [s.visibleFields],
      (visibleFields: expandedSceneLogicValues['visibleFields']) => locationFieldPair(visibleFields),
    ],
    scenesAsOptions: [
      (s) => [s.scenes],
      (scenes: expandedSceneLogicValues['scenes']): { label: string; value: string }[] =>
        (scenes ?? []).map((scene) => ({
          label: scene.name || 'Unnamed Scene',
          value: scene.id || '',
        })),
    ],
    hasStateChanges: [
      (s) => [s.stateChanges, s.loading, s.states, (_, props) => props.sceneId],
      (
        stateChanges: expandedSceneLogicValues['stateChanges'],
        loading: expandedSceneLogicValues['loading'],
        states: expandedSceneLogicValues['states'],
        sceneId
      ) => {
        if (loading && !states) {
          return false
        }
        const currentState = states[sceneId] ?? {}
        return Object.keys(stateChanges).some((key) => stateChanges[key] !== currentState[key])
      },
    ],
  }),
  listeners(({ actions, values }) => ({
    setLocation: ({ location }) => {
      if (values.locationFields) {
        actions.setStateChangesValues(locatedValues(values.locationFields, location))
      }
    },
  })),
])
