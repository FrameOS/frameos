export const appNodeLogic = kea<appNodeLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'Diagram', 'appNodeLogic']),
  props({} as AppNodeLogicProps),
  key((props) => `${props.frameId}/${props.sceneId}/${props.nodeId}`),
  connect(({ sceneId, frameId }: DiagramLogicProps) => ({
    values: [
      appsModel,
      ['apps'],
      diagramLogic({ frameId, sceneId }),
      ['nodes', 'edges', 'scene as currentScene', 'effectiveApps', 'runtimeNodeErrorsByNodeId'],
      frameLogic({ frameId }),
      ['frameForm', 'scenes'],
    ],
    actions: [
      diagramLogic({ frameId, sceneId }),
      ['selectNode', 'updateNodeData', 'deleteApp', 'setNodes', 'setEdges', 'forkSceneApp'],
    ],
  })),
  actions({
    select: true,
    editCodeField: (field: string, newField: string) => ({ field, newField }),
    editCodeFieldOutput: (field: string, newField: string) => ({ field, newField }),
    // updateCodeOutput: (index: number, codeArg: CodeArg) => ({ field, newField }),
  }),
  selectors({
    nodeId: [() => [(_, props) => props.nodeId], (nodeId): string => nodeId],
    node: [
      (s) => [s.nodes, s.nodeId],
      (nodes: DiagramNode[], nodeId: string) => nodes?.find((n) => n.id === nodeId) ?? null,
    ],
    nodeEdges: [
      (s) => [s.edges, s.nodeId],
      (edges: DiagramEdge[], nodeId: appNodeLogicValues['nodeId']): DiagramEdge[] =>
        edges?.filter((e) => e.source === nodeId || e.target === nodeId) ?? [],
    ],
    nodeConfig: [
      (s) => [s.node],
      (node: appNodeLogicValues['node']): Record<string, any> =>
        node && 'config' in node?.data ? node?.data.config ?? {} : {},
      { resultEqualityCheck: equal },
    ],
    codeArgs: [
      (s) => [s.nodeEdges, s.nodeId],
      (nodeEdges: appNodeLogicValues['nodeEdges'], nodeId: appNodeLogicValues['nodeId']) =>
        nodeEdges
          .filter(
            (edge) =>
              (edge.sourceHandle === 'fieldOutput' || edge.sourceHandle?.startsWith('code/')) &&
              nodeId == edge.target &&
              edge.targetHandle?.startsWith('fieldInput/')
          )
          .map((edge) => edge.targetHandle?.replace('fieldInput/', '') ?? ''),
      { resultEqualityCheck: equal },
    ],
    fieldInputFields: [
      (s) => [s.nodeEdges, s.nodeId],
      (nodeEdges: appNodeLogicValues['nodeEdges'], nodeId: appNodeLogicValues['nodeId']): string[] =>
        nodeEdges
          .filter(
            (edge) =>
              (edge.sourceHandle === 'fieldOutput' || edge.sourceHandle?.startsWith('field/')) &&
              nodeId == edge.target &&
              edge.targetHandle?.startsWith('fieldInput/')
          )
          .map((edge) => edge.targetHandle?.replace('fieldInput/', '') ?? ''),
      { resultEqualityCheck: equal },
    ],
    nodeOutputFields: [
      (s) => [s.nodeEdges, s.nodeId],
      (nodeEdges: appNodeLogicValues['nodeEdges'], nodeId: appNodeLogicValues['nodeId']) =>
        nodeEdges
          .filter(
            (edge) => edge.sourceHandle?.startsWith('field/') && nodeId == edge.source && edge.targetHandle === 'prev'
          )
          .map((edge) => edge.sourceHandle?.replace('field/', '') ?? ''),
      { resultEqualityCheck: equal },
    ],
    isSelected: [(s) => [s.node], (node: appNodeLogicValues['node']) => node?.selected ?? false],
    runtimeNodeError: [
      (s) => [s.runtimeNodeErrorsByNodeId, s.nodeId],
      (
        runtimeNodeErrorsByNodeId: Record<string, RuntimeNodeError>,
        nodeId: appNodeLogicValues['nodeId']
      ): RuntimeNodeError | null => runtimeNodeErrorsByNodeId[nodeId] ?? null,
    ],
    sources: [
      (s) => [s.currentScene, s.node],
      (
        currentScene: appNodeLogicValues['currentScene'],
        node: appNodeLogicValues['node']
      ): Record<string, string> | null => {
        if (node && node.data && 'sources' in node.data && node.data.sources) {
          return node.data.sources
        }
        if (node?.type === 'app' && 'keyword' in node.data) {
          return currentScene?.apps?.[node.data.keyword]?.sources ?? null
        }
        return null
      },
    ],
    sourceConfigJson: [
      (s) => [s.sources],
      (sources: appNodeLogicValues['sources']): [Record<string, any> | null, Error | string | null] => {
        try {
          if (sources) {
            const json = sources['config.json']
            if (json) {
              const config = JSON.parse(json)
              if (typeof config === 'object') {
                return [config, null]
              }
            }
          }
        } catch (e) {
          return [null, e instanceof Error ? e : String(e)]
        }
        return [null, null]
      },
    ],
    configJsonError: [
      (s) => [s.sourceConfigJson, s.sources],
      ([_, error]) => {
        return error === null ? null : error instanceof Error ? error.message : String(error)
      },
    ],
    app: [
      (s) => [s.effectiveApps, s.currentScene, s.node],
      (
        effectiveApps: appNodeLogicValues['effectiveApps'],
        currentScene: appNodeLogicValues['currentScene'],
        node: appNodeLogicValues['node']
      ): AppConfig | null => {
        if (node && node.type === 'app' && node.data && 'keyword' in node.data && node.data.keyword) {
          const sceneApp = currentScene?.apps?.[node.data.keyword]
          return sceneApp ? sceneAppToAppConfig(sceneApp) : effectiveApps[node.data.keyword] ?? null
        }
        return null
      },
      { resultEqualityCheck: equal },
    ],
    event: [
      (s) => [s.node, s.currentScene],
      (node: appNodeLogicValues['node'], currentScene: appNodeLogicValues['currentScene']): AppConfig | null => {
        if (node && node.type === 'dispatch' && node.data && 'keyword' in node.data && node.data.keyword) {
          return frameEventForScene(node.data.keyword, currentScene) ?? null
        }
        return null
      },
    ],
    scene: [
      (s) => [s.node, s.scenes],
      (node: appNodeLogicValues['node'], scenes: FrameScene[]): FrameScene | null =>
        node?.type === 'scene'
          ? scenes.find((scene) => scene.id === (node.data as SceneNodeData).keyword) ?? null
          : null,
    ],
    isApp: [(s) => [s.node], (node: appNodeLogicValues['node']) => node?.type === 'app'],
    isDispatch: [(s) => [s.node], (node: appNodeLogicValues['node']) => node?.type === 'dispatch'],
    isScene: [(s) => [s.node], (node: appNodeLogicValues['node']) => node?.type === 'scene'],
    isSceneApp: [
      (s) => [s.currentScene, s.node],
      (currentScene: appNodeLogicValues['currentScene'], node: appNodeLogicValues['node']): boolean =>
        !!(node?.type === 'app' && 'keyword' in node.data && currentScene?.apps?.[node.data.keyword]),
    ],
    isJavaScriptSceneApp: [
      (s) => [s.isSceneApp, s.sources],
      (isSceneApp: appNodeLogicValues['isSceneApp'], sources: appNodeLogicValues['sources']): boolean =>
        isSceneApp && hasJavaScriptAppSource(sources),
    ],
    isNimAppInInterpretedScene: [
      (s) => [s.currentScene, s.node, s.sources, s.frameForm],
      (
        currentScene: appNodeLogicValues['currentScene'],
        node: appNodeLogicValues['node'],
        sources: appNodeLogicValues['sources'],
        frameForm: appNodeLogicValues['frameForm']
      ): boolean => {
        if (sceneExecutionForFrame(currentScene, frameForm?.mode) !== 'interpreted' || node?.type !== 'app') {
          return false
        }
        if (sources) {
          // A JavaScript sibling wins on every plane: only Nim-only sources are a Nim app.
          return hasCompiledNimAppSource(sources)
        }
        return 'keyword' in node.data && !isRepoAppKeyword(node.data.keyword)
      },
    ],
    // A scene-local app that only has Nim: the legacy path, shown as such.
    isLegacyNimApp: [
      (s) => [s.isApp, s.sources],
      (isApp: appNodeLogicValues['isApp'], sources: appNodeLogicValues['sources']): boolean =>
        isApp && hasCompiledNimAppSource(sources),
    ],
    sceneIsCompiled: [
      (s) => [s.currentScene, s.frameForm],
      (currentScene: appNodeLogicValues['currentScene'], frameForm: appNodeLogicValues['frameForm']): boolean =>
        sceneExecutionForFrame(currentScene, frameForm?.mode) !== 'interpreted',
    ],
    // Per node, not per scene: only a code node that still carries Nim and no
    // JavaScript twin gets the legacy Nim editor. Everything else is JavaScript.
    codeNodeLanguage: [
      (s) => [s.node],
      (node: appNodeLogicValues['node']): CodeNodeLanguage => {
        if (node?.type !== 'code') {
          return 'js'
        }
        const data = node.data as CodeNodeData
        return data.code?.trim() && !data.codeJS?.trim() ? 'nim' : 'js'
      },
    ],
    appMenuEditLabel: [
      (s) => [s.isNimAppInInterpretedScene],
      (isNimAppInInterpretedScene: appNodeLogicValues['isNimAppInInterpretedScene']): string =>
        isNimAppInInterpretedScene ? 'View nim app' : 'Edit App',
    ],
    configJson: [
      (s) => [s.app, s.sourceConfigJson],
      (app: appNodeLogicValues['app'], [config]): AppConfig | null => {
        return (config as AppConfig) || app || null
      },
    ],
    allFields: [
      (s) => [s.app, s.event, s.scene, s.currentScene, s.configJson, s.nodeConfig],
      (
        app: appNodeLogicValues['app'],
        event: appNodeLogicValues['event'],
        scene: appNodeLogicValues['scene'],
        currentScene: appNodeLogicValues['currentScene'],
        configJson: appNodeLogicValues['configJson'],
        nodeConfig: appNodeLogicValues['nodeConfig']
      ): (AppConfigField | MarkdownField)[] | null => {
        let fields: (AppConfigField | MarkdownField)[] = []
        if (event) {
          if (event.name === 'setSceneState') {
            fields = currentScene?.fields ?? []
          } else {
            fields = event?.fields ?? []
          }
        } else {
          fields = scene?.fields ?? app?.fields ?? configJson?.fields ?? []
        }

        let realFields: (AppConfigField | MarkdownField)[] = []
        for (const field of fields) {
          if ('seq' in field && Array.isArray(field.seq)) {
            let seqs: [string, number[]][] = []
            for (const [name, _min, _max] of field.seq) {
              let min = typeof _min === 'number' ? _min : parseInt(nodeConfig[_min] ?? '1')
              let max = typeof _max === 'number' ? _max : parseInt(nodeConfig[_max] ?? '1')
              let numbers = []
              for (let i = min; i <= max; i++) {
                numbers.push(i)
              }
              seqs.push([name, numbers])
            }
            let existing: number[][] = []
            for (let i = 0; i < seqs.length; i++) {
              const numbers = seqs[i][1]
              const newExisting = []
              if (existing.length > 0) {
                for (const ext of existing) {
                  for (const num of numbers) {
                    newExisting.push([...ext, num])
                  }
                }
              } else {
                for (const num of numbers) {
                  newExisting.push([num])
                }
              }
              existing = newExisting
            }
            for (const values of existing) {
              let label = field.label
              for (let i = 0; i < values.length; i++) {
                label = label.replace(`{${seqs[i][0]}}`, String(values[i]))
              }
              realFields.push({
                ...field,
                label: label,
                name: `${field.name}[${values.join('][')}]`,
              })
            }
          } else {
            realFields.push(field)
          }
        }
        return realFields
      },
      { resultEqualityCheck: equal },
    ],
    allDefaultValues: [
      (s) => [s.allFields],
      (fields: appNodeLogicValues['allFields']): Record<string, any> => {
        return (
          fields?.reduce((acc, field) => {
            if ('value' in field && 'name' in field) {
              acc[field.name] = field.value
            }
            return acc
          }, {} as Record<string, any>) ?? {}
        )
      },
    ],
    output: [
      (s) => [s.configJson],
      (configJson: appNodeLogicValues['configJson']): OutputField[] | null => {
        return configJson?.output ?? null
      },
    ],
    name: [
      (s) => [s.app, s.event, s.configJson, s.scene],
      (
        app: appNodeLogicValues['app'],
        event: appNodeLogicValues['event'],
        configJson: appNodeLogicValues['configJson'],
        scene: appNodeLogicValues['scene']
      ): string => {
        return event
          ? `Dispatch: ${String(event?.name ?? 'Event')}`
          : app
          ? String(app?.name ?? configJson?.name ?? 'App')
          : scene
          ? String(scene?.name ?? 'Scene')
          : configJson?.name || 'Node'
      },
    ],
    isCustomApp: [
      (s) => [s.node],
      (node: appNodeLogicValues['node']) => {
        return 'sources' in (node?.data ?? {})
      },
    ],
    hasNextPrevNodeConnected: [
      (s) => [s.nodeEdges, s.nodeId],
      (nodeEdges: appNodeLogicValues['nodeEdges'], nodeId: appNodeLogicValues['nodeId']) => {
        return nodeEdges.some(
          (edge) =>
            (edge.target === nodeId && edge.targetHandle === 'prev') ||
            (edge.source === nodeId && edge.sourceHandle === 'next')
        )
      },
    ],
    hasOutputConnected: [
      (s) => [s.nodeEdges, s.nodeId],
      (nodeEdges: appNodeLogicValues['nodeEdges'], nodeId: appNodeLogicValues['nodeId']) => {
        return nodeEdges.some((edge) => edge.source === nodeId && edge.sourceHandle === 'fieldOutput')
      },
    ],
    showOutput: [
      (s) => [s.hasNextPrevNodeConnected, s.hasOutputConnected],
      (
        hasNextPrevNodeConnected: appNodeLogicValues['hasNextPrevNodeConnected'],
        hasOutputConnected: appNodeLogicValues['hasOutputConnected']
      ) => {
        return hasOutputConnected || !hasNextPrevNodeConnected
      },
    ],
    showNextPrev: [
      (s) => [s.hasNextPrevNodeConnected, s.hasOutputConnected, s.configJson],
      (
        hasNextPrevNodeConnected: appNodeLogicValues['hasNextPrevNodeConnected'],
        hasOutputConnected: appNodeLogicValues['hasOutputConnected'],
        configJson: appNodeLogicValues['configJson']
      ) => {
        return (hasNextPrevNodeConnected || !hasOutputConnected) && configJson?.category !== 'data'
      },
    ],
    isStateNode: [(s) => [s.node], (node: appNodeLogicValues['node']) => node?.type === 'state'],
    isDataApp: [
      (s) => [s.node, s.output, s.showOutput],
      (
        node: appNodeLogicValues['node'],
        output: appNodeLogicValues['output'],
        showOutput: appNodeLogicValues['showOutput']
      ) => node?.type === 'app' && !!output && output.length > 0 && showOutput,
    ],
    fields: [
      (s) => [
        s.allFields,
        s.showOutput,
        s.showNextPrev,
        s.nodeConfig,
        s.allDefaultValues,
        s.fieldInputFields,
        s.nodeOutputFields,
        s.event,
        s.scene,
      ],
      (
        allFields: appNodeLogicValues['allFields'],
        showOutput: appNodeLogicValues['showOutput'],
        showNextPrev: appNodeLogicValues['showNextPrev'],
        nodeConfig: appNodeLogicValues['nodeConfig'],
        allDefaultValues: appNodeLogicValues['allDefaultValues'],
        fieldInputFields: appNodeLogicValues['fieldInputFields'],
        nodeOutputFields: appNodeLogicValues['nodeOutputFields'],
        event: appNodeLogicValues['event'],
        scene: appNodeLogicValues['scene']
      ): (AppConfigField | MarkdownField)[] | null => {
        if (!allFields) {
          return null
        }
        // State fields and custom event fields are declared with real types,
        // and their showIf conditions carry typed values; coerce the string
        // form values so "eq true" style conditions match, like every other
        // form does. App config.json fields keep raw values for backwards
        // compatibility with hand-written string comparisons.
        const usesTypedFields = !!event || !!scene
        const values = usesTypedFields
          ? stateFieldShowIfValues(allFields.filter((field) => 'name' in field) as AppConfigField[], nodeConfig)
          : { ...allDefaultValues, ...nodeConfig }
        return filterFieldsByShowIf(allFields, values, {
          metaValues: { '.meta.showOutput': showOutput, '.meta.showNextPrev': showNextPrev },
          connectedFields: [...fieldInputFields, ...nodeOutputFields],
        })
      },
      { resultEqualityCheck: equal },
    ],
    stateFieldType: [
      (s) => [s.isStateNode, s.currentScene, s.node],
      (
        isStateNode: appNodeLogicValues['isStateNode'],
        currentScene: appNodeLogicValues['currentScene'],
        node: appNodeLogicValues['node']
      ): FieldType =>
        isStateNode && node && 'keyword' in node.data
          ? toFieldType(
              currentScene?.fields?.find((f) => f.name === (node.data as StateNodeData).keyword)?.type ?? 'string'
            )
          : 'string',
    ],
    stateFieldTitle: [
      (s) => [s.isStateNode, s.currentScene, s.node],
      (
        isStateNode: appNodeLogicValues['isStateNode'],
        currentScene: appNodeLogicValues['currentScene'],
        node: appNodeLogicValues['node']
      ): string | null => {
        if (isStateNode && node && 'keyword' in node.data) {
          const label = currentScene?.fields?.find((f) => f.name === (node.data as StateNodeData).keyword)?.label
          return label ?? node.data.keyword
        }
        return null
      },
    ],
  }),
  listeners(({ actions, values, props }) => ({
    select: () => {
      if (!values.isSelected) {
        actions.selectNode(values.nodeId)
      }
    },
    editCodeField: ({ field, newField }) => {
      const { nodeId, node, nodeEdges, edges } = values
      const codeFieldEdges = nodeEdges.filter(
        (edge) =>
          edge.target === nodeId && edge.sourceHandle === 'fieldOutput' && edge.targetHandle === `codeField/${field}`
      )
      const codeArgs = (node?.data as CodeNodeData)?.codeArgs ?? []
      if (newField) {
        actions.setEdges(
          edges.map((edge) =>
            edge.target === nodeId && edge.sourceHandle === 'fieldOutput' && edge.targetHandle === `codeField/${field}`
              ? { ...edge, targetHandle: `codeField/${newField}` }
              : edge
          )
        )
        actions.updateNodeData(nodeId, {
          codeFields: codeArgs.find((a) => a.name === newField)
            ? codeArgs.filter((f) => f.name !== field)
            : codeArgs.map((f) => (f.name === field ? newField : f)),
        })
        window.requestAnimationFrame(() => {
          props.updateNodeInternals?.(nodeId)
        })
      } else {
        for (const edge of codeFieldEdges) {
          actions.deleteApp(edge.source)
        }
        actions.updateNodeData(nodeId, { codeArgs: codeArgs.filter((f) => f.name !== field) })
        window.requestAnimationFrame(() => {
          props.updateNodeInternals?.(nodeId)
        })
      }
    },
    editCodeFieldOutput: ({ field, newField }) => {
      const { nodeId, node, nodes, nodeEdges, edges } = values
      const codeOutputEdges = nodeEdges.filter(
        (edge) =>
          edge.source === nodeId && edge.sourceHandle === `fieldOutput` && edge.targetHandle === `codeField/${field}`
      )

      const updatedNodes: Record<string, DiagramNode | false> = {}
      const updatedEdges: Record<string, DiagramEdge | false> = {}
      for (const edge of codeOutputEdges) {
        const otherNode = nodes.find((n) => n.id === edge.target)
        if (!otherNode) {
          continue
        }
        const codeArgs = (otherNode?.data as CodeNodeData)?.codeArgs ?? []

        if (newField) {
          updatedEdges[edge.id] = { ...edge, targetHandle: `codeField/${newField}` }
          updatedNodes[edge.target] = {
            ...otherNode,
            data: {
              ...otherNode.data,
              codeArgs: codeArgs.map((f) => (f.name === field ? { ...f, name: newField } : f)),
            },
          }
        } else {
          updatedEdges[edge.id] = false
          updatedNodes[edge.source] = false
          updatedNodes[edge.target] = {
            ...otherNode,
            data: {
              ...otherNode.data,
              codeArgs: codeArgs.filter((f) => f.name !== field),
            },
          }
        }
      }

      const newEdges = edges.map((edge) => updatedEdges[edge.id] ?? edge).filter((e): e is DiagramEdge => e !== false)
      const newNodes = nodes.map((node) => updatedNodes[node.id] ?? node).filter((n): n is DiagramNode => n !== false)
      actions.setEdges(newEdges)
      actions.setNodes(newNodes)
      if (newNodes.length > 0) {
        window.setTimeout(() => {
          window.requestAnimationFrame(() => {
            props.updateNodeInternals?.(newNodes.map((n) => n.id))
          })
        }, 100)
      }
    },
  })),
])
