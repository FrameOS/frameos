import { MakeLogicType, actions, kea, path, reducers, selectors } from 'kea'

// The defaults "Start slideshow" builds its scene with. Remembered per
// browser (kea-localstorage), not per frame: a default is what you want
// before you have picked anything, and every frame gets the same one.
export const DEFAULT_SLIDESHOW_SECONDS = 900
export const MIN_SLIDESHOW_SECONDS = 5

export function normalizeSlideshowSeconds(value: number | null | undefined): number {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    return DEFAULT_SLIDESHOW_SECONDS
  }
  return Math.max(MIN_SLIDESHOW_SECONDS, Math.round(value))
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface slideshowSettingsLogicValues {
  draftIsValid: boolean
  draftSeconds: number | null
  secondsBetweenImages: number
  settingsOpen: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface slideshowSettingsLogicActions {
  closeSettings: () => {
    value: true
  }
  openSettings: () => {
    value: true
  }
  saveSettings: (seconds: number) => {
    seconds: number
  }
  setDraftSeconds: (seconds: number | null) => {
    seconds: number | null
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface slideshowSettingsLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    draftIsValid: (draftSeconds: number | null) => boolean
  }
}

export type slideshowSettingsLogicType = MakeLogicType<
  slideshowSettingsLogicValues,
  slideshowSettingsLogicActions,
  Record<string, any>
> &
  slideshowSettingsLogicMeta

export const slideshowSettingsLogic = kea<slideshowSettingsLogicType>([
  path(['src', 'scenes', 'frame', 'panels', 'Assets', 'slideshowSettingsLogic']),
  actions({
    openSettings: true,
    closeSettings: true,
    setDraftSeconds: (seconds: number | null) => ({ seconds }),
    saveSettings: (seconds: number) => ({ seconds }),
  }),
  reducers({
    secondsBetweenImages: [
      DEFAULT_SLIDESHOW_SECONDS as number,
      { persist: true, storageKey: 'slideshowSettingsLogic.secondsBetweenImages' },
      {
        saveSettings: (_, { seconds }) => normalizeSlideshowSeconds(seconds),
      },
    ],
    settingsOpen: [
      false,
      {
        openSettings: () => true,
        closeSettings: () => false,
        saveSettings: () => false,
      },
    ],
    // What the modal's field holds while it is open; null = emptied.
    draftSeconds: [
      null as number | null,
      {
        setDraftSeconds: (_, { seconds }) => seconds,
        closeSettings: () => null,
        saveSettings: () => null,
      },
    ],
  }),
  selectors({
    draftIsValid: [
      (s) => [s.draftSeconds],
      (draftSeconds: number | null): boolean =>
        typeof draftSeconds === 'number' && Number.isFinite(draftSeconds) && draftSeconds >= MIN_SLIDESHOW_SECONDS,
    ],
  }),
])
