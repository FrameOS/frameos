/**
 * The viewer's Info panel: everything a photo's metadata says, location
 * first, and the two ways to take it out of the file, for the photo on show
 * or for a selection (docs/photos.md, "Metadata"). The library informs and
 * never strips on its own: a removal is always asked for and confirmed. The
 * panel shares its place beside the photo with the colors editor; opening
 * one closes the other.
 */
export const photoInfoLogic = kea<photoInfoLogicType>([
  path(['src', 'scenes', 'photos', 'photoInfoLogic']),
  connect(() => ({
    values: [photosLogic, ['lightboxPath', 'selectedEntries'], photoColorsLogic, ['imagePath']],
    actions: [
      photosLogic,
      ['openLightbox', 'closeLightbox', 'setFolder', 'updateEntry', 'showNotice', 'refreshFolders', 'loadStatus'],
      photoColorsLogic,
      ['openEditor', 'closeEditor'],
    ],
  })),
  actions({
    /** Show the photo in the viewer with its Info panel open. */
    openInfo: (path: string) => ({ path }),
    closeInfo: true,
    toggleInfo: (path: string) => ({ path }),
    /** Take the location, or all metadata, out of these files, after asking. */
    removeMetadata: (paths: string[], remove: PhotoMetadataRemoval) => ({ paths, remove }),
    /** The same for the photo the panel shows. */
    removeShownMetadata: (remove: PhotoMetadataRemoval) => ({ remove }),
    /** The same for the selected photos that have something to remove. */
    removeSelectedMetadata: (remove: PhotoMetadataRemoval) => ({ remove }),
    setRemoving: (removing: PhotoMetadataRemoval | null) => ({ removing }),
    setRemoveError: (error: string | null) => ({ error }),
  }),
  loaders(() => ({
    metadata: [
      null as { path: string; metadata: PhotoMetadata } | null,
      {
        loadMetadata: async (path: string, breakpoint) => {
          const metadata = await fetchPhotoMetadata(path)
          breakpoint()
          return { path, metadata }
        },
      },
    ],
  })),
  reducers({
    infoOpen: [
      false,
      {
        openInfo: () => true,
        closeInfo: () => false,
        openEditor: () => false,
        closeLightbox: () => false,
        setFolder: () => false,
      },
    ],
    metadataError: [
      null as string | null,
      {
        loadMetadata: () => null,
        loadMetadataFailure: (_, { error }) => error,
      },
    ],
    removing: [null as PhotoMetadataRemoval | null, { setRemoving: (_, { removing }) => removing }],
    removeError: [
      null as string | null,
      {
        setRemoveError: (_, { error }) => error,
        openInfo: () => null,
        openLightbox: () => null,
      },
    ],
  }),
  selectors({
    /** The photo the panel is about: the one on show, while the panel is open. */
    infoPath: [
      (s) => [s.infoOpen, s.lightboxPath],
      (infoOpen: boolean, lightboxPath: string | null): string | null => (infoOpen ? lightboxPath : null),
    ],
    // The previous photo's metadata is not this one's: nothing until it has loaded.
    infoMetadata: [
      (s) => [s.metadata, s.infoPath],
      (metadata: { path: string; metadata: PhotoMetadata } | null, infoPath: string | null): PhotoMetadata | null =>
        metadata && infoPath && metadata.path === infoPath ? metadata.metadata : null,
    ],
    infoGroups: [
      (s) => [s.infoMetadata],
      (infoMetadata: PhotoMetadata | null): PhotoMetadataGroup[] =>
        infoMetadata ? metadataGroups(infoMetadata.fields) : [],
    ],
    infoBlocksSentence: [
      (s) => [s.infoMetadata],
      (infoMetadata: PhotoMetadata | null): string | null =>
        infoMetadata ? metadataBlocksSentence(infoMetadata) : null,
    ],
    infoEmpty: [
      (s) => [s.infoMetadata],
      (infoMetadata: PhotoMetadata | null): boolean => !!infoMetadata && metadataIsEmpty(infoMetadata),
    ],
    canRemoveLocation: [
      (s) => [s.infoMetadata],
      (infoMetadata: PhotoMetadata | null): boolean => !!infoMetadata?.location,
    ],
    canRemoveAll: [
      (s) => [s.infoMetadata],
      (infoMetadata: PhotoMetadata | null): boolean => !!infoMetadata && metadataHasRemovable(infoMetadata),
    ],
    selectedLocationPaths: [
      (s) => [s.selectedEntries],
      (selectedEntries: PhotoEntry[]): string[] =>
        selectedEntries.filter((entry) => canHoldMetadata(entry) && !!entry.location).map((entry) => entry.path),
    ],
    selectedMetadataPaths: [
      (s) => [s.selectedEntries],
      (selectedEntries: PhotoEntry[]): string[] =>
        selectedEntries.filter((entry) => canHoldMetadata(entry)).map((entry) => entry.path),
    ],
  }),
  listeners(({ actions, values }) => ({
    openInfo: ({ path }) => {
      // One panel beside the photo: Info takes the colors editor's place.
      // Closed first, or the viewer's move to `path` would take it along.
      if (values.imagePath) {
        actions.closeEditor()
      }
      if (values.lightboxPath !== path) {
        actions.openLightbox(path)
      } else {
        actions.loadMetadata(path)
      }
    },
    toggleInfo: ({ path }) => {
      if (values.infoPath === path) {
        actions.closeInfo()
      } else {
        actions.openInfo(path)
      }
    },
    // Stepping through the viewer takes the open panel along.
    openLightbox: ({ path }) => {
      if (values.infoOpen) {
        actions.loadMetadata(path)
      }
    },
    removeShownMetadata: ({ remove }) => {
      if (values.infoPath) {
        actions.removeMetadata([values.infoPath], remove)
      }
    },
    removeSelectedMetadata: ({ remove }) => {
      actions.removeMetadata(
        remove === 'location' ? values.selectedLocationPaths : values.selectedMetadataPaths,
        remove
      )
    },
    removeMetadata: async ({ paths, remove }) => {
      if (!paths.length || values.removing) {
        return
      }
      const confirmed = await confirmDialog({ ...metadataRemovalRequest(remove, paths), danger: true })
      if (!confirmed) {
        return
      }
      actions.setRemoving(remove)
      actions.setRemoveError(null)
      try {
        const { entries, changed } = await removePhotoMetadata(paths, remove)
        for (const entry of entries) {
          actions.updateEntry(entry)
        }
        const infoPath = values.infoPath
        if (infoPath && paths.includes(infoPath)) {
          actions.loadMetadata(infoPath)
        }
        // Removing everything makes the files smaller: the folder sizes and
        // the storage meter move. The location is erased in place.
        if (remove === 'all' && changed) {
          actions.refreshFolders(['', ...paths.map(parentPhotoPath)])
          actions.loadStatus()
        }
        actions.showNotice('info', metadataRemovalNotice(remove, changed))
      } catch (error) {
        const message = error instanceof Error && error.message ? error.message : 'Could not remove the metadata.'
        actions.setRemoveError(message)
        actions.showNotice('error', message)
      } finally {
        actions.setRemoving(null)
      }
    },
  })),
])
