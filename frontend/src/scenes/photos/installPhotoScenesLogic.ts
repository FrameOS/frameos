// The Photos page picks albums, then opens this frame's Add scene drawer on
// the photos page. The choice crosses that navigation here rather than in the
// URL: it only has to survive one hop.
const pendingAlbums = new Map<string, string[]>()

export function preselectPhotoAlbums(frameId: FrameId, albums: string[]): void {
  pendingAlbums.set(String(frameId), albums)
}

function takePreselectedAlbums(frameId: FrameId): string[] | null {
  const albums = pendingAlbums.get(String(frameId)) ?? null
  pendingAlbums.delete(String(frameId))
  return albums
}

async function coverImage(entry: PhotoEntry | undefined): Promise<Blob | null> {
  if (!entry?.cover) {
    return null
  }
  try {
    const response = await fetch(photoThumbUrl({ path: entry.cover, mtime: entry.mtime, size: 0 }), {
      credentials: 'include',
    })
    if (!response.ok) {
      return null
    }
    const blob = await response.blob()
    return blob.type.startsWith('image/') ? blob : null
  } catch {
    return null
  }
}

