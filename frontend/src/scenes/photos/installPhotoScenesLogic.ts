export const installPhotoScenesLogic = kea<installPhotoScenesLogicType>([
  path((key) => ['src', 'scenes', 'photos', 'installPhotoScenesLogic', key]),
  props({} as InstallPhotoScenesLogicProps),
  key((props) => String(props.frameId)),
  // applyTemplate below must land on a mounted frameLogic.
  connect((props: InstallPhotoScenesLogicProps) => ({ logic: [frameLogic({ frameId: props.frameId })] })),
  actions({
    toggleAlbum: (path: string) => ({ path }),
    setSelectedAlbums: (paths: string[]) => ({ paths }),
    setSeconds: (seconds: number | undefined) => ({ seconds }),
    setOrder: (order: PhotoAlbumOrder) => ({ order }),
    setFit: (fit: PhotoAlbumFit) => ({ fit }),
    toggleShape: (shape: PhotoAlbumShape) => ({ shape }),
    setShapes: (shapes: PhotoAlbumShape[]) => ({ shapes }),
    /** An album link from elsewhere to play as it is, next to (or instead of) the library's albums. */
    setCustomLink: (link: string) => ({ link }),
    setNewAlbumName: (name: string) => ({ name }),
    /** Make the album named in the drawer and tick it. */
    createAlbum: true,
    setCreatingAlbum: (creating: boolean) => ({ creating }),
    /** Install the ticked albums; or one photo's scene, and make it current, for "Show on frame". */
    install: (options: { photo?: string | null; activate?: boolean; save?: boolean } = {}) => ({ options }),
    setInstalling: (installing: boolean) => ({ installing }),
    setError: (error: string | null) => ({ error }),
  }),
  loaders(() => ({
    library: [
      null as { ready: boolean; message: string | null; albums: PhotoEntry[] } | null,
      {
        loadLibrary: async () => {
          try {
            const status = await fetchPhotosStatus()
            if (!status.ready) {
              return { ready: false, message: status.message, albums: [] }
            }
            const entries = await fetchPhotoFolder('')
            return { ready: true, message: null, albums: entries.filter((entry) => entry.kind === 'folder') }
          } catch (error) {
            return {
              ready: false,
              message: error instanceof Error ? error.message : 'Could not reach the photo library.',
              albums: [],
            }
          }
        },
      },
    ],
  })),
  reducers({
    selectedAlbums: [
      [] as string[],
      {
        toggleAlbum: (state, { path }) =>
          state.includes(path) ? state.filter((item) => item !== path) : [...state, path],
        setSelectedAlbums: (_, { paths }) => paths,
      },
    ],
    seconds: [
      DEFAULT_SLIDESHOW_SECONDS as number,
      { persist: true, storageKey: 'installPhotoScenesLogic.seconds' },
      {
        setSeconds: (state, { seconds }) =>
          typeof seconds === 'number' && Number.isFinite(seconds)
            ? Math.max(MIN_SLIDESHOW_SECONDS, Math.round(seconds))
            : state,
      },
    ],
    order: [
      'random' as PhotoAlbumOrder,
      { persist: true, storageKey: 'installPhotoScenesLogic.order' },
      {
        setOrder: (_, { order }) => order,
      },
    ],
    fit: [
      'cover' as PhotoAlbumFit,
      { persist: true, storageKey: 'installPhotoScenesLogic.fit' },
      {
        setFit: (_, { fit }) => fit,
      },
    ],
    shapes: [
      ALL_PHOTO_ALBUM_SHAPES as PhotoAlbumShape[],
      { persist: true, storageKey: 'installPhotoScenesLogic.shapes' },
      {
        toggleShape: (state, { shape }) =>
          normalizePhotoAlbumShapes(state.includes(shape) ? state.filter((item) => item !== shape) : [...state, shape]),
        setShapes: (_, { shapes }) => normalizePhotoAlbumShapes(shapes),
      },
    ],
    customLink: [
      '',
      {
        setCustomLink: (_, { link }) => link,
      },
    ],
    newAlbumName: [
      '',
      {
        setNewAlbumName: (_, { name }) => name,
      },
    ],
    creatingAlbum: [
      false,
      {
        setCreatingAlbum: (_, { creating }) => creating,
      },
    ],
    installing: [
      false,
      {
        setInstalling: (_, { installing }) => installing,
      },
    ],
    error: [
      null as string | null,
      {
        setError: (_, { error }) => error,
        toggleAlbum: () => null,
        install: () => null,
        createAlbum: () => null,
      },
    ],
  }),
  selectors({
    // Albums first; a folder picked on the Photos page below an album is
    // offered too.
    choices: [
      (s) => [s.library, s.selectedAlbums],
      (
        library: { ready: boolean; message: string | null; albums: PhotoEntry[] } | null,
        selectedAlbums: string[]
      ): { path: string; name: string; entry: PhotoEntry | null }[] => {
        const albums = library?.albums ?? []
        const albumPaths = new Set(albums.map((album) => album.path))
        return [
          ...albums.map((album) => ({ path: album.path, name: album.name, entry: album })),
          ...selectedAlbums
            .filter((path) => !albumPaths.has(path))
            .map((path) => ({ path, name: photoBaseName(path), entry: null })),
        ]
      },
    ],
    customLinkValid: [(s) => [s.customLink], (customLink: string): boolean => isAlbumLink(customLink)],
    canInstall: [
      (s) => [s.selectedAlbums, s.customLinkValid, s.shapes, s.installing],
      (selectedAlbums: string[], customLinkValid: boolean, shapes: PhotoAlbumShape[], installing: boolean): boolean =>
        (selectedAlbums.length > 0 || customLinkValid) && shapes.length > 0 && !installing,
    ],
  }),
  listeners(({ actions, values, props }) => ({
    createAlbum: async () => {
      const name = values.newAlbumName.trim()
      if (!name || values.creatingAlbum) {
        return
      }
      actions.setCreatingAlbum(true)
      try {
        const entry = await createPhotoFolder(name)
        await actions.loadLibrary()
        actions.setNewAlbumName('')
        if (!values.selectedAlbums.includes(entry.path)) {
          actions.setSelectedAlbums([...values.selectedAlbums, entry.path])
        }
      } catch (error) {
        actions.setError(error instanceof Error ? error.message : 'Could not make the album.')
      } finally {
        actions.setCreatingAlbum(false)
      }
    },
    install: async ({ options }) => {
      const frame = frameById(framesModel.values.frames, props.frameId)
      if (!frame) {
        actions.setError('This frame is not loaded.')
        return
      }
      const photo = options.photo ?? null
      // One photo: its album is the folder it is in, and the scene shows it alone.
      const albums = photo ? [parentPhotoPath(photo)] : values.selectedAlbums
      // An album link from elsewhere plays as it is: no share link of ours to make.
      const customLink = !photo && values.customLinkValid ? values.customLink.trim() : ''
      if (!albums.length && !customLink) {
        return
      }
      if (photo && !albums[0]) {
        actions.setError('Move the photo into an album first: the library root cannot be shared.')
        return
      }
      actions.setInstalling(true)
      try {
        const frameStore = frameLogic({ frameId: props.frameId })
        const scenesBefore = (frameStore.values.frameForm?.scenes ?? frameStore.values.scenes) as FrameScene[]
        const sceneIdsBefore = new Set(scenesBefore.map((scene) => scene.id))
        // The listing as it is now, not as it was when the drawer opened:
        // the album's cover (the scene's image) may have arrived since.
        let albumEntries: PhotoEntry[] = values.library?.albums ?? []
        try {
          albumEntries = (await fetchPhotoFolder('')).filter((entry) => entry.kind === 'folder')
        } catch {
          // The cached listing will do.
        }
        // "Show on frame" for a scene the frame already has: show that one.
        let reused: FrameScene | undefined
        let previewed = false
        for (const album of albums) {
          // The frame's own link to the album: it can be withdrawn on its own.
          const share = await createPhotoShare(album, frame.id)
          const albumUrl = shareUrlForFrame(share, frame)
          if (!albumUrl) {
            actions.setError(
              'This frame does not know the address of this backend. Set it in the frame settings, then try again.'
            )
            return
          }
          const relativePhoto = photo ? photo.slice(album.length + 1) : null
          if (options.activate) {
            reused = existingPhotoScene(scenesBefore, albumUrl, relativePhoto)
            if (reused) {
              continue
            }
          }
          const entry = albumEntries.find((item) => item.path === album)
          const scene = buildPhotoAlbumScene({
            name: photo ? photoBaseName(photo) : photoBaseName(album),
            albumUrl,
            seconds: values.seconds,
            order: values.order,
            fit: values.fit,
            shapes: values.shapes,
            ...(relativePhoto ? { photo: relativePhoto } : {}),
          })
          if (options.activate && !options.save) {
            // A preview: the frame shows the scene now and keeps the scenes
            // it has (scenesLogic.previewScene: uploadScenes on both planes).
            scenesLogic({ frameId: props.frameId }).actions.previewScene(scene.id, null, [scene])
            previewed = true
            continue
          }
          const image = photo ? await coverImage({ cover: photo, mtime: 0 } as PhotoEntry) : await coverImage(entry)
          await frameStore.asyncActions.applyTemplate({
            name: scene.name,
            scenes: [scene],
            ...(image ? { image } : {}),
          })
        }
        if (customLink) {
          const albumUrl = customLink.replace(/\/+$/, '')
          if (options.activate) {
            reused = existingPhotoScene(scenesBefore, albumUrl, null)
          }
          if (!reused) {
            const scene = buildPhotoAlbumScene({
              name: 'Photo album',
              albumUrl,
              seconds: values.seconds,
              order: values.order,
              fit: values.fit,
              shapes: values.shapes,
            })
            if (options.activate && !options.save) {
              scenesLogic({ frameId: props.frameId }).actions.previewScene(scene.id, null, [scene])
              previewed = true
            } else {
              await frameStore.asyncActions.applyTemplate({ name: scene.name, scenes: [scene] })
            }
          }
        }
        const scenesAfter = (frameStore.values.frameForm?.scenes ?? frameStore.values.scenes) as FrameScene[]
        const firstNew = scenesAfter.find((scene) => !sceneIdsBefore.has(scene.id))
        if (firstNew) {
          // Installed means saved: the scenes go to the backend now, not on a
          // later Save, and the new scene's drawer opens on the saved frame.
          await frameStore.asyncActions.submitFrameFormRequest(frameStore.values.frameForm as FrameType)
          const saveError = frameStore.values.frameFormSaveError
          if (saveError) {
            actions.setError(saveError.message || 'Could not save the frame.')
            return
          }
        }
        actions.setSelectedAlbums([])
        actions.setCustomLink('')
        if (workspaceLogic.isMounted()) {
          workspaceLogic.actions.closeTemplateDrawer()
        }
        if (previewed) {
          return
        }
        const shown = reused ?? firstNew
        if (shown) {
          scenesLogic({ frameId: props.frameId }).actions.focusScene(shown.id)
          openSceneControlDrawer(props.frameId, shown.id)
          if (options.activate) {
            await activateScene(props.frameId, shown.id)
          }
        }
      } catch (error) {
        actions.setError(error instanceof Error ? error.message : 'Could not install the scenes.')
      } finally {
        actions.setInstalling(false)
      }
    },
  })),
  afterMount(({ actions, props }) => {
    const preselected = takePreselection(props.frameId)
    actions.loadLibrary()
    if (preselected?.shapes) {
      actions.setShapes(preselected.shapes)
    }
    // Albums (or a photo) picked on the Photos page: install right away, no
    // second Install click in the drawer.
    if (preselected?.photo) {
      actions.install({
        photo: preselected.photo,
        activate: preselected.activate ?? false,
        save: preselected.save ?? false,
      })
    } else if (preselected?.albums.length) {
      actions.setSelectedAlbums(preselected.albums)
      actions.install({ activate: preselected.activate ?? false, save: preselected.save ?? false })
    }
  }),
])
