// The Photos page picks albums (or one photo), then opens this frame's Add
// scene drawer on the photos page. The choice crosses that navigation here
// rather than in the URL: it only has to survive one hop.
export interface PhotoScenePreselection {
  albums: string[]
  /** One photo's path: a scene that shows it alone, in place of album scenes. */
  photo?: string | null
  /** "Show on frame": make the scene the frame's current one once it is installed. */
  activate?: boolean
  /** With `activate`: install the scene on the frame (true), or only preview it there (false, the default). */
  save?: boolean
  /** Which photos the scenes play, by shape; every shape when left out. */
  shapes?: PhotoAlbumShape[]
}

/** An album link from elsewhere (another FrameOS backend, or the cloud): an http(s) URL. */
export function isAlbumLink(value: string): boolean {
  return /^https?:\/\/[^\s/?#]+\S*$/i.test(value.trim())
}

const pendingSelections = new Map<string, PhotoScenePreselection>()

export function preselectPhotoAlbums(
  frameId: FrameId,
  albums: string[],
  options: Omit<PhotoScenePreselection, 'albums'> = {}
): void {
  pendingSelections.set(String(frameId), { albums, ...options })
}

function takePreselection(frameId: FrameId): PhotoScenePreselection | null {
  const selection = pendingSelections.get(String(frameId)) ?? null
  pendingSelections.delete(String(frameId))
  return selection
}

/** The scene on the frame that already plays this link (and this photo), if any. */
function existingPhotoScene(scenes: FrameScene[], albumUrl: string, photo: string | null): FrameScene | undefined {
  return scenes.find((scene) =>
    (scene.nodes ?? []).some((node) => {
      const data = node.data as { keyword?: string; config?: Record<string, unknown> } | undefined
      const config = data?.config ?? {}
      return (
        node.type === 'app' &&
        data?.keyword === 'photoAlbum' &&
        config.album === albumUrl &&
        String(config.photo ?? '') === (photo ?? '')
      )
    })
  )
}

/** Make `sceneId` the frame's current scene, like the Scenes panel's Activate. */
async function activateScene(frameId: FrameId, sceneId: string): Promise<void> {
  const response = await apiFetch(`/api/frames/${frameId}/event/setCurrentScene`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ sceneId, state: {} }),
  })
  if (!response.ok) {
    throw new Error('The scene is installed, but the frame could not be told to show it.')
  }
  socketLogic.actions.updateFrame({ id: frameId, active_scene_id: sceneId } as FrameType)
}

async function coverImage(entry: PhotoEntry | undefined): Promise<Blob | null> {
  if (!entry?.cover) {
    return null
  }
  try {
    const response = await fetch(photoThumbUrl({ path: entry.cover, mtime: entry.mtime, size: 0 }), {
      credentials: 'include',
    })
    if (!response.ok) {
      return null
    }
    const blob = await response.blob()
    return blob.type.startsWith('image/') ? blob : null
  } catch {
    return null
  }
}

