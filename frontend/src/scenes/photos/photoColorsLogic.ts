/** `?colors=<path>` names the open editor, as on the Assets panel. */
const COLORS_SEARCH_PARAM = 'colors'

function colorsPathFromSearch(search: Record<string, unknown> | undefined): string | null {
  const raw = search?.[COLORS_SEARCH_PARAM]
  const value = Array.isArray(raw) ? raw[0] : raw
  return value === undefined || value === null || value === '' ? null : String(value)
}

async function fetchPhotoBitmap(path: string): Promise<PreviewSource> {
  const response = await fetch(photoFileUrl(path), { credentials: 'include' })
  if (!response.ok) {
    throw new Error(`Could not load the photo (${response.status})`)
  }
  const bitmap = await createImageBitmap(await response.blob())
  return { bitmap, width: bitmap.width, height: bitmap.height }
}

function sameAdjustments(a: AssetColorProfile, b: AssetColorProfile): boolean {
  return serializeAssetColorProfile({ ...a, palette: null }) === serializeAssetColorProfile({ ...b, palette: null })
}

function entryAt(folderEntries: Record<string, PhotoEntry[]>, path: string | null): PhotoEntry | null {
  if (!path) {
    return null
  }
  return (folderEntries[parentPhotoPath(path)] ?? []).find((entry) => entry.path === path) ?? null
}

