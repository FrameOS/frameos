/**
 * Colors in the Photos library: the "Set colors" editor for one photo (the
 * Assets panel's, through ColorEditorModal) and the lightbox's preview. Both
 * show the photo on a preview target: full fidelity, one of the frames, or a
 * panel family (photoColors.ts). The profile is saved with
 * `POST /api/photos/colors` and reaches frames with the photo
 * (docs/photos.md, "Colors").
 */
export const photoColorsLogic = kea<photoColorsLogicType>([
  path(['src', 'scenes', 'photos', 'photoColorsLogic']),
  connect(() => ({
    values: [framesModel, ['framesList'], photosLogic, ['folderEntries', 'lightboxEntry']],
    actions: [photosLogic, ['updateEntry', 'showNotice', 'openLightbox', 'closeLightbox']],
  })),
  actions({
    setPreviewTarget: (key: string) => ({ key }),
    openEditor: (imagePath: string) => ({ imagePath }),
    closeEditor: true,
    setProfile: (profile: AssetColorProfile) => ({ profile }),
    setAdjustmentMode: (mode: AdjustmentMode) => ({ mode }),
    setAutoEndPoints: (autoEndPoints: AutoEndPoints | null) => ({ autoEndPoints }),
    recomputeAuto: true,
    setPalette: (palette: RgbTriplet[] | null) => ({ palette }),
    setPaletteColor: (index: number, color: RgbTriplet) => ({ index, color }),
    setSelectedTone: (selectedTone: ToneRangeName) => ({ selectedTone }),
    setSelectedHue: (selectedHue: HueRangeName) => ({ selectedHue }),
    setShowDithered: (showDithered: boolean) => ({ showDithered }),
    setShowAdjusted: (showAdjusted: boolean) => ({ showAdjusted }),
    setFit: (fit: PreviewFit) => ({ fit }),
    setSaving: (saving: boolean) => ({ saving }),
    resetProfile: true,
    saveProfile: true,
    removeProfile: true,
    openPreviousImage: true,
    openNextImage: true,
    saveAndOpenNext: true,
    loadLightboxPreview: true,
  }),
  loaders(({ values }) => ({
    source: [
      null as PreviewSource | null,
      {
        loadSource: async (imagePath: string, breakpoint) => {
          const source = await fetchPhotoBitmap(imagePath)
          breakpoint()
          return values.imagePath === imagePath ? source : null
        },
      },
    ],
    // The lightbox's photo, decoded for a canvas: only while it shows a
    // panel or a graded photo (a plain photo is an <img>).
    lightboxSource: [
      null as (PreviewSource & { path: string }) | null,
      {
        loadLightboxSource: async (path: string, breakpoint): Promise<(PreviewSource & { path: string }) | null> => {
          if (values.lightboxSource?.path === path) {
            return values.lightboxSource
          }
          const source = await fetchPhotoBitmap(path)
          breakpoint()
          values.lightboxSource?.bitmap.close()
          return { ...source, path }
        },
      },
    ],
  })),
  reducers({
    previewTargetKey: [
      FULL_FIDELITY_TARGET.key as string,
      { persist: true, storageKey: 'photoColorsLogic.previewTarget' },
      { setPreviewTarget: (_, { key }) => key },
    ],
    imagePath: [
      null as string | null,
      {
        openEditor: (_, { imagePath }) => imagePath,
        closeEditor: () => null,
      },
    ],
    sourceError: [
      null as string | null,
      {
        openEditor: () => null,
        loadSourceFailure: (_, { error }) => error,
      },
    ],
    lightboxSourceError: [
      null as string | null,
      {
        openLightbox: () => null,
        loadLightboxSource: () => null,
        loadLightboxSourceFailure: (_, { error }) => error,
      },
    ],
    profile: [
      defaultAssetColorProfile(),
      {
        openEditor: () => defaultAssetColorProfile(),
        setProfile: (_, { profile }) => profile,
        setPalette: (state, { palette }) => ({ ...state, palette }),
        setPaletteColor: (state, { index, color }) => ({
          ...state,
          palette: (state.palette ?? []).map((entry, i) => (i === index ? color : entry)),
        }),
        resetProfile: () => defaultAssetColorProfile(),
      },
    ],
    autoEndPoints: [
      null as AutoEndPoints | null,
      {
        openEditor: () => null,
        setAutoEndPoints: (_, { autoEndPoints }) => autoEndPoints,
      },
    ],
    selectedTone: ['midtones' as ToneRangeName, { setSelectedTone: (_, { selectedTone }) => selectedTone }],
    selectedHue: ['red' as HueRangeName, { setSelectedHue: (_, { selectedHue }) => selectedHue }],
    showDithered: [
      true,
      { persist: true, storageKey: 'photoColorsLogic.showDithered' },
      { setShowDithered: (_, { showDithered }) => showDithered },
    ],
    showAdjusted: [true, { setShowAdjusted: (_, { showAdjusted }) => showAdjusted, openEditor: () => true }],
    fit: [
      'cover' as PreviewFit,
      { persist: true, storageKey: 'photoColorsLogic.fit' },
      { setFit: (_, { fit }) => fit },
    ],
    saving: [false, { setSaving: (_, { saving }) => saving, openEditor: () => false }],
  }),
  selectors({
    previewTargets: [
      (s) => [s.framesList],
      (framesList: FrameType[]): PhotoPreviewTarget[] => photoPreviewTargets(framesList),
    ],
    previewTarget: [
      (s) => [s.previewTargets, s.previewTargetKey],
      (previewTargets: PhotoPreviewTarget[], previewTargetKey: string): PhotoPreviewTarget =>
        previewTargets.find((target) => target.key === previewTargetKey) ?? FULL_FIDELITY_TARGET,
    ],
    entry: [
      (s) => [s.folderEntries, s.imagePath],
      (folderEntries: Record<string, PhotoEntry[]>, imagePath: string | null): PhotoEntry | null =>
        entryAt(folderEntries, imagePath),
    ],
    savedProfile: [
      (s) => [s.entry],
      (entry: PhotoEntry | null): AssetColorProfile | null => profileOfPhotoColors(entry?.colors),
    ],
    hasSavedProfile: [(s) => [s.entry], (entry: PhotoEntry | null): boolean => !!entry?.colors],
    // The editor's contract has a loading state for profiles fetched on
    // open; a library photo's profile comes with its listing entry.
    savedProfileLoading: [(s) => [s.saving], (saving: boolean): boolean => saving],
    panelPalette: [
      (s) => [s.previewTarget],
      (previewTarget: PhotoPreviewTarget): RgbTriplet[] | null => previewTarget.palette,
    ],
    globalProfile: [
      (s) => [s.previewTarget],
      (previewTarget: PhotoPreviewTarget): AssetColorProfile | null => previewTarget.global,
    ],
    imageSize: [
      (s) => [s.previewTarget, s.source, s.entry],
      (
        previewTarget: PhotoPreviewTarget,
        source: PreviewSource | null,
        entry: PhotoEntry | null
      ): { width: number; height: number } =>
        previewSizeFor(previewTarget, source ?? { width: entry?.width || 800, height: entry?.height || 480 }),
    ],
    isDefault: [(s) => [s.profile], (profile: AssetColorProfile): boolean => profileIsDefault(profile)],
    adjustmentMode: [
      (s) => [s.profile, s.autoEndPoints],
      (profile: AssetColorProfile, autoEndPoints: AutoEndPoints | null): AdjustmentMode =>
        sameAdjustments(profile, defaultAssetColorProfile())
          ? 'none'
          : autoEndPoints && sameAdjustments(profile, autoProfileFor(profile, autoEndPoints))
          ? 'auto'
          : 'custom',
    ],
    isDirty: [
      (s) => [s.profile, s.savedProfile],
      (profile: AssetColorProfile, savedProfile: AssetColorProfile | null): boolean =>
        serializeAssetColorProfile(profile) !== serializeAssetColorProfile(savedProfile ?? defaultAssetColorProfile()),
    ],
    canSave: [
      (s) => [s.isDirty, s.source, s.saving],
      (isDirty: boolean, source: PreviewSource | null, saving: boolean): boolean => isDirty && !!source && !saving,
    ],
    // The photos of the open photo's folder, in the page's order.
    folderImagePaths: [
      (s) => [s.folderEntries, s.imagePath],
      (folderEntries: Record<string, PhotoEntry[]>, imagePath: string | null): string[] =>
        imagePath
          ? (folderEntries[parentPhotoPath(imagePath)] ?? [])
              .filter((entry) => entry.kind === 'file' && isBrowserImageName(entry.name))
              .map((entry) => entry.path)
          : [],
    ],
    imagePosition: [
      (s) => [s.imagePath, s.folderImagePaths],
      (imagePath: string | null, folderImagePaths: string[]): { index: number; count: number } => ({
        index: imagePath ? folderImagePaths.indexOf(imagePath) : -1,
        count: folderImagePaths.length,
      }),
    ],
    previousImagePath: [
      (s) => [s.imagePosition, s.folderImagePaths],
      (position: { index: number; count: number }, folderImagePaths: string[]): string | null =>
        position.index > 0 ? folderImagePaths[position.index - 1] ?? null : null,
    ],
    nextImagePath: [
      (s) => [s.imagePosition, s.folderImagePaths],
      (position: { index: number; count: number }, folderImagePaths: string[]): string | null =>
        position.index >= 0 && position.index < position.count - 1
          ? folderImagePaths[position.index + 1] ?? null
          : null,
    ],
    // The lightbox paints a canvas for a panel, or for a photo with colors;
    // anything else is the file itself.
    lightboxPainted: [
      (s) => [s.lightboxEntry, s.previewTarget],
      (lightboxEntry: PhotoEntry | null, previewTarget: PhotoPreviewTarget): boolean =>
        !!lightboxEntry &&
        isBrowserImageName(lightboxEntry.name) &&
        (previewTarget.group !== 'original' || !!lightboxEntry.colors),
    ],
  }),
  actionToUrl(() => ({
    openEditor: ({ imagePath }) => [
      urls.photos(),
      { ...router.values.searchParams, [COLORS_SEARCH_PARAM]: imagePath },
      router.values.hashParams,
    ],
    closeEditor: () => {
      const { [COLORS_SEARCH_PARAM]: _, ...search } = router.values.searchParams
      return [urls.photos(), search, router.values.hashParams]
    },
  })),
  urlToAction(({ actions, values }) => ({
    [urls.photos()]: (_, search) => {
      const imagePath = colorsPathFromSearch(search)
      if (imagePath && imagePath !== values.imagePath) {
        actions.openEditor(imagePath)
      } else if (!imagePath && values.imagePath) {
        actions.closeEditor()
      }
    },
  })),
  listeners(({ actions, values, cache }) => {
    const save = async (colors: ReturnType<typeof photoColorsOfProfile>): Promise<boolean> => {
      const imagePath = values.imagePath
      if (!imagePath) {
        return false
      }
      actions.setSaving(true)
      try {
        actions.updateEntry(await setPhotoColors(imagePath, colors))
        return true
      } catch (error) {
        actions.showNotice(
          'error',
          error instanceof PhotosApiError || error instanceof Error ? error.message : 'Could not save the colors.'
        )
        return false
      } finally {
        actions.setSaving(false)
      }
    }
    return {
      // The Auto preset depends on the photo as placed and on the palette it
      // is dithered to, so it is recomputed when any of those change.
      loadSourceSuccess: () => actions.recomputeAuto(),
      setFit: () => {
        actions.recomputeAuto()
        actions.loadLightboxPreview()
      },
      setPalette: () => actions.recomputeAuto(),
      setPaletteColor: () => actions.recomputeAuto(),
      setPreviewTarget: () => {
        actions.recomputeAuto()
        actions.loadLightboxPreview()
      },
      recomputeAuto: () => {
        const source = values.source
        if (!source || typeof document === 'undefined') {
          actions.setAutoEndPoints(null)
          return
        }
        const wasAuto = values.adjustmentMode === 'auto'
        const work: HTMLCanvasElement = (cache.autoCanvas ??= document.createElement('canvas'))
        const palette =
          values.profile.palette && values.profile.palette.length > 0
            ? values.profile.palette
            : visiblePalette(values.panelPalette)
        const endPoints = computeAutoEndPoints(work, source, {
          width: values.imageSize.width,
          height: values.imageSize.height,
          fit: values.previewTarget.group === 'original' ? 'contain' : values.fit,
          palette: palette.length > 0 ? palette : null,
        })
        actions.setAutoEndPoints(endPoints)
        // A photo without colors starts where the frame would show it: its
        // automatic fit, when the target has one on. Auto follows the target
        // around; any other slider set stays as it is.
        if (endPoints && (wasAuto || (values.previewTarget.autoFit && !values.hasSavedProfile && values.isDefault))) {
          actions.setProfile(autoProfileFor(values.profile, endPoints))
        }
      },
      setAdjustmentMode: ({ mode }) => {
        if (mode === 'none') {
          actions.setProfile({ ...defaultAssetColorProfile(), palette: values.profile.palette })
        } else if (mode === 'auto' && values.autoEndPoints) {
          actions.setProfile(autoProfileFor(values.profile, values.autoEndPoints))
        }
      },
      openEditor: ({ imagePath }) => {
        if (values.savedProfile) {
          actions.setProfile(values.savedProfile)
        }
        actions.loadSource(imagePath)
      },
      closeEditor: () => {
        values.source?.bitmap.close()
        actions.loadSourceSuccess(null)
      },
      saveProfile: async () => {
        // Auto on a target that fits by itself is what every frame with
        // automatic colors already does, panel by panel: nothing to store.
        const colors =
          values.adjustmentMode === 'auto' && values.previewTarget.autoFit && !values.profile.palette
            ? null
            : photoColorsOfProfile(values.profile)
        if (await save(colors)) {
          actions.closeEditor()
        }
      },
      removeProfile: async () => {
        if (await save(null)) {
          actions.resetProfile()
        }
      },
      // Moving on drops unsaved sliders, as closing does; "Save & next" is
      // the one that keeps them.
      openPreviousImage: () => {
        if (values.previousImagePath) {
          values.source?.bitmap.close()
          actions.openEditor(values.previousImagePath)
        }
      },
      openNextImage: () => {
        if (values.nextImagePath) {
          values.source?.bitmap.close()
          actions.openEditor(values.nextImagePath)
        }
      },
      saveAndOpenNext: async () => {
        const next = values.nextImagePath
        const colors =
          values.adjustmentMode === 'auto' && values.previewTarget.autoFit && !values.profile.palette
            ? null
            : photoColorsOfProfile(values.profile)
        if (values.canSave && !(await save(colors))) {
          return
        }
        if (next) {
          values.source?.bitmap.close()
          actions.openEditor(next)
        }
      },
      openLightbox: () => actions.loadLightboxPreview(),
      updateEntry: () => actions.loadLightboxPreview(),
      loadLightboxPreview: () => {
        const entry = values.lightboxEntry
        if (entry && values.lightboxPainted) {
          actions.loadLightboxSource(entry.path)
        }
      },
      closeLightbox: () => {
        values.lightboxSource?.bitmap.close()
        actions.loadLightboxSourceSuccess(null)
      },
    }
  }),
])
