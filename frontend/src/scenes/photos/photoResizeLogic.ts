import { framesModel } from '../../models/framesModel'
import type { FrameType } from '../../types'
import { panelRenderSize } from '../../utils/assetColors/preview'
import { PREVIEW_SIZE_PRESETS } from './photoColors'
import type { PhotoResizeFit, PhotoResizeFormat, PhotoResizeOptions } from './photosApi'

// The Resize dialog's form (PhotosWorkspace ResizeDialog): a size, from a
// frame or a common panel size or typed in, how the photo meets it, and the
// format with its own settings. Remembered between dialogs: resizing a
// library for one frame is the same choice many times over.

export const RESIZE_FITS: { value: PhotoResizeFit; label: string; hint: string }[] = [
  {
    value: 'cover',
    label: 'Fill and crop',
    hint: 'Fills the box exactly; what does not fit is cropped from the edges.',
  },
  {
    value: 'inside',
    label: 'Fit within',
    hint: 'Keeps the whole photo and its shape; one side may end up smaller than the box.',
  },
  { value: 'contain', label: 'Fit and pad', hint: 'Keeps the whole photo and pads the rest of the box with a color.' },
  { value: 'fill', label: 'Stretch', hint: 'Takes the box exactly, stretching the photo if the shapes differ.' },
]

export const RESIZE_FORMATS: { value: PhotoResizeFormat; label: string }[] = [
  { value: 'keep', label: 'Keep the format' },
  { value: 'jpeg', label: 'JPEG' },
  { value: 'png', label: 'PNG' },
  { value: 'webp', label: 'WebP' },
]

export const PNG_COLOR_CHOICES: { value: string; label: string }[] = [
  { value: '', label: 'All colors' },
  { value: '256', label: '256 colors' },
  { value: '64', label: '64 colors' },
  { value: '16', label: '16 colors' },
  { value: '8', label: '8 colors' },
  { value: '2', label: '2 colors' },
]

export interface ResizeSizeChoice {
  key: string
  label: string
  group: 'frames' | 'presets' | 'custom'
  width: number | null
  height: number | null
}

export const CUSTOM_SIZE_KEY = 'custom'

