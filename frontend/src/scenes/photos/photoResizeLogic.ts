function side(value: unknown): number | null {
  const n = Math.round(Number(value))
  return Number.isFinite(n) && n > 0 ? Math.min(16384, n) : null
}

export const photoResizeLogic = kea<photoResizeLogicType>([
  path(['src', 'scenes', 'photos', 'photoResizeLogic']),
  listeners(({ actions, values }) => ({
    swapSides: () => {
      const { width, height } = values
      actions.setSize(CUSTOM_SIZE_KEY, height, width)
    },
  })),
  connect(() => ({ values: [framesModel, ['framesList']] })),
  actions({
    /** A size choice (a frame, a preset or custom), with the sides it brings. */
    setSize: (key: string, width: number | null, height: number | null) => ({ key, width, height }),
    setWidth: (width: number | null) => ({ width }),
    setHeight: (height: number | null) => ({ height }),
    /** Turn the box on its side: width and height trade places. */
    swapSides: true,
    setFit: (fit: PhotoResizeFit) => ({ fit }),
    setFormat: (format: PhotoResizeFormat) => ({ format }),
    setQuality: (quality: number) => ({ quality }),
    setUpscale: (upscale: boolean) => ({ upscale }),
    setBackground: (background: string) => ({ background }),
    setColors: (colors: string) => ({ colors }),
  }),
  reducers({
    sizeKey: [
      'size:800x480' as string,
      { persist: true, storageKey: 'photoResizeLogic.sizeKey' },
      {
        setSize: (_, { key }) => key,
        setWidth: () => CUSTOM_SIZE_KEY,
        setHeight: () => CUSTOM_SIZE_KEY,
        swapSides: () => CUSTOM_SIZE_KEY,
      },
    ],
    width: [
      800 as number | null,
      { persist: true, storageKey: 'photoResizeLogic.width' },
      { setSize: (_, { width }) => side(width), setWidth: (_, { width }) => side(width) },
    ],
    height: [
      480 as number | null,
      { persist: true, storageKey: 'photoResizeLogic.height' },
      { setSize: (_, { height }) => side(height), setHeight: (_, { height }) => side(height) },
    ],
    fit: [
      'cover' as PhotoResizeFit,
      { persist: true, storageKey: 'photoResizeLogic.fit' },
      { setFit: (_, { fit }) => fit },
    ],
    format: [
      'keep' as PhotoResizeFormat,
      { persist: true, storageKey: 'photoResizeLogic.format' },
      { setFormat: (_, { format }) => format },
    ],
    quality: [
      85,
      { persist: true, storageKey: 'photoResizeLogic.quality' },
      { setQuality: (_, { quality }) => Math.max(1, Math.min(100, Math.round(Number(quality) || 85))) },
    ],
    upscale: [
      false,
      { persist: true, storageKey: 'photoResizeLogic.upscale' },
      { setUpscale: (_, { upscale }) => upscale },
    ],
    background: [
      '#ffffff',
      { persist: true, storageKey: 'photoResizeLogic.background' },
      { setBackground: (_, { background }) => background },
    ],
    colors: ['', { persist: true, storageKey: 'photoResizeLogic.colors' }, { setColors: (_, { colors }) => colors }],
  }),
  selectors({
    // The frames' own panels (turned as they are), the common sizes, and "custom".
    sizeChoices: [
      (s) => [s.framesList],
      (framesList: FrameType[]): ResizeSizeChoice[] => [
        ...framesList
          .filter((frame) => !frame.archived && frame.width && frame.height)
          .map((frame): ResizeSizeChoice => {
            const size = panelRenderSize(frame)
            return {
              key: `frame:${frame.id}`,
              label: `${frame.name || `Frame ${frame.id}`} (${size.width}×${size.height})`,
              group: 'frames',
              ...size,
            }
          }),
        ...PREVIEW_SIZE_PRESETS.map(
          (preset): ResizeSizeChoice => ({
            key: `size:${preset.width}x${preset.height}`,
            label: `${preset.width}×${preset.height} ${preset.label}`,
            group: 'presets',
            width: preset.width,
            height: preset.height,
          })
        ),
        { key: CUSTOM_SIZE_KEY, label: 'Custom size', group: 'custom', width: null, height: null },
      ],
    ],
    options: [
      (s) => [s.width, s.height, s.fit, s.format, s.quality, s.upscale, s.background, s.colors],
      (
        width: number | null,
        height: number | null,
        fit: PhotoResizeFit,
        format: PhotoResizeFormat,
        quality: number,
        upscale: boolean,
        background: string,
        colors: string
      ): PhotoResizeOptions => ({
        width,
        height,
        fit,
        format,
        quality,
        upscale,
        background,
        colors: format === 'png' && colors ? Number(colors) : null,
      }),
    ],
    valid: [
      (s) => [s.options],
      (options: PhotoResizeOptions): boolean =>
        (options.width !== null || options.height !== null) &&
        (options.fit === 'inside' || (options.width !== null && options.height !== null)) &&
        /^#[0-9a-fA-F]{6}$/.test(options.background),
    ],
  }),
])
