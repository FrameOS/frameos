// The Layout select (and its gear) where a card or a board is flashed
// (docs/scene-layouts.md "Chosen at the flash"): the self-hosted backend's SD
// card and ESP32 views in the deploy drawer, and the cloud's "Add frame" SD
// image and ESP32 flasher plus its "Write another SD card" and "Redeploy to
// this board". What the choice becomes is the frame's own Layout select's
// result (utils/flashLayout.ts); how it gets there is per plane: a new cloud
// frame's claim code carries it to enrollment (below), a backend frame's
// scenes are saved before the card is built or the board flashed, and a cloud
// frame that exists is saved the way its Settings would (flashLayoutApply.ts).

export interface FlashLayoutLogicProps {
  /** One picker per flow: `cloud-add-frame`, or the frame's id with its flow. */
  pickerKey: string
  /** The scenes of the frame being flashed, when it exists: its layouts are offered and the one it wears is the start. */
  frameScenes?: FrameScene[] | null
}

/** The starters as every list of them shows them: the desktops, then the full screen layouts. */
export const FLASH_LAYOUT_STARTER_GROUPS: LayoutGroup<LayoutStarter>[] = layoutGroups(LAYOUT_STARTERS, (starter) =>
  isDesktopLayout(starter.scene)
)

