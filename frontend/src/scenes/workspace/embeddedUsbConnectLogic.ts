export const embeddedUsbConnectLogic = kea<embeddedUsbConnectLogicType>([
  path(['src', 'scenes', 'workspace', 'embeddedUsbConnectLogic']),
  props({} as EmbeddedUsbConnectLogicProps),
  key((props) => props.frameId),
  connect(() => ({
    values: [embeddedUsbLogsModel, ['usbLogStreamStatesByFrameId']],
    actions: [embeddedUsbLogsModel, ['stopUsbLogStream']],
  })),
  actions({
    loadPlan: true,
    setPlan: (plan: EmbeddedProvisioningPlan | null) => ({ plan }),
    loadLatestRelease: true,
    setLatestRelease: (release: string | null) => ({ release }),
    connectUsb: true,
    disconnectUsb: true,
    probe: true,
    probeStarted: true,
    probeSuccess: (identity: UsbBoardIdentity) => ({ identity }),
    probeFailure: (error: string) => ({ error }),
    recheck: true,
    resetSession: true,
    applyFrameSettings: (confirmForeign: boolean = false) => ({ confirmForeign }),
    scanNetworks: true,
    setNetworks: (networks: EmbeddedUsbWifiNetwork[] | null) => ({ networks }),
    selectNetwork: (ssid: string) => ({ ssid }),
    setSsid: (ssid: string) => ({ ssid }),
    setPassword: (password: string) => ({ password }),
    applyWifi: true,
    restartDevice: true,
    factoryReset: true,
    copyManualCommand: (command: string) => ({ command }),
    setMessage: (message: string | null) => ({ message }),
    setError: (error: string | null) => ({ error }),
    setFlasherBusy: (busy: boolean) => ({ busy }),
    setUpdateBusy: (busy: boolean) => ({ busy }),
    setSettingsBusy: (busy: boolean) => ({ busy }),
    setRestartBusy: (busy: boolean) => ({ busy }),
    setFactoryResetBusy: (busy: boolean) => ({ busy }),
    setScanBusy: (busy: boolean) => ({ busy }),
    setApplyBusy: (busy: boolean) => ({ busy }),
  }),
  reducers({
    plan: [null as EmbeddedProvisioningPlan | null, { setPlan: (_, { plan }) => plan }],
    latestRelease: [null as string | null, { setLatestRelease: (_, { release }) => release }],
    identity: [
      null as UsbBoardIdentity | null,
      {
        probeSuccess: (_, { identity }) => identity,
        resetSession: () => null,
      },
    ],
    // Whether this USB session has been read (or is being read). Cleared when
    // the session ends and by recheck; set as soon as a probe starts so the
    // stream flapping during the probe itself does not queue a second one.
    probed: [
      false,
      {
        probeStarted: () => true,
        recheck: () => false,
        resetSession: () => false,
      },
    ],
    probing: [
      false,
      {
        probeStarted: () => true,
        probeSuccess: () => false,
        probeFailure: () => false,
        resetSession: () => false,
      },
    ],
    probeError: [
      null as string | null,
      {
        probeStarted: () => null,
        probeFailure: (_, { error }) => error,
        resetSession: () => null,
      },
    ],
    networks: [
      null as EmbeddedUsbWifiNetwork[] | null,
      {
        setNetworks: (_, { networks }) => networks,
        resetSession: () => null,
        factoryReset: () => null,
      },
    ],
    ssid: [
      '',
      {
        setSsid: (_, { ssid }) => ssid,
        selectNetwork: (_, { ssid }) => ssid,
      },
    ],
    password: [
      '',
      {
        setPassword: (_, { password }) => password,
        selectNetwork: () => '',
      },
    ],
    message: [
      null as string | null,
      {
        setMessage: (_, { message }) => message,
        // Every action clears the previous outcome before it starts.
        applyFrameSettings: () => null,
        scanNetworks: () => null,
        applyWifi: () => null,
        restartDevice: () => null,
        factoryReset: () => null,
        connectUsb: () => null,
        selectNetwork: () => null,
      },
    ],
    error: [
      null as string | null,
      {
        setError: (_, { error }) => error,
        applyFrameSettings: () => null,
        scanNetworks: () => null,
        applyWifi: () => null,
        restartDevice: () => null,
        factoryReset: () => null,
        connectUsb: () => null,
        selectNetwork: () => null,
      },
    ],
    copied: [false, { copyManualCommand: () => true }],
    flasherBusy: [false, { setFlasherBusy: (_, { busy }) => busy }],
    updateBusy: [false, { setUpdateBusy: (_, { busy }) => busy }],
    settingsBusy: [false, { setSettingsBusy: (_, { busy }) => busy }],
    restartBusy: [false, { setRestartBusy: (_, { busy }) => busy }],
    factoryResetBusy: [false, { setFactoryResetBusy: (_, { busy }) => busy }],
    scanBusy: [false, { setScanBusy: (_, { busy }) => busy }],
    applyBusy: [false, { setApplyBusy: (_, { busy }) => busy }],
  }),
  selectors({
    mode: [() => [], (): WorkspaceMode => workspaceMode()],
    cloudManaged: [(_, p) => [p.frame], (frame: FrameType): boolean => isEsp32CloudFrame(frame)],
    frameName: [(_, p) => [p.frame], (frame: FrameType): string => frame.name || frameHost(frame)],
    // The self-hosted backend knows what a stock image must be told to become
    // this frame; the cloud pushes its settings over the hub instead, and a
    // device's own admin bundle has no plan to fetch.
    canProvision: [
      (s) => [s.cloudManaged, s.mode],
      (cloudManaged: boolean, mode: WorkspaceMode): boolean => !cloudManaged && mode === 'backend',
    ],
    // Both control planes serve the release listing; the device's own admin
    // bundle serves neither that nor the firmware bytes.
    releaseAvailable: [
      (s, p) => [s.mode, p.frame],
      (mode: WorkspaceMode, frame: FrameType): boolean => mode !== 'frameAdmin' && hasReleaseFirmwarePlatform(frame),
    ],
    usbLogStreamState: [
      (s, p) => [s.usbLogStreamStatesByFrameId, p.frameId],
      (
        states: Record<FrameId, EmbeddedUsbLogStreamState | undefined>,
        frameId: FrameId
      ): EmbeddedUsbLogStreamState | undefined => states[frameId],
    ],
    usbLogStreamOpen: [
      (s) => [s.usbLogStreamState],
      (state: EmbeddedUsbLogStreamState | undefined): boolean => isEmbeddedUsbLogStreamOpen(state),
    ],
    streaming: [
      (s) => [s.usbLogStreamState],
      (state: EmbeddedUsbLogStreamState | undefined): boolean => state?.status === 'streaming',
    ],
    streamBusy: [
      (s) => [s.usbLogStreamState],
      (state: EmbeddedUsbLogStreamState | undefined): boolean =>
        state?.status === 'selecting' || state?.status === 'connecting' || state?.status === 'stopping',
    ],
    flowBusy: [(s) => [s.flasherBusy, s.updateBusy], (a: boolean, b: boolean): boolean => a || b],
    actionBusy: [
      (s) => [s.settingsBusy, s.restartBusy, s.factoryResetBusy, s.scanBusy, s.applyBusy],
      (a: boolean, b: boolean, c: boolean, d: boolean, e: boolean): boolean => a || b || c || d || e,
    ],
    busy: [
      (s) => [s.flowBusy, s.actionBusy, s.probing],
      (flowBusy: boolean, actionBusy: boolean, probing: boolean): boolean => flowBusy || actionBusy || probing,
    ],
    // A flash closes the log stream for its duration; the card stays in its
    // connected layout while one of ours holds the port.
    connected: [
      (s) => [s.usbLogStreamOpen, s.flowBusy],
      (usbLogStreamOpen: boolean, flowBusy: boolean): boolean => usbLogStreamOpen || flowBusy,
    ],
    expectedBackendUrl: [
      (s) => [s.plan],
      (plan: EmbeddedProvisioningPlan | null): string | null =>
        plan?.settings.find((setting) => setting.key === 'backend')?.value ?? null,
    ],
    status: [
      (s) => [s.identity],
      (identity: UsbBoardIdentity | null): EmbeddedUsbStatus | null =>
        identity && identity.kind !== 'silent' ? identity.status : null,
    ],
    deviceVersion: [
      (s) => [s.status],
      (status: EmbeddedUsbStatus | null): string | null => normalizedFirmwareVersion(status?.version),
    ],
    firmwareOutdated: [
      (s) => [s.deviceVersion, s.latestRelease],
      (deviceVersion: string | null, latestRelease: string | null): boolean =>
        Boolean(deviceVersion && latestRelease && deviceVersion !== latestRelease),
    ],
    wifiConfigured: [
      (s) => [s.status],
      (status: EmbeddedUsbStatus | null): boolean => Boolean(status?.config?.wifiSsid),
    ],
    wifiConnected: [(s) => [s.status], (status: EmbeddedUsbStatus | null): boolean => status?.wifi?.state === 2],
    identityKnown: [
      (s) => [s.identity, s.probing],
      (identity: UsbBoardIdentity | null, probing: boolean): boolean => identity !== null && !probing,
    ],
    boardRunsFrameOS: [
      (s) => [s.identityKnown, s.identity],
      (identityKnown: boolean, identity: UsbBoardIdentity | null): boolean =>
        identityKnown && identity !== null && identity.kind !== 'silent',
    ],
    versionLine: [
      (s) => [s.deviceVersion, s.latestRelease, s.firmwareOutdated],
      (deviceVersion: string | null, latestRelease: string | null, firmwareOutdated: boolean): string =>
        deviceVersion
          ? `FrameOS ${deviceVersion}${
              latestRelease ? (firmwareOutdated ? ` · latest ${latestRelease}` : ' · latest') : ''
            }`
          : 'FrameOS (version unknown)',
    ],
  }),
  listeners(({ actions, values, props }) => ({
    loadPlan: async () => {
      if (!values.canProvision) {
        return
      }
      try {
        actions.setPlan(await fetchProvisioningPlan(props.frameId))
      } catch {
        // The flasher fetches its own copy and reports; here the plan only
        // sharpens the identity check and the "set up" button.
      }
    },
    loadLatestRelease: async () => {
      if (!values.releaseAvailable) {
        return
      }
      try {
        const listing = await fetchReleaseFirmwareListing()
        actions.setLatestRelease(normalizedFirmwareVersion(listing.release))
      } catch {
        // Without it the status line just omits "latest".
      }
    },
    connectUsb: async () => {
      const started = await startEmbeddedUsbLogStream(props.frameId)
      if (started) {
        workspaceLogic.actions.openFrameToolBehindDrawer(props.frameId, 'logs')
      }
    },
    disconnectUsb: () => {
      actions.stopUsbLogStream(props.frameId)
    },
    probe: async () => {
      if (values.probing) {
        return
      }
      actions.probeStarted()
      try {
        const result = await runEmbeddedUsbApiCommand(props.frameId, 'status', {
          timeoutMs: PROBE_TIMEOUT_MS,
          mirrorOutput: false,
          probe: true,
        })
        let status: EmbeddedUsbStatus | null = null
        try {
          status = JSON.parse(result.text ?? '') as EmbeddedUsbStatus
        } catch {
          status = null
        }
        actions.probeSuccess(
          classifyUsbBoard(
            props.frame,
            status,
            values.mode,
            values.expectedBackendUrl,
            'The board answered on USB, but not with a FrameOS status.'
          )
        )
      } catch (probeFailure) {
        if (isUsbSilenceError(probeFailure)) {
          actions.probeSuccess(classifyUsbBoard(props.frame, null, values.mode, values.expectedBackendUrl))
        } else {
          actions.probeFailure(errorDetail(probeFailure))
        }
      }
    },
    recheck: () => {
      actions.probe()
    },
    // The USB model's stream state is the session: gone (and no flash of ours
    // holding the port) means the board is gone; streaming again means it is
    // back and unread.
    [embeddedUsbLogsModel.actionTypes.setUsbLogStreamState]: ({ frameId }) => {
      if (frameId !== props.frameId) {
        return
      }
      if (!values.connected && !values.flowBusy) {
        if (values.identity !== null || values.probed) {
          actions.resetSession()
        }
        return
      }
      if (values.streaming && !values.probed && !values.busy) {
        actions.probe()
      }
    },
    applyFrameSettings: async ({ confirmForeign }) => {
      const identity = values.identity
      if (confirmForeign && identity?.kind === 'other-frame') {
        if (
          !window.confirm(
            `This board is currently ${identity.label}. Re-provision it as "${values.frameName}"? It stops being that other frame.`
          )
        ) {
          return
        }
      }
      actions.setSettingsBusy(true)
      try {
        const plan = values.plan ?? (await fetchProvisioningPlan(props.frameId))
        if (!plan.supported) {
          actions.setError(`This frame cannot be provisioned yet: ${plan.blockers.join(' ')}`)
          return
        }
        const { skipped } = await provisionOverUsb(props.frameId, plan, null, actions.setMessage)
        const sent = plan.settings.length - skipped.length
        actions.setMessage(`Sent ${sent} settings to the board; restarting it to apply them.`)
        await usbRestart(props.frameId)
        const notice = skippedSettingsNotice(skipped)
        actions.setMessage(
          `Sent ${sent} settings to the board. It rebooted and is applying them.${notice ? ` ${notice}` : ''}`
        )
        actions.recheck()
      } catch (settingsError) {
        actions.setError(`Applying the frame's settings failed: ${errorDetail(settingsError)}`)
      } finally {
        actions.setSettingsBusy(false)
      }
    },
    scanNetworks: async () => {
      actions.setScanBusy(true)
      try {
        const result = await usbWifiScan(props.frameId)
        // Hidden networks scan as an empty SSID and cannot be selected here.
        actions.setNetworks(result.networks.filter((network) => network.ssid.length > 0))
      } catch (scanError) {
        actions.setError(`Wi-Fi scan failed: ${errorDetail(scanError)}`)
      } finally {
        actions.setScanBusy(false)
      }
    },
    applyWifi: async () => {
      const targetSsid = values.ssid.trim()
      if (!targetSsid) {
        actions.setError('Enter or select a Wi-Fi network name first.')
        return
      }
      actions.setApplyBusy(true)
      try {
        await usbProvisionWifi(props.frameId, targetSsid, values.password)
        actions.setPassword('')
        actions.setMessage(`Wi-Fi settings saved. The device rebooted and is joining "${targetSsid}".`)
        actions.recheck()
      } catch (applyError) {
        actions.setError(`Applying Wi-Fi settings failed: ${errorDetail(applyError)}`)
      } finally {
        actions.setApplyBusy(false)
      }
    },
    restartDevice: async () => {
      actions.setRestartBusy(true)
      try {
        await usbRestart(props.frameId)
        actions.setMessage('Restart acknowledged. The device rebooted and the USB session reconnected.')
        actions.recheck()
      } catch (restartError) {
        actions.setError(`Restart failed: ${errorDetail(restartError)}`)
      } finally {
        actions.setRestartBusy(false)
      }
    },
    factoryReset: async () => {
      // A reset is `nvs_erase_all` on the whole frameos namespace
      // (fos_config.c), which takes a cloud enrollment with it — cloud_url,
      // cloud_fid and the device token all live there. On a cloud-managed
      // frame that is not a reset but an unlink, so say so.
      if (
        !window.confirm(
          values.cloudManaged
            ? `Factory reset "${values.frameName}"? This erases everything the board has stored — Wi-Fi, hardware settings AND its enrollment in this account. It will NOT come back as this frame: re-link it afterwards from "Re-link a wiped board", and this frame row is left behind empty until then. To install new firmware, use "Update firmware, keep settings" instead. This cannot be undone.`
            : `Factory reset "${values.frameName}"? This erases the device's Wi-Fi, backend and hardware settings and reboots it. This cannot be undone.`
        )
      ) {
        return
      }
      actions.setFactoryResetBusy(true)
      try {
        await usbFactoryReset(props.frameId)
        actions.setMessage(
          values.cloudManaged
            ? 'Factory reset complete. The device erased its settings — including its enrollment — and rebooted.'
            : 'Factory reset complete. The device erased its settings and rebooted.'
        )
        actions.recheck()
      } catch (resetError) {
        actions.setError(`Factory reset failed: ${errorDetail(resetError)}`)
      } finally {
        actions.setFactoryResetBusy(false)
      }
    },
    copyManualCommand: ({ command }) => {
      copy(command)
    },
  })),
  afterMount(({ actions }) => {
    actions.loadPlan()
    actions.loadLatestRelease()
  }),
])
