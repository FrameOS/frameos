import { MakeLogicType, actions, afterMount, kea, key, path, props, propsChanged, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { buildAppTypeDeclarations } from '../../utils/appTypeDeclarations'
import { loadAppSources } from '../../utils/sceneApps'

export interface SystemAppSourceLogicProps {
  keyword: string | null
}

const sourceLoadOrder = ['README.md', 'app.ts', 'app.js', 'app.tsx', 'app.jsx', 'app.nim', 'config.nim']
const primaryFiles = ['config.json', 'app.ts', 'app.js', 'app.tsx', 'app.jsx', 'app.nim']

function firstSourceFile(sources: Record<string, string>): string {
  for (const file of sourceLoadOrder) {
    if (file in sources) {
      return file
    }
  }
  return Object.keys(sources)[0] ?? ''
}

function withoutGeneratedSources(sources: Record<string, string>): Record<string, string> {
  if (sources['app_loader.nim'] === undefined) {
    return sources
  }
  const { ['app_loader.nim']: _ignored, ...filteredSources } = sources
  return filteredSources
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface systemAppSourceLogicValues {
  activeFile: string
  appTypeDeclarations: string
  configJson: Record<string, any> | null
  filenames: string[]
  sources: Record<string, string>
  sourcesLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface systemAppSourceLogicActions {
  loadSources: () => any
  loadSourcesFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadSourcesSuccess: (
    sources: Record<string, string>,
    payload?: any
  ) => {
    sources: Record<string, string>
    payload?: any
  }
  setActiveFile: (file: string) => {
    file: string
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface systemAppSourceLogicMeta {
  key: string
  __keaTypeGenInternalSelectorTypes: {
    configJson: (sources: Record<string, string>) => Record<string, any> | null
    appTypeDeclarations: (configJson: Record<string, any> | null) => string
    filenames: (sources: Record<string, string>) => string[]
  }
}

export type systemAppSourceLogicType = MakeLogicType<
  systemAppSourceLogicValues,
  systemAppSourceLogicActions,
  SystemAppSourceLogicProps
> &
  systemAppSourceLogicMeta

export const systemAppSourceLogic = kea<systemAppSourceLogicType>([
  path(['src', 'scenes', 'workspace', 'systemAppSourceLogic']),
  props({} as SystemAppSourceLogicProps),
  key((props) => props.keyword ?? 'none'),
  actions({
    setActiveFile: (file: string) => ({ file }),
  }),
  loaders(({ actions, props }) => ({
    sources: [
      {} as Record<string, string>,
      {
        loadSources: async () => {
          if (!props.keyword) {
            actions.setActiveFile('')
            return {}
          }

          try {
            // Embedded catalogs first, the backend API second (loadAppSources)
            // — on control planes without /api/apps/source (the cloud, the
            // on-device admin) the embedded sources are the only copy.
            const sources = withoutGeneratedSources(await loadAppSources(props.keyword))
            actions.setActiveFile(firstSourceFile(sources))
            return sources
          } catch (error) {
            console.error(error)
            actions.setActiveFile('')
            return {}
          }
        },
      },
    ],
  })),
  reducers({
    activeFile: [
      '',
      {
        setActiveFile: (_, { file }) => file,
      },
    ],
  }),
  selectors({
    configJson: [
      (s) => [s.sources],
      (sources: systemAppSourceLogicValues['sources']): Record<string, any> | null => {
        try {
          return JSON.parse(sources['config.json'])
        } catch (e) {
          return null
        }
      },
    ],
    appTypeDeclarations: [
      (s) => [s.configJson],
      (configJson: systemAppSourceLogicValues['configJson']): string => buildAppTypeDeclarations(configJson),
    ],
    filenames: [
      (s) => [s.sources],
      (sources: systemAppSourceLogicValues['sources']): string[] => {
        const filenames = Object.keys(sources)
        const first = primaryFiles.filter((file) => filenames.includes(file))
        const rest = filenames.filter((file) => !primaryFiles.includes(file)).sort()
        return [...first, ...rest]
      },
    ],
  }),
  propsChanged(({ actions, props }, oldProps) => {
    if (props.keyword !== oldProps.keyword) {
      actions.loadSources()
    }
  }),
  afterMount(({ actions }) => {
    actions.loadSources()
  }),
])
