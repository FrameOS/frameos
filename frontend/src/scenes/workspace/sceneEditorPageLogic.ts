interface NavigationApi {
  currentEntry?: { index: number } | null
}

/** Whether this tab came to the editor from another page of the app: the
 * Navigation API lists only this origin's entries, so an index above 0 is a
 * page of ours to go back to. Without the API there is no telling a page of
 * ours from another site's, and Back goes to the frame. */
export function canGoBackInApp(): boolean {
  const navigation = (window as unknown as { navigation?: NavigationApi }).navigation
  return !!navigation?.currentEntry && navigation.currentEntry.index > 0
}

/** The scenes as the workspace's panels (AI, preview) take them: JSON. */
export function scenesAsJson(scenes: FrameScene[]): SceneJson[] {
  return scenes as unknown as SceneJson[]
}

/** The AI panel's scenes event, applied to the frame's form (unsaved, like
 * every edit in the editor): a modified scene replaces its namesake, a new
 * one joins the frame's scenes. Returns the scene to show — the AI panel's
 * render check targets it, so this runs synchronously, not as an action. */
export function applyAiEventToFrame(
  frameId: FrameId,
  event: AiScenesEvent,
  selectedSceneId: string | null
): string | null {
  const frame = frameLogic({ frameId })
  const form = frame.values.frameForm
  const result = applyAiScenes(scenesAsJson(frame.values.scenes), event, selectedSceneId)
  frame.actions.setFrameFormValues({
    scenes: result.scenes.map((scene) => sanitizeScene(scene as unknown as Partial<FrameScene>, form)),
  })
  if (result.selectedSceneId && result.selectedSceneId !== selectedSceneId) {
    sceneEditorPageLogic({ frameId }).actions.selectScene(result.selectedSceneId)
  }
  return result.selectedSceneId
}

// A frame's scene page (/scenes/:frameId/:sceneId): the scene store's
// workspace (Editor · AI · Preview, frontend/src/sceneWorkspace) over one
// of the frame's scenes. Back goes where the page was opened from; another
// scene (one the AI built) replaces the URL, so that Back still does.
export const sceneEditorPageLogic = kea<sceneEditorPageLogicType>([
  path(['src', 'scenes', 'workspace', 'sceneEditorPageLogic']),
  props({} as SceneEditorPageLogicProps),
  key((props) => props.frameId),
  connect((props: SceneEditorPageLogicProps) => ({
    values: [frameLogic(props), ['frame', 'scenes'], workspaceLogic, ['selectedSceneIdsByFrame', 'selectedSceneId']],
  })),
  actions({
    goBack: true,
    selectScene: (sceneId: string) => ({ sceneId }),
    savePushScene: (sceneId: string) => ({ sceneId }),
    renameScene: (sceneId: string, name: string) => ({ sceneId, name }),
    togglePanel: (panel: SceneEditorPanelName, narrow: boolean) => ({ panel, narrow }),
    showInPreview: (scenes: SceneJson[], sceneId: string, narrow: boolean) => ({ scenes, sceneId, narrow }),
    setPreviewScenes: (scenes: SceneJson[] | null) => ({ scenes }),
  }),
  reducers({
    // The open panels, remembered per browser like the store's (the same key).
    panels: [
      (typeof window === 'undefined' ? null : readStoredPanels()) ?? defaultSceneEditorPanels,
      {
        togglePanel: (state, { panel, narrow }) =>
          narrow ? (state[panel] ? state : { ...state, [panel]: true }) : { ...state, [panel]: !state[panel] },
        showInPreview: (state) => ({ ...state, preview: true }),
      },
    ],
    // A narrow viewport shows one panel at a time: the last one picked.
    activePanel: [
      null as SceneEditorPanelName | null,
      {
        togglePanel: (state, { panel, narrow }) => (narrow ? panel : state),
        showInPreview: (state, { narrow }) => (narrow ? 'preview' : state),
      },
    ],
    // What the Preview panel runs: the frame's scenes as they were when it
    // opened (or the ones an AI frame was rendered from, "Show in preview").
    previewScenes: [
      null as SceneJson[] | null,
      {
        setPreviewScenes: (_, { scenes }) => scenes,
        showInPreview: (_, { scenes }) => scenes,
      },
    ],
  }),
  selectors(({ props }) => ({
    // The raw per-frame selection first: workspaceLogic's selectedSceneId
    // validates against framesModel, which only knows SAVED scenes, while
    // frameLogic's `scenes` holds the form's (an unsaved scene too).
    resolvedSceneId: [
      (s) => [s.scenes, s.selectedSceneIdsByFrame, s.selectedSceneId],
      (
        scenes: FrameScene[],
        selectedSceneIdsByFrame: Record<FrameId, string>,
        selectedSceneId: string | null
      ): string | null => {
        const requested = selectedSceneIdsByFrame[props.frameId] ?? selectedSceneId
        const known = (sceneId: string | null): sceneId is string =>
          !!sceneId && scenes.some((scene) => scene.id === sceneId)
        if (known(requested)) {
          return requested
        }
        if (known(selectedSceneId)) {
          return selectedSceneId
        }
        return (scenes.find((scene) => scene.default) ?? scenes[0])?.id ?? null
      },
    ],
  })),
  listeners(({ actions, values, props }) => ({
    goBack: () => {
      if (canGoBackInApp()) {
        window.history.back()
      } else {
        router.actions.push(urls.frame(props.frameId))
      }
    },
    selectScene: ({ sceneId }) => {
      workspaceLogic.actions.setRouteSelection(props.frameId, sceneId)
      router.actions.replace(urls.scenes(props.frameId, sceneId), router.values.searchParams, router.values.hashParams)
    },
    savePushScene: ({ sceneId }) => {
      // The scene drawer's "Save & push": the scene and the connected scenes
      // it draws or switches to (utils/scenePush.ts), saved first.
      scenesLogic({ frameId: props.frameId }).actions.pushScene(sceneId, false)
    },
    renameScene: ({ sceneId, name }) => {
      frameLogic({ frameId: props.frameId }).actions.updateScene(sceneId, { name })
    },
    togglePanel: ({ panel, narrow }) => {
      // The preview runs what the frame's form holds as it opens.
      if (panel === 'preview' && (narrow || values.panels.preview)) {
        actions.setPreviewScenes(scenesAsJson(values.scenes))
      }
      if (!narrow) {
        storePanels(values.panels)
      }
    },
    showInPreview: ({ sceneId }) => {
      if (values.scenes.some((scene) => scene.id === sceneId)) {
        actions.selectScene(sceneId)
      }
    },
  })),
  subscriptions(({ props }) => ({
    // The shown scene's diagram takes the keyboard (Cmd+Z and the rest).
    resolvedSceneId: (sceneId: string | null) => {
      if (sceneId) {
        sceneFileTreeLogic({ frameId: props.frameId }).actions.syncScene(sceneId)
      }
    },
    frame: (frame: FrameType | null) => {
      const app = isCloudMode() ? 'FrameOS Cloud' : 'FrameOS Backend'
      document.title = frame ? `${frame.name || frameHost(frame)} · Scenes · ${app}` : `Scenes · ${app}`
    },
  })),
  afterMount(({ actions, values, props }) => {
    if (values.panels.preview) {
      actions.setPreviewScenes(scenesAsJson(values.scenes))
    }
    // The workspace's panels call this plane's routes: the SPA's apiFetch
    // (project prefix, session) and the frame as the AI's context. On a
    // backend the preview's proxy is the frame's own; the cloud keeps its
    // store proxy and its turn resume.
    const cloud = isCloudMode()
    setSceneWorkspaceHost({
      fetch: (path, init) => apiFetch(path, init),
      aiChatTurnsUrl: cloud ? '/api/ai/chat/turns' : null,
      aiChatContext: () => ({ frameId: props.frameId }),
      ...(cloud ? {} : { previewProxyUrl: null }),
    })
    if (!cloud) {
      void projectApiPath(`/api/frames/${props.frameId}/scene_preview_proxy`).then((path) =>
        setSceneWorkspaceHost({
          fetch: (url, init) => apiFetch(url, init),
          aiChatTurnsUrl: null,
          aiChatContext: () => ({ frameId: props.frameId }),
          previewProxyUrl: getBasePath() + path,
        })
      )
    }
  }),
])
