/** Resolves once the editor iframe has answered a get-scenes (its reply is
 * the usual scenes message), or after a second without an answer. */
function currentScenesFromEditor(cache: Record<string, any>): Promise<void> {
  const editorWindow = cache.editorWindow as Window | null
  if (!editorWindow) {
    return Promise.resolve()
  }
  return new Promise((resolve) => {
    cache.scenesWaiters = [...(cache.scenesWaiters ?? []), resolve]
    editorWindow.postMessage({ type: 'frameos-editor:get-scenes' }, window.location.origin)
    window.setTimeout(resolve, 1000)
  })
}

function listingOf(template: TemplateType): LocalSceneListing {
  return { name: template.name, description: template.description ?? null }
}

/** The AI panel's scenes event, applied to the saved scene's draft: the
 * editor is loaded with the result (its scenes re-init). Returns the scene to
 * show — the AI panel's render check targets it, so it runs synchronously. */
export function applyAiEventToTemplate(templateId: string, event: AiScenesEvent): string | null {
  const logic = localSceneEditorLogic({ templateId })
  const current = logic.values.latestScenes ?? logic.values.editorScenes ?? []
  const result = applyAiScenes(current, event, logic.values.selectedSceneId)
  logic.actions.loadEditorScenes(result.scenes, result.selectedSceneId)
  return result.selectedSceneId
}

// A backend's saved scene (a template: the local scenes page's Edit) in the
// scene store's workspace (Editor · AI · Preview). It has no frame, so the
// editor column is the editor bundle in an iframe (LocalTemplateEditorColumn);
// this logic keeps the draft — the scenes the editor reports, the listing
// template.json edits — and saves both with the template route's PATCH.
export const localSceneEditorLogic = kea<localSceneEditorLogicType>([
  path(['src', 'scenes', 'workspace', 'localSceneEditorLogic']),
  props({} as LocalSceneEditorLogicProps),
  key((props) => props.templateId),
  connect(() => ({ values: [workspaceLogic, ['theme']] })),
  actions({
    editorScenesChanged: (scenes: SceneJson[]) => ({ scenes }),
    loadEditorScenes: (scenes: SceneJson[], selectedSceneId: string | null) => ({ scenes, selectedSceneId }),
    setListing: (changes: Partial<LocalSceneListing>) => ({ changes }),
    selectScene: (sceneId: string | null) => ({ sceneId }),
    togglePanel: (panel: SceneEditorPanelName, narrow: boolean) => ({ panel, narrow }),
    showInPreview: (scenes: SceneJson[], sceneId: string, narrow: boolean) => ({ scenes, sceneId, narrow }),
    setPreviewScenes: (scenes: SceneJson[] | null) => ({ scenes }),
    save: true,
    saveFinished: (error: string | null, scenesJson: string | null) => ({ error, scenesJson }),
    goBack: true,
    /** The editor iframe's window (LocalTemplateEditorColumn), which Save
     * asks for the scenes as they are (its reports are debounced). */
    setEditorWindow: (editorWindow: Window | null) => ({ editorWindow }),
  }),
  loaders(({ props }) => ({
    template: [
      null as TemplateType | null,
      {
        loadTemplate: async () => {
          const response = await apiFetch(`/api/templates/${encodeURIComponent(props.templateId)}`)
          if (!response.ok) {
            throw new Error(response.status === 404 ? 'This saved scene does not exist.' : 'Could not load the scene.')
          }
          return (await response.json()) as TemplateType
        },
      },
    ],
  })),
  reducers({
    // What the editor is loaded with: the saved scenes, then whatever the AI
    // delivers (a new identity re-inits the editor). Its own edits do not
    // come back here — they would reload it under the user's cursor.
    editorScenes: [
      null as SceneJson[] | null,
      {
        loadTemplateSuccess: (state, { template }) => state ?? ((template?.scenes ?? []) as unknown as SceneJson[]),
        loadEditorScenes: (_, { scenes }) => scenes,
      },
    ],
    // The editor's latest scenes (it reports them debounced).
    latestScenes: [
      null as SceneJson[] | null,
      {
        editorScenesChanged: (_, { scenes }) => scenes,
        loadEditorScenes: (_, { scenes }) => scenes,
      },
    ],
    // The editor echoes the scenes it was handed (normalised: defaults filled
    // in, positions settled) as its first report; that echo, not the stored
    // JSON, is what "unchanged" means. A save moves it to what was saved.
    baselineScenesJson: [
      null as string | null,
      {
        editorScenesChanged: (state, { scenes }) => state ?? JSON.stringify(scenes),
        saveFinished: (state, { error, scenesJson }) => (error || scenesJson === null ? state : scenesJson),
      },
    ],
    listing: [
      null as LocalSceneListing | null,
      {
        loadTemplateSuccess: (_, { template }) => (template ? listingOf(template) : null),
        setListing: (state, { changes }) => (state ? { ...state, ...changes } : state),
      },
    ],
    selectedSceneId: [
      null as string | null,
      {
        selectScene: (_, { sceneId }) => sceneId,
        loadEditorScenes: (state, { selectedSceneId }) => selectedSceneId ?? state,
      },
    ],
    // The open panels, remembered per browser like the store's (the same key).
    panels: [
      (typeof window === 'undefined' ? null : readStoredPanels()) ?? defaultSceneEditorPanels,
      {
        togglePanel: (state, { panel, narrow }) =>
          narrow ? (state[panel] ? state : { ...state, [panel]: true }) : { ...state, [panel]: !state[panel] },
        showInPreview: (state) => ({ ...state, preview: true }),
      },
    ],
    activePanel: [
      null as SceneEditorPanelName | null,
      {
        togglePanel: (state, { panel, narrow }) => (narrow ? panel : state),
        showInPreview: (state, { narrow }) => (narrow ? 'preview' : state),
      },
    ],
    previewScenes: [
      null as SceneJson[] | null,
      {
        setPreviewScenes: (_, { scenes }) => scenes,
        showInPreview: (_, { scenes }) => scenes,
      },
    ],
    saving: [false, { save: () => true, saveFinished: () => false }],
    saveError: [null as string | null, { save: () => null, saveFinished: (_, { error }) => error }],
  }),
  selectors({
    scenesChanged: [
      (s) => [s.latestScenes, s.baselineScenesJson],
      (scenes: SceneJson[] | null, baseline: string | null): boolean =>
        !!scenes && baseline !== null && JSON.stringify(scenes) !== baseline,
    ],
    listingChanged: [
      (s) => [s.listing, s.template],
      (listing: LocalSceneListing | null, template: TemplateType | null): boolean =>
        !!listing &&
        !!template &&
        (listing.name !== template.name || (listing.description ?? '') !== (template.description ?? '')),
    ],
    unsavedChanges: [
      (s) => [s.scenesChanged, s.listingChanged],
      (scenesChanged: boolean, listingChanged: boolean): boolean => scenesChanged || listingChanged,
    ],
  }),
  listeners(({ actions, values, cache }) => ({
    setEditorWindow: ({ editorWindow }) => {
      cache.editorWindow = editorWindow
    },
    editorScenesChanged: () => {
      const waiters = (cache.scenesWaiters ?? []) as (() => void)[]
      cache.scenesWaiters = []
      waiters.forEach((resolve) => resolve())
    },
    loadTemplateSuccess: ({ template }) => {
      if (!values.selectedSceneId && template?.scenes?.length) {
        const scenes = template.scenes
        actions.selectScene((scenes.find((scene) => scene.default) ?? scenes[0]).id)
      }
      if (values.panels.preview && !values.previewScenes) {
        actions.setPreviewScenes(values.editorScenes)
      }
    },
    togglePanel: ({ panel, narrow }) => {
      if (panel === 'preview' && (narrow || values.panels.preview)) {
        actions.setPreviewScenes(values.latestScenes ?? values.editorScenes)
      }
      if (!narrow) {
        storePanels(values.panels)
      }
    },
    showInPreview: ({ sceneId, scenes }) => {
      if (scenes.some((scene) => scene.id === sceneId)) {
        actions.selectScene(sceneId)
      }
    },
    save: async () => {
      const template = values.template
      const listing = values.listing
      if (!template?.id || !listing) {
        actions.saveFinished(null, null)
        return
      }
      const name = listing.name.trim()
      if (!name) {
        actions.saveFinished('A name is required.', null)
        return
      }
      await currentScenesFromEditor(cache)
      const scenes = values.scenesChanged ? values.latestScenes : null
      try {
        const response = await apiFetch(`/api/templates/${encodeURIComponent(template.id)}`, {
          method: 'PATCH',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ name, description: listing.description ?? '', ...(scenes ? { scenes } : {}) }),
        })
        if (!response.ok) {
          const payload = await response.json().catch(() => ({}))
          throw new Error(payload?.detail || payload?.error || `Saving failed (${response.status})`)
        }
        const saved = (await response.json()) as TemplateType
        // The list behind the page (the local scenes page) shows it at once.
        templatesModel.actions.updateTemplate(saved)
        actions.loadTemplateSuccess(saved)
        actions.saveFinished(null, scenes ? JSON.stringify(scenes) : null)
      } catch (error) {
        actions.saveFinished(error instanceof Error ? error.message : String(error), null)
      }
    },
    goBack: () => {
      if (canGoBackInApp()) {
        window.history.back()
      } else {
        router.actions.push(urls.scenesHome('local'))
      }
    },
  })),
  afterMount(({ actions }) => {
    actions.loadTemplate()
    // A saved scene has no frame: the AI gets no frame context, and the
    // preview has no frame's proxy to route through.
    setSceneWorkspaceHost({
      fetch: (path, init) => apiFetch(path, init),
      aiChatTurnsUrl: null,
      previewProxyUrl: null,
    })
  }),
])
