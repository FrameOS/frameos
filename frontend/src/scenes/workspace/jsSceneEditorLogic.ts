import { frameLogic } from '../frame/frameLogic'
import type { FrameId, FrameScene, FrameType, StateField } from '../../types'
import { buildSceneTypeDeclarations } from '../../utils/sceneTypeDeclarations'

export interface JsSceneEditorLogicProps {
  frameId: FrameId
  sceneId: string
}

export const JS_SCENE_MAIN_FILES = ['scene.ts', 'scene.tsx', 'scene.js', 'scene.jsx']

/** Files the frame's module loader resolves: the scene's code, JSON data, and its config. */
export function isJsSceneSourceName(name: string): boolean {
  return /^[\w.\-/]+\.(ts|tsx|js|jsx|json)$/.test(name) && !name.startsWith('/') && !name.includes('..')
}

export function jsSceneMainFile(sources: Record<string, string>): string {
  for (const name of JS_SCENE_MAIN_FILES) {
    if (name in sources) {
      return name
    }
  }
  return Object.keys(sources)[0] ?? 'scene.ts'
}

