/**
 * The editor of a pure JS scene (docs/pure-js-scenes.md): the scene's
 * `sources` map as a file list and one Monaco model per file. Every edit goes
 * straight into the frame form through frameLogic.updateScene, the same way a
 * node edit does, so save/deploy and the live preview see it at once.
 */
export const jsSceneEditorLogic = kea<jsSceneEditorLogicType>([
  path(['scenes', 'workspace', 'jsSceneEditorLogic']),
  props({} as JsSceneEditorLogicProps),
  key((props) => `${props.frameId}/${props.sceneId}`),
  connect(({ frameId }: JsSceneEditorLogicProps) => ({
    values: [frameLogic({ frameId }), ['frameForm']],
    actions: [frameLogic({ frameId }), ['updateScene']],
  })),
  actions({
    setActiveFile: (name: string) => ({ name }),
    updateFile: (name: string, source: string) => ({ name, source }),
    addFile: (name: string) => ({ name }),
    renameFile: (from: string, to: string) => ({ from, to }),
    deleteFile: (name: string) => ({ name }),
  }),
  reducers({
    activeFileName: [
      '',
      {
        setActiveFile: (_, { name }) => name,
        addFile: (_, { name }) => name,
        renameFile: (state, { from, to }) => (state === from ? to : state),
        deleteFile: (state, { name }) => (state === name ? '' : state),
      },
    ],
  }),
  selectors({
    scene: [
      (s, p) => [s.frameForm, p.sceneId],
      (frameForm: Partial<FrameType>, sceneId: string): FrameScene | null =>
        frameForm?.scenes?.find((scene) => scene.id === sceneId) ?? null,
    ],
    sources: [(s) => [s.scene], (scene: FrameScene | null): Record<string, string> => scene?.sources ?? {}],
    fileNames: [
      (s) => [s.sources],
      (sources: Record<string, string>): string[] => {
        const main = jsSceneMainFile(sources)
        return Object.keys(sources).sort((a, b) => (a === main ? -1 : b === main ? 1 : a.localeCompare(b)))
      },
    ],
    mainFile: [(s) => [s.sources], (sources: Record<string, string>): string => jsSceneMainFile(sources)],
    activeFile: [
      (s) => [s.activeFileName, s.sources, s.mainFile],
      (activeFileName: string, sources: Record<string, string>, mainFile: string): string =>
        activeFileName && activeFileName in sources ? activeFileName : mainFile,
    ],
    typeDeclarations: [
      (s) => [s.scene],
      (scene: FrameScene | null): string => buildSceneTypeDeclarations(scene?.fields as StateField[] | undefined),
    ],
  }),
  listeners(({ actions, values, props }) => ({
    updateFile: ({ name, source }) => {
      if (values.sources[name] === source) {
        return
      }
      actions.updateScene(props.sceneId, { sources: { ...values.sources, [name]: source } })
    },
    addFile: ({ name }) => {
      if (!isJsSceneSourceName(name) || name in values.sources) {
        return
      }
      actions.updateScene(props.sceneId, { sources: { ...values.sources, [name]: '' } })
    },
    renameFile: ({ from, to }) => {
      if (from === to || !(from in values.sources) || !isJsSceneSourceName(to) || to in values.sources) {
        return
      }
      const sources: Record<string, string> = {}
      for (const [file, content] of Object.entries(values.sources)) {
        sources[file === from ? to : file] = content
      }
      actions.updateScene(props.sceneId, { sources })
    },
    deleteFile: ({ name }) => {
      if (!(name in values.sources) || name === values.mainFile) {
        return
      }
      const { [name]: _removed, ...sources } = values.sources
      actions.updateScene(props.sceneId, { sources })
    },
  })),
])
