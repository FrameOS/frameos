/**
 * How one frame is asked to update itself — the verb behind the single-frame
 * "Update" affordance on each control plane, so "Update all" does per frame
 * exactly what its own drawer would:
 * - `cloudNotify`: every cloud-managed frame, Pi or esp32, gets the durable
 *   notify_update_available nudge (framesModel.updateFrameFirmware).
 * - `embeddedOta`: a backend esp32 board with two app slots pulls the signed
 *   release through the backend's relay (framesModel.applyEmbeddedFirmwareOta).
 * - `deviceUpgrade`: a Buildroot card the backend only reaches through its
 *   admin login runs frameos/upgrade.nim itself (frameLogic.startDeviceUpgrade).
 * - `fullDeploy`: a Pi the backend has a shell on gets the FrameOS this
 *   backend was built with over SSH (framesModel.deployFrame, the deploy
 *   drawer's "Full deploy"); there is no release upgrade over SSH.
 */
export type FleetUpdateVerb = 'cloudNotify' | 'embeddedOta' | 'deviceUpgrade' | 'fullDeploy'

/** The verb that updates this frame from here, or null when none does (a virtual or Pico frame, a cloud frame listed by a backend). */
export function fleetUpdateVerbForFrame(frame: FrameType): FleetUpdateVerb | null {
  if (isCloudMode()) {
    const mode = workspaceMode()
    return frameMenuActionIsAllowed(mode, 'updateFirmware', frame) &&
      !frameMenuActionDisabledReason(mode, 'updateFirmware', frame)
      ? 'cloudNotify'
      : null
  }
  if (frame.managed_by === 'cloud') {
    return null
  }
  if ((frame.mode ?? 'rpios') === 'embedded') {
    const platform = frame.embedded?.platform ?? ''
    return platform !== EMBEDDED_VIRTUAL && !platform.startsWith('pico') && embeddedOtaSupported(frame)
      ? 'embeddedOta'
      : null
  }
  return frameAdminLoginIsOnlyAccess(frame) ? 'deviceUpgrade' : 'fullDeploy'
}

/** An update this UI already asked for and that has not settled: never ask again on top of it. */
export function fleetUpdateInFlight(frame: FrameType, runningTasks: LongRunningTask[]): boolean {
  if (frameUpgradeIsQueued(frame) || frameStatusWithSpinner.includes(frame.status)) {
    return true
  }
  if (
    runningTasks.some((task) => task.frameId === frame.id && (task.kind === 'deploy' || task.kind === 'embeddedOta'))
  ) {
    return true
  }
  return deviceUpgradeInFlight(frameLogic.findMounted({ frameId: frame.id })?.values.deviceUpgradeStatus)
}

/** The pause between two frames' update requests: one at a time, never a burst at the backend or the hub. */
export const FLEET_UPDATE_STAGGER_MS = 1500

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms))
}

