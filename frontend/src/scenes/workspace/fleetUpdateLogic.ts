/**
 * "Update all" in the frames sidebar: the active frames whose only pending
 * change is a FrameOS upgrade (pendingFrameosUpgrade) and that have no
 * update queued or running, updated one after another with a pause in
 * between. One run at a time: a second click while the loop runs is a no-op,
 * and every frame the loop has asked leaves the list until the next fleet
 * refresh shows the request landed (queued) or the frame moved on.
 */
export const fleetUpdateLogic = kea<fleetUpdateLogicType>([
  path(['src', 'scenes', 'workspace', 'fleetUpdateLogic']),
  connect({
    values: [
      publishedReleaseModel,
      ['latestPublishedRelease'],
      longRunningTasksModel,
      ['runningTasks'],
      workspaceLogic,
      ['homeActiveFramesList'],
    ],
  }),
  actions({
    updateAllFrames: true,
    markFrameUpdateStarted: (frameId: FrameId) => ({ frameId }),
    finishUpdateAll: true,
  }),
  reducers({
    updatingAll: [
      false,
      {
        updateAllFrames: () => true,
        finishUpdateAll: () => false,
      },
    ],
    startedFrameIds: [
      {} as Record<FrameId, number>,
      {
        markFrameUpdateStarted: (state, { frameId }) => ({ ...state, [frameId]: Date.now() }),
      },
    ],
  }),
  selectors({
    framesNeedingUpdate: [
      (s) => [s.homeActiveFramesList, s.latestPublishedRelease, s.runningTasks, s.startedFrameIds],
      (
        homeActiveFramesList: fleetUpdateLogicValues['homeActiveFramesList'],
        latestPublishedRelease: fleetUpdateLogicValues['latestPublishedRelease'],
        runningTasks: fleetUpdateLogicValues['runningTasks'],
        startedFrameIds: fleetUpdateLogicValues['startedFrameIds']
      ): FrameType[] =>
        homeActiveFramesList.filter(
          (frame) =>
            !startedFrameIds[frame.id] &&
            !!pendingFrameosUpgrade(frame, latestPublishedRelease) &&
            !!fleetUpdateVerbForFrame(frame) &&
            !fleetUpdateInFlight(frame, runningTasks)
        ),
    ],
    updateAllTitle: [
      (s) => [s.framesNeedingUpdate, s.latestPublishedRelease],
      (
        framesNeedingUpdate: fleetUpdateLogicValues['framesNeedingUpdate'],
        latestPublishedRelease: fleetUpdateLogicValues['latestPublishedRelease']
      ): string => {
        const count = framesNeedingUpdate.length
        const version = framesNeedingUpdate
          .map((frame) => pendingFrameosUpgrade(frame, latestPublishedRelease)?.currentVersion)
          .find((candidate): candidate is string => !!candidate)
        return `Update ${count} active ${count === 1 ? 'frame' : 'frames'}${version ? ` to FrameOS ${version}` : ''}`
      },
    ],
  }),
  listeners(({ actions, values, cache }) => ({
    updateAllFrames: async () => {
      // The reducer flipped `updatingAll` for the spinner; this flag is what
      // keeps a second click from starting a second loop next to the first.
      if (cache.updatingAll) {
        return
      }
      cache.updatingAll = true
      try {
        const frames = values.framesNeedingUpdate
        for (const [index, frame] of frames.entries()) {
          if (index > 0) {
            await sleep(FLEET_UPDATE_STAGGER_MS)
          }
          actions.markFrameUpdateStarted(frame.id)
          try {
            await startFrameUpdate(frame)
          } catch (error) {
            // The per-verb listener already reported the failure as a task
            // toast; the loop moves on to the next frame.
            console.error(`Update all: could not start the update of frame ${frame.id}`, error)
          }
        }
      } finally {
        cache.updatingAll = false
        actions.finishUpdateAll()
      }
    },
  })),
])

/** Ask one frame to update, the way its own drawer would, and wait for the request to be sent. */
async function startFrameUpdate(frame: FrameType): Promise<void> {
  switch (fleetUpdateVerbForFrame(frame)) {
    case 'cloudNotify':
      await framesModel.asyncActions.updateFrameFirmware(frame.id)
      // updateFrameFirmware does not refetch: the row's pending_command_types
      // is what keeps the frame out of the list once startedFrameIds is stale.
      framesModel.actions.loadFrame(frame.id)
      return
    case 'embeddedOta':
      await framesModel.asyncActions.applyEmbeddedFirmwareOta(frame.id)
      return
    case 'deviceUpgrade': {
      // The sidebar row keeps a frameLogic mounted for every listed frame; an
      // extra mount for the call's duration covers a row that is not.
      const logic = frameLogic({ frameId: frame.id })
      const unmount = logic.mount()
      try {
        await logic.asyncActions.startDeviceUpgrade()
      } finally {
        unmount()
      }
      return
    }
    case 'fullDeploy':
      await framesModel.asyncActions.deployFrame(frame.id, false)
      return
    case null:
      return
  }
}
