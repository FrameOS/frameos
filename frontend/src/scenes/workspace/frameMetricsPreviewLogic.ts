import {
  MakeLogicType,
  actions,
  afterMount,
  listeners,
  beforeUnmount,
  connect,
  kea,
  key,
  path,
  props,
  reducers,
  selectors,
} from 'kea'
import { loaders } from 'kea-loaders'

import type { MetricsType, FrameId } from '../../types'
import { apiFetch } from '../../utils/apiFetch'
import {
  filterMetricsByCategoryAndTimeRange,
  latestBatteryPercentWithFallback,
  latestMetricSummariesByCategoryFromMetrics,
  metricsByCategoryFromMetrics,
  metricTimestamp,
  type MetricSeries,
  type TimeRange,
} from '../frame/panels/Metrics/metricsLogic'
import { socketLogic } from '../socketLogic'
import { withoutBatteryMisreads } from '../../utils/batteryMisreads'

const PREVIEW_METRICS_WINDOW_MS = 60 * 60 * 1000
const PREVIEW_METRICS_LIMIT = 1000
/** Enough of the newest samples to strip an ADC misread from the last one (utils/batteryMisreads.ts). */
const NEWEST_METRICS_LIMIT = 10
const CURRENT_TIME_UPDATE_MS = 60 * 1000

export interface FrameMetricsPreviewLogicProps {
  frameId: FrameId
}

