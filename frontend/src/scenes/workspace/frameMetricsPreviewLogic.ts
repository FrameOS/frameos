export type frameMetricsPreviewLogicType = MakeLogicType<
  frameMetricsPreviewLogicValues,
  frameMetricsPreviewLogicActions,
  FrameMetricsPreviewLogicProps
> &
  frameMetricsPreviewLogicMeta

export const frameMetricsPreviewLogic = kea<frameMetricsPreviewLogicType>([
  path(['src', 'scenes', 'workspace', 'frameMetricsPreviewLogic']),
  props({} as FrameMetricsPreviewLogicProps),
  connect(() => ({ logic: [socketLogic] })),
  key((props) => props.frameId),
  actions({
    setCurrentTime: (currentTime: number) => ({ currentTime }),
  }),
  loaders(({ props }) => ({
    recentMetrics: [
      [] as MetricsType[],
      {
        loadRecentMetrics: async () => {
          try {
            const since = new Date(Date.now() - PREVIEW_METRICS_WINDOW_MS).toISOString()
            const response = await apiFetch(
              `/api/frames/${props.frameId}/metrics/recent?limit=${PREVIEW_METRICS_LIMIT}&since=${encodeURIComponent(
                since
              )}`
            )
            if (!response.ok) {
              throw new Error('Failed to fetch recent metrics')
            }
            const data = await response.json()
            return data.metrics as MetricsType[]
          } catch (error) {
            console.error(error)
            return []
          }
        },
      },
    ],
    // Only fetched when the window is empty: the newest samples whatever
    // their age, so a frame that sleeps for a day or a week keeps its glyph.
    newestMetrics: [
      [] as MetricsType[],
      {
        loadNewestMetrics: async () => {
          try {
            const response = await apiFetch(`/api/frames/${props.frameId}/metrics/recent?limit=${NEWEST_METRICS_LIMIT}`)
            if (!response.ok) {
              throw new Error('Failed to fetch the newest metrics')
            }
            const data = await response.json()
            return data.metrics as MetricsType[]
          } catch (error) {
            console.error(error)
            return []
          }
        },
      },
    ],
  })),
  listeners(({ actions }) => ({
    loadRecentMetricsSuccess: ({ recentMetrics }) => {
      if (recentMetrics.length === 0) {
        actions.loadNewestMetrics()
      }
    },
  })),
  reducers(({ props }) => ({
    currentTime: [
      Date.now(),
      {
        setCurrentTime: (_, { currentTime }) => currentTime,
      },
    ],
    recentMetrics: {
      [socketLogic.actionTypes.newMetrics]: (state, { metrics }) => {
        if (metrics.frame_id !== props.frameId) {
          return state
        }
        const cutoff = Date.now() - PREVIEW_METRICS_WINDOW_MS
        return [...state, metrics as MetricsType].filter((metric) => metricTimestamp(metric) >= cutoff)
      },
    },
  })),
  selectors({
    // Battery readings the neighbouring samples contradict are ADC misreads
    // and are stripped here, at the source, so the header chips, the sidebar
    // glyph and the metric alerts never see one (utils/batteryMisreads.ts).
    sortedRecentMetrics: [
      (s) => [s.recentMetrics],
      (metrics: frameMetricsPreviewLogicValues['recentMetrics']) =>
        withoutBatteryMisreads([...metrics].sort((a, b) => metricTimestamp(a) - metricTimestamp(b))).metrics,
    ],
    previewMetricsTimeRange: [
      (s) => [s.currentTime, s.sortedRecentMetrics],
      (
        currentTime: frameMetricsPreviewLogicValues['currentTime'],
        metrics: frameMetricsPreviewLogicValues['sortedRecentMetrics']
      ): TimeRange | null =>
        metrics.length === 0 ? null : { start: currentTime - PREVIEW_METRICS_WINDOW_MS, end: currentTime },
    ],
    metricsByCategory: [
      (s) => [s.sortedRecentMetrics],
      (metrics: frameMetricsPreviewLogicValues['sortedRecentMetrics']): Record<string, MetricSeries[]> =>
        metricsByCategoryFromMetrics(metrics),
    ],
    headerMetricsByCategory: [
      (s) => [s.metricsByCategory, s.previewMetricsTimeRange],
      (
        metricsByCategory: frameMetricsPreviewLogicValues['metricsByCategory'],
        previewMetricsTimeRange: frameMetricsPreviewLogicValues['previewMetricsTimeRange']
      ) =>
        filterMetricsByCategoryAndTimeRange(
          metricsByCategory,
          ['load', 'memoryUsage', 'diskUsage', 'batteryPercent'],
          previewMetricsTimeRange
        ),
    ],
    latestMetricSummariesByCategory: [
      (s) => [s.sortedRecentMetrics],
      (metrics: frameMetricsPreviewLogicValues['sortedRecentMetrics']): Record<string, string> =>
        latestMetricSummariesByCategoryFromMetrics(metrics),
    ],
    // Frames with a battery pin (ESP32 boards) report a charge estimate;
    // shown as a battery glyph in the header chips and the workspace sidebar,
    // from the newest reading at all when the window has none.
    latestBatteryPercent: [
      (s) => [s.sortedRecentMetrics, s.newestMetrics],
      (
        metrics: frameMetricsPreviewLogicValues['sortedRecentMetrics'],
        newestMetrics: frameMetricsPreviewLogicValues['newestMetrics']
      ): number | null => latestBatteryPercentWithFallback(metrics, newestMetrics),
    ],
  }),
  afterMount(({ actions, cache }) => {
    actions.loadRecentMetrics()
    actions.setCurrentTime(Date.now())
    cache.currentTimeInterval = window.setInterval(() => actions.setCurrentTime(Date.now()), CURRENT_TIME_UPDATE_MS)
  }),
  beforeUnmount(({ cache }) => {
    if (cache.currentTimeInterval) {
      window.clearInterval(cache.currentTimeInterval)
    }
  }),
])
