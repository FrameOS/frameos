// The backend page's half of the flash.frameos.net bridge
// (utils/flasherBridge.ts, cloud/docs/flasher.md): on a page with no Web
// Serial (plain http, a frame of another origin), the frame's USB card opens
// the flasher in a window of its own, hands it this frame's setup document
// and, when it asks, the release image this backend downloads, and files what
// comes back — the progress, the USB log lines, the board's flash size, a
// finished scene upload — under the frame, as its own flashers do.
//
// The window is opened inside the click (`start`'s listener runs in the
// dispatch, before any await), or the browser blocks it.

export interface FlasherBridgeLogicProps {
  frameId: FrameId
  frame: FrameType
}

export type FlasherBridgeStatus = 'idle' | 'waiting' | 'running' | 'done' | 'error' | 'closed'

const CLOSED_POLL_MS = 1000

function errorDetail(error: unknown): string {
  return error instanceof Error ? error.message : String(error)
}

/** This frame as a setup document: the backend's `…/embedded/setup`. */
export async function fetchFrameSetupDocument(frameId: FrameId): Promise<FrameSetupDocument> {
  const response = await apiFetch(`/api/frames/${frameId}/embedded/setup`)
  if (!response.ok) {
    let detail = ''
    try {
      detail = (await response.json())?.detail ?? ''
    } catch {}
    throw new Error(detail || `Could not read this frame's setup (HTTP ${response.status}).`)
  }
  return parseFrameSetupDocument(await response.json())
}

interface BridgeCache {
  popup?: Window | null
  onMessage?: (event: MessageEvent) => void
  closedTimer?: ReturnType<typeof setInterval>
  job?: FlasherJob | null
  flasherReady?: boolean
  jobSent?: boolean
}

