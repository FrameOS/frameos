export const flasherBridgeLogic = kea<flasherBridgeLogicType>([
  path(['src', 'scenes', 'workspace', 'flasherBridgeLogic']),
  props({} as FlasherBridgeLogicProps),
  key((props) => props.frameId),
  actions({
    start: (kind: FlasherJobKind, options: { pushScenes?: boolean; withWifi?: boolean } = {}) => ({ kind, options }),
    setStatus: (status: FlasherBridgeStatus) => ({ status }),
    setProgressReport: (phase: FlasherPhase, message: string | null, progress: number | null) => ({
      phase,
      message,
      progress,
    }),
    setError: (error: string | null) => ({ error }),
    focusWindow: true,
    closeWindow: true,
    downloadSetupFile: true,
    setDownloadBusy: (busy: boolean) => ({ busy }),
  }),
  reducers({
    status: [
      'idle' as FlasherBridgeStatus,
      {
        start: () => 'waiting',
        setStatus: (_, { status }) => status,
      },
    ],
    kind: [
      null as FlasherJobKind | null,
      {
        start: (_, { kind }) => kind,
      },
    ],
    phase: [
      'idle' as FlasherPhase,
      {
        start: () => 'idle',
        setProgressReport: (_, { phase }) => phase,
      },
    ],
    message: [
      null as string | null,
      {
        start: () => null,
        setProgressReport: (_, { message }) => message,
      },
    ],
    progress: [
      null as number | null,
      {
        start: () => null,
        setProgressReport: (_, { progress }) => progress,
      },
    ],
    error: [
      null as string | null,
      {
        start: () => null,
        setError: (_, { error }) => error,
      },
    ],
    downloadBusy: [
      false,
      {
        setDownloadBusy: (_, { busy }) => busy,
      },
    ],
  }),
  selectors({
    windowOpen: [
      (s) => [s.status],
      (status: flasherBridgeLogicValues['status']): boolean => status === 'waiting' || status === 'running',
    ],
    busy: [
      (s) => [s.windowOpen, s.downloadBusy],
      (windowOpen: boolean, downloadBusy: boolean): boolean => windowOpen || downloadBusy,
    ],
  }),
  listeners(({ actions, values, props, cache }) => {
    const bridge = cache as BridgeCache
    const target = (): string => flasherOrigin()

    const post = (message: OpenerToFlasher, transfer: Transferable[] = []): void => {
      // Only ever to the window this logic opened, and only while it shows
      // the flasher's origin: the job carries the frame's API key and Wi-Fi.
      bridge.popup?.postMessage(bridgeMessage(message), target(), transfer)
    }

    const sendJobWhenBothReady = (): void => {
      if (bridge.flasherReady && bridge.job && !bridge.jobSent) {
        bridge.jobSent = true
        post({ type: 'job', job: bridge.job })
        actions.setStatus('running')
      }
    }

    const teardown = (): void => {
      if (bridge.onMessage) {
        window.removeEventListener('message', bridge.onMessage)
      }
      if (bridge.closedTimer) {
        clearInterval(bridge.closedTimer)
      }
      bridge.onMessage = undefined
      bridge.closedTimer = undefined
    }

    const answerImageRequest = async (id: number, platform: string): Promise<void> => {
      try {
        const query = `?platform=${encodeURIComponent(platform)}`
        const response = await apiFetch(`/api/frames/firmware${query}`, { cache: 'no-store' })
        if (!response.ok) {
          throw new Error(`This backend could not download the ${platform} firmware (HTTP ${response.status}).`)
        }
        const bytes = await response.arrayBuffer()
        const signature = await apiFetch(`/api/frames/firmware${query}&signature=1`, { cache: 'no-store' })
        post(
          {
            type: 'image',
            id,
            name: response.headers.get('x-frameos-image-name') ?? '',
            release: response.headers.get('x-frameos-release') ?? '',
            bytes,
            minisig: signature.ok ? await signature.text() : null,
          },
          [bytes]
        )
      } catch (error) {
        post({ type: 'error', id, message: errorDetail(error) })
      }
    }

    const answerListingRequest = async (id: number): Promise<void> => {
      try {
        const response = await apiFetch('/api/frames/firmware')
        if (!response.ok) {
          throw new Error('This backend could not look up the latest FrameOS release.')
        }
        post({ type: 'listing', id, listing: await response.json() })
      } catch (error) {
        post({ type: 'error', id, message: errorDetail(error) })
      }
    }

    return {
      start: async ({ kind, options }) => {
        // In the click: anything awaited before this and the browser blocks
        // the window.
        teardown()
        const popup = window.open(flasherBridgeUrl(), `frameos-flasher-${props.frameId}`, 'popup,width=860,height=940')
        if (!popup) {
          actions.setStatus('error')
          actions.setError(
            'The browser blocked the flasher’s window. Allow pop-ups for this page and try again, or download the setup file and open it on flash.frameos.net.'
          )
          return
        }
        bridge.popup = popup
        bridge.job = null
        bridge.flasherReady = false
        bridge.jobSent = false
        appendBrowserFlashLog(props.frameId, `Opened ${flasherUrl()} to do the USB part for this page.`)

        bridge.onMessage = (event: MessageEvent) => {
          if (event.source !== bridge.popup || event.origin !== target()) {
            return
          }
          const message = readFlasherMessage(event.data)
          if (!message) {
            return
          }
          switch (message.type) {
            case 'ready':
              bridge.flasherReady = true
              // A reload of the flasher's window asks again: the job goes again.
              bridge.jobSent = false
              sendJobWhenBothReady()
              break
            case 'listing-request':
              void answerListingRequest(message.id)
              break
            case 'image-request':
              void answerImageRequest(message.id, message.platform)
              break
            case 'status':
              actions.setProgressReport(message.phase, message.message, message.progress)
              break
            case 'log':
              appendEmbeddedUsbLogLine(props.frameId, message.line)
              break
            case 'flash-size':
              void recordDetectedFlashSize(props.frame, message.flashSize, (line) =>
                appendBrowserFlashLog(props.frameId, line)
              )
              break
            case 'scenes-uploaded':
              void apiFetch(`/api/frames/${props.frameId}/embedded/usb_deploy_complete`, { method: 'POST' }).then(
                (response) => {
                  if (!response.ok) {
                    appendBrowserFlashLog(
                      props.frameId,
                      'Scene upload completed, but backend deploy state update failed'
                    )
                  }
                }
              )
              break
            case 'finished':
              actions.setProgressReport(
                message.outcome === 'done' ? 'done' : message.outcome === 'cancelled' ? 'idle' : 'error',
                message.message,
                null
              )
              if (message.outcome === 'done' || message.outcome === 'written') {
                framesModel.actions.loadFrame(props.frameId)
                scheduleEmbeddedUsbFrameImageRefresh(props.frameId)
              }
              actions.setStatus(
                message.outcome === 'done' ? 'done' : message.outcome === 'cancelled' ? 'running' : 'error'
              )
              break
          }
        }
        window.addEventListener('message', bridge.onMessage)
        bridge.closedTimer = setInterval(() => {
          if (bridge.popup?.closed) {
            teardown()
            bridge.popup = null
            if (values.status === 'waiting' || values.status === 'running') {
              actions.setStatus('closed')
            }
          }
        }, CLOSED_POLL_MS)

        try {
          const setup = await fetchFrameSetupDocument(props.frameId)
          bridge.job = { kind, setup, pushScenes: options.pushScenes, withWifi: options.withWifi }
          sendJobWhenBothReady()
        } catch (error) {
          actions.setStatus('error')
          actions.setError(errorDetail(error))
          popup.close()
          teardown()
        }
      },
      focusWindow: () => {
        bridge.popup?.focus()
      },
      closeWindow: () => {
        bridge.popup?.close()
        teardown()
        bridge.popup = null
        actions.setStatus('closed')
      },
      downloadSetupFile: async () => {
        actions.setDownloadBusy(true)
        actions.setError(null)
        try {
          const response = await apiFetch(`/api/frames/${props.frameId}/embedded/setup`)
          if (!response.ok) {
            throw new Error(`Could not read this frame's setup (HTTP ${response.status}).`)
          }
          // Saved as the backend wrote it; read once to name the file (and to
          // refuse to save something the flasher would refuse to open).
          const text = await response.text()
          const setup = parseFrameSetupDocument(JSON.parse(text))
          downloadBlob(new Blob([text], { type: 'application/json' }), frameSetupFileName(setup.frame.name))
        } catch (error) {
          actions.setError(errorDetail(error))
        } finally {
          actions.setDownloadBusy(false)
        }
      },
    }
  }),
  beforeUnmount(({ cache }) => {
    const bridge = cache as BridgeCache
    if (bridge.onMessage) {
      window.removeEventListener('message', bridge.onMessage)
    }
    if (bridge.closedTimer) {
      clearInterval(bridge.closedTimer)
    }
  }),
])
