import {
  MakeLogicType,
  actions,
  afterMount,
  beforeUnmount,
  connect,
  kea,
  key,
  listeners,
  path,
  props,
  reducers,
  selectors,
} from 'kea'
import { framesModel } from '../../models/framesModel'
import { workspaceLogic } from './workspaceLogic'
import type { FrameId, FrameType } from '../../types'

/** How long one example question stays before the next slides in (ms). Kept
 * in step with the `frameos-ai-example` animation in index.css. */
export const AI_EXAMPLE_INTERVAL_MS = 4200

export interface AiPromptBoxLogicProps {
  /** The frame the box asks about; null on the frames home (every frame). */
  frameId: FrameId | null
}

function frameLabel(frame: FrameType | undefined): string | null {
  const name = frame?.name?.trim()
  return name ? name : null
}

/** Example questions, with the user's own frame names where there are some:
 * "update the kitchen frame" reads better about a kitchen that exists. */
export function aiPromptExamples(frameId: FrameId | null, frames: FrameType[]): string[] {
  if (frameId !== null) {
    return [
      "What's on this frame right now?",
      'Make a scene that shows my next three calendar events',
      'Create a split scene: a clock on the left, the weather on the right',
      'Show the time in huge letters, centered',
      'Why did the last render fail?',
      'Change the refresh interval to 15 minutes',
      'Make the current scene easier to read from across the room',
    ]
  }
  const names = frames.map(frameLabel).filter((name): name is string => !!name)
  const first = names[0] ?? 'kitchen'
  const second = names[1] ?? names[0] ?? 'living room'
  return [
    `Update the ${first} frame to show the weather`,
    'Make a scene that shows a quote of the day',
    `What's on the ${second} frame right now?`,
    'Create a split scene with a clock and the forecast',
    `Why did the ${first} frame stop updating?`,
    `Put my holiday photos on the ${second} frame`,
    'Make a scene that counts down to New Year',
  ]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiPromptBoxLogicValues {
  activeFramesList: FrameType[] // framesModel
  currentExample: string
  exampleIndex: number
  examples: string[]
  input: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiPromptBoxLogicActions {
  acceptExample: () => {
    value: true
  }
  nextExample: () => {
    value: true
  }
  setInput: (input: string) => {
    input: string
  }
  submit: () => {
    value: true
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiPromptBoxLogicMeta {
  key: string
  __keaTypeGenInternalSelectorTypes: {
    examples: (arg: FrameId | null, activeFramesList: FrameType[]) => string[]
    currentExample: (examples: string[], exampleIndex: number) => string
  }
}

export type aiPromptBoxLogicType = MakeLogicType<
  aiPromptBoxLogicValues,
  aiPromptBoxLogicActions,
  AiPromptBoxLogicProps
> &
  aiPromptBoxLogicMeta

/** The AI box on the frames home and on a frame's page: type a question,
 * press Enter, and the AI chat drawer opens with it (docs/ai-chat.md). */
export const aiPromptBoxLogic = kea<aiPromptBoxLogicType>([
  path(['src', 'scenes', 'workspace', 'aiPromptBoxLogic']),
  props({} as AiPromptBoxLogicProps),
  key((props) => (props.frameId === null ? 'home' : String(props.frameId))),
  connect(() => ({ values: [framesModel, ['activeFramesList']] })),
  actions({
    setInput: (input: string) => ({ input }),
    nextExample: true,
    acceptExample: true,
    submit: true,
  }),
  reducers({
    input: ['', { setInput: (_, { input }) => input }],
    exampleIndex: [0, { nextExample: (state) => state + 1 }],
  }),
  selectors({
    examples: [
      (s) => [(_: any, props: AiPromptBoxLogicProps) => props.frameId, s.activeFramesList],
      (frameId: FrameId | null, frames: FrameType[]) => aiPromptExamples(frameId, frames),
    ],
    currentExample: [
      (s) => [s.examples, s.exampleIndex],
      (examples: string[], exampleIndex: number) => examples[exampleIndex % examples.length] ?? '',
    ],
  }),
  listeners(({ actions, values, props }) => ({
    // Tab takes the example on show, to edit or send.
    acceptExample: () => {
      if (!values.input) {
        actions.setInput(values.currentExample)
      }
    },
    submit: () => {
      const prompt = values.input.trim()
      if (!prompt) {
        return
      }
      workspaceLogic.actions.startAiChat(props.frameId, prompt)
      actions.setInput('')
    },
  })),
  afterMount(({ actions, cache }) => {
    cache.exampleTimer = window.setInterval(() => actions.nextExample(), AI_EXAMPLE_INTERVAL_MS)
  }),
  beforeUnmount(({ cache }) => {
    window.clearInterval(cache.exampleTimer)
  }),
])
