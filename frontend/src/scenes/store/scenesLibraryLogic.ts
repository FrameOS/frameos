export type scenesLibraryLogicType = MakeLogicType<
  scenesLibraryLogicValues,
  scenesLibraryLogicActions,
  Record<string, any>
> &
  scenesLibraryLogicMeta

export const scenesLibraryLogic = kea<scenesLibraryLogicType>([
  path(['src', 'scenes', 'store', 'scenesLibraryLogic']),
  connect(() => ({
    values: [
      cloudDriveLogic,
      ['driveTemplates', 'driveTemplatesLoading', 'hasDriveScope', 'cloudConnected', 'cloudEnabled'],
      repositoriesModel,
      ['repositories', 'repositoriesLoading'],
      templatesModel,
      ['templates', 'templatesLoading'],
      workspaceLogic,
      ['search'],
    ],
    actions: [
      cloudDriveLogic,
      ['loadDrive', 'loadDriveIfStale'],
      repositoriesModel,
      ['loadRepositoriesIfStale', 'loadRepositories'],
      templatesModel,
      ['loadTemplatesIfStale', 'loadTemplates', 'removeTemplate', 'exportTemplate'],
    ],
  })),
  actions({
    setRoute: (page: string | null, category: string | null, tag: string | null) => ({ page, category, tag }),
    /** A scene zip: to the account's private scenes on the cloud, to the
     * local saved scenes on a backend. */
    uploadSceneZip: (file: File) => ({ file }),
    uploadSceneZipFinished: (error: string | null) => ({ error }),
    /** The shelf scrolled into view on the unfiltered store, so the side
     * panel's category can follow the page. */
    setVisibleShelf: (slug: string | null) => ({ slug }),
  }),
  reducers({
    page: [
      'store' as ScenesLibraryPage,
      {
        setRoute: (_, { page }) => (page && scenesLibraryPageIsAvailable(page) ? page : 'store'),
      },
    ],
    category: [
      null as string | null,
      {
        setRoute: (_, { category }) => category || null,
      },
    ],
    tag: [
      null as string | null,
      {
        setRoute: (_, { tag }) => (tag ? tag.toLowerCase() : null),
      },
    ],
    uploading: [
      false,
      {
        uploadSceneZip: () => true,
        uploadSceneZipFinished: () => false,
      },
    ],
    uploadError: [
      null as string | null,
      {
        uploadSceneZip: () => null,
        uploadSceneZipFinished: (_, { error }) => error,
      },
    ],
    visibleShelf: [
      null as string | null,
      {
        setVisibleShelf: (_, { slug }) => slug,
        setRoute: () => null,
      },
    ],
  }),
  selectors({
    // The cloud store's scenes, whichever row(s) track it; one entry per
    // store scene even when a backend tracks the store twice.
    storeTemplates: [
      (s) => [s.repositories],
      (repositories: scenesLibraryLogicValues['repositories']): TemplateType[] => storeTemplatesOf(repositories),
    ],
    // Where the store's own pages live (each template's `url` is a scene
    // page there): a self-hosted provider's host, or scenes.frameos.net.
    storeOrigin: [(s) => [s.storeTemplates], (storeTemplates: TemplateType[]): string => storeOriginOf(storeTemplates)],
    storeScenesCount: [(s) => [s.storeTemplates], (storeTemplates: TemplateType[]): number => storeTemplates.length],
    storeShelfCounts: [
      (s) => [s.storeTemplates],
      (storeTemplates: TemplateType[]): StoreShelfCount[] => storeShelfCountsOf(storeTemplates),
    ],
    storeTagCounts: [
      (s) => [s.storeTemplates, s.category],
      (storeTemplates: TemplateType[], category: string | null): StoreTagCount[] =>
        storeTagCountsOf(storeTemplates, category),
    ],
    storeShelves: [
      (s) => [s.storeTemplates, s.search, s.category, s.tag],
      (
        storeTemplates: TemplateType[],
        search: string,
        category: string | null,
        tag: string | null
      ): StoreShelfGroup[] => storeShelvesOf(storeTemplates, { search, category, tag }),
    ],
    drivePageTemplates: [
      (s) => [s.driveTemplates, s.search],
      (driveTemplates: TemplateType[], search: string): TemplateType[] =>
        driveTemplates.filter((template) => templateMatchesSearch(search, template)),
    ],
    localPageTemplates: [
      (s) => [s.templates, s.search],
      (templates: TemplateType[], search: string): TemplateType[] =>
        templates.filter((template) => templateMatchesSearch(search, template)),
    ],
  }),
  listeners(({ actions, values }) => ({
    uploadSceneZip: async ({ file }) => {
      const body = new FormData()
      body.append('file', file)
      try {
        if (isCloudMode()) {
          const response = await apiFetch('/api/account/scenes/upload', { method: 'POST', body })
          const payload = await response.json().catch(() => ({}))
          if (!response.ok) {
            throw new Error(payload?.message || payload?.error || `Upload failed (${response.status})`)
          }
          actions.uploadSceneZipFinished(null)
          // The scene's own page, the full-screen editor.
          const url = typeof payload?.scene?.url === 'string' ? payload.scene.url : null
          if (url) {
            window.location.assign(url)
          } else {
            actions.loadDrive()
            router.actions.push(urls.scenesHome('cloud'))
          }
          return
        }
        const response = await apiFetch('/api/templates', { method: 'POST', body })
        if (!response.ok) {
          const payload = await response.json().catch(() => ({}))
          throw new Error(payload?.detail || payload?.error || `Upload failed (${response.status})`)
        }
        actions.uploadSceneZipFinished(null)
        actions.loadTemplates()
        if (values.page !== 'local') {
          router.actions.push(urls.scenesHome('local'))
        }
      } catch (error) {
        actions.uploadSceneZipFinished(error instanceof Error ? error.message : String(error))
      }
    },
  })),
  urlToAction(({ actions }) => ({
    [urls.scenes()]: (_, search) => {
      actions.setRoute(
        typeof search.page === 'string' ? search.page : null,
        typeof search.category === 'string' ? search.category : null,
        typeof search.tag === 'string' ? search.tag : null
      )
    },
  })),
  afterMount(({ actions }) => {
    actions.loadRepositoriesIfStale(STALE_AFTER_MS)
    if (!isInFrameAdminMode()) {
      actions.loadTemplatesIfStale(STALE_AFTER_MS)
      actions.loadDriveIfStale(STALE_AFTER_MS)
    }
  }),
])
