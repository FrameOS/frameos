import { afterMount, connect, kea, path, selectors } from 'kea'
import type { MakeLogicType } from 'kea'

import { repositoriesModel } from '../../models/repositoriesModel'
import { templatesModel } from '../../models/templatesModel'
import type { RepositoryType, TemplateType } from '../../types'
import { isInFrameAdminMode } from '../../utils/frameAdmin'
import { searchInText } from '../../utils/searchInText'
import { groupByStoreShelf, type StoreCategoryShelf } from '../../utils/storeCategories'
import { cloudDriveLogic } from '../frame/panels/Templates/cloudDriveLogic'
import { isCloudStoreRepository } from '../frame/panels/Templates/templatesLogic'
import { workspaceLogic } from '../workspace/workspaceLogic'

// The scenes library behind the Scenes rail button: the public store, the
// account's private cloud scenes and (on a backend) its local saved scenes.
// Nothing here is fetched twice: the same models the Add scene drawer reads
// serve the pages, and the shell's search box filters them. The catalogs
// come from whichever cloud the plane is linked to — on a backend the
// seeded store repository and the drive proxy, on the device the public
// index proxy, on the cloud its own routes.

const STALE_AFTER_MS = 60_000

export interface StoreShelfGroup {
  shelf: StoreCategoryShelf
  templates: TemplateType[]
}

function matchesSearch(search: string, template: TemplateType): boolean {
  return (
    search === '' ||
    searchInText(search, template.name) ||
    searchInText(search, template.description) ||
    searchInText(search, template.author) ||
    (template.tags ?? []).some((tag) => searchInText(search, tag))
  )
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scenesLibraryLogicValues {
  cloudConnected: boolean // cloudDriveLogic
  cloudEnabled: boolean // cloudDriveLogic
  driveTemplates: TemplateType[] // cloudDriveLogic
  driveTemplatesLoading: boolean // cloudDriveLogic
  hasDriveScope: boolean // cloudDriveLogic
  repositories: RepositoryType[] // repositoriesModel
  repositoriesLoading: boolean // repositoriesModel
  templates: TemplateType[] // templatesModel
  templatesLoading: boolean // templatesModel
  search: string // workspaceLogic
  drivePageTemplates: TemplateType[]
  localPageTemplates: TemplateType[]
  storeScenesCount: number
  storeShelves: StoreShelfGroup[]
  storeTemplates: TemplateType[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scenesLibraryLogicActions {
  loadDrive: () => any // cloudDriveLogic
  loadDriveIfStale: (maxAgeMs: number) => {
    maxAgeMs: number
  } // cloudDriveLogic
  loadRepositories: () => any // repositoriesModel
  loadRepositoriesIfStale: (maxAgeMs: number) => {
    maxAgeMs: number
  } // repositoriesModel
  exportTemplate: (
    id: string,
    format?: string | undefined
  ) => {
    format: string | undefined
    id: string
  } // templatesModel
  loadTemplatesIfStale: (maxAgeMs: number) => {
    maxAgeMs: number
  } // templatesModel
  removeTemplate: (id: string) => {
    id: string
  } // templatesModel
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scenesLibraryLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    storeTemplates: (repositories: RepositoryType[]) => TemplateType[]
    storeScenesCount: (storeTemplates: TemplateType[]) => number
    storeShelves: (storeTemplates: TemplateType[], search: string) => StoreShelfGroup[]
    drivePageTemplates: (driveTemplates: TemplateType[], search: string) => TemplateType[]
    localPageTemplates: (templates: TemplateType[], search: string) => TemplateType[]
  }
}

export type scenesLibraryLogicType = MakeLogicType<
  scenesLibraryLogicValues,
  scenesLibraryLogicActions,
  Record<string, any>
> &
  scenesLibraryLogicMeta

export const scenesLibraryLogic = kea<scenesLibraryLogicType>([
  path(['src', 'scenes', 'store', 'scenesLibraryLogic']),
  connect(() => ({
    values: [
      cloudDriveLogic,
      ['driveTemplates', 'driveTemplatesLoading', 'hasDriveScope', 'cloudConnected', 'cloudEnabled'],
      repositoriesModel,
      ['repositories', 'repositoriesLoading'],
      templatesModel,
      ['templates', 'templatesLoading'],
      workspaceLogic,
      ['search'],
    ],
    actions: [
      cloudDriveLogic,
      ['loadDrive', 'loadDriveIfStale'],
      repositoriesModel,
      ['loadRepositoriesIfStale', 'loadRepositories'],
      templatesModel,
      ['loadTemplatesIfStale', 'removeTemplate', 'exportTemplate'],
    ],
  })),
  selectors({
    // The cloud store's scenes, whichever row(s) track it; one entry per
    // store scene even when a backend tracks the store twice.
    storeTemplates: [
      (s) => [s.repositories],
      (repositories: scenesLibraryLogicValues['repositories']): TemplateType[] => {
        const seen = new Set<string>()
        const templates: TemplateType[] = []
        for (const repository of repositories.filter(isCloudStoreRepository)) {
          for (const template of repository.templates ?? []) {
            const key = template.sceneId ?? template.id ?? template.url ?? template.name
            if (key && seen.has(key)) {
              continue
            }
            if (key) {
              seen.add(key)
            }
            templates.push(template)
          }
        }
        return templates
      },
    ],
    storeScenesCount: [(s) => [s.storeTemplates], (storeTemplates: TemplateType[]): number => storeTemplates.length],
    storeShelves: [
      (s) => [s.storeTemplates, s.search],
      (storeTemplates: TemplateType[], search: string): StoreShelfGroup[] =>
        groupByStoreShelf(storeTemplates.filter((template) => matchesSearch(search, template))),
    ],
    drivePageTemplates: [
      (s) => [s.driveTemplates, s.search],
      (driveTemplates: TemplateType[], search: string): TemplateType[] =>
        driveTemplates.filter((template) => matchesSearch(search, template)),
    ],
    localPageTemplates: [
      (s) => [s.templates, s.search],
      (templates: TemplateType[], search: string): TemplateType[] =>
        templates.filter((template) => matchesSearch(search, template)),
    ],
  }),
  afterMount(({ actions }) => {
    actions.loadRepositoriesIfStale(STALE_AFTER_MS)
    if (!isInFrameAdminMode()) {
      actions.loadTemplatesIfStale(STALE_AFTER_MS)
      actions.loadDriveIfStale(STALE_AFTER_MS)
    }
  }),
])
