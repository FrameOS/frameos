import { actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import type { MakeLogicType } from 'kea'

import { framesModel } from '../../models/framesModel'
import type { FrameId, FrameType, RepositoryType, TemplateType } from '../../types'
import { frameIdsEqual } from '../../utils/frameId'
import { showErrorMessage, showSuccessMessage } from '../../utils/workingMessage'
import { templatesLogic } from '../frame/panels/Templates/templatesLogic'
import { groupFramesByStatus, type FrameStatusGroup } from '../workspace/frameStatusGroups'

// The "Install" on a scene tile: a dialog that asks which frame(s) to put
// the scene on, then hands each frame to the same install the Add scene
// drawer uses (templatesLogic.applyRemoteToFrame for a store or drive
// scene, applyTemplate for a scene saved on this backend), one frame at a
// time, with the drawer's own confirmations and errors.

export interface InstallSceneTarget {
  template: TemplateType
  /** The catalog the scene comes from; none for a local saved scene. */
  repository: RepositoryType | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface installSceneLogicValues {
  framesList: FrameType[] // framesModel
  frameGroups: FrameStatusGroup[]
  installableFrames: FrameType[]
  installing: boolean
  selectedFrameIds: FrameId[]
  target: InstallSceneTarget | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface installSceneLogicActions {
  closeInstall: () => {}
  install: () => {}
  installFinished: () => {}
  openInstall: (
    template: TemplateType,
    repository: RepositoryType | null
  ) => {
    repository: RepositoryType | null
    template: TemplateType
  }
  toggleFrame: (frameId: FrameId) => {
    frameId: FrameId
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface installSceneLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    installableFrames: (framesList: FrameType[]) => FrameType[]
    frameGroups: (installableFrames: FrameType[]) => FrameStatusGroup[]
  }
}

export type installSceneLogicType = MakeLogicType<
  installSceneLogicValues,
  installSceneLogicActions,
  Record<string, any>
> &
  installSceneLogicMeta

export const installSceneLogic = kea<installSceneLogicType>([
  path(['src', 'scenes', 'store', 'installSceneLogic']),
  connect(() => ({
    values: [framesModel, ['framesList']],
  })),
  actions({
    openInstall: (template: TemplateType, repository: RepositoryType | null) => ({ template, repository }),
    closeInstall: () => ({}),
    toggleFrame: (frameId: FrameId) => ({ frameId }),
    install: () => ({}),
    installFinished: () => ({}),
  }),
  reducers({
    target: [
      null as InstallSceneTarget | null,
      {
        openInstall: (_, { template, repository }) => ({ template, repository }),
        closeInstall: () => null,
      },
    ],
    selectedFrameIds: [
      [] as FrameId[],
      {
        openInstall: () => [],
        closeInstall: () => [],
        toggleFrame: (state, { frameId }) =>
          state.some((id) => frameIdsEqual(id, frameId))
            ? state.filter((id) => !frameIdsEqual(id, frameId))
            : [...state, frameId],
      },
    ],
    installing: [
      false,
      {
        install: () => true,
        installFinished: () => false,
        closeInstall: () => false,
      },
    ],
  }),
  selectors({
    // Archived frames are not offered: nothing is deployed to them.
    installableFrames: [
      (s) => [s.framesList],
      (framesList: FrameType[]): FrameType[] => framesList.filter((frame) => frame.status !== 'archived'),
    ],
    frameGroups: [
      (s) => [s.installableFrames],
      (installableFrames: FrameType[]): FrameStatusGroup[] => groupFramesByStatus(installableFrames),
    ],
  }),
  listeners(({ actions, values }) => ({
    install: async () => {
      const target = values.target
      const frameIds = values.selectedFrameIds
      if (!target || frameIds.length === 0) {
        actions.installFinished()
        return
      }
      try {
        for (const frameId of frameIds) {
          // The per-frame logic may not be mounted (the page shows no frame);
          // mount it for the install and keep it, like a visit to the frame
          // would have.
          const logic = templatesLogic({ frameId })
          logic.mount()
          if (target.repository) {
            logic.actions.applyRemoteToFrame(target.repository, target.template, false)
          } else {
            logic.actions.applyTemplate(target.template, false)
          }
        }
        showSuccessMessage(
          frameIds.length === 1
            ? `Installing "${target.template.name}" on the frame.`
            : `Installing "${target.template.name}" on ${frameIds.length} frames.`
        )
        actions.closeInstall()
      } catch (error) {
        showErrorMessage(error instanceof Error ? error.message : String(error))
        actions.installFinished()
      }
    },
  })),
])
