import { actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import type { MakeLogicType } from 'kea'

import { router } from 'kea-router'

import { framesModel } from '../../models/framesModel'
import type { FrameId, FrameScene, FrameType, RepositoryType, TemplateType } from '../../types'
import { urls } from '../../urls'
import { frameIdsEqual } from '../../utils/frameId'
import { showErrorMessage, showSuccessMessage } from '../../utils/workingMessage'
import { frameLogic } from '../frame/frameLogic'
import { chatLogic } from '../frame/panels/Chat/chatLogic'
import { templatesLogic } from '../frame/panels/Templates/templatesLogic'
import { groupFramesByStatus, type FrameStatusGroup } from '../workspace/frameStatusGroups'
import { workspaceLogic } from '../workspace/workspaceLogic'

// The "Install" on a scene tile: a dialog that asks which frame(s) to put
// the scene on, then hands each frame to the same install the Add scene
// drawer uses (templatesLogic.applyRemoteToFrame for a store or drive
// scene, applyTemplate for a scene saved on this backend), one frame at a
// time, with the drawer's own confirmations and errors.

// What the frame picker is for: installing a scene from a catalog or the
// local saved scenes on one or more frames, or — on a backend, where there
// is no frame-less editor — starting a new blank scene on one frame, with
// or without a first prompt for the AI assistant.
export type InstallSceneTarget =
  | {
      kind: 'install'
      template: TemplateType
      /** The catalog the scene comes from; none for a local saved scene. */
      repository: RepositoryType | null
    }
  | { kind: 'blank' }
  | { kind: 'ai'; prompt: string }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface installSceneLogicValues {
  framesList: FrameType[] // framesModel
  frameGroups: FrameStatusGroup[]
  installableFrames: FrameType[]
  installedFrameIds: FrameId[]
  installing: boolean
  selectedFrameIds: FrameId[]
  target: InstallSceneTarget | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface installSceneLogicActions {
  closeInstall: () => {}
  install: () => {}
  installFinished: () => {}
  openInstall: (
    template: TemplateType,
    repository: RepositoryType | null
  ) => {
    repository: RepositoryType | null
    template: TemplateType
  }
  openNewScene: (prompt?: string | null) => {
    prompt: string | null
  }
  selectFrame: (frameId: FrameId) => {
    frameId: FrameId
  }
  toggleFrame: (frameId: FrameId) => {
    frameId: FrameId
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface installSceneLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    installableFrames: (framesList: FrameType[]) => FrameType[]
    frameGroups: (installableFrames: FrameType[]) => FrameStatusGroup[]
    installedFrameIds: (installableFrames: FrameType[], target: InstallSceneTarget | null) => FrameId[]
  }
}

export type installSceneLogicType = MakeLogicType<
  installSceneLogicValues,
  installSceneLogicActions,
  Record<string, any>
> &
  installSceneLogicMeta

function sceneComesFrom(
  origin: FrameScene['origin'],
  target: Extract<InstallSceneTarget, { kind: 'install' }>
): boolean {
  if (!origin) {
    return false
  }
  if (target.template.sceneId && origin.storeSceneId === target.template.sceneId) {
    return true
  }
  const templateId = target.template.id
  if (!templateId || origin.templateId !== templateId) {
    return false
  }
  return target.repository ? origin.repositoryId === target.repository.id : !origin.repositoryId
}

export const installSceneLogic = kea<installSceneLogicType>([
  path(['src', 'scenes', 'store', 'installSceneLogic']),
  connect(() => ({
    values: [framesModel, ['framesList']],
  })),
  actions({
    openInstall: (template: TemplateType, repository: RepositoryType | null) => ({ template, repository }),
    /** A new blank scene on one frame; with a prompt the AI assistant
     * starts on it in the editor. */
    openNewScene: (prompt?: string | null) => ({ prompt: prompt ?? null }),
    closeInstall: () => ({}),
    toggleFrame: (frameId: FrameId) => ({ frameId }),
    /** The one frame a new scene goes on. */
    selectFrame: (frameId: FrameId) => ({ frameId }),
    install: () => ({}),
    installFinished: () => ({}),
  }),
  reducers({
    target: [
      null as InstallSceneTarget | null,
      {
        openInstall: (_, { template, repository }): InstallSceneTarget => ({ kind: 'install', template, repository }),
        openNewScene: (_, { prompt }): InstallSceneTarget => (prompt ? { kind: 'ai', prompt } : { kind: 'blank' }),
        closeInstall: () => null,
      },
    ],
    selectedFrameIds: [
      [] as FrameId[],
      {
        openInstall: () => [],
        openNewScene: () => [],
        closeInstall: () => [],
        toggleFrame: (state, { frameId }) =>
          state.some((id) => frameIdsEqual(id, frameId))
            ? state.filter((id) => !frameIdsEqual(id, frameId))
            : [...state, frameId],
        selectFrame: (_, { frameId }) => [frameId],
      },
    ],
    installing: [
      false,
      {
        install: () => true,
        installFinished: () => false,
        closeInstall: () => false,
      },
    ],
  }),
  selectors({
    // Archived frames are not offered: nothing is deployed to them.
    installableFrames: [
      (s) => [s.framesList],
      (framesList: FrameType[]): FrameType[] => framesList.filter((frame) => frame.status !== 'archived'),
    ],
    frameGroups: [
      (s) => [s.installableFrames],
      (installableFrames: FrameType[]): FrameStatusGroup[] => groupFramesByStatus(installableFrames),
    ],
    // The frames that already have the scene (by the origin every install
    // stamps: the store scene's id, or the repository and template).
    installedFrameIds: [
      (s) => [s.installableFrames, s.target],
      (installableFrames: FrameType[], target: InstallSceneTarget | null): FrameId[] =>
        target?.kind === 'install'
          ? installableFrames
              .filter((frame) => (frame.scenes ?? []).some((scene) => sceneComesFrom(scene.origin, target)))
              .map((frame) => frame.id)
          : [],
    ],
  }),
  listeners(({ actions, values }) => ({
    install: async () => {
      const target = values.target
      const frameIds = values.selectedFrameIds
      if (!target || frameIds.length === 0) {
        actions.installFinished()
        return
      }
      try {
        if (target.kind === 'blank') {
          const frameId = frameIds[0]
          const frameStore = frameLogic({ frameId })
          frameStore.mount()
          await frameStore.asyncActions.createBlankScene('New scene', false, false)
          const scenes = frameStore.values.frameForm?.scenes ?? frameStore.values.scenes
          const scene = scenes[scenes.length - 1]
          if (!scene) {
            throw new Error('The new scene was not created')
          }
          actions.closeInstall()
          router.actions.push(urls.scenes(frameId, scene.id))
          return
        }
        if (target.kind === 'ai') {
          // The assistant builds a new scene on the frame (its build_scene
          // adds it to the frame's scene list and focuses it), so the chat
          // is the frame's, in the frame's scenes workspace. A route change
          // closes every drawer, so the drawer opens after the push.
          const frameId = frameIds[0]
          const chat = chatLogic({ frameId })
          chat.mount()
          actions.closeInstall()
          router.actions.push(urls.scenes(frameId))
          workspaceLogic.actions.openChatDrawer(frameId, null, null)
          chat.actions.startNewChatWithMessage(target.prompt)
          return
        }
        for (const frameId of frameIds) {
          const logic = templatesLogic({ frameId })
          logic.mount()
          if (target.repository) {
            logic.actions.applyRemoteToFrame(target.repository, target.template, false)
          } else {
            logic.actions.applyTemplate(target.template, false)
          }
        }
        showSuccessMessage(
          frameIds.length === 1
            ? `Installing "${target.template.name}" on the frame.`
            : `Installing "${target.template.name}" on ${frameIds.length} frames.`
        )
        actions.closeInstall()
      } catch (error) {
        showErrorMessage(error instanceof Error ? error.message : String(error))
        actions.installFinished()
      }
    },
  })),
])
