import { actions, afterMount, connect, kea, path, reducers, selectors } from 'kea'
import type { MakeLogicType } from 'kea'
import { urlToAction } from 'kea-router'

import { repositoriesModel } from '../../models/repositoriesModel'
import type { RepositoryType, TemplateType } from '../../types'
import { urls } from '../../urls'
import {
  storeOriginOf,
  storeShelfCountsOf,
  storeShelvesOf,
  storeTagCountsOf,
  storeTemplatesOf,
  type StoreShelfCount,
  type StoreShelfGroup,
  type StoreTagCount,
} from './storeCatalog'

// The signed-out store front (the cloud's /store and the scenes host's
// root). Deliberately lean: it reads the public store index through
// repositoriesModel and nothing else — the workspace's own logics load
// account-scoped routes, which apiFetch turns into a trip to /login for a
// visitor without a session. Search is its own field here (there is no
// shell search box), the category and tag come from the URL.

const STALE_AFTER_MS = 60_000

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface publicStoreLogicValues {
  repositories: RepositoryType[] // repositoriesModel
  repositoriesLoading: boolean // repositoriesModel
  category: string | null
  search: string
  storeOrigin: string
  storeScenesCount: number
  storeShelfCounts: StoreShelfCount[]
  storeShelves: StoreShelfGroup[]
  storeTagCounts: StoreTagCount[]
  storeTemplates: TemplateType[]
  tag: string | null
  visibleShelf: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface publicStoreLogicActions {
  loadRepositories: () => any // repositoriesModel
  loadRepositoriesIfStale: (maxAgeMs: number) => {
    maxAgeMs: number
  } // repositoriesModel
  setRoute: (
    category: string | null,
    tag: string | null
  ) => {
    category: string | null
    tag: string | null
  }
  setSearch: (search: string) => {
    search: string
  }
  setVisibleShelf: (slug: string | null) => {
    slug: string | null
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface publicStoreLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    storeTemplates: (repositories: RepositoryType[]) => TemplateType[]
    storeOrigin: (storeTemplates: TemplateType[]) => string
    storeScenesCount: (storeTemplates: TemplateType[]) => number
    storeShelfCounts: (storeTemplates: TemplateType[]) => StoreShelfCount[]
    storeTagCounts: (storeTemplates: TemplateType[]) => StoreTagCount[]
    storeShelves: (
      storeTemplates: TemplateType[],
      search: string,
      category: string | null,
      tag: string | null
    ) => StoreShelfGroup[]
  }
}

export type publicStoreLogicType = MakeLogicType<publicStoreLogicValues, publicStoreLogicActions, Record<string, any>> &
  publicStoreLogicMeta

export const publicStoreLogic = kea<publicStoreLogicType>([
  path(['src', 'scenes', 'store', 'publicStoreLogic']),
  connect(() => ({
    values: [repositoriesModel, ['repositories', 'repositoriesLoading']],
    actions: [repositoriesModel, ['loadRepositories', 'loadRepositoriesIfStale']],
  })),
  actions({
    setSearch: (search: string) => ({ search }),
    setRoute: (category: string | null, tag: string | null) => ({ category, tag }),
    setVisibleShelf: (slug: string | null) => ({ slug }),
  }),
  reducers({
    search: ['', { setSearch: (_, { search }) => search }],
    category: [null as string | null, { setRoute: (_, { category }) => category || null }],
    tag: [null as string | null, { setRoute: (_, { tag }) => (tag ? tag.toLowerCase() : null) }],
    visibleShelf: [
      null as string | null,
      {
        setVisibleShelf: (_, { slug }) => slug,
        setRoute: () => null,
      },
    ],
  }),
  selectors({
    storeTemplates: [
      (s) => [s.repositories],
      (repositories: RepositoryType[]): TemplateType[] => storeTemplatesOf(repositories),
    ],
    storeOrigin: [(s) => [s.storeTemplates], (storeTemplates: TemplateType[]): string => storeOriginOf(storeTemplates)],
    storeScenesCount: [(s) => [s.storeTemplates], (storeTemplates: TemplateType[]): number => storeTemplates.length],
    storeShelfCounts: [
      (s) => [s.storeTemplates],
      (storeTemplates: TemplateType[]): StoreShelfCount[] => storeShelfCountsOf(storeTemplates),
    ],
    storeTagCounts: [
      (s) => [s.storeTemplates],
      (storeTemplates: TemplateType[]): StoreTagCount[] => storeTagCountsOf(storeTemplates),
    ],
    storeShelves: [
      (s) => [s.storeTemplates, s.search, s.category, s.tag],
      (
        storeTemplates: TemplateType[],
        search: string,
        category: string | null,
        tag: string | null
      ): StoreShelfGroup[] => storeShelvesOf(storeTemplates, { search, category, tag }),
    ],
  }),
  urlToAction(({ actions }) => {
    const read = (_: unknown, search: Record<string, unknown>) =>
      actions.setRoute(
        typeof search.category === 'string' ? search.category : null,
        typeof search.tag === 'string' ? search.tag : null
      )
    return { [urls.store()]: read, '/': read }
  }),
  afterMount(({ actions }) => {
    actions.loadRepositoriesIfStale(STALE_AFTER_MS)
  }),
])
