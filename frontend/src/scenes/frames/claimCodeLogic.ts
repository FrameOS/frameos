export type claimCodeLogicType = MakeLogicType<claimCodeLogicValues, claimCodeLogicActions, Record<string, any>> &
  claimCodeLogicMeta

export const claimCodeLogic = kea<claimCodeLogicType>([
  path(['src', 'scenes', 'frames', 'claimCodeLogic']),
  actions({
    setName: (name: string) => ({ name }),
    setProviderUrl: (providerUrl: string) => ({ providerUrl }),
  }),
  reducers({
    name: ['' as string, { setName: (_, { name }) => name, reset: () => '' }],
    providerUrlEdited: [
      null as string | null,
      { setProviderUrl: (_, { providerUrl }) => providerUrl, reset: () => null },
    ],
    claimCodeError: [
      null as string | null,
      {
        createClaimCode: () => null,
        createClaimCodeFailure: (_, { error }) => error,
        reset: () => null,
      },
    ],
  }),
  loaders(({ values }) => ({
    claimCode: [
      null as FrameClaimCode | null,
      {
        // "Another code": back to the form, the spent one forgotten.
        reset: () => null,
        createClaimCode: async () => {
          const response = await apiFetch('/api/frames/claim-tokens', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(values.name.trim() ? { name: values.name.trim() } : {}),
          })
          if (!response.ok) {
            throw new Error(`Could not create a claim code (HTTP ${response.status})`)
          }
          return (await response.json()) as FrameClaimCode
        },
      },
    ],
  })),
  selectors({
    defaultProviderUrl: [
      () => [settingsLogic.selectors.savedSettings],
      (savedSettings: FrameOSSettings): string => providerUrlFromServerHost(defaultNewFrameServerHost(savedSettings)),
    ],
    providerUrl: [
      (s) => [s.providerUrlEdited, s.defaultProviderUrl],
      (providerUrlEdited: claimCodeLogicValues['providerUrlEdited'], defaultProviderUrl: string): string =>
        providerUrlEdited ?? defaultProviderUrl,
    ],
    // What /boot/frameos-cloud.txt takes on a FrameOS SD card: read once on
    // first boot, then shredded (backend/app/tasks/setup_json_reset.py).
    sdCardLines: [
      (s) => [s.providerUrl, s.claimCode, s.name],
      (providerUrl: string, claimCode: FrameClaimCode | null, name: string): string =>
        claimCode
          ? [
              `cloud_url=${providerUrl}`,
              `claim_token=${claimCode.token}`,
              ...(name.trim() ? [`name=${name.trim()}`] : []),
            ].join('\n')
          : '',
    ],
  }),
])
