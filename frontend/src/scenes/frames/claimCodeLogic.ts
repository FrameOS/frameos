/**
 * "Add frame -> Connect with a claim code": this backend as the frame's
 * PROVIDER (docs/cloud-frames.md, "Enrollment"). The owner mints a single-use
 * `FRCT_` code here; the frame redeems it at `{provider}/api/frames/enroll`
 * with its own key and from then on dials this backend's management socket,
 * exactly as it would dial FrameOS Cloud's. The new frame shows up in the
 * frames list when it enrolls (the backend broadcasts `new_frame`).
 */
export interface FrameClaimCode {
  token: string
  expires_at: string
  ttl_seconds: number
}

/** The URL a frame dials: the backend's address as the frame sees it, with a scheme. */
export function providerUrlFromServerHost(serverHost: string | null | undefined): string {
  const host = (serverHost ?? '').trim().replace(/\/+$/, '')
  if (!host) {
    return ''
  }
  return /^https?:\/\//i.test(host) ? host : `http://${host}`
}

