import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import type { DeepPartial } from 'kea-forms'

import { SERVICE_REGISTRY } from '../../generated/services.gen'
import { appsModel } from '../../models/appsModel'
import { framesModel } from '../../models/framesModel'
import type { AppConfig, FrameId, FrameOSSettings, FrameType } from '../../types'
import {
  SERVICE_CREDENTIALS_GROUP,
  type ServiceCredential,
  type ServiceDefinition,
  newCredentialId,
  readServiceCredentials,
  serviceDefinition,
  storedServiceIds,
} from '../../utils/serviceKeys'
import { appServiceDefinitionsFromScenes, collectSecretSettingsFromScenes } from '../frame/panels/secretSettings'
import { settingsLogic } from './settingsLogic'

// The "Service keys" part of the settings page (docs/service-keys.md): every
// service the registry knows, plus any the frames' scenes declare or the
// stored settings hold, each with its default key (the settings group named
// after it) and the named keys beyond it (the `serviceCredentials` group).
// Saved with the page's Save, as the rest of the settings form is.

/** The settings-page anchor of a service's card. The six from before keep theirs, so old deep links land. */
const LEGACY_SERVICE_ANCHORS: Readonly<Record<string, string>> = {
  frameOS: 'settings-gallery',
  github: 'settings-github',
  immich: 'settings-immich',
  unsplash: 'settings-unsplash',
}

export function serviceKeyAnchor(service: string): string {
  return LEGACY_SERVICE_ANCHORS[service] ?? `settings-service-${service}`
}

export interface ServiceKeyCard {
  definition: ServiceDefinition
  anchor: string
  /** The named keys of this service, by name. */
  credentials: { id: string; credential: ServiceCredential }[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface serviceKeysSettingsLogicValues {
  settings: FrameOSSettings // settingsLogic
  savedSettings: FrameOSSettings // settingsLogic
  frames: Record<FrameId, FrameType> // framesModel
  apps: Record<string, AppConfig> // appsModel
  appDefinitions: Record<string, ServiceDefinition>
  declaredServices: string[]
  serviceIds: string[]
  cards: ServiceKeyCard[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface serviceKeysSettingsLogicActions {
  setSettingsValues: (values: DeepPartial<FrameOSSettings>) => { values: DeepPartial<FrameOSSettings> } // settingsLogic
  setSettingsValue: (key: any, value: any) => { key: any; value: any } // settingsLogic
  addServiceCredential: (service: string) => { service: string }
  removeServiceCredential: (id: string) => { id: string }
}

export type serviceKeysSettingsLogicType = MakeLogicType<
  serviceKeysSettingsLogicValues,
  serviceKeysSettingsLogicActions
>

export const serviceKeysSettingsLogic = kea<serviceKeysSettingsLogicType>([
  path(['scenes', 'settings', 'serviceKeysSettingsLogic']),
  connect(() => ({
    values: [settingsLogic, ['settings', 'savedSettings'], framesModel, ['frames'], appsModel, ['apps']],
    actions: [settingsLogic, ['setSettingsValues', 'setSettingsValue']],
  })),
  actions({
    addServiceCredential: (service: string) => ({ service }),
    removeServiceCredential: (id: string) => ({ id }),
  }),
  selectors({
    appDefinitions: [
      (s) => [s.frames, s.apps],
      (frames: Record<FrameId, FrameType>, apps: Record<string, AppConfig>): Record<string, ServiceDefinition> =>
        appServiceDefinitionsFromScenes(
          Object.values(frames ?? {}).flatMap((frame) => frame.scenes ?? []),
          apps ?? {}
        ),
    ],
    declaredServices: [
      (s) => [s.frames, s.apps],
      (frames: Record<FrameId, FrameType>, apps: Record<string, AppConfig>): string[] =>
        collectSecretSettingsFromScenes(
          Object.values(frames ?? {}).flatMap((frame) => frame.scenes ?? []),
          apps ?? {}
        ),
    ],
    serviceIds: [
      (s) => [s.savedSettings, s.settings, s.declaredServices],
      (savedSettings: FrameOSSettings, settings: FrameOSSettings, declared: string[]): string[] => {
        const registered = Object.keys(SERVICE_REGISTRY)
        const others = new Set([...storedServiceIds(savedSettings), ...storedServiceIds(settings), ...declared])
        for (const id of registered) {
          others.delete(id)
        }
        // The registry's first, by title; then the ones apps define, by id.
        const byTitle = (a: string, b: string): number =>
          SERVICE_REGISTRY[a].title.localeCompare(SERVICE_REGISTRY[b].title)
        return [...registered.sort(byTitle), ...[...others].sort()]
      },
    ],
    cards: [
      (s) => [s.serviceIds, s.appDefinitions, s.settings],
      (
        serviceIds: string[],
        appDefinitions: Record<string, ServiceDefinition>,
        settings: FrameOSSettings
      ): ServiceKeyCard[] => {
        const credentials = Object.entries(readServiceCredentials(settings?.[SERVICE_CREDENTIALS_GROUP]))
        return serviceIds.map((id) => ({
          definition: serviceDefinition(id, appDefinitions, settings?.[id]),
          anchor: serviceKeyAnchor(id),
          credentials: credentials
            .filter(([, credential]) => credential.service === id)
            .map(([credentialId, credential]) => ({ id: credentialId, credential }))
            .sort((a, b) => a.credential.name.localeCompare(b.credential.name) || a.id.localeCompare(b.id)),
        }))
      },
    ],
  }),
  listeners(({ actions, values }) => ({
    addServiceCredential: ({ service }) => {
      const current = (values.settings?.[SERVICE_CREDENTIALS_GROUP] ?? {}) as Record<string, unknown>
      let id = newCredentialId()
      while (current[id]) {
        id = newCredentialId()
      }
      const count = Object.values(readServiceCredentials(current)).filter((c) => c.service === service).length
      actions.setSettingsValue([SERVICE_CREDENTIALS_GROUP], {
        ...current,
        [id]: { service, name: `Key ${count + 2}`, values: {} },
      })
    },
    removeServiceCredential: ({ id }) => {
      const current = { ...((values.settings?.[SERVICE_CREDENTIALS_GROUP] ?? {}) as Record<string, unknown>) }
      delete current[id]
      actions.setSettingsValue([SERVICE_CREDENTIALS_GROUP], current)
    },
  })),
])
