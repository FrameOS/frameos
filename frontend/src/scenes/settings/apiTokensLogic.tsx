// Personal API tokens (backend/app/models/api_token.py) and the MCP server
// they unlock (docs/mcp.md). The secret is shown once, right after minting;
// the list only ever carries a hint.

export type ApiTokenAccess = 'full' | 'read_only'

export interface ApiToken {
  id: string
  name: string
  hint: string
  access: ApiTokenAccess
  expires_at: string | null
  last_used_at: string | null
  revoked_at: string | null
  created_at: string | null
}

export interface ApiTokensListing {
  api_tokens: ApiToken[]
  live_count: number
  max_tokens: number
  default_ttl_days: number
  max_ttl_days: number
  can_create: boolean
  mcp_url: string
}

export interface ApiTokenForm {
  name: string
  access: ApiTokenAccess
  expires_in_days: number
  // Minting turns the session into a durable credential, so the backend
  // wants the password again (when the account has one).
  current_password: string
}

export interface CreatedApiToken {
  token: string
  api_token: ApiToken
}

const emptyListing: ApiTokensListing = {
  api_tokens: [],
  live_count: 0,
  max_tokens: 25,
  default_ttl_days: 90,
  max_ttl_days: 365,
  can_create: true,
  mcp_url: '',
}

const defaultTokenForm: ApiTokenForm = {
  name: '',
  access: 'full',
  expires_in_days: 90,
  current_password: '',
}

async function responseErrorMessage(response: Response, fallback: string): Promise<string> {
  try {
    const payload = await response.json()
    if (typeof payload?.detail === 'string') {
      return payload.detail
    }
    if (typeof payload?.detail?.message === 'string') {
      return payload.detail.message
    }
    if (Array.isArray(payload?.detail)) {
      return payload.detail
        .map((detail: { msg?: string }) => detail?.msg)
        .filter(Boolean)
        .join(' ')
    }
  } catch {
    // Use fallback below.
  }
  return fallback
}

export function tokenIsLive(token: ApiToken): boolean {
  if (token.revoked_at) {
    return false
  }
  return !token.expires_at || new Date(token.expires_at).getTime() > Date.now()
}

export function mcpConnectCommand(mcpUrl: string, token: string | null): string {
  const bearer = token ?? 'fb_api_...'
  return `claude mcp add --transport http frameos ${
    mcpUrl || '<backend url>/api/mcp'
  } --header "Authorization: Bearer ${bearer}"`
}

