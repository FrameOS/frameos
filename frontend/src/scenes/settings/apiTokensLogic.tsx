export const apiTokensLogic = kea<apiTokensLogicType>([
  path(['src', 'scenes', 'settings', 'apiTokensLogic']),
  actions({
    setCreateOpen: (open: boolean) => ({ open }),
    toggleMcpInstructions: true,
    setCreatedToken: (created: CreatedApiToken | null) => ({ created }),
    dismissCreatedToken: true,
    copyCreatedToken: true,
    revokeToken: (tokenId: string) => ({ tokenId }),
    revokeTokenFinished: true,
  }),
  reducers({
    createOpen: [
      false,
      {
        setCreateOpen: (_, { open }) => open,
        submitNewTokenSuccess: () => false,
      },
    ],
    // The connect recipe is for the moment a token is minted; closed until asked.
    mcpInstructionsOpen: [
      false,
      {
        toggleMcpInstructions: (state) => !state,
      },
    ],
    createdToken: [
      null as CreatedApiToken | null,
      {
        setCreatedToken: (_, { created }) => created,
        dismissCreatedToken: () => null,
      },
    ],
    revokingTokenId: [
      null as string | null,
      {
        revokeToken: (_, { tokenId }) => tokenId,
        revokeTokenFinished: () => null,
      },
    ],
  }),
  loaders(() => ({
    listing: [
      emptyListing,
      {
        loadListing: async () => {
          const response = await apiFetch('/api/user/api_tokens')
          if (!response.ok) {
            throw new Error(await responseErrorMessage(response, 'Failed to load API tokens'))
          }
          return (await response.json()) as ApiTokensListing
        },
      },
    ],
  })),
  forms(({ actions, values }) => ({
    newToken: {
      defaults: defaultTokenForm,
      options: {
        showErrorsOnTouch: true,
      },
      errors: (form: Partial<ApiTokenForm>) => ({
        name: !form.name?.trim() ? 'Give the token a name' : null,
        expires_in_days:
          !form.expires_in_days || form.expires_in_days < 1 || form.expires_in_days > values.listing.max_ttl_days
            ? `Between 1 and ${values.listing.max_ttl_days} days`
            : null,
      }),
      submit: async (form) => {
        const response = await apiFetch('/api/user/api_tokens', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            name: form.name.trim(),
            access: form.access,
            expires_in_days: form.expires_in_days,
            ...(form.current_password ? { current_password: form.current_password } : {}),
          }),
        })
        if (!response.ok) {
          const message = await responseErrorMessage(response, 'Failed to create the API token')
          if (/password/i.test(message)) {
            actions.setNewTokenManualErrors({ current_password: message })
          } else {
            actions.setNewTokenManualErrors({ name: message })
          }
          return
        }
        const created = (await response.json()) as CreatedApiToken
        actions.setCreatedToken(created)
        actions.resetNewToken(defaultTokenForm)
        actions.loadListing()
      },
    },
  })),
  selectors({
    liveTokens: [
      (s) => [s.listing],
      (listing: apiTokensLogicValues['listing']): ApiToken[] => listing.api_tokens.filter(tokenIsLive),
    ],
    pastTokens: [
      (s) => [s.listing],
      (listing: apiTokensLogicValues['listing']): ApiToken[] =>
        listing.api_tokens.filter((token) => !tokenIsLive(token)),
    ],
    mcpCommand: [
      (s) => [s.listing, s.createdToken],
      (listing: apiTokensLogicValues['listing'], createdToken: apiTokensLogicValues['createdToken']): string =>
        mcpConnectCommand(listing.mcp_url, createdToken?.token ?? null),
    ],
  }),
  listeners(({ actions, values }) => ({
    loadListingSuccess: ({ listing }) => {
      if (values.newToken.expires_in_days === defaultTokenForm.expires_in_days && listing.default_ttl_days) {
        actions.setNewTokenValues({ expires_in_days: listing.default_ttl_days })
      }
    },
    revokeToken: async ({ tokenId }) => {
      try {
        const response = await apiFetch(`/api/user/api_tokens/${tokenId}`, { method: 'DELETE' })
        if (!response.ok) {
          showErrorMessage(await responseErrorMessage(response, 'Failed to revoke the API token'))
          return
        }
        if (values.createdToken?.api_token.id === tokenId) {
          actions.dismissCreatedToken()
        }
        showSuccessMessage('API token revoked')
        actions.loadListing()
      } finally {
        actions.revokeTokenFinished()
      }
    },
    copyCreatedToken: async () => {
      const token = values.createdToken?.token
      if (!token) {
        return
      }
      try {
        await navigator.clipboard.writeText(token)
        showSuccessMessage('Token copied')
      } catch {
        showErrorMessage('Could not copy; select the token and copy it by hand')
      }
    },
  })),
  afterMount(({ actions }) => {
    actions.loadListing()
  }),
])
