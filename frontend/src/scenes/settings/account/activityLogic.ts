export type activityLogicType = MakeLogicType<activityLogicValues, activityLogicActions, Record<string, any>> &
  activityLogicMeta

export const activityLogic = kea<activityLogicType>([
  path(['src', 'scenes', 'settings', 'account', 'activityLogic']),
  actions({
    setSpan: (span: string) => ({ span }),
    setGroup: (group: string) => ({ group }),
    setSearch: (search: string) => ({ search }),
    applySearch: true,
    setQuery: (query: string) => ({ query }),
    setRange: (range: ActivityRange | null) => ({ range }),
    clearFilters: true,
    loadHistogram: true,
    setHistogram: (histogram: ActivityHistogram | null) => ({ histogram }),
    loadEvents: true,
    pageLoaded: (page: ActivityPage) => ({ page }),
    loadEventsFailed: true,
    loadMore: true,
    moreLoaded: (page: ActivityPage) => ({ page }),
    loadMoreFailed: true,
  }),
  reducers({
    span: [
      '30d',
      {
        setSpan: (_, { span }) => span,
      },
    ],
    group: [
      '',
      {
        setGroup: (_, { group }) => group,
        clearFilters: () => '',
      },
    ],
    // What is typed, and what was last submitted.
    search: [
      '',
      {
        setSearch: (_, { search }) => search,
        clearFilters: () => '',
      },
    ],
    query: [
      '',
      {
        setQuery: (_, { query }) => query,
        clearFilters: () => '',
      },
    ],
    // The span changes what the chart covers, so a range picked on the old
    // chart no longer means anything on the new one.
    range: [
      null as ActivityRange | null,
      {
        setRange: (_, { range }) => range,
        setSpan: () => null,
        clearFilters: () => null,
      },
    ],
    histogram: [
      null as ActivityHistogram | null,
      {
        setHistogram: (_, { histogram }) => histogram,
      },
    ],
    events: [
      [] as ActivityEvent[],
      {
        pageLoaded: (_, { page }) => page.events,
        moreLoaded: (state, { page }) => [...state, ...page.events],
      },
    ],
    cursor: [
      null as ActivityCursor | null,
      {
        pageLoaded: (_, { page }) => page.next_cursor,
        moreLoaded: (_, { page }) => page.next_cursor,
      },
    ],
    groups: [
      [] as ActivityGroup[],
      {
        pageLoaded: (state, { page }) => page.groups ?? state,
      },
    ],
    loading: [
      true,
      {
        loadEvents: () => true,
        pageLoaded: () => false,
        loadEventsFailed: () => false,
      },
    ],
    loadingMore: [
      false,
      {
        loadMore: () => true,
        moreLoaded: () => false,
        loadMoreFailed: () => false,
        pageLoaded: () => false,
      },
    ],
    failed: [
      false,
      {
        loadEvents: () => false,
        loadEventsFailed: () => true,
        loadMoreFailed: () => true,
        moreLoaded: () => false,
      },
    ],
    loadedOnce: [
      false,
      {
        pageLoaded: () => true,
        loadEventsFailed: () => true,
      },
    ],
  }),
  selectors({
    filtered: [
      (s) => [s.query, s.group, s.range],
      (query: string, group: string, range: ActivityRange | null): boolean => Boolean(query || group || range),
    ],
  }),
  listeners(({ actions, values }) => ({
    // Every load ends with a breakpoint: a reply from a filter the reader
    // has already moved away from is dropped, not rendered (the breakpoint
    // throws out of the listener when a newer one has started since, and
    // kea swallows that throw).
    //
    // The histogram follows the span, the search and the family, never the
    // drag: it is the thing you drag on, so it keeps showing the whole span.
    loadHistogram: async (_, breakpoint) => {
      const params = new URLSearchParams({ span: values.span })
      if (values.query) {
        params.set('q', values.query)
      }
      if (values.group) {
        params.set('group', values.group)
      }
      let histogram: ActivityHistogram | null = null
      try {
        const response = await apiFetch(`/api/account/activity/histogram?${params}`)
        if (response.ok) {
          histogram = (await response.json()) as ActivityHistogram
        }
      } catch {
        histogram = null
      }
      breakpoint()
      if (histogram) {
        actions.setHistogram(histogram)
      }
    },
    loadEvents: async (_, breakpoint) => {
      let page: ActivityPage | null = null
      try {
        const response = await apiFetch(
          `/api/account/activity?${activityListParams(values.query, values.group, values.range)}`
        )
        if (response.ok) {
          page = (await response.json()) as ActivityPage
        }
      } catch {
        page = null
      }
      breakpoint()
      if (page) {
        actions.pageLoaded(page)
      } else {
        actions.loadEventsFailed()
      }
    },
    loadMore: async (_, breakpoint) => {
      const cursor = values.cursor
      if (!cursor) {
        actions.loadMoreFailed()
        return
      }
      const params = activityListParams(values.query, values.group, values.range)
      params.set('before', cursor.before)
      params.set('before_id', cursor.before_id)
      let page: ActivityPage | null = null
      try {
        const response = await apiFetch(`/api/account/activity?${params}`)
        if (response.ok) {
          page = (await response.json()) as ActivityPage
        }
      } catch {
        page = null
      }
      breakpoint()
      if (page) {
        actions.moreLoaded(page)
      } else {
        actions.loadMoreFailed()
      }
    },
    // Each filter change reloads what it affects.
    setSpan: () => {
      actions.loadHistogram()
      actions.loadEvents()
    },
    setGroup: () => {
      actions.loadHistogram()
      actions.loadEvents()
    },
    applySearch: () => {
      actions.setQuery(values.search.trim())
      actions.loadHistogram()
      actions.loadEvents()
    },
    setRange: () => {
      actions.loadEvents()
    },
    clearFilters: () => {
      actions.loadHistogram()
      actions.loadEvents()
    },
  })),
  afterMount(({ actions }) => {
    actions.loadHistogram()
    actions.loadEvents()
  }),
])
