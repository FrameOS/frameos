import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'

import { apiFetch } from '../../../utils/apiFetch'

// The Activity page: a histogram of events over a chosen span that you drag
// across to pick a time range, a filter row (span, event family, search),
// and the matching events newest first with a keyset cursor behind "Load
// more". Everything comes from /api/account/activity and its /histogram;
// the two share one filter parser on the server, so the bars and the rows
// always describe the same slice.

export interface ActivityEvent {
  created_at: string
  detail: string | null
  event_type: string
  frame_id: string | null
  frame_name: string | null
  id: string
  ip: string | null
  label: string
  scene_name: string | null
}

export interface ActivityBucket {
  count: number
  start: string
}

export interface ActivityHistogram {
  buckets: ActivityBucket[]
  from: string
  step_seconds: number
  to: string
}

export interface ActivityCursor {
  before: string
  before_id: string
}

export interface ActivityRange {
  from: string
  to: string
}

export interface ActivityGroup {
  label: string
  value: string
}

interface ActivityPage {
  events: ActivityEvent[]
  groups?: ActivityGroup[]
  next_cursor: ActivityCursor | null
}

export const activitySpanOptions: { label: string; value: string }[] = [
  { label: 'Last 24 hours', value: '24h' },
  { label: 'Last 7 days', value: '7d' },
  { label: 'Last 30 days', value: '30d' },
  { label: 'Last 90 days', value: '90d' },
  { label: 'All time', value: 'all' },
]

/** The query parameters the list reads: the search, the family and the dragged range. */
export function activityListParams(query: string, group: string, range: ActivityRange | null): URLSearchParams {
  const params = new URLSearchParams()
  if (query) {
    params.set('q', query)
  }
  if (group) {
    params.set('group', group)
  }
  if (range) {
    params.set('from', range.from)
    params.set('to', range.to)
  }
  return params
}

