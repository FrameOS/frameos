// The Security page: the password, the other signed-in sessions, the data
// export and the account's deletion. Two-factor authentication has its own
// logic (twoFactorLogic.ts); this one reads GET /api/account/security for
// what the forms need to know (does the account have a password, is it a
// superadmin, which email confirms a deletion).

export interface AccountSecurity {
  email: string | null
  has_password: boolean
  is_superadmin: boolean
  name: string | null
}

export interface ChangePasswordForm {
  current_password: string
  new_password: string
}

export interface DeleteAccountForm {
  password: string
  confirm_email: string
}

const signOutResumeAction = 'sessions:revoke-all'

