export type securityLogicType = MakeLogicType<securityLogicValues, securityLogicActions>

export const securityLogic = kea<securityLogicType>([
  path(['src', 'scenes', 'settings', 'account', 'securityLogic']),
  actions({
    setPasswordDone: (done: boolean) => ({ done }),
    setPasswordError: (error: string | null) => ({ error }),
    signOutEverywhere: (options: { resumed?: boolean } = {}) => ({ options }),
    setSignOutState: (state: SignOutState) => ({ state }),
    setSignOutResult: (revoked: number) => ({ revoked }),
    setSignOutError: (error: string | null) => ({ error }),
    setDeleteOpen: (open: boolean) => ({ open }),
    setDeleteError: (error: string | null) => ({ error }),
  }),
  loaders(() => ({
    security: [
      null as AccountSecurity | null,
      {
        loadSecurity: async () => {
          const response = await apiFetch('/api/account/security')
          if (!response.ok) {
            throw new Error('Failed to load the account')
          }
          return (await response.json()) as AccountSecurity
        },
      },
    ],
  })),
  reducers({
    passwordDone: [
      false,
      {
        setPasswordDone: (_, { done }) => done,
        submitPasswordRequest: () => false,
      },
    ],
    passwordError: [
      null as string | null,
      {
        setPasswordError: (_, { error }) => error,
        submitPasswordRequest: () => null,
      },
    ],
    signOutState: [
      'idle' as SignOutState,
      {
        setSignOutState: (_, { state }) => state,
      },
    ],
    signOutRevoked: [
      0,
      {
        setSignOutResult: (_, { revoked }) => revoked,
      },
    ],
    signOutError: [
      null as string | null,
      {
        setSignOutError: (_, { error }) => error,
        signOutEverywhere: () => null,
      },
    ],
    deleteOpen: [
      false,
      {
        setDeleteOpen: (_, { open }) => open,
      },
    ],
    deleteError: [
      null as string | null,
      {
        setDeleteError: (_, { error }) => error,
        setDeleteOpen: () => null,
        submitDeleteAccountRequest: () => null,
      },
    ],
  }),
  forms(({ actions }) => ({
    password: {
      defaults: { current_password: '', new_password: '' } as ChangePasswordForm,
      errors: ({ current_password, new_password }: ChangePasswordForm) => ({
        current_password: !current_password ? 'Enter your current password' : undefined,
        new_password: new_password.length < 8 ? 'At least 8 characters' : undefined,
      }),
      submit: async (form: ChangePasswordForm) => {
        const response = await apiCall('/api/account/password', 'POST', {
          currentPassword: form.current_password,
          newPassword: form.new_password,
        })
        if (response.ok) {
          actions.resetPassword()
          actions.setPasswordDone(true)
          return
        }
        const payload = await readJsonPayload(response)
        if (payload?.error === 'invalid_password') {
          actions.setPasswordError('The current password is incorrect.')
        } else if (payload?.error === 'weak_password' && payload.message) {
          actions.setPasswordError(payload.message)
        } else if (payload?.error === 'no_password') {
          actions.setPasswordError('This account has no password yet. Use the password reset flow instead.')
        } else {
          actions.setPasswordError(describeHttpError(response.status))
        }
      },
    },
    deleteAccount: {
      defaults: { password: '', confirm_email: '' } as DeleteAccountForm,
      submit: async (form: DeleteAccountForm) => {
        const response = await apiCall('/api/account/delete', 'POST', {
          confirmEmail: form.confirm_email,
          password: form.password,
        })
        if (response.ok) {
          // The session cookie is already cleared by the response; a full
          // navigation makes sure nothing of the deleted account stays on
          // screen.
          window.location.assign('/login?status=account_deleted')
          return
        }
        const payload = await readJsonPayload(response)
        // A password-less account proves itself on /login/reauth first; the
        // form is still open when the browser comes back.
        if (redirectToReauthIfRequired(response, payload)) {
          return
        }
        if (payload?.error === 'invalid_password') {
          actions.setDeleteError('That password is not correct.')
        } else if (payload?.error === 'invalid_confirmation') {
          actions.setDeleteError('That is not the email address on this account.')
        } else if (payload?.error === 'superadmin_cannot_self_delete') {
          actions.setDeleteError('Superadmin accounts cannot delete themselves. Hand over the flag first.')
        } else {
          actions.setDeleteError(describeHttpError(response.status))
        }
      },
    },
  })),
  listeners(({ actions }) => ({
    // "Sign out everywhere else": every other browser and device holding a
    // session on this account is signed out; this one stays. The route is
    // behind sudo mode, so a stale session bounces through /login/reauth and
    // the action replays on return (the user already pressed the button).
    signOutEverywhere: async ({ options }) => {
      actions.setSignOutState('submitting')
      try {
        const response = await apiCall('/api/account/sessions/revoke-all', 'POST')
        const payload = await readJsonPayload(response)
        if (response.ok) {
          actions.setSignOutResult(typeof payload?.revoked === 'number' ? payload.revoked : 0)
          actions.setSignOutState('done')
          return
        }
        if (!options.resumed && redirectToReauthIfRequired(response, payload, signOutResumeAction)) {
          return
        }
        actions.setSignOutError(
          response.status === 429
            ? describeHttpError(response.status)
            : 'Could not sign out the other sessions. Try again in a moment.'
        )
      } catch {
        actions.setSignOutError('Could not sign out the other sessions. Try again in a moment.')
      }
      actions.setSignOutState('idle')
    },
    setDeleteOpen: ({ open }) => {
      if (!open) {
        actions.resetDeleteAccount()
      }
    },
  })),
  afterMount(({ actions }) => {
    actions.loadSecurity()
    // Back from /login/reauth: the user already pressed the button before
    // the detour, so finish it without asking again.
    if (takePendingReauthAction(signOutResumeAction)) {
      actions.signOutEverywhere({ resumed: true })
    }
  }),
])
