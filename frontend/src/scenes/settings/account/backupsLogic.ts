import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { apiFetch } from '../../../utils/apiFetch'
import { confirmDialog } from '../../../utils/confirmDialogLogic'
import { showErrorMessage } from '../../../utils/workingMessage'
import { apiCall, describeHttpError } from './api'

// The Backups page: the encrypted frame configurations and scenes the
// account's linked backends push (GET /api/account/backups). The list is
// small (maxBackupsPerAccount rows), so the search and the kind filter run
// here rather than as query parameters.
export interface CloudBackup {
  id: string
  name: string | null
  item_key: string
  kind: string
  kind_label: string
  size_bytes: number
  pushed_by: string | null
  updated_at: string
  download_url: string
}

export interface BackupsListing {
  backups: CloudBackup[]
  max_backups: number
}

export type BackupKindFilter = '' | 'frames' | 'templates'

const emptyListing: BackupsListing = { backups: [], max_backups: 0 }

export function backupLabel(backup: CloudBackup): string {
  return backup.name ?? backup.item_key
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface backupsLogicValues {
  deletingId: string | null
  filtered: boolean
  filteredBackups: CloudBackup[]
  kind: BackupKindFilter
  listing: BackupsListing
  listingLoading: boolean
  query: string
  totalBytes: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface backupsLogicActions {
  clearFilters: () => {
    value: true
  }
  deleteBackup: (id: string) => {
    id: string
  }
  deleteFinished: () => {
    value: true
  }
  loadListing: () => any
  loadListingFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadListingSuccess: (
    listing: {
      backups: CloudBackup[]
      max_backups: number
    },
    payload?: any
  ) => {
    listing: {
      backups: CloudBackup[]
      max_backups: number
    }
    payload?: any
  }
  setKind: (kind: BackupKindFilter) => {
    kind: BackupKindFilter
  }
  setQuery: (query: string) => {
    query: string
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface backupsLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    filteredBackups: (listing: BackupsListing, query: string, kind: BackupKindFilter) => CloudBackup[]
    filtered: (query: string, kind: BackupKindFilter) => boolean
    totalBytes: (listing: BackupsListing) => number
  }
}

export type backupsLogicType = MakeLogicType<backupsLogicValues, backupsLogicActions, Record<string, any>> &
  backupsLogicMeta

export const backupsLogic = kea<backupsLogicType>([
  path(['src', 'scenes', 'settings', 'account', 'backupsLogic']),
  actions({
    setQuery: (query: string) => ({ query }),
    setKind: (kind: BackupKindFilter) => ({ kind }),
    clearFilters: true,
    deleteBackup: (id: string) => ({ id }),
    deleteFinished: true,
  }),
  loaders(() => ({
    listing: [
      emptyListing,
      {
        loadListing: async () => {
          const response = await apiFetch('/api/account/backups')
          if (!response.ok) {
            throw new Error('Failed to load the backups')
          }
          const payload = (await response.json()) as Partial<BackupsListing>
          return { backups: payload.backups ?? [], max_backups: payload.max_backups ?? 0 }
        },
      },
    ],
  })),
  reducers({
    query: [
      '',
      {
        setQuery: (_, { query }) => query,
        clearFilters: () => '',
      },
    ],
    kind: [
      '' as BackupKindFilter,
      {
        setKind: (_, { kind }) => kind,
        clearFilters: () => '',
      },
    ],
    deletingId: [
      null as string | null,
      {
        deleteBackup: (_, { id }) => id,
        deleteFinished: () => null,
      },
    ],
  }),
  selectors({
    filteredBackups: [
      (s) => [s.listing, s.query, s.kind],
      (listing: BackupsListing, query: string, kind: BackupKindFilter): CloudBackup[] => {
        const needle = query.trim().toLowerCase()
        return listing.backups.filter((backup) => {
          if (kind && backup.kind !== kind) {
            return false
          }
          if (!needle) {
            return true
          }
          return [backup.name ?? '', backup.item_key, backup.pushed_by ?? ''].some((value) =>
            value.toLowerCase().includes(needle)
          )
        })
      },
    ],
    filtered: [(s) => [s.query, s.kind], (query: string, kind: BackupKindFilter): boolean => !!query.trim() || !!kind],
    totalBytes: [
      (s) => [s.listing],
      (listing: BackupsListing): number => listing.backups.reduce((sum, backup) => sum + backup.size_bytes, 0),
    ],
  }),
  listeners(({ actions, values }) => ({
    deleteBackup: async ({ id }) => {
      try {
        const backup = values.listing.backups.find((entry) => entry.id === id)
        const confirmed = await confirmDialog({
          title: `Delete the cloud backup "${backup ? backupLabel(backup) : id}"?`,
          message: 'The copy on your backend or frame is not touched, but the cloud copy cannot be recovered.',
          confirmLabel: 'Delete backup',
          danger: true,
        })
        if (!confirmed) {
          return
        }
        const response = await apiCall(`/api/account/backups/${encodeURIComponent(id)}`, 'DELETE')
        if (!response.ok) {
          showErrorMessage(describeHttpError(response.status))
          return
        }
        actions.loadListing()
      } finally {
        actions.deleteFinished()
      }
    },
  })),
  afterMount(({ actions }) => {
    actions.loadListing()
  }),
])
