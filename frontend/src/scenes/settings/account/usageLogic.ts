import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { apiFetch } from '../../../utils/apiFetch'
import { confirmDialog } from '../../../utils/confirmDialogLogic'
import { showErrorMessage } from '../../../utils/workingMessage'
import { apiCall } from './api'

// The Usage page: the storage and frame quotas (GET /api/account/usage, the
// same accountUsage() the quota refusals read) and the AI usage with its off
// switch (GET / PUT /api/account/ai). Micro-dollar amounts arrive as decimal
// strings — JSON's number would round a bigint — and stay strings here.

export interface UsageBucket {
  bytes: number
  max_bytes: number
}

export interface AccountUsage {
  ai: {
    billable_micros: string
    daily_cap_allowance?: string
    daily_cap_micros: string
    enabled: boolean
    metering_mode: string
    month_micros: string
    own_key_only: boolean
    previous_month_micros: string
    today_micros: string
    turns_this_month: number
  }
  backups: UsageBucket
  frames: { count: number; max_count: number }
  cloud_rendered_frames?: { count: number; max_count: number; min_interval_seconds: number }
  frame_logs: UsageBucket
  photos: UsageBucket
  plan: { code: string; name: string; price_micros: string; subscribed: boolean }
  scenes: {
    private_bytes: number
    private_max_bytes: number
    public_bytes: number
  }
}

export interface AiUsageSurface {
  credential_source: string
  micros: string
  surface: string | null
  turns: number
}

export interface AiUsageMonth {
  micros: string
  own_key_only: boolean
  surfaces: AiUsageSurface[]
  turns: number
}

export interface AiTurn {
  credited: boolean
  micros: string
  model: string
  occurred_at: string
  own_key: boolean
  surface: string | null
}

export interface AiBalanceLine {
  amount_micros: string
  description: string
  direction: 'credit' | 'debit'
  id: string
  occurred_at: string
}

export interface AiUsage {
  cap: { allowance: 'shared' | 'billable'; daily_micros: string; resets_at: string; today_micros: string }
  balance: { receivable_micros: string; recent_lines?: AiBalanceLine[] }
  enabled: boolean
  metering_mode: string
  months: { current: AiUsageMonth; previous: AiUsageMonth }
  plan: { cancel_at: string | null; code: string; name: string; next_plan_code: string | null; price_micros: string }
  turns: AiTurn[]
}

export interface UsageAccount {
  created_at: string
  email: string
  id: string
  is_superadmin: boolean
  name: string | null
}

export interface UsageResponse {
  /** The signed-in account (the home page's greeting). */
  account?: UsageAccount | undefined
  /** Where to ask for more; null when the deployment has no support address. */
  support_email: string | null
  usage: AccountUsage
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface usageLogicValues {
  ai: AiUsage | null
  aiLoading: boolean
  contactEmail: string | null
  togglingAi: boolean
  usage: AccountUsage | null
  usageLoading: boolean
  usageResponse: UsageResponse | null
  usageResponseLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface usageLogicActions {
  loadAi: () => any
  loadAiFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadAiSuccess: (
    ai: AiUsage,
    payload?: any
  ) => {
    ai: AiUsage
    payload?: any
  }
  loadUsage: () => any
  loadUsageFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadUsageSuccess: (
    usageResponse: {
      account: UsageAccount | undefined
      support_email: string | null
      usage: AccountUsage
    } | null,
    payload?: any
  ) => {
    usageResponse: {
      account: UsageAccount | undefined
      support_email: string | null
      usage: AccountUsage
    } | null
    payload?: any
  }
  setAiEnabled: (enabled: boolean) => {
    enabled: boolean
  }
  toggleAiFinished: () => {
    value: true
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface usageLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    usage: (usageResponse: UsageResponse | null) => AccountUsage | null
    contactEmail: (usageResponse: UsageResponse | null) => string | null
    usageLoading: (usageResponseLoading: boolean) => boolean
  }
}

export type usageLogicType = MakeLogicType<usageLogicValues, usageLogicActions, Record<string, any>> & usageLogicMeta

export const usageLogic = kea<usageLogicType>([
  path(['src', 'scenes', 'settings', 'account', 'usageLogic']),
  actions({
    setAiEnabled: (enabled: boolean) => ({ enabled }),
    toggleAiFinished: true,
  }),
  loaders(() => ({
    usageResponse: [
      null as UsageResponse | null,
      {
        loadUsage: async () => {
          const response = await apiFetch('/api/account/usage')
          if (!response.ok) {
            throw new Error('Failed to load the account usage')
          }
          const payload = (await response.json()) as {
            account?: UsageAccount
            usage?: AccountUsage
            support_email?: string | null
          }
          if (!payload.usage) {
            return null
          }
          return { account: payload.account, support_email: payload.support_email ?? null, usage: payload.usage }
        },
      },
    ],
    ai: [
      null as AiUsage | null,
      {
        loadAi: async () => {
          const response = await apiFetch('/api/account/ai')
          if (!response.ok) {
            throw new Error('Failed to load the AI usage')
          }
          return (await response.json()) as AiUsage
        },
      },
    ],
  })),
  reducers({
    togglingAi: [
      false,
      {
        setAiEnabled: () => true,
        toggleAiFinished: () => false,
      },
    ],
  }),
  selectors({
    usage: [
      (s) => [s.usageResponse],
      (usageResponse: UsageResponse | null): AccountUsage | null => usageResponse?.usage ?? null,
    ],
    contactEmail: [
      (s) => [s.usageResponse],
      (usageResponse: UsageResponse | null): string | null => usageResponse?.support_email ?? null,
    ],
    usageLoading: [(s) => [s.usageResponseLoading], (usageResponseLoading: boolean): boolean => usageResponseLoading],
  }),
  listeners(({ actions }) => ({
    setAiEnabled: async ({ enabled }) => {
      try {
        if (!enabled) {
          const confirmed = await confirmDialog({
            title: 'Turn AI features off?',
            message:
              'Scene chat and the app-code assistant will stop working for this account, and nothing you do can incur AI cost. You can turn them back on at any time.',
            confirmLabel: 'Turn AI off',
            danger: true,
          })
          if (!confirmed) {
            return
          }
        }
        const response = await apiCall('/api/account/ai', 'PUT', { enabled })
        if (!response.ok) {
          showErrorMessage("That didn't work. Try again in a moment.")
          return
        }
        actions.loadAi()
        actions.loadUsage()
      } finally {
        actions.toggleAiFinished()
      }
    },
  })),
  afterMount(({ actions }) => {
    actions.loadUsage()
    actions.loadAi()
  }),
])
