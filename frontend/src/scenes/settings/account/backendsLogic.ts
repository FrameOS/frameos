import { MakeLogicType, actions, afterMount, beforeUnmount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { apiFetch } from '../../../utils/apiFetch'
import { confirmDialog } from '../../../utils/confirmDialogLogic'
import { showErrorMessage } from '../../../utils/workingMessage'
import { apiCall, describeHttpError, readJsonPayload } from './api'
import { redirectToReauthIfRequired, takePendingReauthActionWhere } from './reauth'

// The Backends page: the self-managed backends and frames that link to the
// account for cloud services (login, backups) without handing over
// management. Cloud-managed frames each carry a link too, but they are the
// Frames workspace's; the cloud's listing leaves them out
// (GET /api/account/installs).
export interface LinkedBackend {
  id: string
  name: string
  kind: 'backend' | 'frame'
  /** The scopes beyond the baseline link, as labels. */
  features: string[]
  version: string | null
  last_seen_at: string | null
  created_at: string
  revoked_at: string | null
  /** The local origin the backend reported when it linked, when it can be opened from here. */
  origin: string | null
}

const revokeActionPrefix = 'revoke-install:'

