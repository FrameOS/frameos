export type backendsLogicType = MakeLogicType<backendsLogicValues, backendsLogicActions, Record<string, any>> &
  backendsLogicMeta

// A backend opens in a full-viewport overlay (an iframe of its own UI). The
// URL hash is the source of truth — opening pushes #backend-<id>, so the
// browser's Back closes the overlay instead of leaving the page, and a direct
// link reopens it.
function backendIdFromHash(): string | null {
  if (typeof window === 'undefined') {
    return null
  }
  const match = /^#backend-(.+)$/.exec(window.location.hash)
  return match ? decodeURIComponent(match[1]) : null
}

export const backendsLogic = kea<backendsLogicType>([
  path(['src', 'scenes', 'settings', 'account', 'backendsLogic']),
  actions({
    setShowRevoked: (showRevoked: boolean) => ({ showRevoked }),
    revokeBackend: (id: string, options: { resumed?: boolean } = {}) => ({ id, options }),
    revokeFinished: true,
    openBackendViewer: (id: string) => ({ id }),
    closeBackend: true,
    syncOpenBackendFromHash: true,
  }),
  loaders(() => ({
    backends: [
      [] as LinkedBackend[],
      {
        loadBackends: async () => {
          const response = await apiFetch('/api/account/installs')
          if (!response.ok) {
            throw new Error('Failed to load the linked backends')
          }
          const payload = (await response.json()) as { installs?: LinkedBackend[] }
          return payload.installs ?? []
        },
      },
    ],
  })),
  reducers({
    showRevoked: [
      false,
      {
        setShowRevoked: (_, { showRevoked }) => showRevoked,
      },
    ],
    revokingId: [
      null as string | null,
      {
        revokeBackend: (_, { id }) => id,
        revokeFinished: () => null,
      },
    ],
    openBackendId: [
      backendIdFromHash(),
      {
        openBackendViewer: (_, { id }) => id,
        closeBackend: () => null,
        syncOpenBackendFromHash: () => backendIdFromHash(),
      },
    ],
  }),
  selectors({
    revokedCount: [
      (s) => [s.backends],
      (backends: LinkedBackend[]): number => backends.filter((backend) => backend.revoked_at).length,
    ],
    visibleBackends: [
      (s) => [s.backends, s.showRevoked],
      (backends: LinkedBackend[], showRevoked: boolean): LinkedBackend[] =>
        showRevoked ? backends : backends.filter((backend) => !backend.revoked_at),
    ],
    openBackend: [
      (s) => [s.backends, s.openBackendId],
      (backends: LinkedBackend[], openBackendId: string | null): LinkedBackend | null =>
        backends.find((backend) => backend.id === openBackendId && backend.origin && !backend.revoked_at) ?? null,
    ],
  }),
  listeners(({ actions, values }) => ({
    loadBackendsSuccess: ({ backends }) => {
      // Back from /login/reauth: the revoke was confirmed before the detour,
      // so finish it without asking again.
      const pending = takePendingReauthActionWhere((action) => action.startsWith(revokeActionPrefix))
      const resumedId = pending ? pending.slice(revokeActionPrefix.length) : null
      if (resumedId && backends.some((backend) => backend.id === resumedId && !backend.revoked_at)) {
        actions.revokeBackend(resumedId, { resumed: true })
      }
    },
    revokeBackend: async ({ id, options }) => {
      const backend = values.backends.find((entry) => entry.id === id)
      const name = backend?.name ?? 'this device'
      try {
        if (!options.resumed) {
          const confirmed = await confirmDialog({
            title: `Revoke the cloud link for "${name}"?`,
            message: 'The device loses access until it is linked again.',
            confirmLabel: 'Revoke link',
            danger: true,
          })
          if (!confirmed) {
            return
          }
        }
        const response = await apiCall('/api/device/revoke', 'POST', { linked_client_id: id })
        if (response.ok) {
          actions.loadBackends()
          return
        }
        const payload = await readJsonPayload(response)
        // A resumed call that is still refused (Cancel on the reauth page)
        // stops here instead of bouncing back to /login/reauth.
        if (!options.resumed && redirectToReauthIfRequired(response, payload, `${revokeActionPrefix}${id}`)) {
          return
        }
        showErrorMessage(describeHttpError(response.status))
      } finally {
        actions.revokeFinished()
      }
    },
    openBackendViewer: ({ id }) => {
      window.history.pushState({ frameosBackendViewer: true }, '', `#backend-${encodeURIComponent(id)}`)
    },
    closeBackend: () => {
      // Clear the hash in place instead of history.back(): the framed backend
      // is a separate app whose internal navigation shares the session
      // history, so "back" from here could step through it rather than pop
      // our hash entry.
      if (backendIdFromHash()) {
        window.history.replaceState(null, '', window.location.pathname + window.location.search)
      }
    },
  })),
  afterMount(({ actions, cache }) => {
    actions.loadBackends()
    cache.onHashChange = () => actions.syncOpenBackendFromHash()
    window.addEventListener('popstate', cache.onHashChange)
    window.addEventListener('hashchange', cache.onHashChange)
  }),
  beforeUnmount(({ cache }) => {
    window.removeEventListener('popstate', cache.onHashChange)
    window.removeEventListener('hashchange', cache.onHashChange)
  }),
])
