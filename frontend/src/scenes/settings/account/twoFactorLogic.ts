export const twoFactorLogic = kea<twoFactorLogicType>([
  path(['src', 'scenes', 'settings', 'account', 'twoFactorLogic']),
  actions({
    setError: (error: string | null) => ({ error }),
    setNotice: (notice: string | null) => ({ notice }),
    setBusy: (busy: boolean) => ({ busy }),
    setTotpSetup: (setup: TotpSetup | null) => ({ setup }),
    setTotpCode: (code: string) => ({ code }),
    cancelTotpSetup: true,
    setRecoveryCodes: (codes: string[] | null) => ({ codes }),
    dismissRecoveryCodes: true,
    copyRecoveryCodes: true,
    setPendingProof: (proof: PendingProof | null) => ({ proof }),
    cancelProof: true,
    setProofValue: (value: string) => ({ value }),
    submitProof: true,
    runProofAction: (proof: PendingProof, proofBody: Record<string, string>) => ({ proof, proofBody }),
    setNewPasskeyName: (name: string) => ({ name }),
    setRenaming: (renaming: PasskeyRename | null) => ({ renaming }),
    savePasskeyName: true,
    startTotp: true,
    confirmTotp: true,
    removeTotp: true,
    addPasskey: true,
    removePasskey: (id: string, name: string) => ({ id, name }),
    regenerateRecoveryCodes: true,
    disableAll: true,
  }),
  loaders(() => ({
    status: [
      emptyTwoFactorStatus,
      {
        loadStatus: async () => {
          const response = await apiFetch('/api/account/two-factor')
          if (!response.ok) {
            throw new Error('Failed to load the two-factor status')
          }
          return (await response.json()) as TwoFactorStatus
        },
      },
    ],
  })),
  reducers({
    statusLoaded: [
      false,
      {
        loadStatusSuccess: () => true,
      },
    ],
    error: [
      null as string | null,
      {
        setError: (_, { error }) => error,
        setPendingProof: () => null,
      },
    ],
    notice: [
      null as string | null,
      {
        setNotice: (_, { notice }) => notice,
      },
    ],
    busy: [
      false,
      {
        setBusy: (_, { busy }) => busy,
      },
    ],
    totpSetup: [
      null as TotpSetup | null,
      {
        setTotpSetup: (_, { setup }) => setup,
        cancelTotpSetup: () => null,
      },
    ],
    totpCode: [
      '',
      {
        setTotpCode: (_, { code }) => code,
        setTotpSetup: () => '',
        cancelTotpSetup: () => '',
      },
    ],
    recoveryCodes: [
      null as string[] | null,
      {
        setRecoveryCodes: (_, { codes }) => codes,
        dismissRecoveryCodes: () => null,
      },
    ],
    pendingProof: [
      null as PendingProof | null,
      {
        setPendingProof: (_, { proof }) => proof,
        cancelProof: () => null,
      },
    ],
    // Collected once per click, never cached.
    proofValue: [
      '',
      {
        setProofValue: (_, { value }) => value,
        setPendingProof: () => '',
        cancelProof: () => '',
      },
    ],
    newPasskeyName: [
      '',
      {
        setNewPasskeyName: (_, { name }) => name,
      },
    ],
    renaming: [
      null as PasskeyRename | null,
      {
        setRenaming: (_, { renaming }) => renaming,
      },
    ],
  }),
  listeners(({ actions, values }) => ({
    // Strengthening: the password when there is one, straight through when
    // there is not (the server asks for nothing more in that case).
    startTotp: () => {
      actions.setNotice(null)
      const proof: PendingProof = { kind: 'startTotp', label: 'Set up an authenticator app', tone: 'primary' }
      if (values.status.has_password) {
        actions.setPendingProof(proof)
      } else {
        actions.runProofAction(proof, {})
      }
    },
    addPasskey: () => {
      actions.setNotice(null)
      const proof: PendingProof = { kind: 'addPasskey', label: 'Add a passkey', tone: 'primary' }
      if (values.status.has_password) {
        actions.setPendingProof(proof)
      } else {
        actions.runProofAction(proof, {})
      }
    },
    removeTotp: () => {
      actions.setPendingProof({ kind: 'removeTotp', label: 'Remove the authenticator app', tone: 'danger' })
    },
    removePasskey: ({ id, name }) => {
      actions.setPendingProof({
        kind: 'removePasskey',
        label: `Remove passkey “${name}”`,
        tone: 'danger',
        passkeyId: id,
        passkeyName: name,
      })
    },
    regenerateRecoveryCodes: () => {
      actions.setPendingProof({ kind: 'regenerateCodes', label: 'Generate new recovery codes', tone: 'danger' })
    },
    disableAll: () => {
      actions.setPendingProof({ kind: 'disable', label: 'Turn off two-factor authentication', tone: 'danger' })
    },
    submitProof: () => {
      const proof = values.pendingProof
      if (!proof) {
        return
      }
      actions.runProofAction(
        proof,
        values.status.has_password ? { password: values.proofValue } : { code: values.proofValue }
      )
    },
    // Throws with the message to show; a wrong password keeps the proof form
    // open with the message in it.
    runProofAction: async ({ proof, proofBody }) => {
      actions.setBusy(true)
      actions.setError(null)
      try {
        switch (proof.kind) {
          case 'startTotp': {
            const payload = await call('/api/account/two-factor/totp', 'POST', proofBody)
            actions.setTotpSetup(payload as unknown as TotpSetup)
            break
          }
          case 'removeTotp': {
            await call('/api/account/two-factor/totp', 'DELETE', proofBody)
            actions.setNotice('Authenticator app removed.')
            actions.loadStatus()
            break
          }
          case 'addPasskey': {
            const optionsPayload = await call('/api/account/two-factor/passkeys/options', 'POST', proofBody)
            const { startRegistration } = await import('@simplewebauthn/browser')
            let attestation: unknown
            try {
              attestation = await startRegistration({
                optionsJSON: optionsPayload.options as Parameters<typeof startRegistration>[0]['optionsJSON'],
              })
            } catch (caught) {
              if (caught instanceof Error && caught.name === 'NotAllowedError') {
                throw new Error('Passkey prompt was cancelled.')
              }
              if (caught instanceof Error && caught.name === 'InvalidStateError') {
                throw new Error('This passkey is already registered on this account.')
              }
              throw new Error('Passkeys are not available on this device or browser.')
            }
            const payload = await call('/api/account/two-factor/passkeys', 'POST', {
              name: values.newPasskeyName,
              response: attestation,
            })
            actions.setNewPasskeyName('')
            if (Array.isArray(payload.recovery_codes)) {
              actions.setRecoveryCodes(payload.recovery_codes as string[])
            }
            actions.setNotice(`Passkey added.${revokedTokensNote(payload)}`)
            actions.loadStatus()
            break
          }
          case 'removePasskey': {
            await call(
              `/api/account/two-factor/passkeys/${encodeURIComponent(proof.passkeyId ?? '')}`,
              'DELETE',
              proofBody
            )
            actions.setNotice(`Passkey “${proof.passkeyName ?? ''}” removed.`)
            actions.loadStatus()
            break
          }
          case 'regenerateCodes': {
            const payload = await call('/api/account/two-factor/recovery-codes', 'POST', proofBody)
            actions.setRecoveryCodes(payload.recovery_codes as string[])
            actions.setNotice('New recovery codes generated. The old ones no longer work.')
            actions.loadStatus()
            break
          }
          case 'disable': {
            await call('/api/account/two-factor/disable', 'POST', proofBody)
            actions.setRecoveryCodes(null)
            actions.setNotice('Two-factor authentication is off.')
            actions.loadStatus()
            break
          }
        }
        actions.cancelProof()
      } catch (caught) {
        actions.setError(errorMessage(caught))
      } finally {
        actions.setBusy(false)
      }
    },
    confirmTotp: async () => {
      actions.setNotice(null)
      actions.setError(null)
      actions.setBusy(true)
      try {
        const payload = await call('/api/account/two-factor/totp/confirm', 'POST', { code: values.totpCode })
        actions.cancelTotpSetup()
        if (Array.isArray(payload.recovery_codes)) {
          actions.setRecoveryCodes(payload.recovery_codes as string[])
        }
        actions.setNotice(`Authenticator app enabled.${revokedTokensNote(payload)}`)
        actions.loadStatus()
      } catch (caught) {
        actions.setError(errorMessage(caught))
      } finally {
        actions.setBusy(false)
      }
    },
    savePasskeyName: async () => {
      const renaming = values.renaming
      if (!renaming) {
        return
      }
      actions.setNotice(null)
      actions.setError(null)
      actions.setBusy(true)
      try {
        await call(`/api/account/two-factor/passkeys/${encodeURIComponent(renaming.id)}`, 'PATCH', {
          name: renaming.name,
        })
        actions.setRenaming(null)
        actions.loadStatus()
      } catch (caught) {
        actions.setError(errorMessage(caught))
      } finally {
        actions.setBusy(false)
      }
    },
    copyRecoveryCodes: async () => {
      const codes = values.recoveryCodes
      if (!codes) {
        return
      }
      try {
        await navigator.clipboard.writeText(codes.join('\n'))
        actions.setNotice('Recovery codes copied.')
      } catch {
        actions.setError('Could not copy. Select the codes and copy them by hand.')
      }
    },
  })),
  afterMount(({ actions }) => {
    actions.loadStatus()
  }),
])
