// Two-factor authentication on the Security page: an authenticator app, the
// passkeys, the recovery codes and the off switch, over
// /api/account/two-factor/* (cloud/apps/auth-web/app/api/account/two-factor).
//
// Every action that weakens the account carries a proof: the password when
// the account has one, otherwise a current authenticator/recovery code. The
// page asks for it inline, right where the action is (pendingProof).
// Strengthening actions (enrolling an authenticator or a passkey) ask for the
// password too when the account has one — a second factor added with
// nothing but a session cookie would then vouch for that cookie's owner for
// good — and skip the prompt otherwise.

export interface Passkey {
  backed_up: boolean
  created_at: string
  id: string
  last_used_at: string | null
  name: string
}

export interface TwoFactorStatus {
  enabled: boolean
  has_password: boolean
  passkeys: Passkey[]
  recovery_codes_remaining: number
  totp_enabled: boolean
  totp_pending: boolean
}

export interface TotpSetup {
  otpauth_url: string
  qr_svg: string
  secret: string
}

export type ProofKind = 'startTotp' | 'removeTotp' | 'addPasskey' | 'removePasskey' | 'regenerateCodes' | 'disable'

export interface PendingProof {
  kind: ProofKind
  label: string
  tone: 'danger' | 'primary'
  passkeyId?: string
  passkeyName?: string
}

export interface PasskeyRename {
  id: string
  name: string
}

export const emptyTwoFactorStatus: TwoFactorStatus = {
  enabled: false,
  has_password: false,
  passkeys: [],
  recovery_codes_remaining: 0,
  totp_enabled: false,
  totp_pending: false,
}

function describeTwoFactorError(response: Response, payload: JsonPayload | undefined): string {
  switch (payload?.error) {
    case 'invalid_password':
      return 'The password is incorrect.'
    case 'invalid_code':
      return 'That code is not valid.'
    case 'invalid_passkey':
    case 'challenge_expired':
      return 'The passkey could not be verified. Try again.'
    case 'passkey_exists':
      return 'That passkey is already registered.'
    case 'too_many_passkeys':
      return 'This account already has the maximum number of passkeys.'
    default:
      return describeHttpError(response.status)
  }
}

// Enrolling a factor revokes every personal API token (they were minted
// before it existed and would keep walking past it). The routes report how
// many; the notice has to say so, or an agent's scripts start failing with
// 401 and nothing on this page explains why.
function revokedTokensNote(payload: JsonPayload): string {
  const revoked = typeof payload.api_tokens_revoked === 'number' ? payload.api_tokens_revoked : 0
  if (revoked <= 0) {
    return ''
  }
  return ` ${revoked} API ${revoked === 1 ? 'token was' : 'tokens were'} revoked. Create new ones under Developer.`
}

// A proof-required failure the caller shows; a reauth refusal navigates away
// and never resolves.
async function call(url: string, method: string, body?: unknown): Promise<JsonPayload> {
  const response = await apiCall(url, method, body)
  const payload = await readJsonPayload(response)
  if (!response.ok) {
    if (redirectToReauthIfRequired(response, payload)) {
      return new Promise<never>(() => {})
    }
    throw new Error(describeTwoFactorError(response, payload))
  }
  return payload ?? {}
}

function errorMessage(caught: unknown): string {
  return caught instanceof Error ? caught.message : 'Something went wrong.'
}

