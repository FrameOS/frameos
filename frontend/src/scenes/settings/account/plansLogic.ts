export interface plansLogicValues {
  contactEmail: string | null // usageLogic
  catalog: PlanCatalog | null
  catalogLoading: boolean
  planCards: PlanCard[]
  stopIndexes: Record<string, number>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface plansLogicActions {
  loadCatalog: () => any
  loadCatalogFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadCatalogSuccess: (
    catalog: PlanCatalog | null,
    payload?: any
  ) => {
    catalog: PlanCatalog | null
    payload?: any
  }
  setStopIndex: (
    group: string,
    index: number
  ) => {
    group: string
    index: number
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface plansLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    planCards: (
      catalog: PlanCatalog | null,
      stopIndexes: Record<string, number>,
      contactEmail: string | null
    ) => PlanCard[]
  }
}

export type plansLogicType = MakeLogicType<plansLogicValues, plansLogicActions, Record<string, any>> & plansLogicMeta

export const plansLogic = kea<plansLogicType>([
  path(['src', 'scenes', 'settings', 'account', 'plansLogic']),
  connect(() => ({
    values: [usageLogic, ['contactEmail']],
  })),
  actions({
    setStopIndex: (group: string, index: number) => ({ group, index }),
  }),
  loaders(() => ({
    catalog: [
      null as PlanCatalog | null,
      {
        loadCatalog: async () => {
          const response = await apiFetch('/api/account/plan')
          if (!response.ok) {
            throw new Error('Failed to load the plans')
          }
          const payload = (await response.json()) as { catalog?: PlanCatalog }
          return payload.catalog ?? null
        },
      },
    ],
  })),
  reducers({
    stopIndexes: [
      {} as Record<string, number>,
      {
        setStopIndex: (state, { group, index }) => ({ ...state, [group]: index }),
      },
    ],
  }),
  selectors({
    planCards: [
      (s) => [s.catalog, s.stopIndexes, s.contactEmail],
      (catalog: PlanCatalog | null, stopIndexes: Record<string, number>, contactEmail: string | null): PlanCard[] =>
        planCardsFor(catalog, stopIndexes, contactEmail),
    ],
  }),
  afterMount(({ actions }) => {
    actions.loadCatalog()
  }),
])
