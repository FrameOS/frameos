export interface systemInfoLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    currentDisk: (systemMetrics: SystemMetricsResponse | null, systemInfo: SystemInfoResponse | null) => DiskInfo | null
    currentMemory: (
      systemMetrics: SystemMetricsResponse | null,
      systemInfo: SystemInfoResponse | null
    ) => MemoryInfo | null
    currentLoad: (systemMetrics: SystemMetricsResponse | null, systemInfo: SystemInfoResponse | null) => LoadInfo | null
  }
}

export type systemInfoLogicType = MakeLogicType<systemInfoLogicValues, systemInfoLogicActions, Record<string, any>> &
  systemInfoLogicMeta

export const systemInfoLogic = kea<systemInfoLogicType>([
  path(['src', 'scenes', 'settings', 'systemInfoLogic']),
  loaders(() => ({
    systemInfo: [
      null as SystemInfoResponse | null,
      {
        loadSystemInfo: async () => {
          const response = await apiFetch(`/api/system/info`)
          if (!response.ok) {
            throw new Error('Failed to fetch system information')
          }
          return (await response.json()) as SystemInfoResponse
        },
      },
    ],
    systemMetrics: [
      null as SystemMetricsResponse | null,
      {
        loadSystemMetrics: async () => {
          const response = await apiFetch(`/api/system/metrics`)
          if (!response.ok) {
            throw new Error('Failed to fetch system metrics')
          }
          return (await response.json()) as SystemMetricsResponse
        },
      },
    ],
  })),
  reducers({
    systemInfo: {
      loadSystemInfoFailure: () => null,
    },
    systemMetrics: {
      loadSystemMetricsFailure: () => null,
    },
  }),
  selectors({
    currentDisk: [
      (s) => [s.systemMetrics, s.systemInfo],
      (systemMetrics: systemInfoLogicValues['systemMetrics'], systemInfo: systemInfoLogicValues['systemInfo']) =>
        systemMetrics?.disk ?? systemInfo?.disk ?? null,
    ],
    currentMemory: [
      (s) => [s.systemMetrics, s.systemInfo],
      (systemMetrics: systemInfoLogicValues['systemMetrics'], systemInfo: systemInfoLogicValues['systemInfo']) =>
        systemMetrics?.memory ?? systemInfo?.memory ?? null,
    ],
    currentLoad: [
      (s) => [s.systemMetrics, s.systemInfo],
      (systemMetrics: systemInfoLogicValues['systemMetrics'], systemInfo: systemInfoLogicValues['systemInfo']) =>
        systemMetrics?.load ?? systemInfo?.load ?? null,
    ],
  }),
  afterMount(({ actions, cache }) => {
    actions.loadSystemInfo()
    const refreshMetrics = () => actions.loadSystemMetrics()
    refreshMetrics()
    cache.metricsInterval = window.setInterval(refreshMetrics, 5000)
  }),
  beforeUnmount(({ cache }) => {
    if (cache.metricsInterval) {
      window.clearInterval(cache.metricsInterval)
    }
  }),
])
