import { MakeLogicType, afterMount, beforeUnmount, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { apiFetch } from '../../utils/apiFetch'

export interface DiskInfo {
  totalBytes: number
  usedBytes: number
  freeBytes: number
}

export interface MemoryInfo {
  totalBytes: number | null
  availableBytes: number | null
}

export interface LoadInfo {
  one: number | null
  five: number | null
  fifteen: number | null
}

export interface CacheInfo {
  name: string
  path: string
  sizeBytes: number
  exists: boolean
}

export interface DatabaseInfo {
  path: string | null
  sizeBytes: number | null
  exists: boolean
}

export interface DockerInfo {
  cliAvailable: boolean
  daemonAvailable: boolean
  error?: string | null
}

export interface SystemInfoResponse {
  disk: DiskInfo
  caches: CacheInfo[]
  database: DatabaseInfo
  memory: MemoryInfo
  load: LoadInfo
  docker: DockerInfo
}

export interface SystemMetricsResponse {
  disk: DiskInfo
  memory: MemoryInfo
  load: LoadInfo
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface systemInfoLogicValues {
  currentDisk: DiskInfo | null
  currentLoad: LoadInfo | null
  currentMemory: MemoryInfo | null
  systemInfo: SystemInfoResponse | null
  systemInfoLoading: boolean
  systemMetrics: SystemMetricsResponse | null
  systemMetricsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface systemInfoLogicActions {
  loadSystemInfo: () => any
  loadSystemInfoFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadSystemInfoSuccess: (
    systemInfo: SystemInfoResponse,
    payload?: any
  ) => {
    systemInfo: SystemInfoResponse
    payload?: any
  }
  loadSystemMetrics: () => any
  loadSystemMetricsFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadSystemMetricsSuccess: (
    systemMetrics: SystemMetricsResponse,
    payload?: any
  ) => {
    systemMetrics: SystemMetricsResponse
    payload?: any
  }
}

