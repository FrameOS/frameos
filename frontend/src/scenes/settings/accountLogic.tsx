import type { DeepPartial, DeepPartialMap, FieldName, ValidationErrorType } from 'kea-forms'

export interface AccountUser {
  email: string
}

export interface AccountPasswordForm {
  current_password: string
  password: string
  password2: string
}

export interface AccountEmailForm {
  email: string
  // The email is the login name, so the backend wants the current password
  // (when the account has one) before it changes hands.
  current_password: string
}

const defaultPasswordForm: AccountPasswordForm = {
  current_password: '',
  password: '',
  password2: '',
}

const defaultEmailForm: AccountEmailForm = {
  email: '',
  current_password: '',
}

async function responseErrorMessage(response: Response, fallback: string): Promise<string> {
  try {
    const payload = await response.json()
    if (typeof payload?.detail === 'string') {
      return payload.detail
    }
    if (Array.isArray(payload?.detail)) {
      return payload.detail
        .map((detail: { msg?: string }) => detail?.msg)
        .filter(Boolean)
        .join(' ')
    }
    if (typeof payload?.error === 'string') {
      return payload.error
    }
  } catch {
    // Use fallback below.
  }
  return fallback
}

