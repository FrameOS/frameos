import { afterMount, connect, kea, path, selectors } from 'kea'
import type { MakeLogicType } from 'kea'
import { loaders } from 'kea-loaders'

import { framesModel } from '../../models/framesModel'
import type { FrameType } from '../../types'
import { fetchPhotoFolder, type PhotoEntry } from '../photos/photosApi'
import { usageLogic } from '../settings/account/usageLogic'
import type { AccountUsage, UsageAccount } from '../settings/account/usageLogic'
import type { UsageResponse } from '../settings/account/usageLogic'

// The cloud's home page: who is signed in, the frames and albums touched
// most recently, and the account's usage — each section a few entries and
// a way to the full page. Frames come from the fleet model the workspace
// already holds; the albums are the photo library's root folders; the
// greeting and the usage share the Usage page's logic.

export const HOME_SECTION_LIMIT = 6

function recency(frame: FrameType): number {
  const seen = frame.last_seen_at ? Date.parse(frame.last_seen_at) : NaN
  return Number.isNaN(seen) ? 0 : seen
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface cloudHomeLogicValues {
  framesEverLoaded: boolean // framesModel
  framesList: FrameType[] // framesModel
  usageResponse: UsageResponse | null // usageLogic
  usageResponseLoading: boolean // usageLogic
  account: UsageAccount | null
  albums: PhotoEntry[]
  albumsLoading: boolean
  greetingName: string
  recentAlbums: PhotoEntry[]
  recentFrames: FrameType[]
  usage: AccountUsage | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface cloudHomeLogicActions {
  loadUsage: () => any // usageLogic
  loadAlbums: () => any
  loadAlbumsFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadAlbumsSuccess: (
    albums: PhotoEntry[],
    payload?: any
  ) => {
    albums: PhotoEntry[]
    payload?: any
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface cloudHomeLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    account: (usageResponse: UsageResponse | null) => UsageAccount | null
    greetingName: (account: UsageAccount | null) => string
    usage: (usageResponse: UsageResponse | null) => AccountUsage | null
    recentFrames: (framesList: FrameType[]) => FrameType[]
    recentAlbums: (albums: PhotoEntry[]) => PhotoEntry[]
  }
}

export type cloudHomeLogicType = MakeLogicType<cloudHomeLogicValues, cloudHomeLogicActions, Record<string, any>> &
  cloudHomeLogicMeta

export const cloudHomeLogic = kea<cloudHomeLogicType>([
  path(['src', 'scenes', 'home', 'cloudHomeLogic']),
  connect(() => ({
    values: [framesModel, ['framesList', 'framesEverLoaded'], usageLogic, ['usageResponse', 'usageResponseLoading']],
    actions: [usageLogic, ['loadUsage']],
  })),
  loaders(() => ({
    albums: [
      [] as PhotoEntry[],
      {
        loadAlbums: async () => {
          const entries = await fetchPhotoFolder('')
          return entries.filter((entry) => entry.kind === 'folder')
        },
      },
    ],
  })),
  selectors({
    account: [
      (s) => [s.usageResponse],
      (usageResponse: cloudHomeLogicValues['usageResponse']): UsageAccount | null => usageResponse?.account ?? null,
    ],
    // The display name, else the address before its "@": a greeting with
    // nothing after "Hello" reads like a bug.
    greetingName: [
      (s) => [s.account],
      (account: UsageAccount | null): string => {
        if (account?.name?.trim()) {
          return account.name.trim()
        }
        const email = account?.email ?? ''
        return email.includes('@') ? email.slice(0, email.indexOf('@')) : email
      },
    ],
    usage: [
      (s) => [s.usageResponse],
      (usageResponse: cloudHomeLogicValues['usageResponse']): AccountUsage | null => usageResponse?.usage ?? null,
    ],
    recentFrames: [
      (s) => [s.framesList],
      (framesList: FrameType[]): FrameType[] =>
        framesList
          .toSorted((a, b) => recency(b) - recency(a) || (a.name || '').localeCompare(b.name || ''))
          .slice(0, HOME_SECTION_LIMIT),
    ],
    recentAlbums: [
      (s) => [s.albums],
      (albums: PhotoEntry[]): PhotoEntry[] =>
        albums.toSorted((a, b) => b.mtime - a.mtime || a.name.localeCompare(b.name)).slice(0, HOME_SECTION_LIMIT),
    ],
  }),
  afterMount(({ actions }) => {
    actions.loadAlbums()
    actions.loadUsage()
  }),
])
