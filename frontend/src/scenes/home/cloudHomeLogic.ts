export type cloudHomeLogicType = MakeLogicType<cloudHomeLogicValues, cloudHomeLogicActions, Record<string, any>> &
  cloudHomeLogicMeta

export const cloudHomeLogic = kea<cloudHomeLogicType>([
  path(['src', 'scenes', 'home', 'cloudHomeLogic']),
  connect(() => ({
    values: [
      framesModel,
      ['framesList', 'framesEverLoaded'],
      usageLogic,
      ['usageResponse', 'usageResponseLoading'],
      repositoriesModel,
      ['repositories', 'repositoriesLoading'],
      cloudDriveLogic,
      ['driveTemplates', 'driveTemplatesLoading'],
    ],
    actions: [
      usageLogic,
      ['loadUsage'],
      repositoriesModel,
      ['loadRepositoriesIfStale'],
      cloudDriveLogic,
      ['loadDriveIfStale'],
    ],
  })),
  loaders(() => ({
    albums: [
      [] as PhotoEntry[],
      {
        loadAlbums: async () => {
          const entries = await fetchPhotoFolder('')
          return entries.filter((entry) => entry.kind === 'folder')
        },
      },
    ],
  })),
  selectors({
    account: [
      (s) => [s.usageResponse],
      (usageResponse: cloudHomeLogicValues['usageResponse']): UsageAccount | null => usageResponse?.account ?? null,
    ],
    // The display name, else the address before its "@": a greeting with
    // nothing after "Hello" reads like a bug.
    greetingName: [
      (s) => [s.account],
      (account: UsageAccount | null): string => {
        if (account?.name?.trim()) {
          return account.name.trim()
        }
        const email = account?.email ?? ''
        return email.includes('@') ? email.slice(0, email.indexOf('@')) : email
      },
    ],
    usage: [
      (s) => [s.usageResponse],
      (usageResponse: cloudHomeLogicValues['usageResponse']): AccountUsage | null => usageResponse?.usage ?? null,
    ],
    recentFrames: [
      (s) => [s.framesList],
      (framesList: FrameType[]): FrameType[] =>
        framesList
          .toSorted((a, b) => recency(b) - recency(a) || (a.name || '').localeCompare(b.name || ''))
          .slice(0, HOME_SECTION_LIMIT),
    ],
    recentAlbums: [
      (s) => [s.albums],
      (albums: PhotoEntry[]): PhotoEntry[] =>
        albums.toSorted((a, b) => b.mtime - a.mtime || a.name.localeCompare(b.name)).slice(0, HOME_SECTION_LIMIT),
    ],
    storeTemplates: [
      (s) => [s.repositories],
      (repositories: RepositoryType[]): TemplateType[] => storeTemplatesOf(repositories),
    ],
    // The latest additions to the store: by the `updated` stamp the index
    // carries (a scene without one sorts last, in the index's own order).
    recentStoreScenes: [
      (s) => [s.storeTemplates],
      (storeTemplates: TemplateType[]): TemplateType[] =>
        storeTemplates
          .map((template, index) => ({ template, index, at: template.updated ? Date.parse(template.updated) : NaN }))
          .toSorted((a, b) => {
            if (Number.isNaN(a.at) !== Number.isNaN(b.at)) {
              return Number.isNaN(a.at) ? 1 : -1
            }
            return (Number.isNaN(b.at) ? 0 : b.at) - (Number.isNaN(a.at) ? 0 : a.at) || a.index - b.index
          })
          .map(({ template }) => template)
          .slice(0, HOME_SECTION_LIMIT),
    ],
    recentPrivateScenes: [
      (s) => [s.driveTemplates],
      (driveTemplates: TemplateType[]): TemplateType[] => driveTemplates.slice(0, HOME_SECTION_LIMIT),
    ],
  }),
  afterMount(({ actions }) => {
    actions.loadAlbums()
    actions.loadUsage()
    actions.loadRepositoriesIfStale(60_000)
    actions.loadDriveIfStale(60_000)
  }),
])
