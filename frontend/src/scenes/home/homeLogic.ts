import { fetchPhotoFolder, type PhotoEntry } from '../photos/photosApi'

// The home page behind the rail's logo, on the cloud and on a backend: the
// frames, the store's scenes, the account's cloud scenes and the albums —
// each section a few entries and a way to the full page. Frames come from
// the fleet model the workspace already holds; the scenes from the models the
// scenes library reads; the albums are the photo library's root folders.
// What only one control plane has is in cloudHomeLogic (the greeting and the
// account's usage) and backendHomeLogic (the greeting, the backend's own
// saved scenes, the numbers at a glance).

// Enough to fill one row on a wide screen; the grid shows one row only.
export const HOME_SECTION_LIMIT = 12

// The display name, else the address before its "@": a greeting with nothing
// after "Hello" reads like a bug.
export function greetingNameOf(name: string | null | undefined, email: string | null | undefined): string {
  if (name?.trim()) {
    return name.trim()
  }
  const address = email ?? ''
  return address.includes('@') ? address.slice(0, address.indexOf('@')) : address
}

// Last heard from: the hub's last_seen_at on the cloud, the last log line on
// a backend.
function recency(frame: FrameType): number {
  const seen = frameLastActivityAt(frame)
  return Number.isNaN(seen) ? 0 : seen
}

/** The frames the home page shows: the most recently heard from first,
 * archived frames last. */
export function recentFramesOf(framesList: FrameType[]): FrameType[] {
  return framesList
    .toSorted(
      (a, b) =>
        Number(!!a.archived) - Number(!!b.archived) ||
        recency(b) - recency(a) ||
        (a.name || '').localeCompare(b.name || '')
    )
    .slice(0, HOME_SECTION_LIMIT)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface homeLogicValues {
  driveTemplates: TemplateType[] // cloudDriveLogic
  driveTemplatesLoading: boolean // cloudDriveLogic
  hasDriveScope: boolean // cloudDriveLogic
  framesEverLoaded: boolean // framesModel
  framesList: FrameType[] // framesModel
  repositories: RepositoryType[] // repositoriesModel
  repositoriesLoading: boolean // repositoriesModel
  albums: PhotoEntry[]
  albumsFailed: boolean
  albumsLoading: boolean
  recentAlbums: PhotoEntry[]
  recentFrames: FrameType[]
  recentPrivateScenes: TemplateType[]
  recentStoreScenes: TemplateType[]
  storeTemplates: TemplateType[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface homeLogicActions {
  loadDriveIfStale: (maxAgeMs: number) => {
    maxAgeMs: number
  } // cloudDriveLogic
  loadRepositoriesIfStale: (maxAgeMs: number) => {
    maxAgeMs: number
  } // repositoriesModel
  loadAlbums: () => any
  loadAlbumsFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadAlbumsSuccess: (
    albums: PhotoEntry[],
    payload?: any
  ) => {
    albums: PhotoEntry[]
    payload?: any
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface homeLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    recentFrames: (framesList: FrameType[]) => FrameType[]
    recentAlbums: (albums: PhotoEntry[]) => PhotoEntry[]
    storeTemplates: (repositories: RepositoryType[]) => TemplateType[]
    recentStoreScenes: (storeTemplates: TemplateType[]) => TemplateType[]
    recentPrivateScenes: (driveTemplates: TemplateType[]) => TemplateType[]
  }
}

export type homeLogicType = MakeLogicType<homeLogicValues, homeLogicActions, Record<string, any>> & homeLogicMeta

export const homeLogic = kea<homeLogicType>([
  path(['src', 'scenes', 'home', 'homeLogic']),
  connect(() => ({
    values: [
      framesModel,
      ['framesList', 'framesEverLoaded'],
      repositoriesModel,
      ['repositories', 'repositoriesLoading'],
      cloudDriveLogic,
      ['driveTemplates', 'driveTemplatesLoading', 'hasDriveScope'],
    ],
    actions: [repositoriesModel, ['loadRepositoriesIfStale'], cloudDriveLogic, ['loadDriveIfStale']],
  })),
  loaders(() => ({
    albums: [
      [] as PhotoEntry[],
      {
        loadAlbums: async () => {
          const entries = await fetchPhotoFolder('')
          return entries.filter((entry) => entry.kind === 'folder')
        },
      },
    ],
  })),
  reducers({
    // A library that cannot answer (a backend's photo store not ready) is
    // not an empty one.
    albumsFailed: [
      false,
      {
        loadAlbums: () => false,
        loadAlbumsFailure: () => true,
      },
    ],
  }),
  selectors({
    recentFrames: [(s) => [s.framesList], (framesList: FrameType[]): FrameType[] => recentFramesOf(framesList)],
    recentAlbums: [
      (s) => [s.albums],
      (albums: PhotoEntry[]): PhotoEntry[] =>
        albums.toSorted((a, b) => b.mtime - a.mtime || a.name.localeCompare(b.name)).slice(0, HOME_SECTION_LIMIT),
    ],
    storeTemplates: [
      (s) => [s.repositories],
      (repositories: RepositoryType[]): TemplateType[] => storeTemplatesOf(repositories),
    ],
    recentStoreScenes: [
      (s) => [s.storeTemplates],
      (storeTemplates: TemplateType[]): TemplateType[] =>
        latestStoreAdditions(storeTemplates).slice(0, HOME_SECTION_LIMIT),
    ],
    recentPrivateScenes: [
      (s) => [s.driveTemplates],
      (driveTemplates: TemplateType[]): TemplateType[] => driveTemplates.slice(0, HOME_SECTION_LIMIT),
    ],
  }),
  afterMount(({ actions }) => {
    actions.loadAlbums()
    actions.loadRepositoriesIfStale(60_000)
    actions.loadDriveIfStale(60_000)
  }),
])
