import { afterMount, connect, kea, path, selectors } from 'kea'
import type { MakeLogicType } from 'kea'
import { loaders } from 'kea-loaders'

import { frameIsActive } from '../../decorators/frame'
import { framesModel } from '../../models/framesModel'
import { templatesModel } from '../../models/templatesModel'
import type { FrameType, TemplateType } from '../../types'
import { apiFetch } from '../../utils/apiFetch'
import { inHassioIngress } from '../../utils/inHassioIngress'
import { fetchPhotosStatus, type PhotosStatus } from '../photos/photosApi'
import { greetingNameOf, HOME_SECTION_LIMIT } from './homeLogic'
import versions from '../../../../versions.json'

// A backend's part of the home page (homeLogic has the shared sections): who
// is signed in, the scenes saved on this backend, and its numbers at a
// glance where the cloud shows the account's usage. Under Home Assistant's
// ingress there is no local account (`/api/user` answers 401), so no
// greeting.

// The release this backend runs, as the settings page names it: the docker
// version bumps on every release, the other components only with their own
// sources.
export const backendVersion: string | null = typeof versions.docker === 'string' ? versions.docker.split('+')[0] : null

export interface BackendHomeUser {
  email: string
}

export interface BackendHomeGlance {
  frames: number
  activeFrames: number
  installedScenes: number
  framesWithScenes: number
}

/** The fleet's numbers; archived frames count for none of them. */
export function backendGlanceOf(framesList: FrameType[]): BackendHomeGlance {
  const frames = framesList.filter((frame) => !frame.archived)
  return {
    frames: frames.length,
    activeFrames: frames.filter(frameIsActive).length,
    installedScenes: frames.reduce((total, frame) => total + (frame.scenes?.length ?? 0), 0),
    framesWithScenes: frames.filter((frame) => (frame.scenes?.length ?? 0) > 0).length,
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface backendHomeLogicValues {
  framesList: FrameType[] // framesModel
  templates: TemplateType[] // templatesModel
  templatesLoading: boolean // templatesModel
  glance: BackendHomeGlance
  greetingName: string
  photosStatus: PhotosStatus | null
  photosStatusLoading: boolean
  recentLocalScenes: TemplateType[]
  user: BackendHomeUser | null
  userLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface backendHomeLogicActions {
  loadTemplatesIfStale: (maxAgeMs: number) => {
    maxAgeMs: number
  } // templatesModel
  loadPhotosStatus: () => any
  loadPhotosStatusFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadPhotosStatusSuccess: (
    photosStatus: PhotosStatus | null,
    payload?: any
  ) => {
    photosStatus: PhotosStatus | null
    payload?: any
  }
  loadUser: () => any
  loadUserFailure: (
    error: string,
    errorObject?: any
  ) => {
    error: string
    errorObject?: any
  }
  loadUserSuccess: (
    user: BackendHomeUser | null,
    payload?: any
  ) => {
    user: BackendHomeUser | null
    payload?: any
  }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface backendHomeLogicMeta {
  __keaTypeGenInternalSelectorTypes: {
    greetingName: (user: BackendHomeUser | null) => string
    recentLocalScenes: (templates: TemplateType[]) => TemplateType[]
    glance: (framesList: FrameType[]) => BackendHomeGlance
  }
}

export type backendHomeLogicType = MakeLogicType<backendHomeLogicValues, backendHomeLogicActions, Record<string, any>> &
  backendHomeLogicMeta

export const backendHomeLogic = kea<backendHomeLogicType>([
  path(['src', 'scenes', 'home', 'backendHomeLogic']),
  connect(() => ({
    values: [framesModel, ['framesList'], templatesModel, ['templates', 'templatesLoading']],
    actions: [templatesModel, ['loadTemplatesIfStale']],
  })),
  loaders(() => ({
    user: [
      null as BackendHomeUser | null,
      {
        loadUser: async () => {
          const response = await apiFetch('/api/user')
          return response.ok ? ((await response.json()) as BackendHomeUser) : null
        },
      },
    ],
    photosStatus: [
      null as PhotosStatus | null,
      {
        loadPhotosStatus: async () => {
          try {
            return await fetchPhotosStatus()
          } catch {
            return null
          }
        },
      },
    ],
  })),
  selectors({
    greetingName: [(s) => [s.user], (user: BackendHomeUser | null): string => greetingNameOf(null, user?.email)],
    // In the order the scenes library lists them.
    recentLocalScenes: [
      (s) => [s.templates],
      (templates: TemplateType[]): TemplateType[] => templates.slice(0, HOME_SECTION_LIMIT),
    ],
    glance: [(s) => [s.framesList], (framesList: FrameType[]): BackendHomeGlance => backendGlanceOf(framesList)],
  }),
  afterMount(({ actions }) => {
    if (!inHassioIngress()) {
      actions.loadUser()
    }
    actions.loadPhotosStatus()
    actions.loadTemplatesIfStale(60_000)
  }),
])
